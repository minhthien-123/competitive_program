ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
std::vector<int> adj[maxn + 7];
int dp[maxn + 7];
int ans_all = inf;

void dfs1(int u, int p)
{
    for (int v : adj[u])
    {
        if (v != p)
        {
            dfs1(v, u);
        }
    }

    vi child;
    for (int v : adj[u])
    {
        if (v != p)
        {
            child.pb(dp[v]);
        }
    }

    if (child.empty())
    {
        dp[u] = 0;
        return;
    }

    std::sort(all(child), std::greater<int>());

    int mx = 0;
    for (int i = 0; i < sz(child); i += k)
    {
        int time = i / k + 1;
        mx = std::max(mx, child[i] + time);
    }

    dp[u] = mx;
}

void dfs2(int u, int p, int up_val)
{
    vii vec;
    if (p != -1)
    {
        vec.pb({up_val, p});
    }
    for (int v : adj[u])
    {
        if (v != p)
        {
            vec.pb({dp[v], v});
        }
    }

    std::sort(all(vec), std::greater<ii>());

    int m = sz(vec);

    int cur_ans = 0;
    for (int i = 0; i < m; i += k)
    {
        cur_ans = std::max(cur_ans, vec[i].fi + i / k + 1);
    }
    ans_all = std::min(ans_all, cur_ans);

    if (m == 0)
        return;

    vi pref(m, 0), suff(m, 0);
    for (int i = 0; i < m; i++)
    {
        int val = vec[i].fi + i / k + 1;
        pref[i] = (i == 0) ? val : std::max(pref[i - 1], val);
    }
    for (int i = m - 1; i >= 0; i--)
    {
        if (i > 0)
        {
            int val = vec[i].fi + (i - 1) / k + 1;
            suff[i] = (i == m - 1) ? val : std::max(suff[i + 1], val);
        }
    }

    for (int i = 0; i < m; i++)
    {
        int v = vec[i].se;
        if (v == p)
        {
            continue;
        }

        int next_up = 0;
        if (i > 0)
        {
            next_up = std::max(next_up, pref[i - 1]);
        }
        if (i + 1 < m)
        {
            next_up = std::max(next_up, suff[i + 1]);
        }

        dfs2(v, u, next_up);
    }
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    if (n == 1)
    {
        std::cout << 0;
        return;
    }

    dfs1(1, -1);
    dfs2(1, -1, 0);

    std::cout << ans_all;
}

