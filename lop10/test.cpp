ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

void solve()
{
    long long a, b, d;
    if (!(std::cin >> a >> b >> d))
    {
        return;
    }

    long long g = std::gcd(a, b);
    long long x = a / g;
    long long y = b / g;

    auto get_min_ops = [&](long long val) -> long long
    {
        if (val == 1)
        {
            return 0;
        }
        std::vector<long long> divs;
        for (long long i = 1; i * i <= val; i++)
        {
            if (val % i == 0)
            {
                divs.push_back(i);
                if (i * i != val)
                {
                    divs.push_back(val / i);
                }
            }
        }
        std::sort(divs.begin(), divs.end());
        int m = divs.size();
        std::vector<long long> dp(m, INF);
        dp[0] = 0;

        for (int i = 0; i < m; i++)
        {
            if (dp[i] == INF)
            {
                continue;
            }
            for (int j = 1; j < m; j++)
            {
                if (divs[j] > d)
                {
                    break;
                }
                if (val / divs[i] < divs[j])
                {
                    break;
                }
                long long nx = divs[i] * divs[j];
                if (val % nx == 0)
                {
                    int idx = std::lower_bound(divs.begin(), divs.end(), nx) - divs.begin();
                    if (dp[idx] > dp[i] + 1)
                    {
                        dp[idx] = dp[i] + 1;
                    }
                }
            }
        }
        return dp[m - 1];
    };

    long long ops_x = get_min_ops(x);
    long long ops_y = get_min_ops(y);

    if (ops_x == INF || ops_y == INF)
    {
        std::cout << -1 << "\n";
    }
    else
    {
        std::cout << ops_x + ops_y << "\n";
    }
}

