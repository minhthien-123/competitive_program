ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct BigNum
{
    std::vector<int> d;

    BigNum() {}
    BigNum(long long v)
    {
        if (v == 0)
        {
            d.push_back(0);
        }
        while (v > 0)
        {
            d.push_back(v % 10);
            v /= 10;
        }
    }
    BigNum(std::string s)
    {
        if (s.empty())
        {
            d.push_back(0);
            return;
        }
        for (int i = (int)s.length() - 1; i >= 0; i--)
        {
            d.push_back(s[i] - '0');
        }
        trim();
    }

    void trim()
    {
        while (d.size() > 1 && d.back() == 0)
        {
            d.pop_back();
        }
        if (d.empty())
        {
            d.push_back(0);
        }
    }

    friend std::istream &operator>>(std::istream &is, BigNum &b)
    {
        std::string s;
        is >> s;
        b = BigNum(s);
        return is;
    }
    friend std::ostream &operator<<(std::ostream &os, const BigNum &b)
    {
        if (b.d.empty())
        {
            os << 0;
        }
        for (int i = (int)b.d.size() - 1; i >= 0; i--)
        {
            os << b.d[i];
        }
        return os;
    }

    bool operator<(const BigNum &b) const
    {
        if (d.size() != b.d.size())
        {
            return d.size() < b.d.size();
        }
        for (int i = (int)d.size() - 1; i >= 0; i--)
        {
            if (d[i] != b.d[i])
            {
                return d[i] < b.d[i];
            }
        }
        return false;
    }
    bool operator>(const BigNum &b) const { return b < *this; }
    bool operator==(const BigNum &b) const { return !(*this < b) && !(b < *this); }
    bool operator<=(const BigNum &b) const { return *this < b || *this == b; }
    bool operator>=(const BigNum &b) const { return *this > b || *this == b; }

    BigNum operator+(const BigNum &b) const
    {
        BigNum res;
        int carry = 0;
        for (int i = 0; i < std::max(d.size(), b.d.size()) || carry; i++)
        {
            int sum = carry;
            if (i < d.size())
            {
                sum += d[i];
            }
            if (i < b.d.size())
            {
                sum += b.d[i];
            }
            res.d.push_back(sum % 10);
            carry = sum / 10;
        }
        return res;
    }

    BigNum operator-(const BigNum &b) const
    {
        BigNum res;
        int borrow = 0;
        for (int i = 0; i < (int)d.size(); i++)
        {
            int sub = d[i] - borrow - (i < (int)b.d.size() ? b.d[i] : 0);
            if (sub < 0)
            {
                sub += 10;
                borrow = 1;
            }
            else
            {
                borrow = 0;
            }
            res.d.push_back(sub);
        }
        res.trim();
        return res;
    }

    BigNum operator*(const BigNum &b) const
    {
        BigNum res;
        if ((d.size() == 1 && d[0] == 0) || (b.d.size() == 1 && b.d[0] == 0))
        {
            return BigNum(0);
        }
        res.d.assign(d.size() + b.d.size(), 0);
        for (int i = 0; i < d.size(); i++)
        {
            int carry = 0;
            for (int j = 0; j < b.d.size() || carry; j++)
            {
                long long cur = res.d[i + j] + d[i] * 1LL * (j < b.d.size() ? b.d[j] : 0) + carry;
                res.d[i + j] = cur % 10;
                carry = cur / 10;
            }
        }
        res.trim();
        return res;
    }
};

BigNum C[maxn][maxn];

void ini()
{
    for (int i = 0; i <= 200; i++)
    {
        C[i][0] = BigNum(1);
        for (int j = 1; j <= i; j++)
        {
            C[i][j] = C[i - 1][j - 1] + C[i - 1][j];
        }
    }
}

BigNum calc(int len, int val)
{
    if (val < 0)
    {
        return BigNum(0);
    }
    val = std::min(val, len);
    BigNum res(0);
    for (int i = 0; i <= val; i++)
    {
        res = res + C[len][i];
    }
    return res;
}

int n;
std::string k_str;

void solve()
{
    BigNum k(k_str);
    int total = (n - 1) / 2;

    if (calc(n, total) < k)
    {
        std::cout << -1 << "\n";
        return;
    }

    std::string ans = "";
    int cur_A = 0;

    for (int i = 1; i <= n; i++)
    {
        int len = n - i;
        int rem = total - (cur_A + 1);
        BigNum cnt = calc(len, rem);

        if (k <= cnt)
        {
            ans += 'A';
            cur_A++;
        }
        else
        {
            ans += 'B';
            k = k - cnt;
        }
    }

    std::cout << ans << "\n";
}

