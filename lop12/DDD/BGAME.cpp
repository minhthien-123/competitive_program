const int maxn = 12;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ii a[maxn + 5];
ll cost[1 << maxn];
ll dp[maxn + 5][1 << maxn]; // chi phi phan hoach cac diem trong mask thanh i mau

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].fi >> a[i].se;
    }

    int fm = (1 << n);

    for (int mask = 1; mask < fm; mask++)
    {
        vi xs, ys;
        for (int i = 1; i <= n; i++)
        {
            if ((mask >> (i - 1)) & 1)
            {
                xs.pb(a[i].fi);
                ys.pb(a[i].se);
            }
        }

        std::sort(all(xs));
        std::sort(all(ys));

        int med_x = xs[xs.size() / 2];
        int med_y = ys[ys.size() / 2];

        ll cur = 0;
        for (int x : xs)
        {
            cur += std::abs(x - med_x);
        }
        for (int y : ys)
        {
            cur += std::abs(y - med_y);
        }

        cost[mask] = cur;
    }

    for (int i = 0; i <= k; i++)
    {
        for (int mask = 0; mask < fm; mask++)
        {
            dp[i][mask] = INF;
        }
    }

    dp[0][0] = 0;

    for (int i = 1; i <= k; i++)
    {
        for (int mask = 0; mask < fm; mask++)
        {
            // khong dung them nhom
            dp[i][mask] = dp[i - 1][mask];

            for (int sub = mask; sub > 0; sub = (sub - 1) & mask)
            {
                if (dp[i - 1][mask ^ sub] != INF)
                {
                    dp[i][mask] = std::min(dp[i][mask], dp[i - 1][mask ^ sub] + cost[sub]);
                }
            }
        }
    }

    std::cout << dp[k][fm - 1];
}

