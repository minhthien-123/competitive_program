ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int h[maxn + 7];
char c[maxn + 7];
int e[maxn + 7], w[maxn + 7];
std::stack<int> st;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }

    for (int i = 1; i <= n; i++)
    {
        w[i] = st.size();
        while (!st.empty() && h[st.top()] < h[i])
        {
            st.pop();
        }
        st.push(i);
    }

    while (st.size())
    {
        st.pop();
    }

    for (int i = n; i >= 1; i--)
    {
        e[i] = st.size();
        while (st.size() && h[st.top()] < h[i])
        {
            st.pop();
        }
        st.push(i);
    }

    for (int i = 1; i <= n; i++)
    {
        if (c[i] == 'E')
        {
            std::cout << e[i];
        }
        else
        {
            std::cout << w[i];
        }
        std::cout << " ";
    }
}

