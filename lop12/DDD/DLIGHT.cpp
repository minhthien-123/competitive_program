ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll n, t;
int diff1[maxn + 7];
std::map<ll, int> diff2;

void sub3()
{
    for (int i = 1; i <= t; i++)
    {
        int u, v;
        std::cin >> u >> v;
        diff1[u]++;
        if (v + 1 <= n)
        {
            diff1[v + 1]--;
        }
    }

    int ans = 0;
    int cur = 0;
    for (int i = 1; i <= n; i++)
    {
        cur += diff1[i];
        if (cur % 3 == 0)
        {
            ans++;
        }
    }

    std::cout << ans;
}

void sub4()
{
    diff2[1] = 0;
    diff2[n + 1] = 0;
    
    for (int i = 1; i <= t; i++)
    {
        ll u, v;
        std::cin >> u >> v;
        diff2[u]++;
        if (v + 1 <= n + 1)
        {
            diff2[v + 1]--;
        }
    }

    ll ans = 0;
    ll opt = 0;
    auto it = diff2.begin();
    ll pre = it->fi;
    opt += it->se;
    it++;

    for (; it != diff2.end(); it++)
    {
        ll cur = it->fi;
        ll len = cur - pre;

        if (opt % 3 == 0)
        {
            ans += len;
        }

        opt += it->se;
        pre = cur;
    }

    std::cout << ans;
}

void solve()
{
    std::cin >> n >> t;

    if (n <= 1000000)
    {
        sub3();
    }
    else
    {
        sub4();
    }
}

