ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 7];
ll pre[maxn + 7], suf[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= 3 * n; i++)
    {
        std::cin >> a[i];
    }

    std::priority_queue<ll, std::vector<ll>, std::greater<ll>> min_heap;
    ll sum = 0;

    for (int i = 1; i <= 3 * n; i++)
    {
        min_heap.push(a[i]);
        sum += a[i];

        if (sz(min_heap) > n)
        {
            sum -= min_heap.top();
            min_heap.pop();
        }

        if (i >= n)
        {
            pre[i] = sum;
        }
    }

    std::priority_queue<ll> max_heap;
    sum = 0;

    for (int i = 3 * n; i >= 1; i--)
    {
        max_heap.push(a[i]);
        sum += a[i];

        if (sz(max_heap) > n)
        {
            sum -= max_heap.top();
            max_heap.pop();
        }

        if (i <= 2 * n + 1)
        {
            suf[i] = sum;
        }
    }

    ll ans = -INF;
    for (int i = n; i <= 2 * n; i++)
    {
        ans = std::max(ans, pre[i] - suf[i + 1]);
    }

    std::cout << ans;
}

