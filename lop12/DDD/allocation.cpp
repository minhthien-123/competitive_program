ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
vi adj[maxn];
int st[4 * maxn], lazy[4 * maxn];

void build(int id, int l, int r)
{
    lazy[id] = 0;
    if (l == r)
    {
        st[id] = -l;
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = std::max(st[id * 2], st[id * 2 + 1]);
}

void push(int id)
{
    if (lazy[id] != 0)
    {
        int t = lazy[id];
        st[id * 2] += t;
        lazy[id * 2] += t;
        st[id * 2 + 1] += t;
        lazy[id * 2 + 1] += t;
        lazy[id] = 0;
    }
}

void update(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] += val;
        lazy[id] += val;
        return;
    }
    push(id);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = std::max(st[id * 2], st[id * 2 + 1]);
}

int get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return -inf;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    push(id);
    int mid = (l + r) / 2;
    return std::max(get(id * 2, l, mid, u, v), get(id * 2 + 1, mid + 1, r, u, v));
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        int l, r;
        std::cin >> l >> r;
        adj[r].pb(l);
    }

    build(1, 0, m);

    int mx = std::max(0, n - m);

    for (int r = m; r >= 1; r--)
    {
        for (int l : adj[r])
        {
            update(1, 0, m, l, m, 1);
        }
        mx = std::max(mx, get(1, 0, m, 0, r - 1) + r - m - 1);
    }

    std::cout << n - mx;
}

