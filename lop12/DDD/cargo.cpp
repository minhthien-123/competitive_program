ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct pt
{
    ll c;
    int s;
} a[maxn + 7];

int n, m;
ll k[maxn + 7];
ll sumall[2 << 10];
ll f[2 << 10 + 7];

void solve()
{
    std::cin >> n >> m;
    
    for (int i = 0; i < n; i++)
    {
        std::cin >> k[i];
    }

    int full_mask = (1 << n) - 1;
    for (int mask = 0; mask <= full_mask; mask++)
    {
        f[mask] = 0;
        sumall[mask] = 0;
    }

    ll total = 0;
    for (int j = 1; j <= m; j++)
    {
        ll c;
        int s;
        std::cin >> c >> s;
        int mask = 0;
        for (int t = 0; t < s; t++)
        {
            int type;
            std::cin >> type;
            mask |= (1 << (type - 1));
        }
        f[mask] += c;
        total += c;
    }

    for (int i = 0; i < n; i++)
    {
        for (int mask = 0; mask <= full_mask; mask++)
        {
            if (mask & (1 << i))
            {
                f[mask] += f[mask ^ (1 << i)];
            }
        }
    }

    for (int mask = 1; mask <= full_mask; mask++)
    {
        int bit = __builtin_ctz(mask);
        sumall[mask] = sumall[mask ^ (1 << bit)] + k[bit];

        ll avail = total - f[full_mask ^ mask];
        if (avail < sumall[mask])
        {
            std::cout << "NO";
            return;
        }
    }

    std::cout << "YES";
}

