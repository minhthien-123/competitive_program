ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
std::string s;
std::vector<std::string> opt;
char ans[maxn + 7];
std::vector<int> history;

bool dfs(int u, char c)
{
    ans[u] = c;
    history.push_back(u);

    for (int v : adj[u])
    {
        if (ans[v] != ' ')
        {
            if (ans[v] == ans[u])
            {
                return false;
            }
        }
        else
        {
            if (opt[v][0] == ans[u])
            {
                if (!dfs(v, opt[v][1]))
                {
                    return false;
                }
            }
            else if (opt[v][1] == ans[u])
            {
                if (!dfs(v, opt[v][0]))
                {
                    return false;
                }
            }
        }
    }
    return true;
}

void reset()
{
    for (int u : history)
    {
        ans[u] = ' ';
    }
    history.clear();
}

void solve()
{
    std::cin >> n >> m;
    std::cin >> s;
    s = " " + s;

    memset(ans, ' ', sizeof ans);

    opt.resize(n + 7);
    for (int i = 1; i <= n; i++)
    {
        if (s[i] == 'R')
        {
            opt[i] = "GB";
        }
        else if (s[i] == 'G')
        {
            opt[i] = "RB";
        }
        else if (s[i] == 'B')
        {
            opt[i] = "RG";
        }
    }

    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    for (int i = 1; i <= n; i++)
    {
        if (ans[i] != ' ')
        {
            continue;
        }

        history.clear();
        if (!dfs(i, opt[i][0]))
        {
            reset();
            if (!dfs(i, opt[i][1]))
            {
                std::cout << "Impossible";
                return;
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        /*std::cout << i << " ";
        if (ans[i] == ' ')
        {
            std::cout << "#";
        }*/
        std::cout << ans[i];
    }
}

