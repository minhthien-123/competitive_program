const int maxn = 2e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, D, S;
int a[maxn + 7];
std::set<ii> s;
std::vector<ii> ans;

void solve()
{
    std::cin >> n >> D >> S;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        s.ins({a[i], i});
    }

    while (!s.empty())
    {
        ii p1 = *s.begin();
        ii pn = *s.rbegin();
        int a1 = p1.fi, idx1 = p1.se;
        int an = pn.fi, idxn = pn.se;

        if (a1 + an < S)
        {
            s.erase(p1);
            auto it = s.lower_bound({a1 + D, -INF});
            if (it != s.end() && it->fi == a1 + D)
            {
                ans.pb({idx1, it->se});
                s.erase(it);
            }
            else
            {
                std::cout << -1;
                return;
            }
        }
        else if (a1 + an > S)
        {
            s.erase(pn);
            auto it = s.lower_bound({an - D, -INF});
            if (it != s.end() && it->fi == an - D)
            {
                ans.pb({it->se, idxn});
                s.erase(it);
            }
            else
            {
                std::cout << -1;
                return;
            }
        }
        else // a1 + an == s
        {
            s.erase(p1);
            s.erase(pn);
            ans.pb({idx1, idxn});
        }
    }

    for (auto it : ans)
    {
        std::cout << it.fi << " " << it.se << "\n";
    }
}

