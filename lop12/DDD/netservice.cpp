ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, k;
int h[maxn + 7], t[maxn + 7], p[maxn + 8];
std::vector<ii> adj[maxn + 7];
int d[1007][maxn + 7];

void dijkstra(int idx, int src)
{
    for (int i = 1; i <= n; i++)
    {
        d[idx][i] = INF;
    }
    std::priority_queue<pll, std::vector<pll>, std::greater<pll>> pq;

    d[idx][src] = 0;
    pq.push({0, src});

    while (!pq.empty())
    {
        auto [du, u] = pq.top();
        pq.pop();

        if (du > d[idx][u])
        {
            continue;
        }

        for (auto edge : adj[u])
        {
            int v = edge.fi;
            ll w = edge.se;
            if (d[idx][u] + w < d[idx][v])
            {
                d[idx][v] = d[idx][u] + w;
                pq.push({d[idx][v], v});
            }
        }
    }
}

struct HopcroftKarp
{
    int n, m;
    std::vector<std::vector<int>> adj;
    std::vector<int> match_l, match_r, dist;

    HopcroftKarp(int n, int m) : n(n), m(m)
    {
        adj.resize(n + 7);
        match_l.assign(n + 7, 0);
        match_r.assign(m + 7, 0);
        dist.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
    }

    bool bfs()
    {
        std::queue<int> q;
        for (int i = 1; i <= n; i++)
        {
            if (!match_l[i])
            {
                dist[i] = 0;
                q.push(i);
            }
            else
            {
                dist[i] = INF;
            }
        }
        dist[0] = INF;
        while (!q.empty())
        {
            int u = q.front();
            q.pop();
            if (dist[u] < dist[0])
            {
                for (int v : adj[u])
                {
                    if (dist[match_r[v]] == INF)
                    {
                        dist[match_r[v]] = dist[u] + 1;
                        q.push(match_r[v]);
                    }
                }
            }
        }
        return dist[0] != INF;
    }

    bool dfs(int u)
    {
        if (u != 0)
        {
            for (int v : adj[u])
            {
                if (dist[match_r[v]] == dist[u] + 1)
                {
                    if (dfs(match_r[v]))
                    {
                        match_r[v] = u;
                        match_l[u] = v;
                        return true;
                    }
                }
            }
            dist[u] = INF;
            return false;
        }
        return true;
    }

    int max_matching()
    {
        int res = 0;
        while (bfs())
        {
            for (int i = 1; i <= n; i++)
            {
                if (!match_l[i] && dfs(i))
                {
                    res++;
                }
            }
        }
        return res;
    }
};

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 1; i <= k; i++)
    {
        std::cin >> h[i];
    }
    for (int i = 1; i <= k; i++)
    {
        std::cin >> t[i];
    }
    for (int i = 1; i <= k; i++)
    {
        std::cin >> p[i];
    }

    for (int i = 1; i <= m; i++)
    {
        int u, v, c;
        std::cin >> u >> v >> c;
        adj[u].pb({v, c});
    }

    for (int i = 1; i <= k; i++)
    {
        dijkstra(i, h[i]);
    }

    HopcroftKarp hk(k, k);

    for (int i = 1; i <= k; i++)
    {
        for (int j = 1; j <= k; j++)
        {
            if (i != j)
            {
                int dist = d[i][h[j]];
                if (dist != INF && t[i] + p[i] + dist <= t[j])
                {
                    hk.add_edge(i, j);
                }
            }
        }
    }

    std::cout << k - hk.max_matching();
}

