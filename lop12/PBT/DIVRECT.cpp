ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll k;
ll a[maxn + 7][maxn + 7];
ll sum[maxn + 7][maxn + 7];
int up[maxn + 7][maxn + 7];
int cnt[1000005];

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
            if (a[i][j] == -1)
            {
                up[i][j] = 0;
                sum[i][j] = sum[i - 1][j];
            }
            else
            {
                up[i][j] = up[i - 1][j] + 1;
                sum[i][j] = sum[i - 1][j] + a[i][j];
            }
        }
    }

    ll ans = 0;

    for (int u = 1; u <= n; u++)
    {
        for (int v = u; v <= n; v++)
        {
            int len = v - u + 1;

            int j = 1;
            while (j <= m)
            {
                if (up[v][j] < len)
                {
                    j++;
                    continue;
                }

                int l = j;
                while (j <= m && up[v][j] >= len)
                {
                    j++;
                }
                int r = j - 1;

                vi vec;
                ll cur = 0;
                cnt[0]++;
                vec.pb(0);

                for (int col = l; col <= r; col++)
                {
                    ll val = sum[v][col] - sum[u - 1][col];
                    cur = (cur + val) % k;

                    ans += cnt[cur];

                    cnt[cur]++;
                    vec.pb(cur);
                }

                for (int rem : vec)
                {
                    cnt[rem]--;
                }
            }
        }
    }

    std::cout << ans;
}

