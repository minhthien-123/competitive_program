ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
std::vector<std::pair<int, ll>> adj[maxn + 7];
ll max1[maxn + 7], max2[maxn + 7], dp[maxn + 7];
int par[maxn + 7];

void dfs1(int u, int p)
{
    max1[u] = 0;
    max2[u] = 0;
    par[u] = -1;

    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }

        dfs1(v, u);

        ll cur = max1[v] + w;

        if (cur > max1[u])
        {
            max2[u] = max1[u];
            max1[u] = cur;
            par[u] = v;
        }
        else if (cur > max2[u])
        {
            max2[u] = cur;
        }
    }
}

void dfs2(int u, int p)
{
    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }

        if (v == par[u])
        {
            dp[v] = w + std::max(dp[u], max2[u]);
        }
        else
        {
            dp[v] = w + std::max(dp[u], max1[u]);
        }

        dfs2(v, u);
    }
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        ll c;
        std::cin >> u >> v >> c;
        adj[u].pb({v, c});
        adj[v].pb({u, c});
    }

    dfs1(1, 1);

    dp[1] = 0;
    dfs2(1, 1);

    for (int i = 1; i <= n; i++)
    {
        std::cout << std::max(max1[i], dp[i]) << " ";
    }
}

