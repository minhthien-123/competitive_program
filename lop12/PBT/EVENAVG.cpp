ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll k;
ll a[maxn + 7];
ll pre[maxn + 7];
std::map<pll, vi> mp;

void solve()
{
    std::cin >> n >> k;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    pre[0] = 0;
    mp[{0, 0}].pb(0);

    for (int i = 1; i <= n; i++)
    {
        pre[i] = pre[i - 1] + (a[i] - k);
        mp[{pre[i], i % 2}].pb(i);
    }

    ll ways = 0;
    int maxlen = 0;

    for (auto pt : mp)
    {
        vi vec = pt.se;
        ll m = sz(vec);
        if (m >= 2)
        {
            ways += m * (m - 1) / 2;
            maxlen = std::max(maxlen, vec.back() - vec.front());
        }
    }

    std::cout << ways << " " << maxlen;
}

