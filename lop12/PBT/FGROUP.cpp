const int inf = 1e9;
const int mod = 1e9 + 7;

int n;
ll B;
std::map<ll, int> mp;

void solve()
{
    std::cin >> n >> B;
    mp[0] = 0;
    ll sum = 0;
    int ans = -1;

    for (int i = 1; i <= n; i++)
    {
        ll a;
        std::cin >> a;

        sum += a - B * i;

        if (mp.count(sum))
        {
            ans = std::max(ans, i - mp[sum]);
        }
        else
        {
            mp[sum] = i;
        }
    }

    std::cout << ans << "\n";
}

