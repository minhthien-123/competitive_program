const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;

int n, m;
std::vector<ii> adj[maxn + 7];
int color[maxn + 7];

bool bfs(int s)
{
    std::queue<int> q;
    q.push(s);
    color[s] = 0;

    while (!q.empty())
    {
        int u = q.front();
        q.pop();

        for (auto [v, w] : adj[u])
        {
            if (color[v] == -1)
            {
                color[v] = color[u] ^ w;
                q.push(v);
            }
            else if (color[v] != (color[u] ^ w))
            {
                return false;
            }
        }
    }
    return true;
}

void solve()
{
    std::cin >> n >> m;

    for (int i = 1; i <= m; i++)
    {
        color[i] = -1;
    }

    bool check = true;
    for (int i = 1; i <= n; i++)
    {
        int a, x, y;
        std::cin >> a >> x >> y;

        if (x == y)
        {
            if (a == 0)
                color[x] = 0;
            else
                color[x] = 1;
        }
        else
        {
            adj[x].pb({y, a});
            adj[y].pb({x, a});
        }
    }

    if (!check)
    {
        std::cout << -1;
        return;
    }

    for (int i = 1; i <= m; i++)
    {
        if (color[i] != -1)
        {
            if (!bfs(i))
            {
                std::cout << -1;
                return;
            }
        }
    }

    for (int i = 1; i <= m; i++)
    {
        if (color[i] == -1)
        {
            if (!bfs(i))
            {
                std::cout << -1;
                return;
            }
        }
    }

    std::vector<int> ans;
    for (int i = 1; i <= m; i++)
    {
        if (color[i] == 1)
        {
            ans.pb(i);
        }
    }

    std::cout << sz(ans) << "\n";
    for (int i = 0; i < sz(ans); i++)
    {
        std::cout << ans[i] << " ";
    }
    std::cout << "\n";
}

