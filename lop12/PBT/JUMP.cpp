const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 61;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];
int nxt[2 * maxn + 7];
int up[lg][2 * maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    std::stack<int> st;
    for (int i = n; i >= 1; i--)
    {
        while (!st.empty() && a[st.top()] < a[i])
        {
            st.pop();
        }
        if (!st.empty())
        {
            nxt[i] = st.top();
        }
        else
        {
            nxt[i] = i + n;
        }
        st.push(i);
    }

    while (!st.empty())
    {
        st.pop();
    }
    for (int i = 1; i <= n; i++)
    {
        while (!st.empty() && a[st.top()] > a[i])
        {
            st.pop();
        }
        if (!st.empty())
        {
            nxt[i + n] = st.top() + n;
        }
        else
        {
            nxt[i + n] = i;
        }
        st.push(i);
    }

    for (int i = 1; i <= 2 * n; i++)
    {
        up[0][i] = nxt[i];
    }
    for (int j = 1; j < lg; j++)
    {
        for (int i = 1; i <= 2 * n; i++)
        {
            up[j][i] = up[j - 1][up[j - 1][i]];
        }
    }

    while (m--)
    {
        int x;
        ll k;
        std::cin >> x >> k;
        int u = x;

        for (int j = 0; j < lg; j++)
        {
            if ((k >> j) & 1LL)
            {
                u = up[j][u];
            }
        }

        if (u > n)
        {
            u -= n;
        }
        std::cout << u << "\n";
    }
}

