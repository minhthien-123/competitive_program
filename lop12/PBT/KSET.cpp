ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y < 0)
    {
        return 0;
    }
    ll res = 1;
    ll base = (x % mod + mod) % mod;
    while (y > 0)
    {
        if (y & 1)
        {
            res = mul(res, base);
        }
        base = mul(base, base);
        y >>= 1;
    }
    return res;
}

int minprime[maxn + 7];
int cntPrime[maxn + 7];
std::vector<int> primes;

void sieve(int limit)
{
    for (int i = 2; i <= limit; i++)
    {
        if (minprime[i] == 0)
        {
            minprime[i] = i;
            primes.pb(i);
        }
        for (int p : primes)
        {
            if (p > minprime[i] || (ll)i * p > limit)
            {
                break;
            }
            minprime[i * p] = p;
        }
        cntPrime[i] = cntPrime[i - 1] + (minprime[i] == i);
    }
}

ll fact[maxn + 7], invFact[maxn + 7], invNum[maxn + 7];
ll a[maxn + 7];
int e[maxn + 7];

void init()
{
    fact[0] = invFact[0] = 1;
    for (int i = 1; i <= maxn; i++)
    {
        fact[i] = mul(fact[i - 1], i);
    }
    invFact[maxn] = power(fact[maxn], mod - 2);
    for (int i = maxn - 1; i >= 1; i--)
    {
        invFact[i] = mul(invFact[i + 1], i + 1);
    }

    invNum[1] = 1;
    for (int i = 2; i <= maxn; i++)
    {
        invNum[i] = mul(mod - mod / i, invNum[mod % i]);
    }

    ll cur = 1;
    a[1] = 1;
    for (int i = 2; i <= maxn; i++)
    {
        int temp = i;
        while (temp > 1)
        {
            int p = minprime[temp];
            int cnt = 0;
            while (temp % p == 0)
            {
                cnt++;
                temp /= p;
            }
            if (e[p] > 0)
            {
                cur = mul(cur, invNum[e[p]]);
            }
            e[p] += cnt;
            cur = mul(cur, e[p]);
        }
        a[i] = cur;
    }
}

ll calc(int m, int k)
{
    ll res = 0;
    for (int j = 0; j <= k; j++)
    {
        ll term = mul(power(j, m), mul(invFact[j], invFact[k - j]));
        if ((k - j) & 1)
        {
            res = sub(res, term);
        }
        else
        {
            res = add(res, term);
        }
    }
    return res;
}

ll n, k;

void solve()
{
    std::cin >> n >> k;

    int m = cntPrime[n];
    ll ways = a[n];

    ll part = 0;
    if (k == 2)
    {
        part = power(2, m - 1);
    }
    else
    {
        part = add(calc(m, k), calc(m, k - 1));
    }

    ll ans = mul(ways, part);
    std::cout << ans << "\n";
}

