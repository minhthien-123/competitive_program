ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 7];

struct KRT
{
    struct Edge
    {
        int u, v;
        long long w;
        bool operator<(const Edge &other) const
        {
            return w > other.w;
        }
    };

    int n, node_cnt, lg, timer;
    std::vector<Edge> edges;
    std::vector<long long> val;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> depth, tin, tout, dsu_par;
    std::vector<int> sz_leaf;

    KRT(int n) : n(n), node_cnt(n), timer(0)
    {
        lg = std::ceil(std::log2(2 * n + 5)) + 1;
        int max_nodes = 2 * n + 7;
        val.assign(max_nodes, 0);
        adj.resize(max_nodes);
        up.assign(max_nodes, std::vector<int>(lg + 1, 0));
        depth.assign(max_nodes, 0);
        tin.assign(max_nodes, 0);
        tout.assign(max_nodes, 0);
        sz_leaf.assign(max_nodes, 0);
        dsu_par.resize(max_nodes);
        std::iota(dsu_par.begin(), dsu_par.end(), 0);
    }

    void add_edge(int u, int v, long long w)
    {
        edges.push_back({u, v, w});
    }

    int acs(int v)
    {
        return v == dsu_par[v] ? v : dsu_par[v] = acs(dsu_par[v]);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        up[u][0] = p;
        sz_leaf[u] = (u <= n ? 1 : 0);
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
                sz_leaf[u] += sz_leaf[v];
            }
        }
        tout[u] = timer;
    }

    void build()
    {
        std::sort(edges.begin(), edges.end());
        for (const auto &e : edges)
        {
            int ru = acs(e.u);
            int rv = acs(e.v);
            if (ru != rv)
            {
                node_cnt++;
                val[node_cnt] = e.w;
                adj[node_cnt].push_back(ru);
                adj[node_cnt].push_back(rv);
                dsu_par[ru] = node_cnt;
                dsu_par[rv] = node_cnt;
            }
        }
        for (int i = node_cnt; i >= 1; i--)
        {
            if (dsu_par[i] == i && !tin[i])
            {
                dfs(i, 0);
            }
        }
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        for (int i = lg; i >= 0; i--)
        {
            if (depth[u] - (1 << i) >= depth[v])
            {
                u = up[u][i];
            }
        }
        if (u == v)
            return u;
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_highest_ancestor(int u, long long max_val)
    {
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != 0 && val[up[u][i]] <= max_val)
            {
                u = up[u][i];
            }
        }
        return u;
    }

    long long query_minimax(int u, int v)
    {
        if (acs(u) != acs(v))
            return -1;
        return val[get_lca(u, v)];
    }
};

struct LazySegTree
{
    int n;
    std::vector<long long> st, lazy;

    LazySegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, 0);
        lazy.assign(4 * n + 7, 0);
    }

    void push(int id, int l, int r)
    {
        if (lazy[id] != 0)
        {
            int mid = (l + r) / 2;
            st[2 * id] += lazy[id] * (mid - l + 1);
            lazy[2 * id] += lazy[id];
            st[2 * id + 1] += lazy[id] * (r - mid);
            lazy[2 * id + 1] += lazy[id];
            lazy[id] = 0;
        }
    }

    void update(int id, int l, int r, int u, int v, long long val)
    {
        if (v < l || r < u)
        {
            return;
        }
        if (u <= l && r <= v)
        {
            st[id] += val * (r - l + 1);
            lazy[id] += val;
            return;
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        update(2 * id, l, mid, u, v, val);
        update(2 * id + 1, mid + 1, r, u, v, val);
        st[id] = st[2 * id] + st[2 * id + 1];
    }

    long long get(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return 0;
        }
        if (u <= l && r <= v)
        {
            return st[id];
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        return get(2 * id, l, mid, u, v) + get(2 * id + 1, mid + 1, r, u, v);
    }
};

