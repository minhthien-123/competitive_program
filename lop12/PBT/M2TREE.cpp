void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int p;
        std::cin >> p;
        edges[i].u = i + 1;
        edges[i].v = p;
    }

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    KRT krt(n);
    for (int i = 1; i < n; i++)
    {
        ll w = std::min(a[edges[i].u], a[edges[i].v]);
        krt.add_edge(edges[i].u, edges[i].v, w);
    }

    krt.build();

    LazySegTree seg(krt.timer);

    for (int u = n + 1; u <= krt.node_cnt; u++)
    {
        int lc = krt.adj[u][0];
        int rc = krt.adj[u][1];
        seg.update(1, 1, krt.timer, krt.tin[lc], krt.tout[lc], 1LL * krt.sz_leaf[rc] * krt.val[u]);
        seg.update(1, 1, krt.timer, krt.tin[rc], krt.tout[rc], 1LL * krt.sz_leaf[lc] * krt.val[u]);
    }

    for (int i = 1; i <= n; i++)
    {
        ll ans = seg.get(1, 1, krt.timer, krt.tin[i], krt.tin[i]) + a[i];
        std::cout << ans << (i == n ? "" : " ");
    }
    std::cout << "\n";
}

