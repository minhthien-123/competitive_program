const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

int n;
ll a[maxn + 7];
ll pre[maxn + 7];
ll st[4 * maxn + 7];

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = pre[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = std::max(st[id * 2], st[id * 2 + 1]);
}

int query(int id, int l, int r, int u, int v, ll val)
{
    if (l > v || r < u || st[id] < val)
    {
        return -1;
    }
    if (l == r)
    {
        return l;
    }

    int mid = (l + r) / 2;

    int res = query(id * 2 + 1, mid + 1, r, u, v, val);
    if (res != -1)
    {
        return res;
    }

    return query(id * 2, l, mid, u, v, val);
}

void solve()
{
    std::cin >> n;
    pre[0] = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }

    std::vector<ll> vals;
    for (int i = 0; i <= n; i++)
    {
        vals.pb(pre[i]);
    }
    std::sort(all(vals));
    vals.erase(std::unique(all(vals)), vals.end());

    FenwickTree bit(sz(vals));
    ll ans = 0;

    for (int i = 0; i <= n; i++)
    {
        int rank = std::lower_bound(all(vals), pre[i]) - vals.begin() + 1;
        ans += bit.sum(rank);
        bit.add(rank, 1);
    }

    build(1, 0, n);

    std::vector<int> posL;
    ll mn = INF;
    for (int i = 0; i <= n; i++)
    {
        if (pre[i] < mn)
        {
            posL.pb(i);
            mn = pre[i];
        }
    }

    ll res = 0;
    for (int k = 0; k < sz(posL); k++)
    {
        int i = posL[k];
        int j = query(1, 0, n, i + 1, n, pre[i]);

        if (j != -1)
        {
            if (k == 0 || pre[j] < pre[posL[k - 1]])
            {
                res++;
            }
        }
    }

    std::cout << ans - res << "\n";
}

