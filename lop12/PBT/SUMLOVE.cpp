ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k, q;
ll dp[maxn + 7];
int queries[maxn + 8];
int mxk = 0;

void solve()
{
    std::cin >> n >> q;

    for (int i = 1; i <= q; i++)
    {
        std::cin >> queries[i];
        mxk = std::max(mxk, queries[i]);
    }

    dp[0] = 1;

    for (int i = 1; i <= std::min(n, mxk); i++)
    {
        for (int s = mxk; s >= 0; s--)
        {
            // không chọn i
            ll ways = dp[s];

            // 1 trong 2 người chọn i
            if (s >= i)
            {
                ways = add(ways, mul(2, dp[s - i]));
            }
            // cả 2 người cùng chọn i
            if (s >= 2 * i)
            {
                ways = add(ways, dp[s - 2 * i]);
            }

            dp[s] = ways;
        }
    }

    for (int i = 1; i <= q; i++)
    {
        k = queries[i];
        std::cout << dp[k] << "\n";
    }
}

