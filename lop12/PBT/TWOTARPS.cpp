ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct Tarp
{
    int r1, c1, r2, c2, cnt1;
    friend bool operator<(Tarp a, Tarp b)
    {
        return a.cnt1 < b.cnt1;
    }
};

int n, m, k;
Tarp a[maxk + 7];
int cover[maxn + 7][maxn + 7];
int pref1[maxn + 7][maxn + 7];
int pref2[maxn + 7][maxn + 7];

int getsum(int pref[maxn + 7][maxn + 7], int r1, int c1, int r2, int c2)
{
    if (r1 > r2 || c1 > c2)
    {
        return 0;
    }
    return pref[r2][c2] - pref[r1 - 1][c2] - pref[r2][c1 - 1] + pref[r1 - 1][c1 - 1];
}

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 1; i <= k; i++)
    {
        int r1, c1, r2, c2;
        std::cin >> r1 >> c1 >> r2 >> c2;
        a[i] = {r1, c1, r2, c2, 0};
        cover[r1][c1]++;
        cover[r1][c2 + 1]--;
        cover[r2 + 1][c1]--;
        cover[r2 + 1][c2 + 1]++;
    }

    int C = 0;
    for (int r = 1; r <= n; r++)
    {
        for (int c = 1; c <= m; c++)
        {
            cover[r][c] += cover[r - 1][c] + cover[r][c - 1] - cover[r - 1][c - 1];
            if (cover[r][c] > 0)
            {
                C++;
            }

            pref1[r][c] = pref1[r - 1][c] + pref1[r][c - 1] - pref1[r - 1][c - 1] + (cover[r][c] == 1);
            pref2[r][c] = pref2[r - 1][c] + pref2[r][c - 1] - pref2[r - 1][c - 1] + (cover[r][c] == 2);
        }
    }

    for (int i = 1; i <= k; i++)
    {
        a[i].cnt1 = getsum(pref1, a[i].r1, a[i].c1, a[i].r2, a[i].c2);
    }
    
    int mn = inf;
    for (int i = 1; i <= k; i++)
    {
        for (int j = i + 1; j <= k; j++)
        {
            int ir1 = std::max(a[i].r1, a[j].r1);
            int ic1 = std::max(a[i].c1, a[j].c1);
            int ir2 = std::min(a[i].r2, a[j].r2);
            int ic2 = std::min(a[i].c2, a[j].c2);

            int cnt2 = getsum(pref2, ir1, ic1, ir2, ic2);
            mn = std::min(mn, a[i].cnt1 + a[j].cnt1 + cnt2);
        }
    }

    std::cout << C - mn;
}

