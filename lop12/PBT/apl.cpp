ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll fact[maxn], invFact[maxn];

void prepare()
{
    fact[0] = 1;
    invFact[0] = 1;
    for (int i = 1; i < maxn; i++)
    {
        fact[i] = mul(fact[i - 1], i);
    }
    invFact[maxn - 1] = power(fact[maxn - 1], mod - 2);
    for (int i = maxn - 2; i >= 1; i--)
    {
        invFact[i] = mul(invFact[i + 1], i + 1);
    }
}

ll nCr(int n, int r)
{
    if (r < 0 || r > n)
    {
        return 0;
    }
    return mul(fact[n], mul(invFact[r], invFact[n - r]));
}

ll h1, h2, n;

void solve()
{
    std::cin >> h1 >> h2 >> n;

    ll ans = 0;
    ll diff = h2 - h1;

    for (int m = 0; m <= n; m++)
    {
        if ((m + diff) % 2 != 0)
        {
            continue;
        }
        ll u = (m + diff) / 2;
        if (u < 0 || u > m)
        {
            continue;
        }

        ll cnt = nCr(m, u);

        ll cnt_bad = 0;
        ll bad = m + h1 + h2 + 2;
        if (bad % 2 == 0)
        {
            ll u_bad = bad / 2;
            if (u_bad >= 0 && u_bad <= m)
            {
                cnt_bad = nCr(m, u_bad);
            }
        }

        ans = add(ans, mul(nCr(n, m), sub(cnt, cnt_bad)));
    }

    std::cout << ans;
}

