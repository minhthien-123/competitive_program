ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::string s;
int n = 0;
int L[maxn + 7], R[maxn + 7];
int edge[maxn + 7];

int build(int &pos)
{
    int u = ++n;
    pos++;
    if (s[pos] == ')')
    {
        pos++;
        L[u] = R[u] = 0;
        edge[u] = 0;
        return u;
    }

    L[u] = build(pos);
    R[u] = build(pos);
    pos++;
    edge[u] = edge[L[u]] + edge[R[u]] + 2;
    return u;
}

int count(int u, int d, bool is_root)
{
    if (!is_root && edge[u] % d == 0)
    {
        return 0;
    }
    if (L[u] == 0)
    {
        return 0;
    }
    return count(L[u], d, 0) + count(R[u], d, 0) + 2;
}

bool check(int u, int ru, int d)
{
    if ((L[u] == 0) != (L[ru] == 0))
    {
        return false;
    }
    if (edge[L[u]] % d != edge[L[ru]] % d)
    {
        return false;
    }
    if (edge[R[u]] % d != edge[R[ru]] % d)
    {
        return false;
    }

    if (edge[L[u]] % d != 0)
    {
        if (!check(L[u], L[ru], d))
        {
            return false;
        }
    }
    if (edge[R[u]] % d != 0)
    {
        if (!check(R[u], R[ru], d))
        {
            return false;
        }
    }

    return true;
}

bool check(int d)
{
    if (count(1, d, true) != d)
    {
        return false;
    }
    for (int i = 1; i <= n; i++)
    {
        if (edge[i] % d == 0 && edge[i])
        {
            if (!check(i, 1, d))
            {
                return false;
            }
        }
    }

    return true;
}

ll dp[maxn + 7];

void solve()
{
    std::cin >> s;
    int pos = 0;
    int root = build(pos);
    int m = edge[root];

    vi vec;
    for (int d = 2; d <= m; d += 2)
    {
        if (m % d == 0)
        {
            if (check(d))
            {
                vec.pb(d);
            }
        }
    }

    for (int i = 0; i <= sz(vec); i++)
    {
        dp[i] = INF;
    }

    dp[0] = 0;
    for (int i = 0; i < sz(vec); i++)
    {
        if (dp[i] == INF)
        {
            continue;
        }

        for (int j = i + 1; j < sz(vec); j++)
        {
            if (vec[j] % vec[i] == 0)
            {
                ll step = (vec[j] / vec[i]) - 1;
                dp[j] = std::min(dp[j], dp[i] + step);
            }
        }
    }

    std::cout << (dp[sz(vec) - 1] >= INF ? -1 : dp[sz(vec) - 1]);
}

