ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
std::vector<ii> adj[maxn + 7];
ii edges[maxn + 7];
int tin[maxn + 7], tout[maxn + 7], timer = 0;
int edge[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p)
    {
        tin[u] = ++timer;
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (auto [v, id] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                edge[id] = v;
                dfs(v, u);
            }
        }

        tout[u] = timer;
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb({v, i});
        adj[v].pb({u, i});
        edges[i] = {u, v};
    }

    LCA lca(n);
    lca.build(1);
    FenwickTree bit(n);

    while (m--)
    {
        int opt;
        std::cin >> opt;
        if (opt == 1)
        {
            int u, v;
            std::cin >> u >> v;
            bit.add(tin[u], 1);
            bit.add(tin[v], 1);
            bit.add(tin[lca.get_lca(u, v)], -2);
        }
        else
        {
            int i;
            std::cin >> i;
            int node = edge[i];
            std::cout << bit.sum(tin[node], tout[node]) << "\n";
        }
    }
}

