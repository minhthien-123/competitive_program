ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int p[maxn + 7];
std::vector<int> C;
std::deque<int> H;
std::string ans;

void addC()
{
    ans += 'C';
    int val = C.back();
    C.pop_back();
    H.pb(val);
}

void addH()
{
    if (sz(H) == 1 && !ans.empty() && ans.back() == 'C')
    {
        ans.pop_back();
        int val = H.front();
        H.pop_front();
        C.pb(val);
        return;
    }

    ans += 'H';
    int val = H.front();
    H.pop_front();
    C.pb(val);
}

void qsH(int l, int r, bool rev);

void quick_sort(int l, int r, bool rev = false)
{
    if (l >= r)
    {
        return;
    }

    int len = r - l + 1;

    bool is_sorted = true;
    for (int i = 0; i < len; i++)
    {
        int expected = (!rev ? (l + i) : (r - i));
        if (C[sz(C) - 1 - i] != expected)
        {
            is_sorted = false;
            break;
        }
    }
    if (is_sorted)
    {
        return;
    }

    bool is_rev = true;
    for (int i = 0; i < len; i++)
    {
        int expected = (!rev ? (r - i) : (l + i));
        if (C[sz(C) - 1 - i] != expected)
        {
            is_rev = false;
            break;
        }
    }
    if (is_rev)
    {
        for (int i = 0; i < len; i++)
        {
            addC();
        }
        for (int i = 0; i < len; i++)
        {
            addH();
        }
        return;
    }

    for (int i = 0; i < len; i++)
    {
        addC();
    }
    qsH(l, r, rev);
}

void qsH(int l, int r, bool rev = false)
{
    if (l >= r)
    {
        addH();
        return;
    }

    int len = r - l + 1;
    int mid = (l + r) / 2;
    int cnt1 = r - mid;     
    int cnt2 = mid - l + 1; 

    if (!rev)
    {
        for (int i = 0; i < len; i++)
        {
            if (H.front() <= mid)
            {
                addH();
            }
            else
            {
                addH();
                addC();
            }
        }

        qsH(mid + 1, r, true);

        for (int i = 0; i < cnt1; i++)
        {
            addC();
        }
        for (int i = 0; i < cnt2; i++)
        {
            addC();
        }
        for (int i = 0; i < cnt1; i++)
        {
            addH();
        }

        qsH(l, mid, false);
    }
    else
    {
        for (int i = 0; i < len; i++)
        {
            if (H.front() > mid)
            {
                addH();
            }
            else
            {
                addH();
                addC();
            }
        }

        qsH(l, mid, false);

        for (int i = 0; i < cnt2; i++)
        {
            addC();
        }
        for (int i = 0; i < cnt1; i++)
        {
            addC();
        }
        for (int i = 0; i < cnt2; i++)
        {
            addH();
        }

        qsH(mid + 1, r, true);
    }
}
void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> p[i];
    }

    for (int i = n; i >= 1; i--)
    {
        C.pb(p[i]);
    }

    quick_sort(1, n);

    std::cout << ans << "\n";
}

