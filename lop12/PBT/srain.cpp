const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, T;
ll a[maxn + 7], b[maxn + 7];

struct node
{
    ll sum;
    ll mn;
    int cnt;
    ll lz;
};

node st[4 * maxn + 7];

node merge(node l, node r)
{
    return {l.sum + r.sum, std::min(l.mn, r.mn), l.cnt + r.cnt, 0};
}

void apply(int id, ll val)
{
    if (st[id].cnt == 0)
    {
        return;
    }
    st[id].sum += val * st[id].cnt;
    st[id].mn -= val;
    st[id].lz += val;
}

void down(int id)
{
    if (st[id].lz != 0)
    {
        apply(id * 2, st[id].lz);
        apply(id * 2 + 1, st[id].lz);
        st[id].lz = 0;
    }
}

void build(int id, int l, int r)
{
    st[id].lz = 0;
    if (l == r)
    {
        st[id].sum = a[l];
        if (a[l] < b[l])
        {
            st[id].cnt = 1;
            st[id].mn = b[l] - a[l];
        }
        else
        {
            st[id].cnt = 0;
            st[id].mn = INF;
        }
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void update(int id, int l, int r, int u, int v, ll val)
{
    if (v < l || r < u || st[id].cnt == 0)
    {
        return;
    }

    if (u <= l && r <= v && val < st[id].mn)
    {
        apply(id, val);
        return;
    }

    if (l == r)
    {
        st[id].sum = std::min(b[l], st[id].sum + val);
        if (st[id].sum == b[l])
        {
            st[id].cnt = 0;
            st[id].mn = INF;
        }
        else
        {
            st[id].mn = b[l] - st[id].sum;
        }
        return;
    }
    down(id);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

ll query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id].sum;
    }
    down(id);
    int mid = (l + r) / 2;
    return query(id * 2, l, mid, u, v) + query(id * 2 + 1, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i] >> b[i];
    }

    build(1, 1, n);

    std::cin >> T;
    while (T--)
    {
        int type;
        std::cin >> type;
        if (type == 0)
        {
            int l, r;
            ll d;
            std::cin >> l >> r >> d;
            update(1, 1, n, l, r, d);
        }
        else
        {
            int l, r;
            std::cin >> l >> r;
            std::cout << query(1, 1, n, l, r) << "\n";
        }
    }
}

