ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int m, n, K;
int dp[maxn + 7];

struct pt
{
    int id, sum;
    std::vector<int> pre;
};

void solve()
{
    std::cin >> n >> m >> K;
    std::vector<std::vector<int>> a(n + 1, std::vector<int>(m + 1)), pre(n + 1, std::vector<int>(m + 1));
    std::vector<int> dec;
    dec.pb(0);
    std::vector<pt> inc;
    inc.pb({0, 0, {0}});

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
        }
        if (m == 1 || a[i][1] >= a[i][m])
        {
            for (int j = 1; j <= m; j++)
            {
                dec.pb(a[i][j]);
            }
        }
        else
        {
            pt tmp;
            tmp.id = i;
            tmp.sum = 0;
            tmp.pre.assign(m + 1, 0);
            for (int j = 1; j <= m; j++)
            {
                tmp.pre[j] = tmp.pre[j - 1] + a[i][j];
                tmp.sum += a[i][j];
            }
            inc.pb(tmp);
        }
    }

    std::sort(dec.begin() + 1, dec.end(), std::greater<int>());
    int dec_sz = sz(dec) - 1;

    std::vector<int> pre_dec(dec_sz + 1, 0);
    for (int i = 1; i <= dec_sz; i++)
    {
        pre_dec[i] = pre_dec[i - 1] + dec[i];
    }

    std::vector<std::vector<int>> all_inc(m);
    std::vector<std::vector<int>> pre_inc(m);

    int inc_sz = sz(inc) - 1;

    for (int rem = 0; rem < m; rem++)
    {
        all_inc[rem].pb(0);

        for (int i = 1; i <= inc_sz; i++)
        {
            all_inc[rem].pb(inc[i].sum);
        }

        for (int j = 1; rem + j * m <= dec_sz; j++)
        {
            int chunk_sum = pre_dec[rem + j * m] - pre_dec[rem + (j - 1) * m];
            all_inc[rem].pb(chunk_sum);
        }

        std::sort(all_inc[rem].begin() + 1, all_inc[rem].end(), std::greater<int>());

        int num = sz(all_inc[rem]) - 1;
        pre_inc[rem].assign(num + 1, 0);

        for (int i = 1; i <= num; i++)
        {
            pre_inc[rem][i] = pre_inc[rem][i - 1] + all_inc[rem][i];
        }
    }

    int ans = 0;

    int rem0 = K % m;
    if (rem0 <= dec_sz)
    {
        int Y = K / m;
        int num = sz(all_inc[rem0]) - 1;
        if (Y <= num)
        {
            ans = std::max(ans, pre_dec[rem0] + pre_inc[rem0][Y]);
        }
    }

    for (int i = 1; i <= inc_sz; i++)
    {
        for (int p = 1; p < m; p++)
        {
            int C = K - p;
            if (C < 0)
            {
                continue;
            }

            int rem = C % m;
            if (rem > dec_sz)
            {
                continue;
            }

            int Y = C / m;
            int num = sz(all_inc[rem]) - 1;

            if (Y > num - 1)
            {
                continue;
            }

            int pos = std::lower_bound(all_inc[rem].begin() + 1, all_inc[rem].end(), inc[i].sum, std::greater<int>()) - all_inc[rem].begin();

            int sum = 0;
            if (pos <= Y)
            {
                sum = pre_inc[rem][Y + 1] - inc[i].sum;
            }
            else
            {
                sum = pre_inc[rem][Y];
            }

            int tmp = inc[i].pre[p] + pre_dec[rem] + sum;
            ans = std::max(ans, tmp);
        }
    }

    std::cout << ans << "\n";
}

