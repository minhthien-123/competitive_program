ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k, t;
int cnt[maxn + 7];

struct pt
{
    int t;
    vi alarm;
};

void solve()
{
    std::cin >> n >> k >> t;

    std::vector<ii> vec;

    vec.pb({0, 0});
    vec.pb({t, 0});

    for (int i = 1; i <= n; i++)
    {
        int m;
        std::cin >> m;
        for (int j = 1; j <= m; j++)
        {
            int t;
            std::cin >> t;
            vec.pb({t, i});
        }
    }

    std::sort(all(vec));

    std::vector<pt> a;
    for (auto e : vec)
    {
        if (a.empty() || a.back().t != e.fi)
        {
            a.pb({e.fi, vi()});
        }

        if (e.se != 0)
        {
            a.back().alarm.pb(e.se);
        }
    }

    int target = n - k;
    int ans = 0;

    for (int i = 0; i < sz(a) - 1; i++)
    {
        ans = std::max(ans, a[i + 1].t - a[i].t);
    }

    int dem = 0;  
    int L = 1;      

    for (int R = 1; R < sz(a) - 1; R++)
    {
        for (int u : a[R].alarm)
        {
            if (cnt[u] == 0)
            {
                dem++;
            }
            cnt[u]++;
        }

        while (dem > target && L <= R)
        {
            for (int u : a[L].alarm)
            {
                cnt[u]--;
                if (cnt[u] == 0)
                {
                    dem--;
                }
            }
            L++;
        }

        if (dem <= target)
        {
            ans = std::max(ans, a[R + 1].t - a[L - 1].t);
        }
    }

    std::cout << ans;
}

