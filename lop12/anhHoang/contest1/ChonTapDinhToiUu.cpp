const int maxn = 2e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
std::vector<std::pair<int, ll>> adj[maxn + 7];
int flag[maxn + 7], cnt[maxn + 7];
int S[maxn + 7];
ll cost[maxn + 7];

void dfs1(int u, int p, ll d)
{
    cnt[u] = flag[u];
    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }

        dfs1(v, u, d + w);
        cnt[u] += cnt[v];
    }
    cost[1] += flag[u] * d;
}

void dfs2(int u, int p, int k)
{
    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }

        cost[v] = cost[u] - w * cnt[v] + w * (k - cnt[v]);
        dfs2(v, u, k);
    }
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        ll c;
        std::cin >> u >> v >> c;
        adj[u].pb({v, c});
        adj[v].pb({u, c});
    }

    for (int i = 1; i <= q; i++)
    {
        int k;
        std::cin >> k;
        for (int j = 1; j <= k; j++)
        {
            std::cin >> S[j];
            flag[S[j]] = 1;
        }

        cost[1] = 0;
        dfs1(1, 1, 0);
        dfs2(1, 1, k);

        std::vector<ll> cur;
        for (int j = 1; j <= n; j++)
        {
            cur.pb(cost[j]);
        }
        std::sort(all(cur));

        ll ans = 0;
        for (int j = 0; j < k; j++)
        {
            ans += cur[j];
        }
        std::cout << ans << "\n";

        for (int j = 1; j <= k; j++)
        {
            flag[S[j]] = 0;
        }
    }
}

