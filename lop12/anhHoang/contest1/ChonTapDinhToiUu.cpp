ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, Q;
std::vector<std::pair<int, ll>> adj[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth;
    std::vector<ll> dist;
    std::vector<int> tin, tout;
    int timer = 0;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
        dist.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
    }

    void dfs(int u, int p, ll d)
    {
        tin[u] = ++timer;
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        depth[u] = depth[p] + 1;
        dist[u] = d;

        for (auto [v, w] : adj[u])
        {
            if (v != p)
            {
                dfs(v, u, d + w);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root, 0);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    ll get_dist(int u, int v)
    {
        return dist[u] + dist[v] - 2 * dist[get_lca(u, v)];
    }
};

LCA lca(0);

struct VirtualTree
{
    int n;
    std::vector<std::vector<int>> v_adj;
    std::vector<int> nodes;

    VirtualTree(int n)
    {
        this->n = n;
        v_adj.resize(n + 7);
    }

    int build(std::vector<int> S)
    {
        if (S.empty())
        {
            return -1;
        }
        auto cmp = [&](int u, int v)
        {
            return lca.tin[u] < lca.tin[v];
        };
        std::sort(S.begin(), S.end(), cmp);

        int k = S.size();
        for (int i = 0; i < k - 1; i++)
        {
            S.push_back(lca.get_lca(S[i], S[i + 1]));
        }

        std::sort(S.begin(), S.end(), cmp);
        S.erase(std::unique(S.begin(), S.end()), S.end());

        for (int u : S)
        {
            v_adj[u].clear();
        }

        std::stack<int> st;
        st.push(S[0]);
        for (int i = 1; i < (int)S.size(); i++)
        {
            int u = S[i];
            while (!st.empty())
            {
                int p = st.top();
                if (lca.tin[p] <= lca.tin[u] && lca.tout[u] <= lca.tout[p])
                {
                    break;
                }
                st.pop();
            }
            if (!st.empty())
            {
                v_adj[st.top()].push_back(u);
            }
            st.push(u);
        }
        nodes = S;
        return S[0];
    }
};

VirtualTree vt(0);

int vis[maxn + 7];
bool flag[maxn + 7];
int cnt[maxn + 8];
int S[maxn + 7];
int tinS[maxn + 7];

void dfs(int u)
{
    cnt[u] = flag[u];
    for (int v : vt.v_adj[u])
    {
        dfs(v);
        cnt[u] += cnt[v];
    }
}

void solve()
{
    std::cin >> n >> Q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        ll c;
        std::cin >> u >> v >> c;
        adj[u].pb({v, c});
        adj[v].pb({u, c});
    }

    lca = LCA(n);
    lca.build(1);
    vt = VirtualTree(n);

    for (int q = 1; q <= Q; q++)
    {
        int k;
        std::cin >> k;
        std::vector<int> S;
        for (int i = 1; i <= k; i++)
        {
            int s;
            std::cin >> s;
            S.pb(s);
            flag[s] = true;
            tinS[i] = lca.tin[s];
        }

        std::sort(tinS + 1, tinS + k + 1);

        int vroot = vt.build(S);

        dfs(vroot);

        int centroid = vroot;
        int cur = vroot;
        while (true)
        {
            int nxt = -1;
            for (int v : vt.v_adj[cur])
            {
                if (cnt[v] > k / 2)
                {
                    nxt = v;
                    break;
                }
            }
            if (nxt == -1)
            {
                centroid = cur;
                break;
            }
            cur = nxt;
        }

        ll cost = 0;
        for (int u : S)
        {
            cost += lca.get_dist(centroid, u);
        }

        std::priority_queue<pll, std::vector<pll>, std::greater<pll>> pq;
        pq.push({cost, centroid});

        ll ans = 0;
        int taken = 0;

        while (!pq.empty() && taken < k)
        {
            auto [c, u] = pq.top();
            pq.pop();

            if (vis[u] == q)
            {
                continue;
            }
            vis[u] = q;

            ans += c;
            taken++;

            if (taken == k)
            {
                break;
            }

            for (auto [v, w] : adj[u])
            {
                if (vis[v] == q)
                {
                    continue;
                }

                int cntv = 0;
                if (lca.depth[v] > lca.depth[u])
                {
                    cntv = std::upper_bound(tinS + 1, tinS + k + 1, lca.tout[v]) - std::lower_bound(tinS + 1, tinS + k + 1, lca.tin[v]);
                }
                else
                {
                    int cntu = std::upper_bound(tinS + 1, tinS + k + 1, lca.tout[u]) - std::lower_bound(tinS + 1, tinS + k + 1, lca.tin[u]);
                    cntv = k - cntu;
                }

                ll cost_v = c + w * (k - 2LL * cntv);
                pq.push({cost_v, v});
            }
        }

        std::cout << ans << "\n";

        for (int u : S)
        {
            flag[u] = false;
        }
    }
}

