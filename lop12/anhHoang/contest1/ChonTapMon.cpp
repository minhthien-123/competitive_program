ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[105][2005];
int sum[105];
int dp[105][205];

void solve()
{

    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        sum[i] = 0;
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
            sum[i] = add(sum[i], a[i][j]);
        }
    }

    int ans = 1;
    for (int i = 1; i <= n; i++)
    {
        ans = mul(ans, add(sum[i], 1));
    }
    ans = sub(ans, 1);

    int res = 0;

    for (int j = 1; j <= m; j++)
    {
        for (int i = 0; i <= n; i++)
        {
            for (int diff = 0; diff <= 2 * n + 2; diff++)
            {
                dp[i][diff] = 0;
            }
        }

        dp[0][n + 1] = 1;

        for (int i = 1; i <= n; i++)
        {
            int sum1 = sub(sum[i], a[i][j]);
            for (int diff = 1; diff <= 2 * n + 1; diff++)
            {
                if (dp[i - 1][diff] == 0)
                {
                    continue;
                }

                dp[i][diff] = add(dp[i][diff], dp[i - 1][diff]);
                dp[i][diff + 1] = add(dp[i][diff + 1], mul(dp[i - 1][diff], a[i][j]));
                dp[i][diff - 1] = add(dp[i][diff - 1], mul(dp[i - 1][diff], sum1));
            }
        }

        for (int diff = n + 2; diff <= 2 * n + 1; diff++)
        {
            res = add(res, dp[n][diff]);
        }
    }

    ans = sub(ans, res);
    std::cout << ans;
}

