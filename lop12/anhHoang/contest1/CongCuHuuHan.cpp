const int maxn = 5e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, k;
ll x;
pll a[maxn + 7], s[maxn + 7];
ll min_cost[maxn + 7];
ll dp[maxn + 7];
ll pre[maxn + 7];

struct node
{
    ll mx, dp_max, dp_min, lz, max_val;
} st[4 * maxn + 7];

void del_node(int id)
{
    st[id].mx = -INF;
    st[id].dp_max = -INF;
    st[id].dp_min = INF;
    st[id].max_val = -INF;
    st[id].lz = -1;
}

void apply(int id, ll cost)
{
    if (st[id].dp_max == -INF)
    {
        return;
    }
    st[id].lz = cost;
    st[id].max_val = st[id].mx - cost;
}

node merge(node l, node r)
{
    node res;
    res.mx = std::max(l.mx, r.mx);
    res.dp_max = std::max(l.dp_max, r.dp_max);
    res.dp_min = std::min(l.dp_min, r.dp_min);
    res.max_val = std::max(l.max_val, r.max_val);
    res.lz = -1;
    return res;
}

void down(int id)
{
    if (st[id].lz != -1)
    {
        apply(id * 2, st[id].lz);
        apply(id * 2 + 1, st[id].lz);
        st[id].lz = -1;
    }
}

void build(int id, int l, int r)
{
    del_node(id);
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
}

void add_node(int id, int l, int r, int pos, ll dp_val, ll val)
{
    if (l == r)
    {
        st[id].mx = val;
        st[id].dp_max = dp_val;
        st[id].dp_min = dp_val;
        st[id].lz = -1;
        st[id].max_val = val;
        return;
    }
    down(id);
    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        add_node(id * 2, l, mid, pos, dp_val, val);
    }
    else
    {
        add_node(id * 2 + 1, mid + 1, r, pos, dp_val, val);
    }
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void update(int id, int l, int r, int u, int v, ll cost)
{
    if (v < l || r < u || st[id].dp_max == -INF)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        if (cost <= st[id].dp_min)
        {
            apply(id, cost);
            return;
        }
        if (cost > st[id].dp_max)
        {
            del_node(id);
            return;
        }
    }
    down(id);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v, cost);
    update(id * 2 + 1, mid + 1, r, u, v, cost);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

ll query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u || st[id].dp_max == -INF)
    {
        return -INF;
    }
    if (u <= l && r <= v)
    {
        return st[id].max_val;
    }
    down(id);
    int mid = (l + r) / 2;
    ll get1 = query(id * 2, l, mid, u, v);
    ll get2 = query(id * 2 + 1, mid + 1, r, u, v);
    return std::max(get1, get2);
}

void solve()
{
    std::cin >> n >> m >> k >> x;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].fi >> a[i].se;
        pre[i] = pre[i - 1] + a[i].se;
    }
    for (int i = 1; i <= m; i++)
    {
        std::cin >> s[i].fi >> s[i].se;
    }
    std::sort(s + 1, s + m + 1);

    min_cost[m + 1] = INF;
    for (int j = m; j >= 1; j--)
    {
        min_cost[j] = std::min(min_cost[j + 1], s[j].se);
    }

    build(1, 1, n);
    dp[0] = x;
    vi st;

    for (int i = 1; i <= n; i++)
    {
        if (dp[i - 1] != -1)
        {
            add_node(1, 0, n, i - 1, dp[i - 1], dp[i - 1] - pre[i - 1]);
        }

        while (!st.empty() && a[st.back()].fi <= a[i].fi)
        {
            st.pop_back();
        }

        int L = st.empty() ? 0 : st.back();

        int pos = m + 1;
        int l = 1, r = m;
        while (l <= r)
        {
            int mid = (l + r) / 2;
            if (s[mid].fi >= a[i].fi)
            {
                pos = mid;
                r = mid - 1;
            }
            else
            {
                l = mid + 1;
            }
        }

        ll cost_i = min_cost[pos];

        update(1, 0, n, L, i - 1, cost_i);
        st.push_back(i);

        ll best = query(1, 0, n, std::max(0, i - k), i - 1);

        if (best == -INF)
        {
            dp[i] = -1;
        }
        else
        {
            dp[i] = best + pre[i];
        }
    }

    if (dp[n] != -1)
    {
        std::cout << "Yes\n";
    }
    else
    {
        std::cout << "No\n";
    }
}

