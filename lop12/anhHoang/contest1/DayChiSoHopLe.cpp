const int maxn = 2e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int bl = 450;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int d[maxn + 7], v[maxn + 7];
int dp[maxn + 8];
int sum[bl + 7][bl + 7];
int sum_all[bl + 7][bl + 7];
int sumd[bl + 7][bl + 7];
std::vector<ii> S[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> d[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> v[i];
    }

    int ans = 0;
    for (int i = 1; i <= n; i++)
    {
        int s = 0;

        if (d[i] <= bl)
        {
            for (int x = 1; x <= d[i]; x++)
            {
                s = add(s, sumd[x][i % x]);
            }
            s = add(s, sum_all[d[i]][i % d[i]]);
            s = sub(s, sum[d[i]][i % d[i]]);
        }
        else
        {
            for (int x = 1; x <= bl; x++)
            {
                s = add(s, sumd[x][i % x]);
            }

            for (auto p : S[i])
            {
                if (p.fi <= d[i])
                {
                    s = add(s, p.se);
                }
            }

            for (int j = i - d[i]; j >= 1; j -= d[i])
            {
                if (d[j] > d[i])
                {
                    s = add(s, dp[j]);
                }
            }
        }

        dp[i] = mul(v[i], add(1, s));
        ans = add(ans, dp[i]);

        for (int x = 1; x <= bl; x++)
        {
            sum_all[x][i % x] = add(sum_all[x][i % x], dp[i]);
        }

        if (d[i] <= bl)
        {
            sumd[d[i]][i % d[i]] = add(sumd[d[i]][i % d[i]], dp[i]);
            for (int x = d[i]; x <= bl; x++)
            {
                sum[x][i % x] = add(sum[x][i % x], dp[i]);
            }
        }
        else
        {
            if (i + d[i] <= n)
            {
                S[i + d[i]].pb({d[i], dp[i]});
            }
        }

        for (auto p : S[i])
        {
            if (i + p.fi <= n)
            {
                S[i + p.fi].pb(p);
            }
        }
    }

    std::cout << ans;
}

