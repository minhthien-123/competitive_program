ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}

int n, m;

struct Combinatorics
{
    int n;
    long long MOD;
    std::vector<long long> fact, inv_fact, inverse;

    Combinatorics(int n, long long MOD) : n(n), MOD(MOD)
    {
        fact.assign(n + 1, 1);
        inv_fact.assign(n + 1, 1);
        inverse.assign(n + 1, 1);

        for (int i = 2; i <= n; i++)
        {
            inverse[i] = MOD - (MOD / i) * inverse[MOD % i] % MOD;
        }

        for (int i = 2; i <= n; i++)
        {
            fact[i] = (fact[i - 1] * i) % MOD;
            inv_fact[i] = (inv_fact[i - 1] * inverse[i]) % MOD;
        }
    }

    long long nCr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[r] % MOD * inv_fact[n - r] % MOD;
    }

    long long nPr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[n - r] % MOD;
    }
};

void solve()
{
    std::cin >> n >> m;
    Combinatorics comb(n + 1, mod);

    int S = 0;
    int C = 1;

    for (int k = 0; k <= n - 1; k++)
    {
        int term = mul(C, comb.inverse[n - k + 1]);
        S = add(S, term);

        int num = (m - n + k + 1) % mod;
        int den = comb.inverse[k + 1];
        C = mul(C, mul(num, den));
    }

    S = mul(S, comb.fact[n + 1]);
    std::cout << S << "\n";
}

