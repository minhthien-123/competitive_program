ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int f[maxn + 7];
ll w[maxn + 7];
vi adj[maxn + 7];
std::vector<ll> dp[maxn + 7];
ll ans[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        adj[i].clear();
        dp[i].clear();
        ans[i] = 0;
    }
    f[1] = 0;
    for (int i = 2; i <= n; i++)
    {
        std::cin >> f[i];
        adj[f[i]].pb(i);
    }
    w[1] = 0;
    for (int i = 2; i <= n; i++)
    {
        std::cin >> w[i];
    }

    for (int u = n; u >= 1; u--)
    {
        int max_h = 0;
        for (int v : adj[u])
        {
            max_h = std::max(max_h, sz(dp[v]));
        }

        dp[u].assign(max_h + 1, 0);

        dp[u][0] = w[u];

        for (int v : adj[u])
        {
            for (int k = 0; k < sz(dp[v]); k++)
            {
                dp[u][k + 1] += dp[v][k];
            }
        }

        ll total = 0;
        for (int k = 1; k <= max_h; k++)
        {
            total += dp[u][k];
        }
        ans[u] = total;

        if (u > 1)
        {
            for (int k = 1; k <= max_h; k++)
            {
                dp[u][k] = std::min(dp[u][k], w[u]);
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << " ";
    }
    std::cout << "\n";
}

