ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct SegTreeBeats
{
    struct Node
    {
        ll sum, max1, max2, lazy_min;
        int cnt_max;
    };
    int n;
    std::vector<Node> st;

    void init(int _n)
    {
        n = _n;
        st.assign(4 * n + 5, {0, 0, -INF, INF, 1});
        build(1, 1, n);
    }

    void build(int id, int l, int r)
    {
        st[id] = {0, 0, -INF, INF, r - l + 1};
        if (l == r)
            return;
        int mid = (l + r) >> 1;
        build(id << 1, l, mid);
        build(id << 1 | 1, mid + 1, r);
    }

    inline void pull(int id)
    {
        int lc = id << 1, rc = id << 1 | 1;
        st[id].sum = st[lc].sum + st[rc].sum;
        if (st[lc].max1 == st[rc].max1)
        {
            st[id].max1 = st[lc].max1;
            st[id].cnt_max = st[lc].cnt_max + st[rc].cnt_max;
            st[id].max2 = std::max(st[lc].max2, st[rc].max2);
        }
        else if (st[lc].max1 > st[rc].max1)
        {
            st[id].max1 = st[lc].max1;
            st[id].cnt_max = st[lc].cnt_max;
            st[id].max2 = std::max(st[lc].max2, st[rc].max1);
        }
        else
        {
            st[id].max1 = st[rc].max1;
            st[id].cnt_max = st[rc].cnt_max;
            st[id].max2 = std::max(st[lc].max1, st[rc].max2);
        }
    }

    inline void apply_chmin(int id, ll val)
    {
        if (st[id].max1 <= val)
            return;
        st[id].sum -= (st[id].max1 - val) * st[id].cnt_max;
        st[id].max1 = val;
        st[id].lazy_min = std::min(st[id].lazy_min, val);
    }

    inline void push(int id)
    {
        if (st[id].lazy_min != INF)
        {
            apply_chmin(id << 1, st[id].lazy_min);
            apply_chmin(id << 1 | 1, st[id].lazy_min);
            st[id].lazy_min = INF;
        }
    }

    void point_add(int id, int l, int r, int pos, ll val)
    {
        if (l == r)
        {
            st[id].sum += val;
            st[id].max1 = st[id].sum;
            st[id].max2 = -INF;
            st[id].cnt_max = 1;
            st[id].lazy_min = INF;
            return;
        }
        push(id);
        int mid = (l + r) >> 1;
        if (pos <= mid)
            point_add(id << 1, l, mid, pos, val);
        else
            point_add(id << 1 | 1, mid + 1, r, pos, val);
        pull(id);
    }

    void range_chmin(int id, int l, int r, int u, int v, ll val)
    {
        if (v < l || r < u || st[id].max1 <= val)
            return;
        if (u <= l && r <= v && st[id].max2 < val)
        {
            apply_chmin(id, val);
            return;
        }
        push(id);
        int mid = (l + r) >> 1;
        range_chmin(id << 1, l, mid, u, v, val);
        range_chmin(id << 1 | 1, mid + 1, r, u, v, val);
        pull(id);
    }

    void extract_and_clear(int id, int l, int r, int u, int v, std::vector<ll> &out)
    {
        if (v < l || r < u || st[id].max1 == 0)
            return;
        if (l == r)
        {
            out[l - u] = st[id].sum;
            st[id] = {0, 0, -INF, INF, 1};
            return;
        }
        push(id);
        int mid = (l + r) >> 1;
        extract_and_clear(id << 1, l, mid, u, v, out);
        extract_and_clear(id << 1 | 1, mid + 1, r, u, v, out);
        pull(id);
    }

    ll query_sum(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
            return 0;
        if (u <= l && r <= v)
            return st[id].sum;
        push(id);
        int mid = (l + r) >> 1;
        return query_sum(id << 1, l, mid, u, v) + query_sum(id << 1 | 1, mid + 1, r, u, v);
    }
} seg;

int n;
vi f, len, heavy, dfn;
std::vector<ll> w, ans;
vi head_adj, to_adj, nxt_adj;
int edge_cnt;

void add_edge(int u, int v)
{
    to_adj[++edge_cnt] = v;
    nxt_adj[edge_cnt] = head_adj[u];
    head_adj[u] = edge_cnt;
}

void solve()
{
    std::cin >> n;
    f.assign(n + 1, 0);
    w.assign(n + 1, 0);
    len.assign(n + 1, 1);
    heavy.assign(n + 1, 0);
    dfn.assign(n + 1, 0);
    ans.assign(n + 1, 0);

    head_adj.assign(n + 1, 0);
    to_adj.assign(n + 1, 0);
    nxt_adj.assign(n + 1, 0);
    edge_cnt = 0;

    for (int i = 2; i <= n; i++)
        std::cin >> f[i];
    for (int i = 2; i <= n; i++)
        std::cin >> w[i];

    for (int i = n; i >= 2; i--)
    {
        int p = f[i];
        if (len[i] + 1 > len[p])
        {
            len[p] = len[i] + 1;
            heavy[p] = i;
        }
    }

    for (int i = n; i >= 2; i--)
    {
        if (heavy[f[i]] != i)
        {
            add_edge(f[i], i);
        }
    }

    int timer = 0;
    vi stk;
    stk.reserve(n);
    stk.pb(1);

    vi order;
    order.reserve(n);

    while (!stk.empty())
    {
        int u = stk.back();
        stk.pop_back();
        dfn[u] = ++timer;
        order.pb(u);

        for (int e = head_adj[u]; e; e = nxt_adj[e])
        {
            stk.pb(to_adj[e]);
        }
        if (heavy[u])
        {
            stk.pb(heavy[u]);
        }
    }

    seg.init(n);
    std::vector<ll> tmp;

    for (int idx = n - 1; idx >= 0; idx--)
    {
        int u = order[idx];
        int l = dfn[u], r = dfn[u] + len[u] - 1;

        for (int e = head_adj[u]; e; e = nxt_adj[e])
        {
            int v = to_adj[e];
            int lv = dfn[v], rv = dfn[v] + len[v] - 1;
            tmp.assign(len[v], 0);
            seg.extract_and_clear(1, 1, n, lv, rv, tmp);
            for (int d = 0; d < len[v]; d++)
            {
                if (tmp[d] > 0)
                {
                    seg.point_add(1, 1, n, l + 1 + d, tmp[d]);
                }
            }
        }

        if (l + 1 <= r)
        {
            ans[u] = seg.query_sum(1, 1, n, l + 1, r);
        }
        else
        {
            ans[u] = 0;
        }

        if (u != 1)
        {
            seg.point_add(1, 1, n, l, w[u]);
            if (l + 1 <= r)
            {
                seg.range_chmin(1, 1, n, l + 1, r, w[u]);
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << " ";
    }
    std::cout << "\n";
}

