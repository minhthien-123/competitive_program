ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct pt
{
    int l, r;
    ll t;
};

int n, m, k, t;
ll a, b, c;
pt p[maxk], p_init[maxk];
ll len[maxk], len_init[maxk];
ll d[maxn];
int pref[maxn];
ll pre_mx[maxn], suf_mx[maxn];
int pre_cnt[maxn], suf_cnt[maxn];

void solve()
{
    std::cin >> n >> m >> k >> t >> a >> b >> c;

    for (int i = 1; i <= k; i++)
    {
        std::cin >> p_init[i].l >> len_init[i] >> p_init[i].t;
        p_init[i].r = p_init[i].l + (len_init[i] % (m - p_init[i].l + 1));
        p[i] = p_init[i];
        len[i] = len_init[i];
        d[p[i].l] += p[i].t;
        d[p[i].r + 1] -= p[i].t;
    }

    int cur = k, old = 1;
    for (int i = k + 1; i <= n; i++)
    {
        int nxt = old;
        p[nxt].l = ((p[cur].l ^ (1LL * a * p[old].l)) % m) + 1;
        len[nxt] = ((len[cur] ^ (1LL * b * len[old])) % m) + 1;
        p[nxt].t = ((p[cur].t ^ (1LL * c * p[old].t)) % t) + 1;
        p[nxt].r = p[nxt].l + (len[nxt] % (m - p[nxt].l + 1));

        d[p[nxt].l] += p[nxt].t;
        d[p[nxt].r + 1] -= p[nxt].t;

        cur = nxt;
        old = (old % k) + 1;
    }

    ll mx = -1;
    for (int i = 1; i <= m; i++)
    {
        d[i] += d[i - 1];
        if (d[i] > mx)
        {
            mx = d[i];
        }
    }

    pre_mx[0] = -1;
    pre_cnt[0] = 0;
    for (int i = 1; i <= m; i++)
    {
        pref[i] = pref[i - 1] + (d[i] == mx);
        if (d[i] > pre_mx[i - 1])
        {
            pre_mx[i] = d[i];
            pre_cnt[i] = 1;
        }
        else if (d[i] == pre_mx[i - 1])
        {
            pre_mx[i] = d[i];
            pre_cnt[i] = pre_cnt[i - 1] + 1;
        }
        else
        {
            pre_mx[i] = pre_mx[i - 1];
            pre_cnt[i] = pre_cnt[i - 1];
        }
    }

    suf_mx[m + 1] = -1;
    suf_cnt[m + 1] = 0;
    for (int i = m; i >= 1; i--)
    {
        if (d[i] > suf_mx[i + 1])
        {
            suf_mx[i] = d[i];
            suf_cnt[i] = 1;
        }
        else if (d[i] == suf_mx[i + 1])
        {
            suf_mx[i] = d[i];
            suf_cnt[i] = suf_cnt[i + 1] + 1;
        }
        else
        {
            suf_mx[i] = suf_mx[i + 1];
            suf_cnt[i] = suf_cnt[i + 1];
        }
    }

    for (int i = 1; i <= k; i++)
    {
        p[i] = p_init[i];
        len[i] = len_init[i];
    }

    ll ans = 0;
    int tot_mx = pref[m];
    cur = k;
    old = 1;

    for (int i = 1; i <= n; i++)
    {
        int l, r;
        ll ti;
        if (i <= k)
        {
            l = p[i].l;
            r = p[i].r;
            ti = p[i].t;
        }
        else
        {
            int nxt = old;
            p[nxt].l = ((p[cur].l ^ (1LL * a * p[old].l)) % m) + 1;
            len[nxt] = ((len[cur] ^ (1LL * b * len[old])) % m) + 1;
            p[nxt].t = ((p[cur].t ^ (1LL * c * p[old].t)) % t) + 1;
            p[nxt].r = p[nxt].l + (len[nxt] % (m - p[nxt].l + 1));

            l = p[nxt].l;
            r = p[nxt].r;
            ti = p[nxt].t;

            cur = nxt;
            old = (old % k) + 1;
        }

        int in_mx = pref[r] - pref[l - 1];
        if (in_mx < tot_mx)
        {
            ans += tot_mx - in_mx;
        }
        else
        {
            ll cur_mx = mx - ti;
            int cur_cnt = in_mx;

            if (pre_mx[l - 1] > cur_mx)
            {
                cur_mx = pre_mx[l - 1];
                cur_cnt = pre_cnt[l - 1];
            }
            else if (pre_mx[l - 1] == cur_mx)
            {
                cur_cnt += pre_cnt[l - 1];
            }

            if (suf_mx[r + 1] > cur_mx)
            {
                cur_mx = suf_mx[r + 1];
                cur_cnt = suf_cnt[r + 1];
            }
            else if (suf_mx[r + 1] == cur_mx)
            {
                cur_cnt += suf_cnt[r + 1];
            }

            ans += cur_cnt;
        }
    }

    std::cout << ans;
}

