ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, k;
int a[maxn + 7];
std::vector<int> adj[maxn + 7];
int vis[maxn + 7];
int timer = 0;

std::vector<int> color_group[maxn + 7];
std::vector<int> active_colors;

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7, 1);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];

            if (adj[u].empty())
            {
                adj[u].swap(adj[v]);
            }
            else
            {
                adj[u].insert(adj[u].end(), adj[v].begin(), adj[v].end());
                adj[v].clear();
            }
        }
    }
};

ii edges[maxn + 7];
int cnt[maxn + 7], rep[maxn + 7];

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 0; i <= k; i++)
    {
        cnt[i] = 0;
        rep[i] = 0;
    }

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        std::vector<int>().swap(adj[i]);
    }

    DSU dsu(n);

    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        edges[i] = {u, v};
        if (a[u] == a[v])
        {
            dsu.join(u, v);
        }
    }

    for (int i = 1; i <= n; i++)
    {
        if (dsu.acs(i) == i)
        {
            cnt[a[i]]++;
            rep[a[i]] = i;
        }
    }

    for (int i = 1; i <= m; i++)
    {
        auto [u, v] = edges[i];
        if (a[u] != a[v])
        {
            adj[dsu.acs(u)].pb(dsu.acs(v));
            adj[dsu.acs(v)].pb(dsu.acs(u));
        }
    }

    std::queue<int> q;

    for (int i = 1; i <= k; i++)
    {
        if (cnt[i] == 1)
        {
            int u = dsu.acs(rep[i]);
            a[u] = 0;
            q.push(u);
            cnt[i] = 0;
        }
    }

    while (!q.empty())
    {
        int u = q.front();
        q.pop();

        u = dsu.acs(u);
        timer++;

        active_colors.clear();

        for (int v : adj[u])
        {
            v = dsu.acs(v);
            if (u != v && vis[v] != timer)
            {
                vis[v] = timer;
                int c = a[v];
                if (color_group[c].empty())
                {
                    active_colors.pb(c);
                }
                color_group[c].pb(v);
            }
        }
        adj[u].clear();

        bool check = false;

        if (!color_group[0].empty())
        {
            auto &vec = color_group[0];
            int base = vec[0];

            for (int i = 1; i < sz(vec); i++)
            {
                int nxt = vec[i];
                if (dsu.acs(base) != dsu.acs(nxt))
                {
                    dsu.join(base, nxt);
                    base = dsu.acs(base);
                }
            }
            if (dsu.acs(u) != dsu.acs(base))
            {
                dsu.join(u, base);
                u = dsu.acs(u);
                check = true;
            }
            vec.clear();
        }

        for (int c : active_colors)
        {
            if (c == 0)
            {
                continue;
            }

            auto &vec = color_group[c];
            int base = vec[0];

            for (int i = 1; i < sz(vec); i++)
            {
                int nxt = vec[i];
                if (dsu.acs(base) != dsu.acs(nxt))
                {
                    dsu.join(base, nxt);
                    base = dsu.acs(base);
                    cnt[c]--;
                }
            }

            if (cnt[c] == 1)
            {
                a[base] = 0;
                cnt[c] = 0;
                q.push(base);
            }
            adj[u].pb(base);
            vec.clear();
        }

        if (check)
        {
            q.push(u);
        }
    }

    bool ok = true;
    for (int i = 1; i <= k; i++)
    {
        if (cnt[i] > 0)
        {
            ok = false;
            break;
        }
    }

    std::cout << (ok ? "YES\n" : "NO\n");
}

