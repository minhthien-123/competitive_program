ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ll a[maxn + 7][17];
ll dp[maxn + 7];
ll best[maxn + 7];

ll getV(int id, int mask)
{
    ll res = 0;
    for (int c = 0; c < k; c++)
    {
        if ((mask >> c) & 1)
        {
            res += a[id][c];
        }
        else
        {
            res -= a[id][c];
        }
    }
    return res;
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 0; j < k; j++)
        {
            std::cin >> a[i][j];
        }
    }

    for (int mask = 0; mask < (1 << k); mask++)
    {
        best[mask] = -getV(1, mask);
    }

    for (int i = 1; i <= n; i++)
    {
        dp[i] = 0;
        for (int mask = 0; mask < (1 << k); mask++)
        {
            dp[i] = std::max(dp[i], getV(i, mask) + best[mask]);
        }

        for (int mask = 0; mask < (1 << k); mask++)
        {
            best[mask] = std::max(best[mask], dp[i] - getV(i + 1, mask));
        }
    }

    std::cout << dp[n] << "\n";
}

