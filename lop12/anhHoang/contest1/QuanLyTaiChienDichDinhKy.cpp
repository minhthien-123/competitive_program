ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int q;
ll sum_light[bl + 5][2 * bl + 5];

struct FenwickTree
{
    std::vector<ll> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<ll> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    ll sum(int r)
    {
        ll res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    ll sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, ll delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

FenwickTree ft(maxn + 5);

void update_light(int x, int k, int sign)
{
    ll val = 1LL * x * sign;
    for (int rem = 1; rem <= k; rem++)
    {
        sum_light[k][rem] += val;
    }
}

void update_heavy(int x, int k, int sign)
{
    ll val = 1LL * x * sign;
    for (int i = 0;; i++)
    {
        int L = i * 2 * k + 1;
        int R = i * 2 * k + k;
        if (L > maxn)
        {
            break;
        }
        R = std::min(R, maxn);
        ft.add(L, val);
        ft.add(R + 1, -val);
    }
}

void solve()
{
    std::cin >> q;
    while (q--)
    {
        std::string type;
        std::cin >> type;

        if (type == "ADD" || type == "DEL")
        {
            int x, k;
            std::cin >> x >> k;
            int sign = (type == "ADD" ? 1 : -1);

            if (k <= bl)
            {
                update_light(x, k, sign);
            }
            else
            {
                update_heavy(x, k, sign);
            }
        }
        else if (type == "ASK")
        {
            int t;
            std::cin >> t;

            ll ans = ft.sum(t);

            for (int k = 1; k <= bl; k++)
            {
                int rem = (t - 1) % (2 * k) + 1;
                ans += sum_light[k][rem];
            }

            std::cout << ans << "\n";
        }
    }
}

