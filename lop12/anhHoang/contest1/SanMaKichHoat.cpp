ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];

struct Sieve
{
    int n;
    std::vector<int> min_prime;
    std::vector<int> primes;
    std::vector<int> prime_idx;

    Sieve(int n) : n(n)
    {
        min_prime.assign(n + 1, 0);
        prime_idx.assign(n + 1, 0);
        for (int i = 2; i <= n; i++)
        {
            if (min_prime[i] == 0)
            {
                min_prime[i] = i;
                prime_idx[i] = primes.size();
                primes.push_back(i);
            }
            for (int p : primes)
            {
                if (p > min_prime[i] || i * p > n)
                {
                    break;
                }
                min_prime[i * p] = p;
            }
        }
    }

    bool is_prime(int x)
    {
        if (x < 2)
        {
            return false;
        }
        return min_prime[x] == x;
    }
};

Sieve sieve(maxv);

struct Node
{
    int lc, rc;
    int mn;
} st[maxn * 180];
int roots[maxn + 7];
int node_cnt = 0;

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        st[id].mn = 0;
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    st[id].mn = 0;
    return id;
}

int update(int old_id, int l, int r, int pos, int val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];

    if (l == r)
    {
        st[id].mn = val;
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    st[id].mn = std::min(st[st[id].lc].mn, st[st[id].rc].mn);
    return id;
}

int query(int id, int l, int r, int val)
{
    if (l == r)
    {
        return l;
    }

    int mid = (l + r) / 2;
    if (st[st[id].lc].mn < val)
    {
        return query(st[id].lc, l, mid, val);
    }
    else
    {
        return query(st[id].rc, mid + 1, r, val);
    }
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    int m = sz(sieve.primes);
    roots[0] = build(0, m - 1);
    for (int i = 1; i <= n; i++)
    {
        int tmp = a[i];
        int cur_root = roots[i - 1];
        while (tmp > 1)
        {
            int p = sieve.min_prime[tmp];
            cur_root = update(cur_root, 0, m - 1, sieve.prime_idx[p], i);
            while (tmp % p == 0)
            {
                tmp /= p;
            }
        }
        roots[i] = cur_root;
    }

    while (q--)
    {
        int l, r;
        std::cin >> l >> r;
        int ans = query(roots[r], 0, m - 1, l);
        std::cout << sieve.primes[ans] << "\n";
    }
}

