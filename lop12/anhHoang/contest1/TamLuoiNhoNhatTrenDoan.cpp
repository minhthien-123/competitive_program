ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll calc(int l, int r, ll L_val, ll R_val)
{
    if (L_val <= -inf && R_val >= inf)
    {
        return inf;
    }
    if (R_val >= inf)
    {
        return r - L_val;
    }
    if (L_val <= -inf)
    {
        return R_val - l;
    }

    ll mid = (L_val + R_val) / 2;
    ll res = -1;

    res = std::max(res, std::min((ll)l - L_val, R_val - l));
    res = std::max(res, std::min((ll)r - L_val, R_val - r));

    for (ll p = mid - 1; p <= mid + 1; p++)
    {
        if (p >= l && p <= r)
        {
            res = std::max(res, std::min(p - L_val, R_val - p));
        }
    }
    return res;
}

struct SegTree
{
    int n;
    std::vector<ll> min_L, max_L, lazy_L;
    std::vector<ll> min_R, max_R, lazy_R;
    std::vector<ll> max_ans;

    SegTree(int n = 0)
    {
        this->n = n;
        min_L.assign(4 * n + 7, -inf);
        max_L.assign(4 * n + 7, -inf);
        lazy_L.assign(4 * n + 7, -inf);

        min_R.assign(4 * n + 7, inf);
        max_R.assign(4 * n + 7, inf);
        lazy_R.assign(4 * n + 7, inf);

        max_ans.assign(4 * n + 7, inf);
    }

    void pull(int id)
    {
        int lc = 2 * id, rc = 2 * id + 1;
        min_L[id] = std::min(min_L[lc], min_L[rc]);
        max_L[id] = std::max(max_L[lc], max_L[rc]);
        min_R[id] = std::min(min_R[lc], min_R[rc]);
        max_R[id] = std::max(max_R[lc], max_R[rc]);
        max_ans[id] = std::max(max_ans[lc], max_ans[rc]);
    }

    void apply_l(int id, int l, int r, ll val)
    {
        min_L[id] = max_L[id] = lazy_L[id] = val;
        max_ans[id] = calc(l, r, min_L[id], min_R[id]);
    }

    void apply_R(int id, int l, int r, ll val)
    {
        min_R[id] = max_R[id] = lazy_R[id] = val;
        max_ans[id] = calc(l, r, min_L[id], min_R[id]);
    }

    void push(int id, int l, int r)
    {
        int mid = (l + r) / 2;
        int lc = 2 * id, rc = 2 * id + 1;

        if (lazy_L[id] != -inf)
        {
            if (min_R[lc] == max_R[lc])
            {
                apply_l(lc, l, mid, lazy_L[id]);
            }
            if (min_R[rc] == max_R[rc])
            {
                apply_l(rc, mid + 1, r, lazy_L[id]);
            }
            lazy_L[id] = -inf;
        }

        if (lazy_R[id] != inf)
        {
            if (min_L[lc] == max_L[lc])
            {
                apply_R(lc, l, mid, lazy_R[id]);
            }
            if (min_L[rc] == max_L[rc])
            {
                apply_R(rc, mid + 1, r, lazy_R[id]);
            }
            lazy_R[id] = inf;
        }
    }

    void updateL(int id, int l, int r, int u, int v, ll x)
    {
        if (v < l || r < u || min_L[id] >= x)
        {
            return;
        }
        if (u <= l && r <= v && max_L[id] < x && min_R[id] == max_R[id])
        {
            apply_l(id, l, r, x);
            return;
        }
        if (l == r)
        {
            min_L[id] = max_L[id] = x;
            max_ans[id] = calc(l, r, min_L[id], min_R[id]);
            return;
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        updateL(2 * id, l, mid, u, v, x);
        updateL(2 * id + 1, mid + 1, r, u, v, x);
        pull(id);
    }

    void updateR(int id, int l, int r, int u, int v, ll x)
    {
        if (v < l || r < u || max_R[id] <= x)
        {
            return;
        }
        if (u <= l && r <= v && min_R[id] > x && min_L[id] == max_L[id])
        {
            apply_R(id, l, r, x);
            return;
        }
        if (l == r)
        {
            min_R[id] = max_R[id] = x;
            max_ans[id] = calc(l, r, min_L[id], min_R[id]);
            return;
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        updateR(2 * id, l, mid, u, v, x);
        updateR(2 * id + 1, mid + 1, r, u, v, x);
        pull(id);
    }

    ll query(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return -1;
        }
        if (u <= l && r <= v)
        {
            return max_ans[id];
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        return std::max(query(2 * id, l, mid, u, v), query(2 * id + 1, mid + 1, r, u, v));
    }
};

int n, q;
SegTree seg;

void solve()
{
    std::cin >> n >> q;
    seg = SegTree(n);

    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int d, x;
            std::cin >> d >> x;
            if (d == 1)
            {
                seg.updateL(1, 1, n, x, n, x);
            }
            else
            {
                seg.updateR(1, 1, n, 1, x, x);
            }
        }
        else
        {
            int l, r;
            std::cin >> l >> r;
            ll ans = seg.query(1, 1, n, l, r);
            if (ans >= inf)
            {
                std::cout << -1 << "\n";
            }
            else
            {
                std::cout << ans << "\n";
            }
        }
    }
}

