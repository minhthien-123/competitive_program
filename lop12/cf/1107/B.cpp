std::vector<ll> vec;

void init()
{
    for (int d1 = 0; d1 <= 9; d1++)
    {
        for (int d2 = d1; d2 <= 9; d2++)
        {
            auto dfs = [&](auto tmp, ll val) -> void
            {
                if (val >= 2 && val <= 1e9)
                {
                    vec.pb(val);
                }
                if (val > 1e8)
                {
                    return;
                }
                if (val > 0 || d1 > 0)
                {
                    tmp(tmp, val * 10 + d1);
                }
                if (d1 != d2 && (val > 0 || d2 > 0))
                {
                    tmp(tmp, val * 10 + d2);
                }
            };
            dfs(dfs, 0);
        }
    }
    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());
}

bool is_good(ll val)
{
    int mask = 0;
    int dist = 0;
    while (val > 0)
    {
        int d = val % 10;
        if (!(mask & (1 << d)))
        {
            mask |= (1 << d);
            dist++;
            if (dist > 2)
            {
                return false;
            }
        }
        val /= 10;
    }
    return true;
}

void solve()
{
    ll x;
    std::cin >> x;
    for (ll y : vec)
    {
        if (is_good(x * y))
        {
            std::cout << y << "\n";
            return;
        }
    }
}

