void solve()
{
    int n;
    std::cin >> n;
    std::vector<ll> a(n + 2, 0), b(n + 2, 0), f(n + 2, 0);
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> b[i];
    }
    for (int i = 1; i <= n; i++)
    {
        ll A = (i % 2 == 0) ? a[i] : -a[i];
        ll B = (i % 2 == 0) ? b[i] : -b[i];
        f[i] = A - B;
    }
    ll mx = 0;
    bool flag = true;
    for (int i = 1; i <= n + 1; i++)
    {
        ll pre1 = std::max(0LL, f[i - 1]);
        ll cur1 = std::max(0LL, f[i]);
        ll pre2 = std::max(0LL, -f[i - 1]);
        ll cur2 = std::max(0LL, -f[i]);
        ll D = (i % 2 == 0) ? (pre1 - cur1) : (pre2 - cur2);
        mx += D;
        if (mx < 0)
        {
            flag = false;
            break;
        }
    }
    if (flag)
    {
        std::cout << "YES\n";
    }
    else
    {
        std::cout << "NO\n";
    }
}

