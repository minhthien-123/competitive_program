ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
std::map<ll, ll> distA, distB;

void dfs(ll u, ll c, std::map<ll, ll> &dist, ll x)
{
    if (dist.count(u) && dist[u] <= c)
    {
        return;
    }
    dist[u] = c;
    if (u == 0)
    {
        return;
    }
    dfs(u / x, c + 1, dist, x);
    dfs(u / x + 1, c + (x - u % x) + 1, dist, x);
}

void solve()
{
    ll a, b, x;
    std::cin >> a >> b >> x;
    distA.clear();
    distB.clear();
    dfs(a, 0, distA, x);
    dfs(b, 0, distB, x);
    ll ans = inf;
    for (auto x : distA)
    {
        for (auto y : distB)
        {
            ll cost = x.se + y.se + std::abs(x.fi - y.fi);
            if (cost < ans)
            {
                ans = cost;
            }
        }
    }
    std::cout << ans << "\n";
}

