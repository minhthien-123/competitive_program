ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<ii> adj[maxn + 7];
int n, m;
int sz[maxn + 7];
bool flag[maxn + 7], dp[maxx + 7];
int q[maxn + 7];
bool ans[maxn + 7];

void get_sz(int u, int p)
{
    sz[u] = 1;
    for (auto e : adj[u])
    {
        int v = e.fi;
        if (v == p || flag[v])
        {
            continue;
        }
        get_sz(v, u);
        sz[u] += sz[v];
    }
}

int get_centroid(int u, int p, int total_sz)
{
    for (auto e : adj[u])
    {
        int v = e.fi;
        if (v == p || flag[v])
        {
            continue;
        }
        if (sz[v] > total_sz / 2)
        {
            return get_centroid(v, u, total_sz);
        }
    }

    return u;
}

void get_dist(int u, int p, int dist, std::vector<int> &d)
{
    if (dist > maxx)
    {
        return;
    }
    d.pb(dist);
    for (auto e : adj[u])
    {
        auto [v, w] = e;
        if (v == p || flag[v])
        {
            continue;
        }
        get_dist(v, u, dist + w, d);
    }
}

void build(int u)
{
    get_sz(u, 0);
    int centroid = get_centroid(u, 0, sz[u]);

    flag[centroid] = true;
    dp[0] = true;

    std::vector<int> Q;

    for (auto e : adj[centroid])
    {
        auto [v, w] = e;
        if (!flag[v])
        {
            std::vector<int> sub_dist;
            get_dist(v, centroid, w, sub_dist);

            for (int d : sub_dist)
            {
                for (int i = 1; i <= m; i++)
                {
                    if (q[i] >= d && dp[q[i] - d])
                    {
                        ans[i] = true;
                    }
                }
            }

            for (int d : sub_dist)
            {
                if (!dp[d])
                {
                    dp[d] = true;
                    Q.pb(d);
                }
            }
        }
    }

    for (int d : Q)
    {
        dp[d] = false;
    }

    for (auto e : adj[centroid])
    {
        int v = e.fi;
        if (!flag[v])
        {
            build(v);
        }
    }
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    for (int i = 1; i <= m; i++)
    {
        std::cin >> q[i];
    }

    build(1);

    for (int i = 1; i <= m; i++)
    {
        std::cout << (ans[i] ? "AYE\n" : "NAY\n");
    }
}

