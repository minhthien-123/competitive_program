ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::string s;
int n;
int dp[maxn + 7][maxn + 7], mask[27][27];
std::bitset<305> L[26][305], R[26][305];
std::vector<ii> rules[26];

void solve()
{
    std::cin >> s >> n;
    for (int i = 1; i <= n; i++)
    {
        char c, p, q;
        std::cin >> c >> p >> q;
        rules[c - 'a'].push_back({p - 'a', q - 'a'});
    }

    for (int i = 0; i < sz(s); i++)
    {
        int c = s[i] - 'a';
        L[c][i].set(i + 1);
        R[c][i].set(i);
    }

    for (int len = 2; len <= sz(s); len++)
    {
        for (int i = 0; i + len - 1 < sz(s); i++)
        {
            int j = i + len - 1;

            for (int c = 0; c < 26; c++)
            {
                if (L[c][i].test(j + 1))
                {
                    continue;
                }

                for (auto [p, q] : rules[c])
                {
                    if ((L[p][i] & R[q][j]).any())
                    {

                        L[c][i].set(j + 1);
                        R[c][j].set(i);

                        break;
                    }
                }
            }
        }
    }

    bool flag = false;
    for (char c = 'a'; c <= 'z'; c++)
    {
        if (L[c - 'a'][0].test(sz(s)))
        {
            std::cout << c;
            flag = true;
        }
    }

    if (!flag)
    {
        std::cout << "No Solution.";
    }
}

