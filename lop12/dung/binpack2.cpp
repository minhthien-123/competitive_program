ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ii a[maxn + 7];
int ans[maxn + 7];

void solve()
{
    std::cin >> n >> k;
    ll sum = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].fi;
        a[i].se = i;
        sum += a[i].fi;
        ans[i] = 0;
    }
    sum /= 2;
    sort(a + 1, a + n + 1);
    std::set<ii> s;
    for (int i = 1; i <= n - k; i++)
    {
        s.ins(a[i]);
    }
    ll sum2 = 0;
    while (s.size() && sum2 < sum)
    {
        ll tmp = sum - sum2;
        auto it = s.upper_bound(ii(tmp, 1e9));
        if (it != s.begin())
        {
            it--;
            auto [val, idx] = (*it);
            s.erase(it);
            sum2 += val;
            ans[idx] = 2;
        }
        else
        {
            break;
        }
    }
    for (auto [val, idx] : s)
    {
        ans[idx] = 1;
    }
    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i];
    }
    std::cout << "\n";
}

