ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int m, n;
ll a[maxn + 7][maxn + 7];
ll pre[maxn + 7][maxn + 7];

// Xây dựng mảng cộng dồn 2D (1-indexed)
// pre[i][j] = pre[i-1][j] + pre[i][j-1] - pre[i-1][j-1] + a[i][j];
// Tính tổng HCN (r1, c1) -> (r2, c2):
// sum = pre[r2][c2] - pre[r1-1][c2] - pre[r2][c1-1] + pre[r1-1][c1-1];

void solve()
{
    std::cin >> m >> n;

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
            pre[i][j] = (pre[i - 1][j] + pre[i][j - 1] - pre[i - 1][j - 1] + a[i][j] + 9) % 9;
        }
    }

    ll ans = 0;
    for (int x = 1; x <= m; x++)
    {
        for (int y = x; y <= m; y++)
        {
            ll cnt[9] = {0};
            cnt[0] = 1;
            for (int j = 1; j <= n; j++)
            {
                ll val = (pre[y][j] - pre[x - 1][j] - pre[y][0] + pre[x - 1][0] + 9) % 9;
                ans += cnt[val];
                cnt[val]++;
            }
        }
    }

    std::cout << ans;
}

