ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
std::vector<ii> adj[maxn + 7];

struct query
{
    int type, u, v, w;
    friend bool operator<(query a, query b)
    {
        return a.w < b.w;
    }
};

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth, dist;
    std::vector<bool> vis;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
        dist.assign(n + 7, 0);
        vis.assign(n + 7, false);
    }

    void add_edge(int u, int v, int w)
    {
        adj[u].push_back({v, w});
        adj[v].push_back({u, w});
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        vis[u] = true;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (auto [v, w] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dist[v] = dist[u] + w;
                dfs(v, u);
            }
        }
    }

    void build()
    {
        for (int i = 1; i <= n; i++)
        {
            if (!vis[i])
            {
                depth[i] = 0;
                dfs(i, i);
            }
        }
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_dist(int u, int v)
    {
        int lca = get_lca(u, v);
        return dist[u] + dist[v] - 2 * dist[lca];
    }
};

void solve()
{
    std::cin >> n >> k;

    DSU dsu(n);
    LCA lca(n);

    std::vector<query> queries;
    for (int i = 1; i <= k; i++)
    {
        int type, u, v, w;
        std::cin >> type;
        if (type == 1)
        {
            std::cin >> u >> v >> w;
            queries.pb({type, u, v, w});
            adj[u].pb({v, w});
            adj[v].pb({u, w});
        }
        else
        {
            int u, v;
            std::cin >> u >> v;
            queries.pb({type, u, v, 0});
        }
    }

    lca.build();

    for (auto qr : queries)
    {
        int u = qr.u;
        int v = qr.v;
        if (qr.type == 1)
        {
            dsu.join(u, v);
        }
        else
        {
            if (dsu.acs(u) != dsu.acs(v))
            {
                std::cout << -1 << "\n";
            }
            else
            {
                std::cout << lca.get_dist(u, v) << "\n";
            }
        }
    }
}

