ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
std::vector<int> adj[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> depth;

    LCA () {}
    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

LCA lca;

void solve()
{
    std::cin >> n;
    lca = LCA(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        lca.add_edge(u, v);
    }

    lca.build();

    std::cin >> q;
    while (q--)
    {
        int u, v, r;
        std::cin >> u >> v >> r;
        int uv = lca.get_lca(u, v);
        int ur = lca.get_lca(u, r);
        int vr = lca.get_lca(v, r);

        if (uv == ur)
        {
            std::cout << vr << "\n";
        }
        else if (uv == vr)
        {
            std::cout << ur << "\n";
        }
        else
        {
            std::cout << uv << "\n";
        }
    }
}

