ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, root;
int a[maxn + 7], p[maxn + 7];
int dp[maxn + 7][2];

void calc(int u, int p)
{
    dp[u][0] = 0;
    dp[u][1] = a[u];

    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        calc(v, u);
        dp[u][0] += dp[v][1];
        dp[u][1] += std::min(dp[v][0], dp[v][1]);
    }
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> p[i];
        if (p[i] == 0)
        {
            root = i;
        }
        else
        {
            adj[p[i]].pb(i);
        }
    }

    calc(root, -1);

    std::cout << std::min(dp[root][0], dp[root][1]) << "\n";
}

