ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
std::vector<ii> adj[maxn + 7];
int sz[maxn + 7];
int ans[maxn + 7];

void dfs1(int u, int p)
{
    sz[u] = 1;
    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        dfs1(v, u);
        sz[u] += sz[v];
        ans[1] += sz[v] * w;
    }
}

void dfs2(int u, int p)
{
    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        ans[v] = ans[u] + (n - 2 * sz[v]) * w;
        dfs2(v, u);
    }
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    dfs1(1, 0);
    dfs2(1, 0);

    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << "\n";
    }
}

