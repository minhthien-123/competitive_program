std::string s;

struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};

void solve()
{
    std::cin >> s;
    std::string t = std::string(s.rbegin(), s.rend());
    int n = s.length();

    StringHash S(s);
    StringHash T(t);

    int pre = 1;
    for (int i = 1; i <= n; i++)
    {
        if (S.get_hash(1, i) == T.get_hash(n - i + 1, n))
        {
            pre = i;
        }
    }

    int suf = 1;
    for (int i = 1; i <= n; i++)
    {
        if (S.get_hash(n - i + 1, n) == T.get_hash(1, i))
        {
            suf = i;
        }
    }

    if (pre >= suf)
    {
        std::string rem = s.substr(pre);
        std::reverse(rem.begin(), rem.end());
        std::cout << rem << s;
    }
    else
    {
        std::string rem = s.substr(0, n - suf);
        std::reverse(rem.begin(), rem.end());
        std::cout << s << rem;
    }
}

