struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash() {}

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    ll get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return ((ll)hash1 << 32) | hash2;
    }
};

void solve()
{
    if (!(std::cin >> n))
    {
        return;
    }
    std::cin >> s;

    StringHash S(s);

    int l = 1, r = n - 1, ans = 0;
    while (l <= r)
    {
        int mid = (l + r) / 2;
        std::vector<ll> hashes;
        hashes.reserve(n - mid + 1);

        for (int i = 1; i <= n - mid + 1; i++)
        {
            hashes.push_back(S.get_hash(i, i + mid - 1));
        }
        std::sort(hashes.begin(), hashes.end());

        bool ok = false;
        for (int i = 1; i < sz(hashes); i++)
        {
            if (hashes[i] == hashes[i - 1])
            {
                ok = true;
                break;
            }
        }

        if (ok)
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << ans << "\n";
}

