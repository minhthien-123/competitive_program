struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash() {}

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};

void solve()
{
    std::cin >> lenA >> lenB;
    std::cin >> s >> t;

    StringHash S(s);
    StringHash T(t);

    int q;
    std::cin >> q;

    s = " " + s;
    t = " " + t;

    while (q--)
    {
        int l, r, u, v;
        std::cin >> l >> r >> u >> v;

        int subs = r - l + 1;
        int subt = v - u + 1;

        int L = 1, R = std::min(subs, subt), lcp = 0;

        while (L <= R)
        {
            int mid = (L + R) / 2;
            if (S.get_hash(l, l + mid - 1) == T.get_hash(u, u + mid - 1))
            {
                lcp = mid;
                L = mid + 1;
            }
            else
            {
                R = mid - 1;
            }
        }

        if (lcp == subs && lcp == subt)
        {
            std::cout << "=";
        }
        else if (lcp == subs)
        {
            std::cout << "<";
        }
        else if (lcp == subt)
        {
            std::cout << ">";
        }
        else
        {
            if (s[l + lcp] < t[u + lcp])
            {
                std::cout << "<";
            }
            else
            {
                std::cout << ">";
            }
        }
    }
}

