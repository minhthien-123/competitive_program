struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash() {}

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};
std::string s1, s2;

void solve()
{
    std::cin >> s1 >> s2;

    int n = s1.length();
    StringHash h1(s1);
    StringHash h2(s2);

    int ans = 0;
    for (int i = 1; i <= n - 2; i++)
    {
        for (int j = 1; j <= n - i - 1; j++)
        {
            int k = n - i - j;

            auto hx = h2.get_hash(1, i);
            auto hy = h2.get_hash(i + 1, i + j);
            auto hz = h2.get_hash(i + j + 1, n);

            bool ok = false;

            if (!ok && h1.get_hash(1, i) == hx && h1.get_hash(i + 1, i + j) == hy && h1.get_hash(i + j + 1, n) == hz)
            {
                ok = true;
            }
            if (!ok && h1.get_hash(1, i) == hx && h1.get_hash(i + 1, i + k) == hz && h1.get_hash(i + k + 1, n) == hy)
            {
                ok = true;
            }
            if (!ok && h1.get_hash(1, j) == hy && h1.get_hash(j + 1, j + i) == hx && h1.get_hash(j + i + 1, n) == hz)
            {
                ok = true;
            }
            if (!ok && h1.get_hash(1, j) == hy && h1.get_hash(j + 1, j + k) == hz && h1.get_hash(j + k + 1, n) == hx)
            {
                ok = true;
            }
            if (!ok && h1.get_hash(1, k) == hz && h1.get_hash(k + 1, k + i) == hx && h1.get_hash(k + i + 1, n) == hy)
            {
                ok = true;
            }
            if (!ok && h1.get_hash(1, k) == hz && h1.get_hash(k + 1, k + j) == hy && h1.get_hash(k + j + 1, n) == hx)
            {
                ok = true;
            }

            if (ok)
            {
                ans++;
            }
        }
    }

    std::cout << ans;
}

