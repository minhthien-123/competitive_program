struct Compress {

    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init() {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x) {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 1, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size())
    {
        for (int i = 0; i < a.size(); i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r >= 0; r = (r & (r + 1)) - 1)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if(l > r) return 0;
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx < n; idx = idx | (idx + 1))
        {
            bit[idx] += delta;
        }
    }
};

void solve()
{
    std::cin >> n >> k;
    Compress comp;
    comp.add(0);
    for (int i = 1; i <= n; ++i)
    {
        std::cin >> a[i];
        pre[i] = pre[i - 1] + a[i] - k;
        comp.add(pre[i]);
    }

    comp.init();
    int m = comp.size();
    FenwickTree bit(m);
    int ans = 0;

    for (int i = 0; i <= n; i++)
    {
        int pos = comp.get(pre[i]) - 1;
        ans += bit.sum(pos);
        bit.add(pos, 1);
    }

    std::cout << ans;
}

