struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

struct SegTree
{
    int n;
    std::vector<long long> st;

    SegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, 0);
    }

    void update(int id, int l, int r, int pos, long long val)
    {
        if (pos < l || pos > r)
        {
            return;
        }
        if (l == r)
        {
            st[id] = std::max(st[id], val);
            return;
        }
        int mid = (l + r) / 2;
        update(2 * id, l, mid, pos, val);
        update(2 * id + 1, mid + 1, r, pos, val);
        st[id] = std::max(st[2 * id], st[2 * id + 1]);
    }

    long long query(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return 0;
        }
        if (u <= l && r <= v)
        {
            return st[id];
        }
        int mid = (l + r) / 2;
        return std::max(query(2 * id, l, mid, u, v), query(2 * id + 1, mid + 1, r, u, v));
    }
};

void solve()
{
    std::cin >> n >> d;
    Compress comp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        comp.add(a[i]);
    }

    comp.init();
    int m = comp.size();
    SegTree st(m);
    int ans = 0;

    for (int i = 1; i <= n; i++)
    {
        int mx = 0;

        auto it1 = std::upper_bound(comp.vals.begin(), comp.vals.end(), a[i] - d);
        if (it1 != comp.vals.begin())
        {
            int id1 = it1 - comp.vals.begin();
            mx = std::max(mx, st.query(1, 1, m, 1, id1));
        }

        auto it2 = std::lower_bound(comp.vals.begin(), comp.vals.end(), a[i] + d);
        if (it2 != comp.vals.end())
        {
            int id2 = it2 - comp.vals.begin() + 1;
            mx = std::max(mx, st.query(1, 1, m, id2, m));
        }

        dp[i] = mx + 1;
        ans = std::max(ans, dp[i]);

        int id = comp.get(a[i]);
        st.update(1, 1, m, id, dp[i]);
    }

    std::cout << ans;
}

