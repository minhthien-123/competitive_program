struct BigNum
{
    std::vector<int> d;

    BigNum() {}
    BigNum(long long v)
    {
        if (v == 0)
            d.push_back(0);
        while (v > 0)
        {
            d.push_back(v % 10);
            v /= 10;
        }
    }
    BigNum(std::string s)
    {
        if (s.empty())
        {
            d.push_back(0);
            return;
        }
        for (int i = (int)s.length() - 1; i >= 0; i--)
        {
            d.push_back(s[i] - '0');
        }
        trim();
    }

    void trim()
    {
        while (d.size() > 1 && d.back() == 0)
            d.pop_back();
    }

    friend std::istream &operator>>(std::istream &is, BigNum &b)
    {
        std::string s;
        is >> s;
        b = BigNum(s);
        return is;
    }
    friend std::ostream &operator<<(std::ostream &os, const BigNum &b)
    {
        if (b.d.empty())
            os << 0;
        for (int i = (int)b.d.size() - 1; i >= 0; i--)
            os << b.d[i];
        return os;
    }

    bool operator<(const BigNum &b) const
    {
        if (d.size() != b.d.size())
            return d.size() < b.d.size();
        for (int i = (int)d.size() - 1; i >= 0; i--)
        {
            if (d[i] != b.d[i])
                return d[i] < b.d[i];
        }
        return false;
    }
    bool operator>(const BigNum &b) const { return b < *this; }
    bool operator==(const BigNum &b) const { return !(*this < b) && !(b < *this); }
    bool operator<=(const BigNum &b) const { return *this < b || *this == b; }
    bool operator>=(const BigNum &b) const { return *this > b || *this == b; }

    BigNum operator+(const BigNum &b) const
    {
        BigNum res;
        int carry = 0;
        for (int i = 0; i < std::max(d.size(), b.d.size()) || carry; i++)
        {
            int sum = carry;
            if (i < d.size())
                sum += d[i];
            if (i < b.d.size())
                sum += b.d[i];
            res.d.push_back(sum % 10);
            carry = sum / 10;
        }
        return res;
    }

    BigNum operator-(const BigNum &b) const
    {
        BigNum res;
        int borrow = 0;
        for (int i = 0; i < d.size(); i++)
        {
            int sub = d[i] - borrow - (i < b.d.size() ? b.d[i] : 0);
            if (sub < 0)
            {
                sub += 10;
                borrow = 1;
            }
            else
            {
                borrow = 0;
            }
            res.d.push_back(sub);
        }
        res.trim();
        return res;
    }

    BigNum operator*(const BigNum &b) const
    {
        BigNum res;
        if ((d.size() == 1 && d[0] == 0) || (b.d.size() == 1 && b.d[0] == 0))
            return BigNum(0);
        res.d.assign(d.size() + b.d.size(), 0);
        for (int i = 0; i < d.size(); i++)
        {
            int carry = 0;
            for (int j = 0; j < b.d.size() || carry; j++)
            {
                long long cur = res.d[i + j] + d[i] * 1LL * (j < b.d.size() ? b.d[j] : 0) + carry;
                res.d[i + j] = cur % 10;
                carry = cur / 10;
            }
        }
        res.trim();
        return res;
    }
};

int n;
BigNum dp[100005][10];

void solve()
{
    std::cin >> n;

    if (n == 0)
    {
        std::cout << 0 << "\n";
        return;
    }

    for (int i = 0; i <= 9; i++)
    {
        if (i != 0 && i != 8)
        {
            dp[1][i] = BigNum(1);
        }
        else
        {
            dp[1][i] = BigNum(0);
        }
    }

    std::vector<int> moves[10] = {{4, 6}, {6, 8}, {7, 9}, {4, 8}, {3, 9, 0}, {}, {1, 7, 0}, {2, 6}, {1, 3}, {2, 4}};

    for (int i = 2; i <= n; i++)
    {
        for (int j = 0; j <= 9; j++)
        {
            dp[i][j] = BigNum(0);
            for (int k : moves[j])
            {
                dp[i][j] = dp[i][j] + dp[i - 1][k];
            }
            if (dp[i][j].d.size() > 50)
            {
                dp[i][j].d.resize(50);
            }
        }
    }

    BigNum ans = BigNum(0);
    for (int i = 0; i <= 9; i++)
    {
        ans = ans + dp[n][i];
    }
    if (ans.d.size() > 50)
    {
        ans.d.resize(50);
    }

    std::cout << ans << "\n";
}

