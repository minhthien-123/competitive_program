ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m, v, ans;
int a[maxn + 7];
int f[maxn + 7][50000 + 7];
std::queue<ii> q;

void pour(int x, int y, int val)
{
    for (int i = 0; i <= n; i++)
    {
        if (a[i] > x + y)
        {
            break;
        }

        int tmp = std::min(x + y - a[i], v - x - y);
        if (f[i][tmp] == -1)
        {
            f[i][tmp] = val + 1;
            q.push(ii(i, tmp));
        }
    }
}

void bfs()
{
    memset(f, -1, sizeof f);
    f[0][0] = 0;
    q.push(ii(0, 0));

    while (!q.empty())
    {
        int x = q.front().fi;
        int y = q.front().se;
        q.pop();
        int z = v - a[x] - y;

        if (a[x] == m || y == m || z == m)
        {
            ans = f[x][y];
            return;
        }

        pour(a[x], y, f[x][y]);
        pour(a[x], z, f[x][y]);
        pour(y, a[x], f[x][y]);
        pour(y, z, f[x][y]);
        pour(z, a[x], f[x][y]);
        pour(z, y, f[x][y]);
    }
}

void solve()
{
    std::cin >> v >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    a[++n] = v;

    ans = -1;
    bfs();
    std::cout << ans << "\n";
}

