ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];

struct node
{
    int sum, pre, suf, mx;
} st[4 * maxn + 7];

node merge(node a, node b)
{
    node res;
    res.sum = a.sum + b.sum;
    res.pre = std::max(a.pre, a.sum + b.pre);
    res.suf = std::max(a.suf + b.sum, b.suf);
    res.mx = std::max({a.mx, b.mx, a.suf + b.pre});
    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = {a[l], a[l], a[l], a[l]};
        return;
    }
    int mid = l + r >> 1;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
    st[id] = merge(st[2 * id], st[2 * id + 1]);
}

node query(int id, int l, int r, int x, int y)
{
    if (y < l || r < x)
    {
        return {0, -inf, -inf, -inf};
    }
    if (x <= l && r <= y)
    {
        return st[id];
    }
    int mid = l + r >> 1;
    return merge(query(2 * id, l, mid, x, y), query(2 * id + 1, mid + 1, r, x, y));
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    std::cin >> m;
    build(1, 1, n);
    while (m--)
    {
        int x, y;
        std::cin >> x >> y;
        std::cout << query(1, 1, n, x, y).mx << "\n";
    }
}

