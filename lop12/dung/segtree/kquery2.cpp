ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];
int bit[707][maxv + 7];

void add_bit(int b, int idx, int val)
{
    for (; idx <= maxv; idx += idx & -idx)
    {
        bit[b][idx] += val;
    }
}

int sum_bit(int b, int idx)
{
    int res = 0;
    for (; idx > 0; idx -= idx & -idx)
    {
        res += bit[b][idx];
    }
    return res;
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        add_bit((i - 1) / bl, a[i], 1);
    }

    std::cin >> m;
    while (m--)
    {
        char type;
        std::cin >> type;
        if (type == 'S')
        {
            int i, k;
            std::cin >> i >> k;
            add_bit((i - 1) / bl, a[i], -1);
            a[i] = k;
            add_bit((i - 1) / bl, k, 1);
        }
        else
        {
            int l, r, k;
            std::cin >> l >> r >> k;
            int bL = (l - 1) / bl;
            int bR = (r - 1) / bl;
            int res = 0;

            if (bL == bR)
            {
                for (int i = l; i <= r; i++)
                {
                    res += (a[i] > k);
                }
            }
            else
            {
                for (int i = l; i <= (bL + 1) * bl; i++)
                {
                    res += (a[i] > k);
                }
                for (int b = bL + 1; b < bR; b++)
                {
                    res += sum_bit(b, maxv) - sum_bit(b, k);
                }

                for (int i = bR * bl + 1; i <= r; i++)
                {
                    res += (a[i] > k);
                }
            }

            std::cout << res << "\n";
        }
    }
}

