ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];
int st[4 * maxn + 7], lz[4 * maxn + 7];

void down(int id, int l, int r)
{
    if (lz[id])
    {
        int mid = (l + r) >> 1;

        st[id * 2] = (mid - l + 1) - st[id * 2];
        lz[id * 2] ^= 1;

        st[id * 2 + 1] = (r - mid) - st[id * 2 + 1];
        lz[id * 2 + 1] ^= 1;

        lz[id] = 0;
    }
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid = l + r >> 1;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
    st[id] = st[2 * id] + st[2 * id + 1];
}

void update(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] = (r - l + 1) - st[id];
        lz[id] ^= 1;
        return;
    }

    down(id, l, r);
    int mid = (l + r) >> 1;
    update(2 * id, l, mid, u, v);
    update(2 * id + 1, mid + 1, r, u, v);
    st[id] = st[2 * id] + st[2 * id + 1];
}

int query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    down(id, l, r);
    int mid = l + r >> 1;
    int get1 = query(2 * id, l, mid, u, v);
    int get2 = query(2 * id + 1, mid + 1, r, u, v);
    return get1 + get2;
}

void solve()
{
    std::cin >> n >> m;
    build(1, 1, n);
    while (m--)
    {
        int type, s, e;
        std::cin >> type >> s >> e;
        if (type == 0)
        {
            update(1, 1, n, s, e);
        }
        else
        {
            std::cout << query(1, 1, n, s, e) << "\n";
        }
    }
}

