ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int M, n;
int L[maxn + 7], R[maxn + 7];
int st[4 * maxn + 7];
int lazy[4 * maxn + 7];

struct Compress
{
    std::vector<int> vals;
    void add(int x)
    {
        if (x > 0)
            vals.push_back(x);
    }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(int x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size()
    {
        return vals.size();
    }
};

void push(int id)
{
    if (lazy[id])
    {
        st[id * 2] = 1;
        lazy[id * 2] = 1;
        st[id * 2 + 1] = 1;
        lazy[id * 2 + 1] = 1;
        lazy[id] = 0;
    }
}

void update(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] = 1;
        lazy[id] = 1;
        return;
    }
    push(id);
    int mid = (l + r) / 2;
    update(id * 2, l, mid, u, v);
    update(id * 2 + 1, mid + 1, r, u, v);
    st[id] = st[id * 2] | st[id * 2 + 1];
}

int query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    push(id);
    int mid = (l + r) / 2;
    return query(id * 2, l, mid, u, v) | query(id * 2 + 1, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> M >> n;

    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> L[i] >> R[i];
        if (L[i] > R[i])
        {
            std::swap(L[i], R[i]);
        }
        cmp.add(L[i]);
        cmp.add(R[i]);
        cmp.add(L[i] - 1);
        cmp.add(R[i] + 1);
    }
    cmp.init();

    int ans = 0;

    for (int i = n; i >= 1; i--)
    {
        int l = cmp.get(L[i]);
        int r = cmp.get(R[i]);

        if (query(1, 1, cmp.size(), l, r) == 0)
        {
            ans++;
        }
        update(1, 1, cmp.size(), l, r);
    }

    std::cout << ans;
}

