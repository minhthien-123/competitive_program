int n, m;
std::vector<int> adj[maxn + 7];
int a[maxn + 7];

struct EulerTour
{
    int n, timer;
    std::vector<int> tin, tout, tour;

    EulerTour(int n)
    {
        this->n = n;
        timer = 0;
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        tour.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        tour[timer] = u;
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        timer = 0;
        dfs(root, 0);
    }
};

int st[4 * maxn + 8], lz[4 * maxn + 8];
EulerTour et(0);

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = a[et.tour[l]];
        return;
    }

    int mid = (l + r) >> 1;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

void down(int id, int l, int r)
{
    if (lz[id])
    {
        int mid = (l + r) >> 1;

        lz[id * 2] += lz[id];
        st[id * 2] += (mid - l + 1) * lz[id];

        lz[id * 2 + 1] += lz[id];
        st[id * 2 + 1] += (r - mid) * lz[id];

        lz[id] = 0;
    }
}

void update(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        lz[id] += val;
        st[id] += (r - l + 1) * val;
        return;
    }

    down(id, l, r);
    int mid = (l + r) >> 1;
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

int query(int id, int l, int r, int pos)
{
    if (l == r)
    {
        return st[id];
    }
    down(id, l, r);
    int mid = (l + r) >> 1;
    if (pos <= mid)
    {
        return query(id * 2, l, mid, pos);
    }
    else
    {
        return query(id * 2 + 1, mid + 1, r, pos);
    }
}

void solve()
{
    std::cin >> n >> m;
    et = EulerTour(n);

    std::cin >> a[1];

    for (int i = 2; i <= n; i++)
    {
        int p;
        std::cin >> a[i] >> p;
        et.add_edge(p, i);
    }

    et.build();
    build(1, 1, n);

    for (int i = 1; i <= m; i++)
    {
        char type;
        std::cin >> type;
        if (type == 'p')
        {
            int u, x;
            std::cin >> u >> x;
            update(1, 1, n, et.tin[u] + 1, et.tout[u], x);
        }
        else if (type == 'u')
        {
            int u;
            std::cin >> u;
            std::cout << query(1, 1, n, et.tin[u]) << "\n";
        }
    }
}

