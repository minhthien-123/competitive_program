ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, delta;
int a[maxn + 7], f[maxn + 7];

struct node
{
    int mx, idx;
};
node st[4 * maxn + 7];

node merge(node a, node b)
{
    if (a.mx > b.mx)
    {
        return a;
    }
    return b;
}

void update(int id, int l, int r, int pos, int val, int idx)
{
    if (l == r)
    {
        if (val > st[id].mx)
        {
            st[id].mx = val;
            st[id].idx = idx;
        }
        return;
    }
    int mid = (l + r) >> 1;
    if (pos <= mid)
    {
        update(id * 2, l, mid, pos, val, idx);
    }
    else
    {
        update(id * 2 + 1, mid + 1, r, pos, val, idx);
    }
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

node query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return {0, 0};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) >> 1;
    return merge(query(id * 2, l, mid, u, v), query(id * 2 + 1, mid + 1, r, u, v));
}

struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

int dp[maxn + 7], trace[maxn + 7];

void solve()
{
    std::cin >> n >> delta;
    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> f[i];
        cmp.add(f[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        a[i] = cmp.get(f[i]);
    }

    int ans = 0, pos = -1;

    for (int i = 1; i <= n; i++)
    {
        int u = f[i] - delta;
        int v = f[i] + delta;

        int l = std::lower_bound(cmp.vals.begin(), cmp.vals.end(), u) - cmp.vals.begin() + 1;
        int r = std::upper_bound(cmp.vals.begin(), cmp.vals.end(), v) - cmp.vals.begin();

        if (l <= r)
        {
            node res = query(1, 1, cmp.size(), l, r);
            dp[i] = res.mx + 1;
            trace[i] = res.idx;
        }
        else
        {
            dp[i] = 1;
            trace[i] = 0;
        }

        if (dp[i] > ans)
        {
            ans = dp[i];
            pos = i;
        }

        update(1, 1, cmp.size(), a[i], dp[i], i);
    }

    std::vector<int> res;
    int cur = pos;
    while (cur != 0)
    {
        res.pb(f[cur]);
        cur = trace[cur];
    }
    std::reverse(all(res));
    std::cout << ans << "\n";
    for (int i : res)
    {
        std::cout << i << " ";
    }
}

