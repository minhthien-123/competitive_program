struct Matrix
{
    std::vector<std::vector<long long>> a;
    int r, c;

    Matrix(int r, int c, bool is_identity = false) : r(r), c(c)
    {
        a.assign(r, std::vector<long long>(c, 0));
        if (is_identity)
        {
            for (int i = 0; i < std::min(r, c); i++)
            {
                a[i][i] = 1;
            }
        }
    }

    Matrix operator*(const Matrix &other) const
    {
        Matrix res(r, other.c);
        for (int i = 0; i < r; i++)
        {
            for (int k = 0; k < c; k++)
            {
                if (a[i][k] == 0)
                {
                    continue;
                }
                for (int j = 0; j < other.c; j++)
                {
                    res.a[i][j] = (res.a[i][j] + a[i][k] * other.a[k][j]) % mod;
                }
            }
        }
        return res;
    }

    Matrix power(long long p)
    {
        Matrix res(r, c, true);
        Matrix base = *this;
        while (p > 0)
        {
            if (p & 1)
            {
                res = res * base;
            }
            base = base * base;
            p >>= 1;
        }
        return res;
    }
};

void solve()
{
    int m = sz(s);

    Matrix I(m, m);

    for (int len = 0; len < m; len++)
    {
        std::string cur = s.substr(0, len);
        for (char c = '0'; c <= '1'; c++)
        {
            std::string nxt = cur + c;

            if (sz(nxt) >= m && nxt.substr(sz(nxt) - m) == s)
            {
                continue;
            }

            int nxt_len = 0;
            for (int k = std::min(m - 1, sz(nxt)); k >= 1; k--)
            {
                if (nxt.substr(sz(nxt) - k) == s.substr(0, k))
                {
                    nxt_len = k;
                    break;
                }
            }

            I.a[nxt_len][len] = add(I.a[nxt_len][len], 1);
        }
    }

    Matrix res = I.power(n);

    ll ans = 0;
    for (int i = 0; i < m; i++)
    {
        ans = add(ans, res.a[i][0]);
    }

    std::cout << ans << "\n";
}

