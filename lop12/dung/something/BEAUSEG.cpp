ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];

int dp[maxn + 7][maxn + 7], old[maxn + 7][maxn + 7], pre[maxn + 7][maxn + 7];
int n, k, d;

void solve()
{
    std::cin >> n >> k >> d;

    for (int j = 0; j <= n; j++)
    {
        for (int v = 0; v <= n; v++)
        {
            dp[j][v] = 0;
        }
    }

    for (int v = 1; v <= std::min(n, d); v++)
    {
        dp[v][v] = 1;
    }

    for (int i = 2; i <= k; i++)
    {
        for (int j = 0; j <= n; j++)
        {
            for (int v = 0; v <= n; v++)
            {
                old[j][v] = dp[j][v];
                dp[j][v] = 0;
                pre[j][v] = 0;
            }
        }

        for (int j = 1; j <= n; j++)
        {
            for (int v = 1; v <= n; v++)
            {
                pre[j][v] = add(pre[j][v - 1], old[j][v]);
            }
        }

        for (int j = 1; j <= n; j++)
        {
            for (int v = i; v <= j; v++)
            {
                int psum = j - v;
                if (psum < 0)
                {
                    continue;
                }

                int R = v - 1;
                int L = std::max(1LL, v - d);

                if (L <= R)
                {
                    dp[j][v] = sub(pre[psum][R], pre[psum][L - 1]);
                }
            }
        }
    }

    int ans = 0;
    for (int v = 1; v <= n; v++)
    {
        ans = add(ans, dp[n][v]);
    }

    std::cout << ans;
}

