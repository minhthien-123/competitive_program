ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<ii> adj[maxn + 7];
int n, L, R;
int sz[maxn + 7];
bool flag[maxn + 7];

int q[maxn + 7];
double mx[maxn + 7];
double sub_mx[maxn + 7];

struct SubTree
{
    int max_dep, v, w;
    bool operator<(const SubTree &o) const
    {
        return max_dep < o.max_dep;
    }
};

std::vector<SubTree> subtrees[maxn + 7];
std::vector<int> child_cd[maxn + 7];
int root_cd;

void get_sz(int u, int p)
{
    sz[u] = 1;
    for (auto e : adj[u])
    {
        int v = e.fi;
        if (v == p || flag[v])
        {
            continue;
        }
        get_sz(v, u);
        sz[u] += sz[v];
    }
}

int get_centroid(int u, int p, int total_sz)
{
    for (auto e : adj[u])
    {
        int v = e.fi;
        if (v == p || flag[v])
        {
            continue;
        }
        if (sz[v] > total_sz / 2)
        {
            return get_centroid(v, u, total_sz);
        }
    }
    return u;
}

int get_max_dep(int u, int p, int d)
{
    int res = d;
    for (auto e : adj[u])
    {
        int v = e.fi;
        if (v != p && !flag[v])
        {
            res = std::max(res, get_max_dep(v, u, d + 1));
        }
    }
    return res;
}

int build_cd(int u)
{
    get_sz(u, 0);
    int centroid = get_centroid(u, 0, sz[u]);

    flag[centroid] = true;

    for (auto e : adj[centroid])
    {
        int v = e.fi, w = e.se;
        if (!flag[v])
        {
            int md = get_max_dep(v, centroid, 1);
            subtrees[centroid].pb({md, v, w});
        }
    }

    std::sort(all(subtrees[centroid]));

    for (auto e : adj[centroid])
    {
        int v = e.fi;
        if (!flag[v])
        {
            int nxt_c = build_cd(v);
            child_cd[centroid].pb(nxt_c);
        }
    }
    return centroid;
}

void get_dists(int u, int p, int d, double dist, double mid)
{
    sub_mx[d] = std::max(sub_mx[d], dist);
    for (auto e : adj[u])
    {
        int v = e.fi, w = e.se;
        if (v != p && !flag[v])
        {
            get_dists(v, u, d + 1, dist + w - mid, mid);
        }
    }
}

bool check_cd(int c, double mid)
{
    flag[c] = true;
    int mx_pre = 0;
    mx[0] = 0;
    bool found = false;

    for (auto sub : subtrees[c])
    {
        int md = sub.max_dep;
        int v = sub.v;
        int w = sub.w;

        for (int i = 1; i <= md; i++)
        {
            sub_mx[i] = -INF;
        }
        get_dists(v, c, 1, w - mid, mid);

        int head = 1, tail = 0;
        int cur_add = 0;

        for (int d = md; d >= 1; d--)
        {
            int up = R - d;
            int low = L - d;

            while (cur_add <= up && cur_add <= mx_pre)
            {
                while (head <= tail && mx[q[tail]] <= mx[cur_add])
                {
                    tail--;
                }
                q[++tail] = cur_add;
                cur_add++;
            }

            while (head <= tail && q[head] < low)
            {
                head++;
            }

            if (head <= tail && sub_mx[d] + mx[q[head]] >= 0)
            {
                found = true;
                break;
            }
        }

        if (found)
        {
            break;
        }

        for (int d = 1; d <= md; d++)
        {
            mx[d] = std::max(mx[d], sub_mx[d]);
        }
        mx_pre = std::max(mx_pre, md);
    }

    for (int i = 0; i <= mx_pre; i++)
    {
        mx[i] = -INF;
    }

    if (found)
    {
        return true;
    }

    for (int nxt_c : child_cd[c])
    {
        if (check_cd(nxt_c, mid))
        {
            return true;
        }
    }
    return false;
}

bool check(double mid)
{
    for (int i = 1; i <= n; i++)
    {
        flag[i] = false;
    }
    return check_cd(root_cd, mid);
}

void solve()
{
    std::cin >> n >> L >> R;
    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    for (int i = 0; i <= n + 2; i++)
    {
        mx[i] = -INF;
        sub_mx[i] = -INF;
    }

    root_cd = build_cd(1);

    double l = -1e6, r = 1e6, ans = 0;
    for (int step = 0; step < 50; step++)
    {
        double mid = l + (r - l) / 2.0;
        if (check(mid))
        {
            ans = mid;
            l = mid;
        }
        else
        {
            r = mid;
        }
    }

    std::cout << std::fixed << std::setprecision(3) << ans << "\n";
}

