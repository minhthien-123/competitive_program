ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ii a[maxn + 7];

int st[4 * maxn];

void build(int id, int l, int r)
{
    st[id] = 1;
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
}

void update(int id, int l, int r, int pos)
{
    if (l == r)
    {
        st[id] = 0;
        return;
    }
    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        update(2 * id, l, mid, pos);
    }
    else
    {
        update(2 * id + 1, mid + 1, r, pos);
    }
    st[id] = st[2 * id] | st[2 * id + 1];
}

int walk(int id, int l, int r, int L)
{
    if (st[id] == 0 || r < L)
    {
        return 0;
    }

    if (l == r)
    {
        return l;
    }

    int mid = (l + r) / 2;

    int res = walk(2 * id, l, mid, L);

    if (res == 0)
    {
        res = walk(2 * id + 1, mid + 1, r, L);
    }

    return res;
}

bool check(int k)
{
    std::vector<ii> vec;
    for (int i = 1; i <= k; i++)
    {
        vec.pb({a[i].se, a[i].fi});
    }

    std::sort(all(vec));

    build(1, 1, m);

    for (auto p : vec)
    {
        int L = p.se;
        int R = p.fi;

        int pos = walk(1, 1, m, L);

        if (pos == 0 || pos > R)
        {
            return false;
        }

        update(1, 1, m, pos);
    }
    return true;
}

void solve()
{
    std::cin >> m >> n;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].fi >> a[i].se;
    }

    int l = 1, r = std::min(n, m);
    int ans = 0;

    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << ans << "\n";
}

