const int maxn = 1e3;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ii obs[maxn + 7], ball[maxn + 7];
bool g[maxn + 7][maxn + 7];
int d[maxn + 7][maxn + 7];
int f[maxn + 7][maxn + 7];
int cnt[maxn + 7][maxn + 7];

int dist(ii a, ii b)
{
    return std::abs(a.fi - b.fi) + std::abs(a.se - b.se);
}

void bfs(int sx, int sy)
{
    std::queue<ii> q;
    for (int i = 0; i <= 200; i++)
    {
        for (int j = 0; j <= 200; j++)
        {
            d[i][j] = inf;
        }
    }

    d[sx][sy] = 0;
    q.push({sx, sy});

    while (q.size())
    {
        auto tmp = q.front();
        q.pop();
        int x = tmp.fi, y = tmp.se;

        for (int k = 0; k < 4; k++)
        {
            int nx = x + dx[k];
            int ny = y + dy[k];

            if (nx < 0 || nx > 200 || ny < 0 || ny > 200)
            {
                continue;
            }
            if (g[nx][ny])
            {
                continue;
            }
            if (d[nx][ny] > d[x][y] + 1)
            {
                d[nx][ny] = d[x][y] + 1;
                q.push({nx, ny});
            }
        }
    }

    for (int i = 0; i <= 200; i++)
    {
        for (int j = 0; j <= 200; j++)
        {
            if (d[i][j] < inf)
            {
                f[i][j] += d[i][j];
                cnt[i][j]++;
            }
        }
    }
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> obs[i].fi >> obs[i].se;
    }
    std::cin >> m;
    for (int i = 1; i <= m; i++)
    {
        std::cin >> ball[i].fi >> ball[i].se;
    }

    if (n == 0)
    {
        std::vector<int> x, y;
        for (int i = 1; i <= m; i++)
        {
            x.pb(ball[i].fi);
            y.pb(ball[i].se);
        }
        std::sort(all(x));
        std::sort(all(y));
        int X = x[sz(x) / 2];
        int Y = y[sz(y) / 2];
        int res = 0;
        for (int i = 1; i <= m; i++)
        {
            res += std::abs(ball[i].fi - X) + std::abs(ball[i].se - Y);
        }
        std::cout << res;
        return;
    }

    for (int i = 1; i <= n; i++)
    {
        g[obs[i].fi][obs[i].se] = true;
    }

    for (int i = 1; i <= m; i++)
    {
        bfs(ball[i].fi, ball[i].se);
    }

    int ans = inf;
    for (int x = 0; x <= 200; x++)
    {
        for (int y = 0; y <= 200; y++)
        {
            if (!g[x][y] && cnt[x][y] == m)
            {
                ans = std::min(ans, f[x][y]);
            }
        }
    }

    std::cout << (ans == inf ? -1 : ans);
}

