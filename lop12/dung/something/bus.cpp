ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, k;
int a[maxn + 7];
int dp[maxn + 7][200];
ld pre[maxn + 7], presq[maxn + 7];

struct DnC_DP
{
    int n, k;
    std::vector<std::vector<ld>> dp;
    const ld INF = 1e18;

    int mo_l = 1, mo_r = 0;
    long long current_cost = 0;

    DnC_DP(int n, int k) : n(n), k(k)
    {
        dp.assign(k + 1, std::vector<ld>(n + 7, INF));
    }

    ld cost(int l, int r)
    {
        ld len = r - l + 1;
        ld s = pre[r] - pre[l - 1];
        ld ssq = presq[r] - presq[l - 1];
        return ssq - s * s / len;
    }

    void compute(int dp_idx, int l, int r, int opt_l, int opt_r)
    {
        if (l > r)
            return;
        int mid = (l + r) / 2;
        int best_k = -1;
        ld best_val = INF;

        for (int j = opt_l; j <= std::min(mid - 1, opt_r); j++)
        {
            if (dp[dp_idx - 1][j] != INF)
            {
                ld cur_val = dp[dp_idx - 1][j] + cost(j + 1, mid);
                if (cur_val < best_val)
                {
                    best_val = cur_val;
                    best_k = j;
                }
            }
        }

        dp[dp_idx][mid] = best_val;
        int safe_opt = (best_k == -1) ? opt_l : best_k;

        compute(dp_idx, l, mid - 1, opt_l, safe_opt);
        compute(dp_idx, mid + 1, r, safe_opt, opt_r);
    }

    void solve()
    {
        dp[0][0] = 0;
        for (int i = 1; i <= k; i++)
        {
            compute(i, 1, n, 0, n - 1);
        }
    }
};

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    std::sort(a + 1, a + n + 1);

    for (int i = 1; i <= n; i++)
    {
        pre[i] = pre[i - 1] + a[i];
        presq[i] = presq[i - 1] + a[i] * a[i];
    }

    DnC_DP dnc(n, k);
    dnc.solve();

    std::cout << std::fixed << std::setprecision(6) << dnc.dp[k][n];
}

