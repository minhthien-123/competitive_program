ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

struct Point
{
    int x, y;
};

int n, k, mxy;
Point pts[maxn + 7];

bool cmp(Point a, Point b)
{
    if (a.x != b.x)
    {
        return a.x < b.x;
    }
    return a.y < b.y;
}

bool check(int mid)
{
    FenwickTree bit(mxy + 5);
    int L = 1;
    int cnt = 0;

    for (int R = 1; R <= n; R++)
    {
        while (pts[R].x - pts[L].x > mid)
        {
            bit.add(pts[L].y + 1, 1);
            L++;
        }

        cnt += (R - L);

        int l = std::max(1LL, pts[R].y + 1 - mid);
        int r = std::min(mxy + 2, pts[R].y + 1 + mid);
        cnt += bit.sum(l, r);
    }

    if (cnt >= k)
    {
        return true;
    }
    return false;
}

void solve()
{
    std::cin >> n >> k;

    mxy = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> pts[i].x >> pts[i].y;
        if (pts[i].y > mxy)
        {
            mxy = pts[i].y;
        }
    }

    std::sort(pts + 1, pts + n + 1, cmp);

    int l = 0;
    int r = 1e5;
    int ans = -1;

    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    std::cout << ans;
}

