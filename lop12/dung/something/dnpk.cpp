ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, k;
int f[maxn + 7][maxn + 7];

int Try(int i, int j)
{
    if (i > n && j < k)
    {
        return 1;
    }

    if (f[i][j] != -1)
    {
        return f[i][j];
    }

    f[i][j] = 0;
    f[i][j] += Try(i + 1, 0);
    if (j + 1 < k)
    {
        f[i][j] += Try(i + 1, j + 1);
    }
    return f[i][j] % mod;
}

void solve()
{
    memset(f, -1, sizeof(f));
    std::cout << Try(1, 0) << "\n";
}

