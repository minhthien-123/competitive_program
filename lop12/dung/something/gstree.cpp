ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 7];
int idx[maxn + 7];
int par[maxn + 7];

int acs(int u)
{
    return u == par[u] ? u : par[u] = acs(par[u]);
}

void join(int u, int v)
{
    u = acs(u);
    v = acs(v);

    if (u != v)
    {
        par[v] = u;
    }
}

void solve()
{
    std::cin >> n;

    for (int i = 1; i <= n; i++)
    {
        par[i] = i;
    }

    ll ans = 0;
    int cnt = 0;
    ll mx = 0;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        mx = std::max(mx, a[i]);

        if (idx[a[i]] == 0)
        {
            idx[a[i]] = i;
        }
        else
        {
            int u = i;
            int v = idx[a[i]];
            if (acs(u) != acs(v))
            {
                join(u, v);
                ans += (123456LL - a[i]);
                cnt++;
            }
        }
    }

    for (int g = mx; g >= 1; g--)
    {
        if (cnt == n - 1)
        {
            break;
        }

        int u = 0;
        for (int mult = g; mult <= mx; mult += g)
        {
            if (idx[mult] != 0)
            {
                int v = idx[mult];
                if (u == 0)
                {
                    u = v;
                }
                else
                {
                    if (acs(u) != acs(v))
                    {
                        join(u, v);
                        ans += (123456LL - g);
                        cnt++;
                        if (cnt == n - 1)
                        {
                            break;
                        }
                    }
                }
            }
        }
    }

    std::cout << ans;
}

