ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int p[maxn + 7];
ll w[maxn + 7], t[maxn + 7];
int dsu[maxn + 7];

int acs(int u)
{
    return u == dsu[u] ? u : dsu[u] = acs(dsu[u]);
}

struct pt
{
    int id;
    ll w, t;
    friend bool operator<(pt a, pt b)
    {
        ll l = a.w * b.t;
        ll r = a.t * b.w;
        if (l != r)
        {
            return l > r;
        }
        return (a.id < b.id);
    }
};

std::set<pt> s;

void solve()
{
    std::cin >> n;
    for (int i = 0; i < n; i++)
    {
        std::cin >> p[i];
    }
    for (int i = 0; i < n; i++)
    {
        std::cin >> w[i];
    }
    for (int i = 0; i < n; i++)
    {
        std::cin >> t[i];
    }

    ll ans = 0;
    for (int i = 0; i < n; i++)
    {
        ans += t[i] * w[i];
        dsu[i] = i;
        if (i != 0)
        {
            s.insert({i, w[i], t[i]});
        }
    }

    while (!s.empty())
    {
        pt c = *s.begin();
        s.erase(s.begin());

        int u = c.id;
        int par = acs(p[u]);

        if (par != 0)
        {
            s.erase({par, w[par], t[par]});
        }

        ans += t[par] * w[u];
        w[par] += w[u];
        t[par] += t[u];
        dsu[u] = par;

        if (par != 0)
        {
            s.insert({par, w[par], t[par]});
        }
    }

    std::cout << ans << "\n";
}

