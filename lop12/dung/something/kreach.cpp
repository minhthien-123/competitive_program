struct Matrix
{
    std::vector<std::vector<long long>> a;
    int r, c;

    Matrix(int r, int c, bool is_identity = false) : r(r), c(c)
    {
        a.assign(r, std::vector<long long>(c, 0));
        if (is_identity)
        {
            for (int i = 0; i < std::min(r, c); i++)
                a[i][i] = 1;
        }
    }

    Matrix operator*(const Matrix &other) const
    {
        Matrix res(r, other.c);
        for (int i = 0; i < r; i++)
        {
            for (int k = 0; k < c; k++)
            {
                if (a[i][k] == 0)
                    continue;
                for (int j = 0; j < other.c; j++)
                {
                    res.a[i][j] = (res.a[i][j] + a[i][k] * other.a[k][j]) % mod;
                }
            }
        }
        return res;
    }

    Matrix power(long long p)
    {
        Matrix res(r, c, true);
        Matrix base = *this;
        while (p > 0)
        {
            if (p & 1)
                res = res * base;
            base = base * base;
            p >>= 1;
        }
        return res;
    }
};

bool vis[maxn + 7][maxn + 7][33];
bool cur[maxn + 7], nxt[maxn + 7];
int n, m, q;

void solve()
{
    std::cin >> n >> m;

    for (int i = 1; i <= m; i++)
    {
        int l, r;
        std::cin >> l >> r;
        vis[l][r][0] = 1;
    }

    for (int p = 1; p <= 30; p++)
    {
        for (int i = 1; i <= n; i++)
        {
            for (int j = 1; j <= n; j++)
            {
                for (int mid = 1; mid <= n; mid++)
                {
                    if (vis[i][mid][p - 1] && vis[mid][j][p - 1])
                    {
                        vis[i][j][p] = 1;
                    }
                }
            }
        }
    }

    std::cin >> q;
    while (q--)
    {
        int u, k;
        std::cin >> u >> k;

        for (int i = 1; i <= n; i++)
        {
            cur[i] = 0;
        }
        cur[u] = 1;

        for (int i = 31; i >= 0; i--)
        {
            if (!((k >> i) & 1))
            {
                continue;
            }
            for (int j = 1; j <= n; j++)
            {
                nxt[j] = 0;
                for (int l = 1; l <= n; l++)
                {
                    if (cur[l] && vis[l][j][i])
                    {
                        nxt[j] = 1;
                        break;
                    }
                }
            }
            for (int j = 1; j <= n; j++)
            {
                cur[j] = nxt[j];
            }
        }

        int cnt = 0;
        for (int j = 1; j <= n; j++)
        {
            cnt += cur[j];
        }
        std::cout << cnt << '\n';
    }
}

