ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int m, n, C;
int a[maxn + 7][maxn + 7], c[maxn + 7][maxn + 7];
int dp1[maxn + 7][maxn + 7], dp2[maxn + 7][maxn + 7], dp3[maxn + 7][maxn + 7];

void solve()
{
    std::cin >> m >> n >> C;
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
        }
    }
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> c[i][j];
        }
    }

    for (int i = 0; i <= m + 1; i++)
    {
        for (int j = 0; j <= n + 1; j++)
        {
            dp1[i][j] = dp2[i][j] = dp3[i][j] = -INF;
        }
    }

    for (int j = 1; j <= n; j++)
    {
        dp1[1][j] = c[1][j];
    }
    for (int i = 2; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            int mx = -INF;
            if (j > 1)
            {
                mx = std::max(mx, dp1[i - 1][j - 1]);
            }
            mx = std::max(mx, dp1[i - 1][j]);
            if (j < n)
            {
                mx = std::max(mx, dp1[i - 1][j + 1]);
            }
            if (mx != -INF)
            {
                dp1[i][j] = mx + c[i][j];
            }
        }
    }

    for (int j = 1; j <= n; j++)
    {
        dp2[m][j] = c[m][j];
    }
    for (int i = m - 1; i >= 1; i--)
    {
        for (int j = 1; j <= n; j++)
        {
            int mx = -INF;
            if (j > 1)
            {
                mx = std::max(mx, dp2[i + 1][j - 1]);
            }
            mx = std::max(mx, dp2[i + 1][j]);
            if (j < n)
            {
                mx = std::max(mx, dp2[i + 1][j + 1]);
            }
            if (mx != -INF)
            {
                dp2[i][j] = mx + c[i][j];
            }
        }
    }

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            int mx = -INF;
            if (i > 1)
            {
                if (j > 1)
                {
                    mx = std::max(mx, dp3[i - 1][j - 1]);
                }
                mx = std::max(mx, dp3[i - 1][j]);
                if (j < n)
                {
                    mx = std::max(mx, dp3[i - 1][j + 1]);
                }
            }
            if (mx != -INF)
            {
                dp3[i][j] = mx + c[i][j];
            }
            if (a[i][j])
            {
                dp3[i][j] = std::max(dp3[i][j], c[i][j]);
            }
        }
    }

    int ans = -INF;
    for (int j = 1; j <= n; j++)
    {
        ans = std::max(ans, dp1[m][j]);
    }

    int A = -INF, B = -INF, D = -INF;

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (a[i][j])
            {
                A = std::max(A, dp1[i][j]);
                B = std::max(B, dp2[i][j]);
                D = std::max(D, dp3[i][j]);
            }
        }
    }

    if (C == 1)
    {
        ans = std::max(ans, A + B);
    }
    else if (C >= 2)
    {
        ans = std::max(ans, A + D * (C - 1) + B);
    }

    std::cout << ans;
}

