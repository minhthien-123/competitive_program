ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int dp[maxn + 7][11];
int digit[maxn + 7];
int n;
int a, b;

int f(int pos, bool tight, bool lead, int last)
{
    if (pos == n)
    {
        return 1;
    }

    int &memo = dp[pos][last];
    if (tight && !lead && memo != -1)
    {
        return memo;
    }

    int lim = tight ? 9 : digit[pos];
    int res = 0;
    for (int i = 0; i <= lim; i++)
    {
        if (lead && i == 0)
        {
            res += f(pos + 1, tight || (i < lim), 1, 10);
        }
        else
        {
            if (i == 3 && last == 1)
            {
                continue;
            }
            res += f(pos + 1, tight || (i < lim), 0, i);
        }
    }

    if (tight && !lead)
    {
        memo = res;
    }
    return res;
}

int g(int k)
{
    if (k < 0)
    {
        return 0;
    }
    std::vector<int> tmp;
    if (k == 0)
    {
        tmp.pb(0);
    }
    while (k > 0)
    {
        tmp.pb(k % 10);
        k /= 10;
    }
    std::reverse(tmp.begin(), tmp.end());
    n = tmp.size();
    for (int i = 0; i < tmp.size(); i++)
    {
        digit[i] = tmp[i];
    }

    memset(dp, -1, sizeof dp);
    return f(0, 0, 1, 10);
}

void solve()
{
    std::cout << g(b) - g(a - 1) << "\n";
}

