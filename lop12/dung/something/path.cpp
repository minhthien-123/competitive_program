const int maxn = 1e3;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
char a[maxn + 8][maxn + 8];
int d[maxn + 7][maxn + 7];

void bfs()
{
    std::deque<ii> dq;
    for (int i = 2; i < m; i++)
    {
        if (a[i][1] == '.')
        {
            d[i][1] = 1;
        }
        else
        {
            d[i][1] = 0;
        }
        if (a[i][1] == '#')
        {
            dq.push_front({i, 1});
        }
        else
        {
            dq.push_back({i, 1});
        }
    }

    while (!dq.empty())
    {
        int x = dq.front().fi;
        int y = dq.front().se;
        dq.pop_front();
        for (int i = 0; i <= 7; i++)
        {
            int nx = x + dx[i];
            int ny = y + dy[i];
            if (nx < 2 || nx >= m || ny < 1 || ny > n)
            {
                continue;
            }
            int tmp;
            if (a[nx][ny] == '.')
            {
                tmp = 1;
            }
            else
            {
                tmp = 0;
            }
            if (d[nx][ny] > d[x][y] + tmp)
            {
                d[nx][ny] = d[x][y] + tmp;
                if (tmp == 0)
                {
                    dq.push_front({nx, ny});
                }
                else
                {
                    dq.push_back({nx, ny});
                }
            }
        }
    }   
}

void solve()
{   
    std::cin >> m >> n;
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
            d[i][j] = inf;
        }
    }

    bfs();

    int ans = inf;
    for (int i = 2; i < m; i++)
    {
        ans = std::min(ans, d[i][n]);
    }

    std::cout << ans;
}

