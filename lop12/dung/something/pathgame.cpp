const int maxn = 1e3;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, q;
char a[maxn + 7][maxn + 7];
int d[maxn + 7][maxn + 7];

bool valid(int x, int y)
{
    return (x >= 1 && x <= m && y >= 1 && y <= n);
}

std::deque<ii> dq;
void bfs()
{
    while (!dq.empty())
    {
        int x = dq.front().fi;
        int y = dq.front().se;
        dq.pop_front();
        for (int i = 0; i < 4; i++)
        {
            int nx = x + dx[i];
            int ny = y + dy[i];
            if (!valid(nx, ny))
            {
                continue;
            }

            int cost = 0;
            if (a[nx][ny] != a[x][y])
            {
                cost = 1;
            }

            if (d[nx][ny] > d[x][y] + cost)
            {
                d[nx][ny] = d[x][y] + cost;
                if (cost == 0)
                {
                    dq.push_front({nx, ny});
                }
                else
                {
                    dq.pb({nx, ny});
                }
            }
        }
    }
}

void solve()
{
    std::cin >> m >> n >> q;
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
            if (a[i][j] == '*')
            {
                d[i][j] = 0;
                dq.push_back({i, j});
            }
            else
            {
                d[i][j] = inf;
            }
        }
    }

    bfs();

    while (q--)
    {
        int x, y;
        std::cin >> x >> y;
        std::cout << d[x][y] << "\n";
        
    }

    
}

