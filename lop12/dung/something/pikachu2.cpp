ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int f[maxn][maxn], a[maxn][maxn];
int d[maxn][maxn];
std::vector<std::pair<ii, ii>> pairs;

int bfs(int s, int t, int sx, int sy, int k)
{
    for (int i = 0; i <= n + 1; i++)
    {
        for (int j = 0; j <= m + 1; j++)
        {
            d[i][j] = inf;
        }
    }

    std::queue<ii> q;
    d[s][t] = 0;
    q.push({s, t});

    while (!q.empty())
    {
        int u = q.front().fi;
        int v = q.front().se;
        q.pop();

        if (d[u][v] == k)
        {
            continue;
        }

        for (int i = u + 1; i <= n + 1; i++)
        {
            if (i == sx && v == sy)
            {
                return d[u][v] + 1;
            }
            if (a[i][v] != 0)
            {
                break;
            }
            if (d[i][v] > d[u][v] + 1)
            {
                d[i][v] = d[u][v] + 1;
                q.push({i, v});
            }
        }

        for (int i = u - 1; i >= 0; i--)
        {
            if (i == sx && v == sy)
            {
                return d[u][v] + 1;
            }
            if (a[i][v] != 0)
            {
                break;
            }
            if (d[i][v] > d[u][v] + 1)
            {
                d[i][v] = d[u][v] + 1;
                q.push({i, v});
            }
        }

        for (int j = v + 1; j <= m + 1; j++)
        {
            if (u == sx && j == sy)
            {
                return d[u][v] + 1;
            }
            if (a[u][j] != 0)
            {
                break;
            }
            if (d[u][j] > d[u][v] + 1)
            {
                d[u][j] = d[u][v] + 1;
                q.push({u, j});
            }
        }

        for (int j = v - 1; j >= 0; j--)
        {
            if (u == sx && j == sy)
            {
                return d[u][v] + 1;
            }
            if (a[u][j] != 0)
            {
                break;
            }
            if (d[u][j] > d[u][v] + 1)
            {
                d[u][j] = d[u][v] + 1;
                q.push({u, j});
            }
        }
    }
    return inf;
}

bool check(int k)
{
    for (int i = 0; i < sz(pairs); i++)
    {
        int r1 = pairs[i].fi.fi;
        int c1 = pairs[i].fi.se;
        int r2 = pairs[i].se.fi;
        int c2 = pairs[i].se.se;
        a[r1][c1] = f[r1][c1];
        a[r2][c2] = f[r2][c2];
    }

    int cnt = sz(pairs);
    std::vector<bool> removed(sz(pairs), false);

    bool changed = true;
    while (changed)
    {
        changed = false;
        for (int i = 0; i < sz(pairs); i++)
        {
            if (!removed[i])
            {
                int r1 = pairs[i].fi.fi;
                int c1 = pairs[i].fi.se;
                int r2 = pairs[i].se.fi;
                int c2 = pairs[i].se.se;

                if (bfs(r1, c1, r2, c2, k) <= k)
                {
                    a[r1][c1] = 0;
                    a[r2][c2] = 0;
                    removed[i] = true;
                    changed = true;
                    cnt--;
                }
            }
        }
    }

    return cnt == 0;
}

void solve()
{
    std::cin >> n >> m;
    std::map<int, ii> pos;
    pairs.clear();

    for (int i = 0; i <= n + 1; i++)
    {
        for (int j = 0; j <= m + 1; j++)
        {
            f[i][j] = 0;
            a[i][j] = 0;
        }
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> f[i][j];
            a[i][j] = f[i][j];
            if (f[i][j] != 0)
            {
                if (pos.count(f[i][j]))
                {
                    pairs.pb({pos[f[i][j]], {i, j}});
                }
                else
                {
                    pos[f[i][j]] = {i, j};
                }
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (pos[f[i][j]] == ii(i, j))
            {
                f[i][j] = 0;
                a[i][j] = 0;
            }
        }
    }

    int l = 1;
    int r = 4;
    int ans = -1;

    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    std::cout << ans << "\n";
}

