ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    int mid = n / 2;
    std::vector<int> v1, v2;

    for (int mask = 0; mask < (1 << mid); mask++)
    {
        int sum = 0;
        for (int i = 0; i < mid; i++)
        {
            if (mask & (1 << i))
            {
                sum = (sum + a[i + 1]) % m;
            }
        }
        v1.push_back(sum);
    }

    int rem = n - mid;
    for (int mask = 0; mask < (1 << rem); mask++)
    {
        int sum = 0;
        for (int i = 0; i < rem; i++)
        {
            if (mask & (1 << i))
            {
                sum = (sum + a[mid + i + 1]) % m;
            }
        }
        v2.push_back(sum);
    }

    std::sort(v2.begin(), v2.end());
    v2.erase(std::unique(v2.begin(), v2.end()), v2.end());

    int ans = 0;
    for (int x : v1)
    {
        auto it = std::upper_bound(v2.begin(), v2.end(), m - 1 - x);
        if (it != v2.begin())
        {
            ans = std::max(ans, x + *std::prev(it));
        }
        ans = std::max(ans, (x + v2.back()) % m);
    }
    std::cout << ans;
}

