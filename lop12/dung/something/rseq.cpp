ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7], f[maxn + 7];
bool flag[maxn + 7], check[maxn + 7];

struct DSU
{
    std::vector<int> par, sz, sum;

    DSU(int n)
    {
        par.resize(n + 7);
        sum.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
            sum[u] += sum[v];
        }
    }
};

int res[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int i = 1; i <= m; i++)
    {
        std::cin >> f[i];
        flag[f[i]] = 1;
    }

    DSU dsu(n);

    int cur = 0;

    for (int i = 1; i <= n; i++)
    {
        if (!flag[i])
        {
            check[i] = true;

            dsu.sum[i] = a[i];
            cur = std::max(cur, dsu.sum[i]);
            if (i > 1 && check[i - 1])
            {
                dsu.join(i, i - 1);
                cur = std::max(cur, dsu.sum[dsu.acs(i)]);
            }
        }
    }
    res[m] = cur;

    for (int i = m; i >= 1; i--)
    {
        int pos = f[i];
        check[pos] = 1;
        dsu.sum[pos] = a[pos];
        cur = std::max(cur, dsu.sum[pos]);
        if (pos > 1 && check[pos - 1])
        {
            dsu.join(pos, pos - 1);
        }
        if (pos < n && check[pos + 1])
        {
            dsu.join(pos, pos + 1);
        }
        cur = std::max(cur, dsu.sum[dsu.acs(pos)]);
        res[i - 1] = cur;
    }

    for (int i = 1; i <= m; i++)
    {
        std::cout << res[i] << "\n";
    }
}

