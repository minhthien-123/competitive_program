ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int m, n, k;
std::string x, y;
int dp[maxn + 7][maxn + 7][maxn + 7];
int nxtx[maxn + 7][27], nxty[maxn + 7][27];

void solve()
{
    std::cin >> m >> n >> k;
    std::cin >> x >> y;
    int lenx = sz(x);
    int leny = sz(y);
    x = " " + x;
    y = " " + y;

    for (int c = 0; c < 26; c++)
    {
        nxtx[lenx][c] = lenx + 1;
        nxtx[lenx + 1][c] = lenx + 1;
    }
    for (int i = lenx - 1; i >= 0; i--)
    {
        for (int c = 0; c < 26; c++)
        {
            nxtx[i][c] = nxtx[i + 1][c];
        }
        nxtx[i][x[i + 1] - 'a'] = i + 1;
    }

    for (int c = 0; c < 26; c++)
    {
        nxty[leny][c] = leny + 1;
        nxty[leny + 1][c] = leny + 1;
    }
    for (int i = leny - 1; i >= 0; i--)
    {
        for (int c = 0; c < 26; c++)
        {
            nxty[i][c] = nxty[i + 1][c];
        }
        nxty[i][y[i + 1] - 'a'] = i + 1;
    }

    for (int i = 1; i <= lenx; i++)
    {
        dp[0][i][leny + 1] = 1;
    }

    for (int len = 1; len <= n; len++)
    {
        for (int i = 0; i <= lenx; i++)
        {
            for (int j = 0; j <= leny + 1; j++)
            {
                int sum = 0;
                for (int c = 0; c < 26; c++)
                {
                    if (nxtx[i][c] <= lenx)
                    {
                        sum += dp[len - 1][nxtx[i][c]][nxty[j][c]];
                    }
                }
                dp[len][i][j] = sum % k;
            }
        }
    }

    while (m--)
    {
        std::string s;
        std::cin >> s;
        int lens = sz(s);
        s = " " + s;
        int posx = 0;
        int posy = 0;
        for (int i = 1; i <= lens; i++)
        {
            posx = nxtx[posx][s[i] - 'a'];
            posy = nxty[posy][s[i] - 'a'];
        }

        if (posx > lenx)
        {
            std::cout << "-1\n";
        }
        else
        {
            if (posy <= leny)
            {
                std::cout << "-1\n";
            }
            else
            {
                int ans = 1;
                posx = 0;
                posy = 0;
                for (int i = 1; i <= lens; i++)
                {
                    for (int c = 0; c < s[i] - 'a'; c++)
                    {
                        ans = (ans + dp[n - i][nxtx[posx][c]][nxty[posy][c]]) % k;
                    }
                    posx = nxtx[posx][s[i] - 'a'];
                    posy = nxty[posy][s[i] - 'a'];
                }
                std::cout << ans << "\n";
            }
        }
    }
}

