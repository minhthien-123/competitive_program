ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct pt
{
    int c, v, w, cost, efec;
};

int calc(pt x, int s)
{
    return s * (x.v - x.w * (s - 1) / 2);
}

int n, m;
pt a[maxn + 7];
int T[maxn + 7];
int freq[maxv + 7][maxv + 7];
int dp[maxv + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].c >> a[i].v >> a[i].w;

        for (int val = a[i].v; val > 0; val -= a[i].w)
        {
            freq[a[i].c][val]++;
        }
    }

    std::vector<ii> vec;
    for (int c = 1; c <= maxv; c++)
    {
        int lim = maxv / c;
        int cnt = 0;

        for (int val = maxv; val >= 1; val--)
        {
            while (freq[c][val] && cnt < lim)
            {
                vec.pb({c, val});
                cnt++;
                freq[c][val]--;
            }

            if (cnt == lim)
            {
                break;
            }
        }
    }

    for (auto [c, val] : vec)
    {
        for (int s = maxv; s >= c; s--)
        {
            dp[s] = std::max(dp[s], dp[s - c] + val);
        }
    }

    for (int i = 1; i <= m; i++)
    {
        std::cin >> T[i];
        int ans = 0;
        for (int s = 1; s <= T[i]; s++)
        {
            ans = std::max(ans, dp[s]);
        }
        std::cout << ans << " ";
    }
}

