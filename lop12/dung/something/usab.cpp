int calc(int pos, int cur, int X)
{
    if (pos > m)
    {
        return 1;
    }
    if (cur > X / p[m])
    {
        return 1;
    }

    int res = 0;
    for (int i = 0; i <= k[pos]; i++)
    {
        res += calc(pos + 1, cur, X);
        if (cur > X / p[pos])
        {
            break;
        }
        cur *= p[pos];
    }
    return res;
}

void solve()
{
    std::cin >> m;
    std::vector<ii> primes;
    for (int i = 1; i <= m; i++)
    {
        int pi, ki;
        std::cin >> pi >> ki;
        primes.pb({pi, ki});
    }

    std::sort(primes.rbegin(), primes.rend());
    for (int i = 1; i <= m; i++)
    {
        p[i] = primes[i - 1].fi;
        k[i] = primes[i - 1].se;
    }

    for (int i = 1; i <= 3; i++)
    {
        int A, B;
        std::cin >> A >> B;
        int ans2 = 0;
        int ans1 = 0;

        if (B >= 1)
        {
            ans2 = calc(1, 1, B);
        }
        if (A - 1 >= 1)
        {
            ans1 = calc(1, 1, A - 1);
        }

        std::cout << ans2 - ans1 << "\n";
    }
}

