ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, k;
int dp[maxn + 7][maxn + 7][2];

int calc(int pos, int cnt, bool check)
{
    if (pos > n)
    {
        return (check || cnt != n - cnt);
    }

    int &memo = dp[pos][cnt][check];
    if (memo != -1)
    {
        return memo;
    }

    int res = 0;
    res += calc(pos + 1, cnt + 1, check);
    if (!check)
    {
        if (cnt < pos - cnt)
        {
            res += calc(pos + 1, cnt, 1);
        }
        else
        {
            res += calc(pos + 1, cnt, 0);
        }
    }
    else
    {
        res += calc(pos + 1, cnt, 1);
    }

    return memo = res;
}

void solve()
{
    std::cin >> n >> k;
    memset(dp, -1, sizeof dp);
    int tmp = calc(1, 0, 0);
    std::string s = "";
    int cnt = 0;
    bool check = false;
    for (int i = 1; i <= n; i++)
    {
        int cnt1 = calc(i + 1, cnt + 1, check);
        if (k > cnt1)
        {
            k -= cnt1;
            s += ')';
            if (cnt < i - cnt)
            {
                check = true;
            }
        }
        else
        {
            s += '(';
            cnt++;
        }
    }
    std::cout << s;
}

