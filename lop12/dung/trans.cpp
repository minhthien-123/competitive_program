ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int a, b, d;
int dp[maxn + 7];

int count(int val)
{
    std::vector<int> divs;
    for (int i = 1; i * i <= val; i++)
    {
        if (val % i == 0)
        {
            divs.push_back(i);
            if (i * i != val)
            {
                divs.push_back(val / i);
            }
        }
    }
    std::sort(all(divs));
    int m = divs.size();
    for (int i = 1; i <= m; i++)
    {
        dp[i] = INF;
    }
    dp[0] = 0;

    for (int i = 0; i < m; i++)
    {
        if (dp[i] == INF)
        {
            continue;
        }

        for (int j = 1; j < m; j++)
        {
            if (divs[j] > d)
            {
                break;
            }
            if (val / divs[j] < divs[i])
            {
                break;
            }
            int nxt = divs[j] * divs[i];
            if (val % nxt == 0)
            {
                int id = std::lower_bound(all(divs), nxt) - divs.begin();
                dp[id] = std::min(dp[id], dp[i] + 1);
            }
        }
    }

    return dp[m - 1];
}

void solve()
{
    std::cin >> a >> b >> d;

    int g = std::__gcd(a, b);
    int x = a / g;
    int y = b / g;

    int cntx = count(x);
    // std::cout << cntx << "\n";
    int cnty = count(y);
    // std::cout << cnty << "\n";

    if (cntx == INF || cnty == INF)
    {
        std::cout << -1 << "\n";
        return;
    }

    std::cout << cntx + cnty;
}

