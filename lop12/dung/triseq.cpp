ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, t;
int a[maxn + 7];
int dp[maxn + 7][maxn + 7][maxn + 7][maxn + 7];

int calc(int pos, int m1, int m2, int mx)
{
    if (pos > n)
    {
        return m1 + m2 > mx;
    }

    ll &memo = dp[pos][m1][m2][mx];
    if (memo != -1)
    {
        return memo;
    }

    int res = 0;
    for (int i = 1; i <= n; i++)
    {
        int nm1 = m1;
        int nm2 = m2;
        int nmx = std::max(mx, i);
        if (i <= m1)
        {
            nm2 = nm1;
            nm1 = i;
        }
        else if (i < m2)
        {
            nm2 = i;
        }

        res += calc(pos + 1, nm1, nm2, nmx);
    }

    return memo = res;
}

void solve()
{
    std::cin >> n >> t;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    memset(dp, -1, sizeof dp);
    std::cout << calc(1, 20, 20, 0) << "\n";

    std::vector<int> vec;
    int m1 = 20, m2 = 20, mx = 0;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            int nm1 = m1;
            int nm2 = m2;
            int nmx = std::max(mx, j);
            if (j <= nm1)
            {
                nm2 = nm1;
                nm1 = j;
            }
            else if (j < nm2)
            {
                nm2 = j;
            }
            int tmp = calc(i + 1, nm1, nm2, nmx);
            if (t > tmp)
            {
                t -= tmp;
            }
            else
            {
                vec.pb(j);
                m1 = nm1;
                m2 = nm2;
                mx = nmx;
                break;
            }
        }
    }
    for (int x : vec)
    {
        std::cout << x << " ";
    }
    std::cout << "\n";

    m1 = 20, m2 = 20, mx = 0;
    int ans = 0;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j < a[i]; j++)
        {
            int nm1 = m1;
            int nm2 = m2;
            int nmx = std::max(mx, j);
            if (j <= nm1)
            {
                nm2 = nm1;
                nm1 = j;
            }
            else if (j < nm2)
            {
                nm2 = j;
            }
            ll tmp = calc(i + 1, nm1, nm2, nmx);
            ans += tmp;
        }
        if (a[i] <= m1)
        {
            m2 = m1;
            m1 = a[i];
        }
        else if (a[i] < m2)
        {
            m2 = a[i];
        }
        mx = std::max(mx, a[i]);
    }
    std::cout << ans + 1;
}

