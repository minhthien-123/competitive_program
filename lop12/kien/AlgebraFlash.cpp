ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int c[maxn + 7], p[45], ban[maxn + 7];
int adj[45], dp[maxn + 7], W[maxn + 7];
bool ok[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
        c[i]--;
    }

    int sum = 0;
    for (int i = 0; i < m; i++)
    {
        std::cin >> p[i];
        sum += p[i];
        adj[i] = 0;
    }

    adj[c[1]] |= (1LL << c[1]);
    adj[c[n]] |= (1LL << c[n]);

    for (int i = 1; i < n; i++)
    {
        int u = c[i];
        int v = c[i + 1];
        adj[u] |= (1LL << v);
        adj[v] |= (1LL << u);
    }

    int h = m / 2;
    int r = m - h;
    dp[0] = 0;

    for (int mask = 1; mask < (1LL << r); mask++)
    {
        int bit = __builtin_ctz(mask);
        int v = bit + h;
        int avail = mask ^ (1LL << bit);
        dp[mask] = dp[avail];

        if ((adj[v] & (1LL << v)) == 0)
        {
            int sh = (adj[v] >> h);
            int cp = avail & (~sh);
            if (dp[cp] + p[v] > dp[mask])
            {
                dp[mask] = dp[cp] + p[v];
            }
        }
    }

    ok[0] = true;
    W[0] = 0;
    ban[0] = 0;
    int mx = dp[(1 << r) - 1];

    for (int mask = 1; mask < (1LL << h); mask++)
    {
        int bit = __builtin_ctz(mask);
        int avail = mask ^ (1LL << bit);
        ok[mask] = false;

        if (ok[avail])
        {
            if ((adj[bit] & mask) == 0)
            {
                ok[mask] = true;
                W[mask] = W[avail] + p[bit];
                ban[mask] = ban[avail] | (adj[bit] >> h);

                int cp = ((1LL << r) - 1) & (~ban[mask]);

                if (W[mask] + dp[cp] > mx)
                {
                    mx = W[mask] + dp[cp];
                }
            }
        }
    }

    std::cout << sum - mx;
}

