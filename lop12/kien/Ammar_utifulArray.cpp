ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
ll a[maxn + 7], f[maxn + 7];
int c[maxn + 7];
ll sum = 0;
std::vector<ll> pre[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }
    for (int i = 1; i <= maxn; i++)
    {
        pre[i].pb(0);
    }
    for (int i = 1; i <= n; i++)
    {
        ll lst = pre[c[i]].back();
        pre[c[i]].pb(lst + a[i]);
    }

    std::cin >> q;
    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int col;
            ll x;
            std::cin >> col >> x;
            sum += x;
            f[col] -= x;
        }
        else
        {
            int col;
            ll y;
            std::cin >> col >> y;
            int l = 1, r = sz(pre[col]) - 1;
            ll tmp = sum + f[col];
            int ans = 0;
            while (l <= r)
            {
                int mid = (l + r) / 2;
                ll cur = pre[col][mid] + mid * tmp;
                if (cur <= y)
                {
                    ans = mid;
                    l = mid + 1;
                }
                else
                {
                    r = mid - 1;
                }
            }
            std::cout << ans << '\n';
        }
    }
}

