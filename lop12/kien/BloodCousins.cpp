const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7];
int tin[maxn + 7], tout[maxn + 7], timer = 0;
int up[maxn + 7][lg + 1], d[maxn + 7];
std::vector<int> cnt[maxn + 7];

void dfs(int u, int p)
{
    tin[u] = ++timer;
    cnt[d[u]].pb(tin[u]);
    up[u][0] = p;
    for (int i = 1; i <= lg; i++)
    {
        up[u][i] = up[up[u][i - 1]][i - 1];
    }
    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        d[v] = d[u] + 1;
        dfs(v, u);
    }
    tout[u] = timer;
}

int get(int u, int p)
{
    for (int i = 0; i <= lg; i++)
    {
        if ((p >> i) & 1)
        {
            u = up[u][i];
        }
    }
    return u;
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        int p;
        std::cin >> p;
        if (p == 0)
        {
            adj[0].pb(i);
        }
        else
        {
            adj[p].pb(i);
        }
    }
    d[0] = 0;
    dfs(0, 0);
    std::cin >> m;
    while (m--)
    {
        int v, p;
        std::cin >> v >> p;
        if (d[v] <= p)
        {
            std::cout << 0 << "\n";
        }
        else
        {
            int u = get(v, p);
            auto it1 = std::lower_bound(all(cnt[d[v]]), tin[u]);
            auto it2 = std::upper_bound(all(cnt[d[v]]), tout[u]);
            std::cout << (it2 - it1) - 1 << "\n";
        }
    }
}

