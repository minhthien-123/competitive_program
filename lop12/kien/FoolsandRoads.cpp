ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<ii> adj[maxn + 7];
int n, k;
int f[maxn + 7];
int ans[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int i = 0; i < sz(adj[u]); i++)
        {
            int v = adj[u][i].fi;
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int diff = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((diff >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

int dfs(int u, int p)
{
    int sum = f[u];
    for (auto [v, id] : adj[u])
    {
        if (v == p)
        {
            continue;
        }

        int tmp = dfs(v, u);
        ans[id] = tmp;
        sum += tmp;
    }
    return sum;
}

void solve()
{
    std::cin >> n;
    for (int i = 1, u, v; i < n; i++)
    {
        std::cin >> u >> v;
        adj[u].pb({v, i});
        adj[v].pb({u, i});
    }
    LCA lca(n);
    lca.build(1);
    std::cin >> k;
    for (int i = 1, u, v; i <= k; i++)
    {
        std::cin >> u >> v;
        f[u]++;
        f[v]++;
        f[lca.get_lca(u, v)] -= 2;
    }
    dfs(1, 0);
    for (int i = 1; i < n; i++)
    {
        std::cout << ans[i] << " ";
    }
    std::cout << "\n";
}

