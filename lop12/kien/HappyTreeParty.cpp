struct SegTree
{
    int n;
    std::vector<long long> st;

    SegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, 1);
    }

    long long prod(long long a, long long b)
    {
        if (a == 0 || b == 0)
        {
            return 0;
        }
        if (a > INF / b)
        {
            return INF;
        }
        return a * b;
    }

    void update(int id, int l, int r, int pos, long long val)
    {
        if (pos < l || pos > r)
            return;
        if (l == r)
        {
            st[id] = val;
            return;
        }
        int mid = (l + r) / 2;
        update(2 * id, l, mid, pos, val);
        update(2 * id + 1, mid + 1, r, pos, val);
        st[id] = prod(st[2 * id], st[2 * id + 1]);
    }

    long long get(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
            return 1;
        if (u <= l && r <= v)
            return st[id];
        int mid = (l + r) / 2;
        return prod(get(2 * id, l, mid, u, v), get(2 * id + 1, mid + 1, r, u, v));
    }
};

SegTree seg(0);

struct HLD
{
    int n, timer;
    std::vector<std::vector<int>> adj;
    std::vector<int> par, depth, heavy, head, pos, sz;

    HLD(int n)
    {
        this->n = n;
        timer = 0;
        adj.resize(n + 7);
        par.resize(n + 7);
        depth.resize(n + 7);
        heavy.assign(n + 7, -1);
        head.resize(n + 7);
        pos.resize(n + 7);
        sz.resize(n + 7);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    int dfs(int v, int p)
    {
        sz[v] = 1;
        par[v] = p;
        int max_sub = 0;
        for (int u : adj[v])
        {
            if (u != p)
            {
                depth[u] = depth[v] + 1;
                int sub_sz = dfs(u, v);
                sz[v] += sub_sz;
                if (sub_sz > max_sub)
                {
                    max_sub = sub_sz;
                    heavy[v] = u;
                }
            }
        }
        return sz[v];
    }

    void decompose(int v, int h, int p)
    {
        head[v] = h;
        pos[v] = ++timer;
        if (heavy[v] != -1)
        {
            decompose(heavy[v], h, v);
        }
        for (int u : adj[v])
        {
            if (u != p && u != heavy[v])
            {
                decompose(u, u, v);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
        decompose(root, root, root);
    }

    long long query_path(int u, int v)
    {
        long long res = 1;
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
                std::swap(u, v);
            res = seg.prod(res, seg.get(1, 1, n, pos[head[u]], pos[u]));
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
            std::swap(u, v);
        if (u != v)
        {
            res = seg.prod(res, seg.get(1, 1, n, pos[u] + 1, pos[v]));
        }
        return res;
    }
};

std::vector<ii> edges;
int n, m;
int W[maxn + 7], e[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    HLD hld(n);

    edges.pb({0, 0});
    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        hld.add_edge(u, v);
        edges.pb({u, v});
        W[i] = w;
    }

    hld.build(1);
    seg = SegTree(n);

    for (int i = 1; i < n; i++)
    {
        auto [u, v] = edges[i];
        int child = (hld.depth[u] > hld.depth[v]) ? u : v;
        e[i] = child;
        seg.update(1, 1, n, hld.pos[child], W[i]);
    }

    while (m--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int a, b, y;
            std::cin >> a >> b >> y;
            long long prod = hld.query_path(a, b);
            if (prod == 0)
                std::cout << 0 << "\n";
            else
                std::cout << y / prod << "\n";
        }
        else if (type == 2)
        {
            int p, c;
            std::cin >> p >> c;
            seg.update(1, 1, n, hld.pos[e[p]], c);
        }
    }
}

