ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7];
int cnt[maxn + 7];
int ans = 0, bits = 0;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cnt[a[i]]++;
    }

    for (int i = 0; i < 20; i++)
    {
        for (int mask = (1 << 20) - 1; mask >= 0; mask--)
        {
            if ((mask & (1 << i)) == 0)
            {
                cnt[mask] += cnt[mask | (1 << i)];
            }
        }
    }

    int ans = 0;
    for (int mask = 0; mask < (1 << 20); mask++)
    {
        int ways = power(2, cnt[mask]);
        bits = __builtin_popcount(mask);
        if (bits % 2 == 1)
        {
            ans = sub(ans, ways);
        }
        else
        {
            ans = add(ans, ways);
        }
    }

    std::cout << ans;
}

