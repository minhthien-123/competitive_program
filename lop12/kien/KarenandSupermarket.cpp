ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, b;
int c[maxn + 7], d[maxn + 7], sz[maxn + 7];
int dp[maxn + 7][maxn + 7][2];
int f[maxn + 8][2];

void dfs(int u)
{
    sz[u] = 1;
    dp[u][0][0] = 0;
    dp[u][1][0] = c[u];
    dp[u][1][1] = c[u] - d[u];

    for (int v : adj[u])
    {
        dfs(v);

        for (int i = 0; i <= sz[u] + sz[v]; i++)
        {
            f[i][0] = f[i][1] = INF;
        }

        for (int i = 0; i <= sz[u]; i++)
        {
            for (int j = 0; j <= sz[v]; j++)
            { 
                if (dp[u][i][0] != INF && dp[v][j][0] != INF)
                {
                    f[i + j][0] = std::min(f[i + j][0], dp[u][i][0] + dp[v][j][0]);
                }

                if (dp[u][i][1] != INF)
                {
                    if (dp[v][j][0] != INF)
                    {
                        f[i + j][1] = std::min(f[i + j][1], dp[u][i][1] + dp[v][j][0]);
                    }

                    if (dp[v][j][1] != INF)
                    {
                        f[i + j][1] = std::min(f[i + j][1], dp[u][i][1] + dp[v][j][1]);
                    }
                }
            }
        }

        sz[u] += sz[v];
        for (int i = 0; i <= sz[u]; i++)
        {
            dp[u][i][0] = f[i][0];
            dp[u][i][1] = f[i][1];
        }
    }
}

void solve()
{
    std::cin >> n >> b;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 0; j <= n; j++)
        {
            dp[i][j][0] = dp[i][j][1] = INF;
        }
    }

    std::cin >> c[1] >> d[1];
    for (int i = 2; i <= n; i++)
    {
        int p;
        std::cin >> c[i] >> d[i] >> p;
        adj[p].pb(i);
    }

    dfs(1);

    int ans = 0;
    for (int i = n; i >= 0; i--)
    {
        if (std::min(dp[1][i][0], dp[1][i][1]) <= b)
        {
            ans = i;
            break;
        }
    }

    std::cout << ans;
}

