ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m, q;
ll a[maxn + 7], b[maxn + 7], c[maxn + 7];
std::vector<ll> vec;
ll sa[maxn + 7], sb[maxn + 7];

ll get(ll sum)
{
    auto it = std::lower_bound(all(vec), sum);
    ll res = INF;
    if (it != vec.end())
    {
        res = std::min(res, std::abs(sum - *it));
    }
    if (it != vec.begin())
    {
        it--;
        res = std::min(res, std::abs(sum - *it));
    }
    return res;
}

void solve()
{
    std::cin >> n >> m >> q;
    ll suma = 0, sumb = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        if (i % 2 == 0)
        {
            suma -= a[i];
        }
        else
        {
            suma += a[i];
        }
    }
    for (int i = 1; i <= m; i++)
    {
        std::cin >> b[i];
    }
    for (int i = 1; i <= n; i++)
    {
        if (i % 2 == 0)
        {
            sumb -= b[i];
        }
        else
        {
            sumb += b[i];
        }
    }
    vec.pb(sumb);
    int d = 1;
    if (n % 2 == 0)
    {
        d = -1;
    }
    for (int j = 1; j <= m - n; j++)
    {
        sumb = -sumb + b[j] + d * b[j + n];
        vec.pb(sumb);
    }
    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());

    std::cout << get(suma) << "\n";
    while (q--)
    {
        int l, r;
        ll x;
        std::cin >> l >> r >> x;
        if ((r - l + 1) % 2 != 0)
        {
            if (l % 2 == 0)
            {
                suma -= x;
            }
            else
            {
                suma += x;
            }
        }
        std::cout << get(suma) << "\n";
    }
}

