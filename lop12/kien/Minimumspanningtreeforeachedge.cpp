ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll ans[maxn + 7];

struct edge
{
    int u, v;
    ll w;
    int id;
    bool check;

    friend bool operator<(edge a, edge b)
    {
        return a.w < b.w;
    }
} edges[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<std::pair<int, ll>>> adj;
    std::vector<std::vector<int>> up;
    std::vector<std::vector<ll>> mx;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        mx.assign(n + 7, std::vector<ll>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void add_edge(int u, int v, ll w)
    {
        adj[u].push_back({v, w});
        adj[v].push_back({u, w});
    }

    void dfs(int u, int p, ll w)
    {
        up[u][0] = p;
        mx[u][0] = w;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
            mx[u][i] = std::max(mx[u][i - 1], mx[up[u][i - 1]][i - 1]);
        }
        for (auto e : adj[u])
        {
            int v = e.fi;
            ll w = e.se;
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u, w);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root, 0);
    }

    ll get_max(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        ll res = 0;
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                res = std::max(res, mx[u][i]);
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return res;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                res = std::max(res, std::max(mx[u][i], mx[v][i]));
                u = up[u][i];
                v = up[v][i];
            }
        }
        res = std::max(res, std::max(mx[u][0], mx[v][0]));
        return res;
    }
};

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);

        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        if (v == par[v])
        {
            return v;
        }
        par[v] = acs(par[v]);
        return par[v];
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        edges[i] = {u, v, w, i, 0};
    }

    std::sort(edges + 1, edges + m + 1);
    ll res = 0;
    DSU dsu(n);
    LCA lca(n);

    for (int i = 1; i <= m; i++)
    {
        int u = edges[i].u, v = edges[i].v;
        ll w = edges[i].w;
        if (dsu.acs(u) != dsu.acs(v))
        {
            dsu.join(u, v);
            edges[i].check = true;
            res += edges[i].w;
            lca.add_edge(u, v, w);
        }
    }

    lca.build(1);

    for (int i = 1; i <= m; i++)
    {
        if (edges[i].check)
        {
            ans[edges[i].id] = res;
        }
        else
        {
            ll mx = lca.get_max(edges[i].u, edges[i].v);
            ans[edges[i].id] = res - mx + edges[i].w;
        }
    }

    for (int i = 1; i <= m; i++)
    {
        std::cout << ans[i] << "\n";
    }
}

