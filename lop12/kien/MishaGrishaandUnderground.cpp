ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; ++i)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; ++i)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; --i)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int dist(int u, int v)
    {
        return depth[u] + depth[v] - 2 * depth[get_lca(u, v)];
    }
};

void solve()
{
    int n, q;
    std::cin >> n >> q;
    LCA lca(n);
    for (int i = 2; i <= n; i++)
    {
        int p;
        std::cin >> p;
        lca.add_edge(p, i);
    }
    lca.build(1);

    for (int i = 1; i <= q; i++)
    {
        int a, b, c;
        std::cin >> a >> b >> c;

        int ab = lca.dist(a, b);
        int bc = lca.dist(b, c);
        int ca = lca.dist(c, a);

        int get1 = (ab + ca - bc) / 2 + 1;
        int get2 = (ab + bc - ca) / 2 + 1;
        int get3 = (bc + ca - ab) / 2 + 1;

        std::cout << std::max({get1, get2, get3}) << "\n";
    }
}

