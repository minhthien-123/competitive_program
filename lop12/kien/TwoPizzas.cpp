ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int f[maxn + 7], b[maxn + 7][10], c[maxn + 7], a[maxn + 7][10], r[maxn + 7];
int cnt[maxn + 7];
std::multiset<ii> s[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> f[i];
        int mask = 0;
        for (int j = 1; j <= f[i]; j++)
        {
            std::cin >> b[i][j];
            mask |= (1 << (b[i][j] - 1));
        }
        cnt[mask]++;
    }
    for (int i = 1; i <= m; i++)
    {
        std::cin >> c[i];
        std::cin >> r[i];
        int mask = 0;
        for (int j = 1; j <= r[i]; j++)
        {
            std::cin >> a[i][j];
            mask |= (1 << (a[i][j] - 1));
        }
        s[mask].insert({c[i], i});
        while (sz(s[mask]) > 2)
        {
            s[mask].erase(--s[mask].end());
        }
    }

    ii pos = {0, 0};
    int mincost = 2 * INF + 1;
    int res = 0;
    for (int i = 0; i < (1 << 9); i++)
    {
        for (int j = 0; j < (1 << 9); j++)
        {
            int cur = 0;
            int pos1 = -1, pos2 = -1;
            if (i == j)
            {
                if (sz(s[i]) < 2)
                {
                    continue;
                }
                auto it1 = s[i].begin();
                auto it2 = s[i].begin();
                ++it2;
                cur = it1->fi + it2->fi;
                pos1 = it1->se;
                pos2 = it2->se;
            }
            else
            {
                if (sz(s[i]) == 0 || sz(s[j]) == 0)
                {
                    continue;
                }
                auto it1 = s[i].begin();
                auto it2 = s[j].begin();
                // std::cout
                cur = it1->fi + it2->fi;
                pos1 = it1->se;
                pos2 = it2->se;
            }

            int ans = 0;
            int mask = i | j;
            for (int k = 0; k < (1 << 9); k++)
            {
                if ((k & mask) == k)
                {
                    ans += cnt[k];
                }
            }

            // std::cout << ans << " " << res << "\n";

            if (ans > res)
            {
                res = ans;
                mincost = cur;
                pos = {pos1, pos2};
            }
            else if (ans == res)
            {
                if (cur < mincost)
                {
                    mincost = cur;
                    pos = {pos1, pos2};
                }
            }
        }
    }

    std::cout << pos.fi << " " << pos.se;
}

