struct LazySegTree
{
    int n;
    std::vector<long long> st, lazy;

    LazySegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, 0);
        lazy.assign(4 * n + 7, -1);
    }

    void push(int id, int l, int r)
    {
        if (lazy[id] != -1)
        {
            int mid = (l + r) / 2;
            st[2 * id] = lazy[id] * (mid - l + 1);
            lazy[2 * id] = lazy[id];
            st[2 * id + 1] = lazy[id] * (r - mid);
            lazy[2 * id + 1] = lazy[id];
            lazy[id] = -1;
        }
    }

    void update(int id, int l, int r, int u, int v, long long val)
    {
        if (v < l || r < u)
            return;
        if (u <= l && r <= v)
        {
            st[id] = val * (r - l + 1);
            lazy[id] = val;
            return;
        }
        push(id, l, r);
        int mid = (l + r) / 2;
        update(2 * id, l, mid, u, v, val);
        update(2 * id + 1, mid + 1, r, u, v, val);
        st[id] = st[2 * id] + st[2 * id + 1];
    }

    long long get(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
            return 0;
        if (u <= l && r <= v)
            return st[id];
        push(id, l, r);
        int mid = (l + r) / 2;
        return get(2 * id, l, mid, u, v) + get(2 * id + 1, mid + 1, r, u, v);
    }
};

LazySegTree seg(0);

struct HLD
{
    int n, timer;
    std::vector<std::vector<int>> adj;
    std::vector<int> par, depth, heavy, head, pos, sz;

    HLD(int n)
    {
        this->n = n;
        timer = 0;
        adj.resize(n + 7);
        par.resize(n + 7);
        depth.resize(n + 7);
        heavy.assign(n + 7, -1);
        head.resize(n + 7);
        pos.resize(n + 7);
        sz.resize(n + 7);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    int dfs(int v, int p)
    {
        sz[v] = 1;
        par[v] = p;
        int max_sub = 0;
        for (int u : adj[v])
        {
            if (u != p)
            {
                depth[u] = depth[v] + 1;
                int sub_sz = dfs(u, v);
                sz[v] += sub_sz;
                if (sub_sz > max_sub)
                {
                    max_sub = sub_sz;
                    heavy[v] = u;
                }
            }
        }
        return sz[v];
    }

    void decompose(int v, int h, int p)
    {
        head[v] = h;
        pos[v] = ++timer;
        if (heavy[v] != -1)
        {
            decompose(heavy[v], h, v);
        }
        for (int u : adj[v])
        {
            if (u != p && u != heavy[v])
            {
                decompose(u, u, v);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
        decompose(root, root, root);
    }

    long long query_path(int u, int v)
    {
        long long res = 0;
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
                std::swap(u, v);
            res += seg.get(1, 1, n, pos[head[u]], pos[u]);
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
            std::swap(u, v);
        res += seg.get(1, 1, n, pos[u], pos[v]);
        return res;
    }

    void update_path(int u, int v, long long val)
    {
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
                std::swap(u, v);
            seg.update(1, 1, n, pos[head[u]], pos[u], val);
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
            std::swap(u, v);
        seg.update(1, 1, n, pos[u], pos[v], val);
    }
};

void solve()
{
    std::cin >> n;
    HLD hld(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        hld.add_edge(u, v);
    }

    hld.build(1);
    seg = LazySegTree(n);

    int q;
    std::cin >> q;
    while (q--)
    {
        int type, v;
        std::cin >> type >> v;
        if (type == 1)
        {
            seg.update(1, 1, n, hld.pos[v], hld.pos[v] + hld.sz[v] - 1, 1);
        }
        else if (type == 2)
        {
            hld.update_path(v, 1, 0);
        }
        else if (type == 3)
        {
            std::cout << seg.get(1, 1, n, hld.pos[v], hld.pos[v]) << "\n";
        }
    }
}

