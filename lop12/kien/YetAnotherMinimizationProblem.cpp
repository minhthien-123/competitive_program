ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7], b[maxn + 7];
int dp[maxn + 7][20007];

void solve()
{
    std::cin >> n;
    int s = 0, ssq = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        s += a[i];
        ssq += a[i] * a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> b[i];
        s += b[i];
        ssq += b[i] * b[i];
    }

    for (int i = 0; i <= n; i++)
    {
        for (int j = 0; j <= 2e4; j++)
        {
            dp[i][j] = 0;
        }
    }

    dp[0][0] = 1;
    for (int i = 1; i <= n; i++)
    {
        for (int j = s; j >= 0; j--)
        {
            if (j >= a[i])
            {
                if (dp[i - 1][j - a[i]])
                {
                    dp[i][j] = true;
                }
            }
            if (j >= b[i])
            {
                if (dp[i - 1][j - b[i]])
                {
                    dp[i][j] = true;
                }
            }
        }
    }

   int ans = INF;
    for (int j = 0; j <= s; j++)
    {
        if (dp[n][j])
        {
            ans = std::min(ans, j * j + (s - j) * (s - j));
        }
    }

    ans += (n - 2) * ssq;
    std::cout << ans << "\n";
}

