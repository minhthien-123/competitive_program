ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, x, y;
int a[maxn + 7];
int dp[207][maxn + 7][2];

void solve()
{
    std::cin >> n >> x >> y;
    int sum = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 0; i <= n; i++)
    {
        for (int j = 0; j <= x; j++)
        {
            dp[i][j][0] = dp[i][j][1] = INF;
        }
    }

    if (a[1] <= x)
    {
        dp[1][a[1]][0] = 0;
    }
    if (a[1] <= y)
    {
        dp[1][0][1] = 0;
    }

    int cnt = a[1];
    for (int i = 2; i <= n; i++)
    {
        cnt += a[i];
        for (int j = 0; j <= x; j++)
        {
            if (j >= a[i])
            {
                if (dp[i - 1][j - a[i]][0] != INF)
                {
                    dp[i][j][0] = std::min(dp[i][j][0], dp[i - 1][j - a[i]][0]);
                }
                if (dp[i - 1][j - a[i]][1] != INF)
                {
                    dp[i][j][0] = std::min(dp[i][j][0], dp[i - 1][j - a[i]][1] + std::min(a[i], a[i - 1]));
                }
            }

            int k = cnt - j;
            if (0 <= k && k <= y)
            {
                if (dp[i - 1][j][1] != INF)
                {
                    dp[i][j][1] = std::min(dp[i][j][1], dp[i - 1][j][1]);
                }
                if (dp[i - 1][j][0] != INF)
                {
                    dp[i][j][1] = std::min(dp[i][j][1], dp[i - 1][j][0] + std::min(a[i], a[i - 1]));
                }
            }
        }
    }

    int ans = INF;
    for (int j = 0; j <= x; j++)
    {
        ans = std::min({ans, dp[n][j][0], dp[n][j][1]});
    }

    std::cout << ((ans == INF) ? -1 : ans);
}

