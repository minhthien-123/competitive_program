const int maxn = 22;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int adj[maxn + 8][maxn + 8];
int val[maxn + 7];

int dp[1 << maxn];
ii pre[1 << maxn];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u][v] = adj[v][u] = true;
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (adj[i][j])
            {
                val[i] |= (1 << (j - 1));
            }
        }
    }

    bool check = true;
    for (int i = 1; i <= n; i++)
    {
        for (int j = i + 1; j <= n; j++)
        {
            if (!adj[i][j])
            {
                check = false;
            }
        }
    }

    if (check)
    {
        std::cout << 0 << "\n";
        return;
    }

    for (int i = 0; i < (1 << n); i++)
    {
        dp[i] = inf;
        pre[i] = {-1, -1};
    }

    for (int i = 1; i <= n; i++)
    {
        dp[(1 << (i - 1))] = 0;
    }

    for (int mask = 0; mask < (1 << n); mask++)
    {
        if (dp[mask] == inf)
        {
            continue;
        }

        for (int i = 1; i <= n; i++)
        {
            if (mask & (1 << (i - 1)))
            {
                int nmask = mask | val[i];
                if (dp[mask] + 1 < dp[nmask])
                {
                    dp[nmask] = dp[mask] + 1;
                    pre[nmask] = {mask, i};
                }
            }
        }
    }

    std::vector<int> id;
    int cur = (1 << n) - 1;

    while (cur != -1 && pre[cur].fi != -1)
    {
        id.pb(pre[cur].se);
        cur = pre[cur].fi;
    }

    std::reverse(all(id));
    std::cout << dp[(1 << n) - 1] << "\n";
    for (int x : id)
    {
        std::cout << x << " ";
    }
    std::cout << "\n";
}

