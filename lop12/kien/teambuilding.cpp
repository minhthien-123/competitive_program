ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, p, k;
int dp[maxn + 7][1 << 7 + 1];

struct teambuilding
{
    int x;
    int s[7 + 1];

    friend bool operator<(teambuilding a, teambuilding b)
    {
        return a.x > b.x;
    }
};
teambuilding a[maxn + 7];

void solve()
{
    std::cin >> n >> p >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].x;
    }
    for (int i = 1; i <= n; i++)
    {
        for (int j = 0; j < p; j++)
        {
            std::cin >> a[i].s[j];
        }
    }

    memset(dp, -1, sizeof dp);
    std::sort(a + 1, a + n + 1);

    dp[0][0] = 0;
    for (int i = 1; i <= n; i++)
    {
        for (int mask = 0; mask < (1 << p); mask++)
        {
            int cnt = 0;
            for (int j = 0; j < p; j++)
            {
                if (mask & (1 << j))
                {
                    cnt++;
                }
            }

            cnt = i - cnt;
            if (cnt <= k)
            {
                if (dp[i - 1][mask] != -1)
                {
                    dp[i][mask] = dp[i - 1][mask] + a[i].x;
                }
            }
            else
            {
                if (dp[i - 1][mask] != -1)
                {
                    dp[i][mask] = dp[i - 1][mask];
                }
            }

            for (int j = 0; j < p; j++)
            {
                if ((mask & (1 << j)) && dp[i - 1][mask ^ (1 << j)] != -1)
                {
                    dp[i][mask] = std::max(dp[i][mask], dp[i - 1][mask ^ (1 << j)] + a[i].s[j]);
                }
            }
        }
    }

    std::cout << dp[n][(1 << p) - 1];
}

