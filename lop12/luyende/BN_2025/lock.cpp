int n, t;
int l[maxn + 7], r[maxn + 7];
std::vector<int> vals;
int pre[maxn + 7];

int get(int x)
{
    return std::lower_bound(all(vals), x) - vals.begin();
}

void solve()
{
    std::cin >> n >> t;
    for (int i = 1; i <= t; i++)
    {
        std::cin >> l[i] >> r[i];
        vals.pb(l[i]);
        vals.pb(r[i] + 1);
    }
    vals.pb(1);
    vals.pb(n + 1);

    std::sort(all(vals));
    vals.erase(std::unique(all(vals)), vals.end());

    for (int i = 1; i <= t; i++)
    {
        int L = get(l[i]);
        int R = get(r[i] + 1);
        pre[L]++;
        pre[R]--;
    }

    int cur = 0;
    int ans = 0;
    for (int i = 0; i < sz(vals) - 1; i++)
    {
        cur += pre[i];

        if (cur % 3 == 0)
        {
            if (vals[i] <= n)
            {
                ans += vals[i + 1] - vals[i];
            }
        }
    }

    std::cout << ans;
}
