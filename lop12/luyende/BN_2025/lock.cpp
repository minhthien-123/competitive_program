ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }   
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

