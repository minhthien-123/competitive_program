void sieve()
{
    for (int i = 1; i <= maxn; i++)
    {
        spf[i] = i;
    }

    for (int i = 2; i * i <= maxn; i++)
    {
        if (spf[i] == i)
        {
            for (int j = i * i; j <= maxn; j += i)
            {
                if (spf[j] == j)
                {
                    spf[j] = i;
                }
            }
        }
    }

    for (int i = 2; i < maxn; i++)
    {
        if (spf[i] == i)
        {
            h[i] = rng();
        }
    }
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];

        int mask = 0;
        int tmp = a[i];

        while (tmp > 1)
        {
            int p = spf[tmp];
            int cnt = 0;

            while (tmp % p == 0)
            {
                cnt++;
                tmp /= p;
            }

            if (cnt % 2 != 0)
            {
                mask ^= h[p];
            }
        }

        pre[i] = pre[i - 1] ^ mask;
    }

    while (q--)
    {
        int l, r;
        std::cin >> l >> r;

        int tmp = pre[r] ^ pre[l - 1];

        std::cout << ((tmp == 0) ? "YES\n" : "NO\n");
    }
}
