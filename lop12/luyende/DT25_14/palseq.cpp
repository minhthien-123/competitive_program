ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll l, n, k;

bool is_pal(const vi &p)
{
    int d = sz(p);
    for (int i = 0; i < d / 2; i++)
    {
        if (p[i] != p[d - 1 - i])
        {
            return false;
        }
    }
    return true;
}

ll count_prefix(const vi &p, ll max_len)
{
    int d = sz(p);
    ll ans = 0;
    for (ll m = d; m <= max_len; m++)
    {
        if (m >= 2LL * d - 1)
        {
            ans = add(ans, power(l, (m + 1) / 2 - d));
        }
        else
        {
            bool ok = true;
            for (int i = (m + 1) / 2; i < d; i++)
            {
                if (p[i] != p[m - 1 - i])
                {
                    ok = false;
                    break;
                }
            }
            if (ok)
            {
                ans = add(ans, 1);
            }
        }
    }
    return ans;
}

void sub1()
{
    vi p;
    for (int step = 1; step <= n; step++)
    {
        bool found = false;
        for (int c = 0; c < l; c++)
        {
            p.pb(c);
            ll cnt = count_prefix(p, n);
            if (k <= cnt)
            {
                found = true;
                break;
            }
            k -= cnt;
            p.pop_back();
        }
        if (!found)
        {
            std::cout << 0 << "\n";
            return;
        }
        if (is_pal(p))
        {
            if (k == 1)
            {
                std::cout << sz(p) << "\n";
                return;
            }
            k--;
        }
    }
    std::cout << 0 << "\n";
}

void solve()
{
    std::cin >> l >> n >> k;
    sub1();
}

