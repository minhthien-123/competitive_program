const int maxn = 50007;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;

int n;
int h[maxn];
int vals[maxn];
int idx;

int st1[4 * maxn], st2[4 * maxn], st3[4 * maxn], st4[4 * maxn];

void build(int node, int l, int r)
{
    st1[node] = st2[node] = st3[node] = st4[node] = -inf;
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;
    build(2 * node, l, mid);
    build(2 * node + 1, mid + 1, r);
}

void update(int st[], int node, int l, int r, int pos, int val)
{
    if (pos < l || pos > r)
    {
        return;
    }
    if (l == r)
    {
        st[node] = std::max(st[node], val);
        return;
    }
    int mid = (l + r) / 2;
    update(st, 2 * node, l, mid, pos, val);
    update(st, 2 * node + 1, mid + 1, r, pos, val);
    st[node] = std::max(st[2 * node], st[2 * node + 1]);
}

int get(int st[], int node, int l, int r, int u, int v)
{
    if (u > r || v < l)
    {
        return -inf;
    }
    if (u <= l && r <= v)
    {
        return st[node];
    }
    int mid = (l + r) / 2;
    int get1 = get(st, 2 * node, l, mid, u, v);
    int get2 = get(st, 2 * node + 1, mid + 1, r, u, v);
    return std::max(get1, get2);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i];
        vals[i] = h[i];
    }

    std::sort(vals + 1, vals + 1 + n);
    idx = std::unique(vals + 1, vals + 1 + n) - (vals + 1);

    build(1, 1, idx);
    int ans = 0;

    for (int i = 1; i <= n; i++)
    {
        int x = std::lower_bound(vals + 1, vals + 1 + idx, h[i]) - vals;

        int b0 = std::max(1LL, get(st1, 1, 1, idx, 1, x - 1) + 1);

        int q1 = get(st1, 1, 1, idx, x + 1, idx);
        int q2 = get(st2, 1, 1, idx, x + 1, idx);
        int b2 = -inf;
        if (q1 >= 2)
        {
            b2 = std::max(b2, q1 + 1);
        }
        if (q2 >= 3)
        {
            b2 = std::max(b2, q2 + 1);
        }

        int q1i = get(st2, 1, 1, idx, 1, x - 1);
        int q2i = get(st3, 1, 1, idx, 1, x - 1);
        int b3 = -inf;
        if (q1i >= 3)
        {
            b3 = std::max(b3, q1i + 1);
        }
        if (q2i >= 4)
        {
            b3 = std::max(b3, q2i + 1);
        }

        int q3d = get(st3, 1, 1, idx, x + 1, idx);
        int q4d = get(st4, 1, 1, idx, x + 1, idx);
        int b4 = -inf;
        if (q3d >= 4)
        {
            b4 = std::max(b4, q3d + 1);
        }
        if (q4d >= 5)
        {
            b4 = std::max(b4, q4d + 1);
        }

        update(st1, 1, 1, idx, x, b0);
        if (b2 > 0)
        {
            update(st2, 1, 1, idx, x, b2);
        }
        if (b3 > 0)
        {
            update(st3, 1, 1, idx, x, b3);
        }
        if (b4 > 0)
        {
            update(st4, 1, 1, idx, x, b4);
        }

        ans = std::max(ans, b4);
    }

    std::cout << ans << "\n";
}

