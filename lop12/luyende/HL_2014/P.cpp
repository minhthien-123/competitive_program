ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int freq[maxn + 7];

struct Sieve
{
    int n;
    std::vector<int> min_prime;
    std::vector<int> primes;

    Sieve(int n) : n(n)
    {
        min_prime.assign(n + 1, 0);
        for (int i = 2; i <= n; i++)
        {
            if (min_prime[i] == 0)
            {
                min_prime[i] = i;
                primes.push_back(i);
            }
            for (int p : primes)
            {
                if (p > min_prime[i] || i * p > n)
                    break;
                min_prime[i * p] = p;
            }
        }
    }

    bool is_prime(int x)
    {
        if (x < 2)
        {
            return false;
        }
        return min_prime[x] == x;
    }
};

const int max_val = 1e4;

struct BFS
{
    int n;
    std::vector<std::vector<int>> adj;
    std::vector<long long> dist;

    BFS(int n)
    {
        this->n = n;
        adj.resize(n + 7);
        dist.assign(n + 7, -1);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void run(int s)
    {
        dist.assign(n + 7, -1);
        std::queue<int> q;

        dist[s] = 0;
        q.push(s);

        while (!q.empty())
        {
            int u = q.front();
            q.pop();

            for (int v : adj[u])
            {
                if (dist[v] == -1)
                {
                    dist[v] = dist[u] + 1;
                    q.push(v);
                }
            }
        }
    }
};

long long ans[max_val + 7];

void solve()
{
    std::cin >> n;
    for (int i = 0; i <= max_val; i++)
    {
        ans[i] = 0;
        freq[i] = 0;
    }

    Sieve sieve(max_val);

    std::vector<int> start_nodes;

    for (int i = 1; i <= n; i++)
    {
        int x;
        std::cin >> x;
        freq[x]++;
        if (freq[x] == 1)
        {
            start_nodes.push_back(x);
        }
    }

    BFS bfs(max_val);

    for (int i = 1; i <= max_val; i++)
    {
        for (int p : sieve.primes)
        {
            if (i * p > max_val)
            {
                break;
            }
            bfs.add_edge(i, i * p);
        }
    }

    for (int start_node : start_nodes)
    {
        bfs.run(start_node);

        for (int j = 1; j <= max_val; j++)
        {
            if (bfs.dist[j] != -1)
            {
                ans[j] += bfs.dist[j] * freq[start_node];
            }
        }
    }

    long long res = INF;
    int pos = 1;

    for (int j = 1; j <= max_val; j++)
    {
        if (ans[j] < res)
        {
            res = ans[j];
            pos = j;
        }
    }

    std::cout << res << " " << pos << "\n";
}

