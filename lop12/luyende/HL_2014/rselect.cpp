ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7][maxn + 7];

struct Edge
{
    int u, v, w;
    friend bool operator<(Edge a, Edge b)
    {
        return a.w < b.w;
    }
};

struct DSURollback
{
    std::vector<int> par, sz;

    struct SaveNode
    {
        int u, v, par_v, sz_u;
    };
    std::stack<SaveNode> st;

    DSURollback(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7, 1);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
        }
    }

    int acs(int v)
    {
        while (v != par[v])
        {
            v = par[v];
        }
        return v;
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }

            st.push({u, v, par[v], sz[u]});

            par[v] = u;
            sz[u] += sz[v];
        }
    }

    void rollback(int checkpoint)
    {
        while (sz(st) > checkpoint)
        {
            SaveNode s = st.top();
            st.pop();
            par[s.v] = s.par_v;
            sz[s.u] = s.sz_u;
        }
    }
};

int idx(int i, int j)
{
    return (i - 1) * n + j;
}

void solve()
{
    std::cin >> n;

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
        }
    }

    std::vector<Edge> edges;

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (i + 1 <= n)
            {
                edges.pb({idx(i, j), idx(i + 1, j), std::abs(a[i][j] - a[i + 1][j])});
            }
            if (j + 1 <= n)
            {
                edges.pb({idx(i, j), idx(i, j + 1), std::abs(a[i][j] - a[i][j + 1])});
            }
        }
    }

    std::sort(all(edges));

    DSURollback dsu(n * n);
    int ans = 1;
    int i = 0;

    while (i < sz(edges))
    {
        int j = i;
        int checkpoint = sz(dsu.st);

        while (j < sz(edges) && edges[j].w == edges[i].w)
        {
            dsu.join(edges[j].u, edges[j].v);
            j++;
        }

        for (int k = i; k < j; k++)
        {
            int ru = dsu.acs(edges[k].u);
            int rv = dsu.acs(edges[k].v);
            ans = std::max({ans, dsu.sz[ru], dsu.sz[rv]});
        }

        dsu.rollback(checkpoint);
        i = j;
    }

    std::cout << ans;
}

