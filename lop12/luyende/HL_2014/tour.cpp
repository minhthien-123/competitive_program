ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;

struct SPFA
{
    int n;
    std::vector<std::vector<std::pair<int, ld>>> adj;
    std::vector<ld> dist;
    std::vector<int> cnt;
    std::vector<bool> in_q;

    SPFA(int n) : n(n)
    {
        adj.resize(n + 7);
        dist.assign(n + 7, 0.0);
        cnt.assign(n + 7, 0);
        in_q.assign(n + 7, false);
    }

    void add_edge(int u, int v, ld w)
    {
        adj[u].push_back({v, w});
    }

    bool run(ld mid)
    {
        std::fill(dist.begin(), dist.end(), 0.0);
        std::fill(cnt.begin(), cnt.end(), 0);
        std::fill(in_q.begin(), in_q.end(), true);

        std::queue<int> q;
        for (int i = 1; i <= n; i++)
        {
            q.push(i);
        }

        while (!q.empty())
        {
            int u = q.front();
            q.pop();
            in_q[u] = false;

            for (auto [v, w] : adj[u])
            {
                if (dist[u] + w - mid < dist[v])
                {
                    dist[v] = dist[u] + w - mid;
                    if (!in_q[v])
                    {
                        q.push(v);
                        in_q[v] = true;
                        cnt[v]++;
                        if (cnt[v] >= n)
                        {
                            return true;
                        }
                    }
                }
            }
        }
        return false;
    }
};

void solve()
{
    std::cin >> n >> m;

    SPFA spfa(n);
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        ld c;
        std::cin >> u >> v >> c;
        spfa.add_edge(u, v, c);
    }

    ld l = 0, r = 1e9, ans = -1;
    for (int i = 0; i < 70; i++)
    {
        ld mid = (l + r) / 2.0;
        if (spfa.run(mid))
        {
            ans = mid;
            r = mid;
        }
        else
        {
            l = mid;
        }
    }

    if (ans == -1)
    {
        std::cout << "NO TOUR";
    }
    else
    {
        std::cout << std::fixed << std::setprecision(2) << ans;
    }
}

