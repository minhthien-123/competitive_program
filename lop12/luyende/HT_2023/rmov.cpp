ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int m, n, K;

void solve()
{
    std::cin >> m >> n >> K;

    std::vector<std::vector<int>> a(m + 1, std::vector<int>(n + 1));
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
        }
    }

    std::vector<std::vector<std::vector<int>>> dp(2, std::vector<std::vector<int>>(n + 1, std::vector<int>(K + 1, -INF)));
    dp[1][1][0] = 0;
    if (K >= 1)
    {
        dp[1][1][1] = a[1][1];
    }

    for (int i = 1; i <= m; i++)
    {
        int cur = i % 2;
        int pre = 1 - cur;

        for (int j = 1; j <= n; j++)
        {
            if (i == 1 && j == 1)
            {
                continue;
            }
            for (int k = 0; k <= K; k++)
            {
                int best = -INF;
                if (i > 1)
                {
                    best = std::max(best, dp[pre][j][k]);
                }
                if (j > 1)
                {
                    best = std::max(best, dp[cur][j - 1][k]);
                }
                dp[cur][j][k] = best;

                if (k > 0)
                {
                    if (i > 1 && dp[pre][j][k - 1] != -INF)
                    {
                        dp[cur][j][k] = std::max(dp[cur][j][k], dp[pre][j][k - 1] + a[i][j]);
                    }
                    if (j > 1 && dp[cur][j - 1][k - 1] != -INF)
                    {
                        dp[cur][j][k] = std::max(dp[cur][j][k], dp[cur][j - 1][k - 1] + a[i][j]);
                    }
                }
            }
        }
    }

    int ans = 0;
    for (int k = 0; k <= K; k++)
    {
        ans = std::max(ans, dp[m % 2][n][k]);
    }
    std::cout << ans;
}

