ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, s, d, k;
std::multiset<int> s1, s2;
int a[maxn + 7];
int sum = 0;

void balance()
{
    while (sz(s1) < k && !s2.empty())
    {
        auto it = std::prev(s2.end());
        sum += *it;
        s1.ins(*it);
        s2.erase(it);
    }
    while (sz(s1) > k)
    {
        auto it = s1.begin();
        sum -= *it;
        s2.ins(*it);
        s1.erase(it);
    }
    while (!s1.empty() && !s2.empty() && *s1.begin() < *s2.rbegin())
    {
        auto it1 = s1.begin();
        auto it2 = std::prev(s2.end());
        sum += *it2 - *it1;
        s1.ins(*it2);
        s2.ins(*it1);
        s1.erase(it1);
        s2.erase(it2);
    }
}

void solve()
{
    std::cin >> n >> s >> d;
    for (int i = 0; i < n; i++)
    {
        std::cin >> a[i];
    }

    int ans = 0;
    for (int l = s; l >= 0; l--)
    {
        s1.clear();
        s2.clear();
        sum = 0;
        k = 0;

        for (int i = l; i <= s; i++)
        {
            s2.ins(a[i]);
        }

        for (int r = s; r < n; r++)
        {
            if (r > s)
            {
                s2.ins(a[r]);
            }

            int cost = r - l + std::min(s - l, r - s);

            if (d >= cost)
            {
                k = d - cost;
                balance();
                ans = std::max(ans, sum);
            }
            else
            {
                break;
            }
        }
    }

    std::cout << ans;
}

