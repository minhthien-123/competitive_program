ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];

int n;
int a[maxn + 7];
int inc[maxn + 7], dec[maxn + 7];
int dp[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[n - i + 1];
    }

    int sz = 0;
    for (int i = 1; i <= n; i++)
    {
        int pos = std::lower_bound(dp + 1, dp + 1 + sz, a[i]) - dp;
        dp[pos] = a[i];
        if (pos > sz)
        {
            sz++;
        }
        inc[i] = pos;
    }

    sz = 0;
    for (int i = 1; i <= n; i++)
    {
        int pos = std::lower_bound(dp + 1, dp + 1 + sz, -a[i]) - dp;
        dp[pos] = -a[i];
        if (pos > sz)
        {
            sz++;
        }
        dec[i] = pos;
    }

    int ans = 0;
    for (int i = 1; i <= n; i++)
    {
        ans = std::max(ans, inc[i] + dec[i] - 1);
    }

    std::cout << ans << "\n";
}

