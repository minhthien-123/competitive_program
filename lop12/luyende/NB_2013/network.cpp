ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree() { n = 0; }

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 1, 0);
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= (r & -r))
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
            return 0;
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += (idx & -idx))
        {
            bit[idx] += delta;
        }
    }
};

FenwickTree bit;

struct HLD
{
    int n, timer;
    std::vector<std::vector<int>> adj;
    std::vector<int> par, depth, heavy, head, pos, sz;

    HLD(int n)
    {
        this->n = n;
        timer = 0;
        adj.resize(n + 7);
        par.resize(n + 7);
        depth.resize(n + 7);
        heavy.assign(n + 7, -1);
        head.resize(n + 7);
        pos.resize(n + 7);
        sz.resize(n + 7);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    int dfs(int v, int p)
    {
        sz[v] = 1;
        par[v] = p;
        int max_sub = 0;
        for (int u : adj[v])
        {
            if (u != p)
            {
                depth[u] = depth[v] + 1;
                int sub_sz = dfs(u, v);
                sz[v] += sub_sz;
                if (sub_sz > max_sub)
                {
                    max_sub = sub_sz;
                    heavy[v] = u;
                }
            }
        }
        return sz[v];
    }

    void decompose(int v, int h, int p)
    {
        head[v] = h;
        pos[v] = ++timer;
        if (heavy[v] != -1)
        {
            decompose(heavy[v], h, v);
        }
        for (int u : adj[v])
        {
            if (u != p && u != heavy[v])
            {
                decompose(u, u, v);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
        decompose(root, root, root);
    }

    long long query_path(int u, int v)
    {
        long long res = 0;
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
                std::swap(u, v);
            res += bit.sum(pos[head[u]], pos[u]);
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
            std::swap(u, v);
        if (pos[u] + 1 <= pos[v])
        {
            res += bit.sum(pos[u] + 1, pos[v]);
        }
        return res;
    }
};

int n, m;
struct Edge
{
    int u, v, w, child, id;
};
Edge edges[maxn + 7];

struct Query
{
    int type, a, b, c, k, id;
};
Query queries[maxn + 8];

int edge_order[maxn + 7];
int ans[maxn + 8];

bool cmpE(int i, int j)
{
    return edges[i].w < edges[j].w;
}

bool cmpQ(const Query &q1, const Query &q2)
{
    return q1.c < q2.c;
}

void solve()
{
    std::cin >> n >> m;

    HLD hld(n);
    for (int i = 1; i < n; i++)
    {
        std::cin >> edges[i].u >> edges[i].v >> edges[i].w;
        edges[i].id = i;
        hld.add_edge(edges[i].u, edges[i].v);
    }

    hld.build(1);
    bit = FenwickTree(n + 7);

    for (int i = 1; i < n; i++)
    {
        if (hld.depth[edges[i].u] > hld.depth[edges[i].v])
        {
            edges[i].child = edges[i].u;
        }
        else
        {
            edges[i].child = edges[i].v;
        }
    }

    for (int i = 1; i <= m; i++)
    {
        char type;
        std::cin >> type;
        queries[i].id = i;
        if (type == 'P')
        {
            queries[i].type = 1;
            std::cin >> queries[i].a >> queries[i].b >> queries[i].c;
        }
        else
        {
            queries[i].type = 2;
            std::cin >> queries[i].k >> queries[i].c;
        }
    }

    for (int i = 1; i < n; i++)
    {
        edge_order[i] = i;
    }

    std::sort(edge_order + 1, edge_order + n, cmpE);
    std::sort(queries + 1, queries + m + 1, cmpQ);

    int ptr = 1;
    int tot = 0;

    for (int i = 1; i <= m; i++)
    {
        while (ptr < n && edges[edge_order[ptr]].w <= queries[i].c)
        {
            int e_idx = edge_order[ptr];
            int child = edges[e_idx].child;
            bit.add(hld.pos[child], 1);
            tot++;
            ptr++;
        }

        if (queries[i].type == 1)
        {
            ans[queries[i].id] = hld.query_path(queries[i].a, queries[i].b);
        }
        else
        {
            int k = queries[i].k;
            int child = edges[k].child;
            int target = edges[k].v;

            int sub_sum = bit.sum(hld.pos[child] + 1, hld.pos[child] + hld.sz[child] - 1);

            if (target == child)
            {
                ans[queries[i].id] = sub_sum;
            }
            else
            {
                int c = (edges[k].w <= queries[i].c ? 1 : 0);
                ans[queries[i].id] = tot - sub_sum - c;
            }
        }
    }

    for (int i = 1; i <= m; i++)
    {
        std::cout << ans[i] << "\n";
    }
}

