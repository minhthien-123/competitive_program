ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];

int m, n;
char a[maxn + 7][maxn + 7];
int h[maxn + 7][maxn + 7], v[maxn + 7][maxn + 7], dp1[maxn + 7][maxn + 7], dp2[maxn + 7][maxn + 7];

void solve()
{
    std::cin >> m >> n;
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
        }
    }

    for (int i = 1; i <= m; i++)
    {
        int j = 1;
        while (j <= n)
        {
            if (a[i][j] == '#')
            {
                j++;
                continue;
            }
            int start = j;
            while (j <= n && a[i][j] == '.')
            {
                j++;
            }
            for (int k = start; k < j; k++)
            {
                h[i][k] = j - start;
            }
        }
    }

    for (int j = 1; j <= n; j++)
    {
        int i = 1;
        while (i <= m)
        {
            if (a[i][j] == '#')
            {
                i++;
                continue;
            }
            int start = i;
            while (i <= m && a[i][j] == '.')
            {
                i++;
            }
            for (int k = start; k < i; k++)
            {
                v[k][j] = i - start;
            }
        }
    }

    for (int c = 1; c <= n; c++)
    {
        int i = 1, j = c;
        while (i <= m && j <= n)
        {
            if (a[i][j] == '#')
            {
                i++;
                j++;
                continue;
            }
            int si = i, sj = j;
            while (i <= m && j <= n && a[i][j] == '.')
            {
                i++;
                j++;
            }
            for (int k = 0; k < i - si; k++)
            {
                dp1[si + k][sj + k] = i - si;
            }
        }
    }

    for (int r = 2; r <= m; r++)
    {
        int i = r, j = 1;
        while (i <= m && j <= n)
        {
            if (a[i][j] == '#')
            {
                i++;
                j++;
                continue;
            }
            int si = i, sj = j;
            while (i <= m && j <= n && a[i][j] == '.')
            {
                i++;
                j++;
            }
            for (int k = 0; k < i - si; k++)
            {
                dp1[si + k][sj + k] = i - si;
            }
        }
    }

    for (int c = 1; c <= n; c++)
    {
        int i = 1, j = c;
        while (i <= m && j >= 1)
        {
            if (a[i][j] == '#')
            {
                i++;
                j--;
                continue;
            }
            int si = i, sj = j;
            while (i <= m && j >= 1 && a[i][j] == '.')
            {
                i++;
                j--;
            }
            for (int k = 0; k < i - si; k++)
            {
                dp2[si + k][sj - k] = i - si;
            }
        }
    }

    for (int r = 2; r <= m; r++)
    {
        int i = r, j = n;
        while (i <= m && j >= 1)
        {
            if (a[i][j] == '#')
            {
                i++;
                j--;
                continue;
            }
            int si = i, sj = j;
            while (i <= m && j >= 1 && a[i][j] == '.')
            {
                i++;
                j--;
            }
            for (int k = 0; k < i - si; k++)
            {
                dp2[si + k][sj - k] = i - si;
            }
        }
    }

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (a[i][j] == '#')
            {
                std::cout << 0 << " ";
            }
            else
            {
                std::cout << h[i][j] + v[i][j] + dp1[i][j] + dp2[i][j] - 3 << " ";
            }
        }
        std::cout << "\n";
    }
}

