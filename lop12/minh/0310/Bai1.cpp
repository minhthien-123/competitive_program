ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll n, k, x, d, q, R;

ll count(ll mid)
{
    if (mid == 0)
    {
        return 0;
    }

    ll cnt = mid * q;
    ll lst = x + mid - 1;

    if (lst < k)
    {
        if (x <= R)
        {
            cnt += std::min(lst, R) - x + 1;
        }
    }
    else
    {
        if (x <= R)
        {
            cnt += R - x + 1;
        }
        ll lst2 = lst - k;
        cnt += std::min(lst2, R) + 1;
    }
    return cnt;
}

void solve()
{
    std::cin >> n >> k >> x >> d;

    x %= k;
    R = n % k;
    q = n / k;

    ll l = 1, r = k;
    ll ans = -1;
    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (count(mid) >= d)
        {
            ans = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    ll val = (x + ans - 1) % k;
    ll sz = count(ans) - count(ans - 1);
    ll pre_cnt = count(ans - 1);
    ll rem = d - pre_cnt;

    // res = val + (j - 1) * k
    ll res = val + (sz - rem) * k;
    std::cout << res << "\n";
}

