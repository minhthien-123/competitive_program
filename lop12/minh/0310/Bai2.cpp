ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
vi adj[maxn + 7];
vi path;

bool find_path(int u, int p, int target)
{
    path.pb(u);
    if (u == target)
    {
        return true;
    }
    for (int v : adj[u])
    {
        if (v != p)
        {
            if (find_path(v, u, target))
            {
                return true;
            }
        }
    }
    path.pop_back();
    return false;
}

int cut_u = -1, cut_v = -1;

int dfs(int u, int p)
{
    vi times;
    for (int v : adj[u])
    {
        if (v == p || (u == cut_u && v == cut_v) || (u == cut_v && v == cut_u))
        {
            continue;
        }
        times.pb(dfs(v, u));
    }
    std::sort(times.rbegin(), times.rend());

    int res = 0;
    for (int i = 0; i < sz(times); i++)
    {
        res = std::max(res, times[i] + i + 1);
    }

    return res;
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    std::cin >> m;
    std::vector<int> root;
    for (int i = 1; i <= m; i++)
    {
        int x;
        std::cin >> x;
        root.pb(x);
    }

    if (m == 1)
    {
        std::cout << dfs(root[0], 0);
        return;
    }

    find_path(root[0], 0, root[1]);

    int ans = inf;

    for (int i = 0; i < sz(path) - 1; i++)
    {
        cut_u = path[i];
        cut_v = path[i + 1];

        int time1 = dfs(root[0], 0);
        int time2 = dfs(root[1], 0);

        ans = std::min(ans, std::max(time1, time2));
    }

    std::cout << ans;
}

