struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> mx, up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        mx.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

