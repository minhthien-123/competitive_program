ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 1, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size())
    {
        for (int i = 0; i < a.size(); i++)
        {
            add(i, a[i]);
        }
    }

    int get(int r)
    {
        int res = 0;
        for (; r >= 0; r = (r & (r + 1)) - 1)
        {
            res = std::max(res, bit[r]);
        }
        return res;
    }

    void add(int idx, int delta)
    {
        for (; idx < n; idx = idx | (idx + 1))
        {
            bit[idx] = std::max(bit[idx], delta);
        }
    }
};

std::vector<int> adj[maxn + 7];
int n;
int l[maxn + 7], r[maxn + 7];
int dp[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 0; i < n; i++)
    {
        std::cin >> l[i] >> r[i];
    }

    FenwickTree bit(n);

    int ans = 0;

    // i > j + r_j
    // j < i - l_i - 1

    for (int i = 0; i < n; i++)
    {
        if (i - 1 >= 0)
        {
            for (int j : adj[i - 1])
            {
                bit.add(j + 1, dp[j]);
            }
        }

        int mx = bit.get(i - l[i]);
        dp[i] = mx + 1;
        ans = std::max(ans, dp[i]);

        if (i + r[i] < n)
        {
            adj[i + r[i]].pb(i);
        }
    }

    std::cout << ans;
}

