struct StringHash
{
    int n;
    long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};

StringHash hash("");

int get(int len, int &start)
{
    std::vector<std::pair<ii, int>> vec;

    for (int i = 1; i <= n - len + 1; i++)
    {
        vec.pb({hash.get_hash(i, i + len - 1), i});
    }

    if (vec.empty())
    {
        return 0;
    }

    std::sort(all(vec));

    int cnt = 1;
    int mx = 0;
    int ans = -1;

    for (int i = 1; i < sz(vec); i++)
    {
        if (vec[i].fi == vec[i - 1].fi)
        {
            cnt++;
        }
        else
        {
            if (cnt > mx)
            {
                mx = cnt;
                ans = vec[i - 1].se;
            }
            cnt = 1;
        }
    }

    if (cnt > mx)
    {
        mx = cnt;
        ans = vec.back().se;
    }

    start = ans;
    return mx;
}

void solve()
{
    std::cin >> s;

    hash = StringHash(s);

    n = sz(s);
    s = " " + s;

    int l = 2, r = n - 1;
    int len = 2, start = -1, freq = -1;
    int mx = get(2, start);

    while (l <= r)
    {
        int mid = (l + r) / 2;
        int pos = -1;
        int tmp = get(mid, pos);

        if (tmp == mx)
        {
            len = mid;
            start = pos;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << mx << "\n" << s.substr(start, len);
}

