ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, t;
int a[maxn + 7];

struct Sieve
{
    int n;
    std::vector<int> min_prime;
    std::vector<int> primes;

    Sieve(int n) : n(n)
    {
        min_prime.assign(n + 1, 0);
        for (int i = 2; i <= n; i++)
        {
            if (min_prime[i] == 0)
            {
                min_prime[i] = i;
                primes.push_back(i);
            }
            for (int p : primes)
            {
                if (p > min_prime[i] || i * p > n)
                {
                    break;
                }
                min_prime[i * p] = p;
            }
        }
    }

    bool is_prime(int x)
    {
        if (x < 2)
        {
            return false;
        }
        return min_prime[x] == x;
    }
};

void solve()
{
    Sieve sv(1e7);
    std::cin >> n >> t;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 1; i <= n; i++)
    {
        a[i] = (sv.min_prime[a[i]] + 1) * (sv.min_prime[a[i]] + 1);
    }

    while (t--)
    {
        int q;
        std::cin >> q;

        int l = 1;
        int len = 0;

        std::deque<int> mx, mn;

        for (int r = 1; r <= n; r++)
        {
            while (mx.size() && a[mx.back()] <= a[r])
            {
                mx.pop_back();
            }
            mx.push_back(r);

            while (mn.size() && a[mn.back()] >= a[r])
            {
                mn.pop_back();
            }
            mn.push_back(r);

            while (mx.size() && mn.size() && a[mx.front()] - a[mn.front()] > q)
            {
                l++;

                if (mx.front() < l)
                {
                    mx.pop_front();
                }
                if (mn.front() < l)
                {
                    mn.pop_front();
                }
            }

            len = std::max(len, r - l + 1);
        }

        std::cout << len << "\n";
    }
}

