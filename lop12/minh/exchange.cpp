std::pair<std::vector<int>, int> get(std::vector<int> a, int target)
{
    if (target <= 0)
    {
        return {{}, 0};
    }

    std::sort(all(a));

    int S = 0;
    int c = 0;

    for (int i = sz(a) - 1; i >= 0; i--)
    {
        S += a[i];
        c++;
        if (S >= target)
        {
            break;
        }
    }

    std::multiset<int> mts;
    for (int i = 0; i < sz(a) - c; i++)
    {
        mts.ins(a[i]);
    }

    std::vector<int> vec;
    for (int i = sz(a) - c; i < sz(a); i++)
    {
        vec.pb(a[i]);
    }

    for (int i = 0; i < c; i++)
    {
        int need = target - S + vec[i];

        auto it = mts.lower_bound(need);
        if (it != mts.end() && *it < vec[i])
        {
            int x = *it;
            S = S - vec[i] + x;

            mts.erase(it);
            mts.ins(vec[i]);
            vec[i] = x;
        }
    }

    return {vec, S};
}
void solve()
{
    std::cin >> n >> p;

    int sum1 = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cnt[a[i]]++;
        sum1 += a[i];
    }

    std::vector<int> vec1, vec2;

    for (auto [v, c] : cnt)
    {
        vec1.pb(v);
        for (int k = 1; k < c; k++)
        {
            vec2.pb(v);
        }
    }

    std::vector<int> ans;
    int sum = 0;
    int sum2 = 0;
    for (int i : vec2)
    {
        sum2 += i;
    }

    if (sum2 >= p)
    {
        auto res = get(vec2, p);
        ans = res.fi;
        sum = res.se;
    }
    else
    {
        for (int x : vec2)
        {
            ans.pb(x);
            sum += x;
        }

        auto res = get(vec1, p - sum);
        for (int x : res.fi)
        {
            ans.pb(x);
            sum += x;
        }
    }

    for (int x : ans)
    {
        cnt[x]--;
    }
    int dem = 0;
    for (int i = 1; i <= n; i++)
    {
        if (cnt[a[i]])
        {
            cnt[a[i]] = 0;
            dem++;
        }
    }

    std::cout << dem << " " << sum << "\n";
    std::sort(all(ans));
    for (int x : ans)
    {
        std::cout << x << " ";
    }
}

