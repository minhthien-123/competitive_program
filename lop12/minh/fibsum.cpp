struct Matrix
{
    std::vector<std::vector<long long>> a;
    int r, c;

    Matrix(int r, int c, bool is_identity = false) : r(r), c(c)
    {
        a.assign(r, std::vector<long long>(c, 0));
        if (is_identity)
        {
            for (int i = 0; i < std::min(r, c); i++)
                a[i][i] = 1;
        }
    }

    Matrix operator*(const Matrix &other) const
    {
        Matrix res(r, other.c);
        for (int i = 0; i < r; i++)
        {
            for (int k = 0; k < c; k++)
            {
                if (a[i][k] == 0)
                    continue;
                for (int j = 0; j < other.c; j++)
                {
                    res.a[i][j] = (res.a[i][j] + a[i][k] * other.a[k][j]) % mod;
                }
            }
        }
        return res;
    }

    Matrix operator+(const Matrix &other) const
    {
        Matrix res(r, c);
        for (int i = 0; i < r; ++i)
        {
            for (int j = 0; j < c; ++j)
            {
                res.a[i][j] = (a[i][j] + other.a[i][j]) % mod;
            }
        }
        return res;
    }

    Matrix power(long long p)
    {
        Matrix res(r, c, true);
        Matrix base = *this;
        while (p > 0)
        {
            if (p & 1)
                res = res * base;
            base = base * base;
            p >>= 1;
        }
        return res;
    }
};

struct SegTree
{
    int n;
    std::vector<Matrix> st;
    std::vector<Matrix> lazy;
    std::vector<bool> lz;

    SegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, Matrix(2, 1));
        lazy.assign(4 * n + 7, Matrix(2, 2, true));
        lz.assign(4 * n + 7, false);
    }

    void build(int id, int l, int r)
    {
        if (l == r)
        {
            Matrix I(2, 2);
            I.a[0][0] = 1;
            I.a[0][1] = 1;
            I.a[1][0] = 1;
            I.a[1][1] = 0;

            Matrix F(2, 1);
            F.a[0][0] = 1;
            F.a[1][0] = 0;

            st[id] = I.power(a[l]) * F;
            return;
        }
        int mid = (l + r) / 2;
        build(2 * id, l, mid);
        build(2 * id + 1, mid + 1, r);
        st[id] = st[2 * id] + st[2 * id + 1];
    }

    void push(int id)
    {
        if (lz[id])
        {
            lazy[2 * id] = lazy[id] * lazy[2 * id];
            st[2 * id] = lazy[id] * st[2 * id];
            lz[2 * id] = true;

            lazy[2 * id + 1] = lazy[id] * lazy[2 * id + 1];
            st[2 * id + 1] = lazy[id] * st[2 * id + 1];
            lz[2 * id + 1] = true;

            lazy[id] = Matrix(2, 2, true);
            lz[id] = false;
        }
    }

    void update(int id, int l, int r, int u, int v, Matrix val)
    {
        if (v < l || r < u)
        {
            return;
        }
        if (u <= l && r <= v)
        {
            st[id] = val * st[id];
            lazy[id] = val * lazy[id];
            lz[id] = true;
            return;
        }
        push(id);
        int mid = (l + r) / 2;
        update(2 * id, l, mid, u, v, val);
        update(2 * id + 1, mid + 1, r, u, v, val);
        st[id] = st[2 * id] + st[2 * id + 1];
    }

    Matrix query(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return Matrix(2, 1);
        }
        if (u <= l && r <= v)
        {
            return st[id];
        }
        push(id);
        int mid = (l + r) / 2;
        return query(2 * id, l, mid, u, v) + query(2 * id + 1, mid + 1, r, u, v);
    }
};

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    SegTree tree(n);
    tree.build(1, 1, n);

    Matrix I(2, 2);
    I.a[0][0] = 1;
    I.a[0][1] = 1;
    I.a[1][0] = 1;
    I.a[1][1] = 0;

    while (m--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int x, val;
            std::cin >> x >> val;
            tree.update(1, 1, n, x, x, I.power(val));
        }
        else if (type == 2)
        {
            int l, r, val;
            std::cin >> l >> r >> val;
            tree.update(1, 1, n, l, r, I.power(val));
        }
        else if (type == 3)
        {
            int l, r;
            std::cin >> l >> r;
            Matrix res = tree.query(1, 1, n, l, r);
            std::cout << res.a[1][0] << "\n";
        }
    }
}

