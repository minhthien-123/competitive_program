std::string s;
int dp[maxn + 7][9][32][2];

int calc(int pos, int sum9, int mask, bool tight, bool start)
{
    if (pos == sz(s))
    {
        if (!start)
        {
            return 0;
        }
        return (sum9 % 3 == 0 && sum9 != 0);
    }

    if (tight && dp[pos][sum9][mask][start] != -1)
    {
        return dp[pos][sum9][mask][start];
    }

    int up = tight ? 9 : (s[pos] - '0');

    ll res = 0;

    for (int d = 0; d <= up; d++)
    {
        int r = d % 5;
        int need = (5 - r) % 5;

        if (start && (mask & (1 << need)))
        {
            continue;
        }

        bool nxt_start = start || (d != 0);

        int nxt_mask = mask;
        if (nxt_start)
        {
            nxt_mask |= (1 << r);
        }

        res = add(res,calc(pos + 1, (sum9 + d) % 9, nxt_mask, tight || (d < up), nxt_start));
    }

    if (tight)
    {
        dp[pos][sum9][mask][start] = res;
    }

    return res;
}
ll get(std::string str)
{
    s = str;
    memset(dp, -1, sizeof(dp));
    return calc(0, 0, 0, 0, 0);
}

std::string sub1(std::string s)
{
    if (s == "0")
    {
        return "0";
    }
    int n = sz(s);
    int i = n - 1;
    while (i >= 0 && s[i] == '0')
    {
        s[i] = '9';
        i--;
    }
    s[i]--;
    if (s[0] == '0' && sz(s) > 1)
    {
        s.erase(0, 1);
    }
    return s;
}

void solve()
{
    std::string a, b;
    std::cin >> a >> b;
    std::cout << sub(get(b), get(sub1(a))) << "\n";
}

