ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
int a[maxn + 7];
int sum[bl + 7][bl + 7];

void solve()
{
    std::cin >> n >> q;

    while (q--)
    {
        int type, x, y;
        std::cin >> type >> x >> y;
        if (type == 1)
        {
            a[x] += y;
            for (int i = 1; i <= bl; i++)
            {
                sum[i][x % i] += y;
            }
        }
        else
        {
            if (x <= bl)
            {
                std::cout << sum[x][y] << "\n";
            }
            else
            {
                int ans = 0;
                for (int k = y; k <= n; k += x)
                {
                    ans += a[k];
                }
                std::cout << ans << "\n";
            }
        }
    }
}

