const int maxn = 5e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7], divs[maxn + 6];
int n, q;
int a[maxn + 7];
int iv[maxn + 7];
int sum[maxn + 7];
int S = 0;
int cnt[maxn + 7];
int s[maxn + 7], sq[maxn + 7];

void init()
{
    for (int i = 1; i <= maxn; i++)
    {
        for (int j = i; j <= maxn; j += i)
        {
            s[i] = add(s[i], cnt[j] * j);
            sq[i] = add(sq[i], mul(mul(cnt[j], j), j));
            divs[j].pb(i);
        }
    }
    for (int i = 1; i <= maxn; i++)
    {
        iv[i] = power(mul(i, i), mod - 2);
    }
    for (int i = 1; i <= maxn; i++)
    {
        S = add(S, mul(sub(mul(s[i], s[i]), sq[i]), iv[i]));
    }
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cnt[a[i]]++;
    }

    init();
    S = mul(S, inv);
    std::cout << S << "\n";
    while (q--)
    {
        int x, y;
        std::cin >> x >> y;
        for (int i : divs[a[x]])
        {
            s[i] = sub(s[i], a[x]);
            S = sub(S, mul(mul(a[x], s[i]), iv[i]));
        }
        a[x] = y;
        for (int i : divs[y])
        {
            S = add(S, mul(mul(y, s[i]), iv[i]));
            s[i] = add(s[i], y);
        }
        std::cout << S << '\n';
    }
}

