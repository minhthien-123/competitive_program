const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7];
std::map<int, std::vector<int>> pos;

void solve()
{
    std::cin >> n >> m;
    pos.clear();
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        pos[a[i]].pb(i);
    }

    int ans = 0;
    int tot = (n * (n + 1) / 2) % mod;
    int sum_m = mul(m % mod, (m + 1) % mod);
    sum_m = mul(sum_m, inv);

    ans = mul(tot, sum_m);

    for (auto it : pos)
    {
        int x = it.fi;
        std::vector<int> p = it.se;

        ans = sub(ans, mul(tot, x % mod));

        int res = 0;
        int last = 0;
        for (int i = 0; i < sz(p); i++)
        {
            int len = p[i] - last - 1;
            if (len > 0)
            {
                int ways = (len * (len + 1) / 2) % mod;
                res = add(res, ways);
            }
            last = p[i];
        }
        int len = (n + 1) - last - 1;
        if (len > 0)
        {
            int ways = (len * (len + 1) / 2) % mod;
            res = add(res, ways);
        }

        ans = add(ans, mul(res, x % mod));
    }

    std::cout << ans;
}

