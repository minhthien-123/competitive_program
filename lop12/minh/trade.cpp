struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);

        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

void solve()
{
    std::cin >> n >> m >> k;
    DSU dsu(n);
    for (int i = 1; i <= k; i++)
    {
        std::cin >> a[i];
        if (i > 1)
        {
            dsu.join(a[i], a[i - 1]);
        }
    }
    for (int i = 1; i <= m; i++)
    {
        int u, v, c;
        std::cin >> u >> v >> c;
        edges.pb({u, v, c});
    }

    std::sort(all(edges));

    int cost = 0;
    for (auto [u, v, c] : edges)
    {
        if (dsu.acs(u) != dsu.acs(v))
        {
            dsu.join(u, v);
            cost += c;
        }
    }
    int cnt = 0;
    for (int i = 1; i <= n; i++)
    {
        if (dsu.acs(i) == i)
        {
            cnt++;
        }
    }
    if (cnt != 1)
    {
        std::cout << -1;
        return;
    }
    std::cout << cost;
}

