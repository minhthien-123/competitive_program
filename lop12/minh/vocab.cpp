int dp[2][2];

void solve()
{
    std::cin >> a >> b >> c;
    int len = std::max({a.length(), b.length(), c.length()});
    a = " " + a;
    b = " " + b;
    c = " " + c;

    dp[1][1] = 1;

    for (int i = 1; i <= len; i++)
    {
        int old[2][2];
        for (int fA = 0; fA < 2; fA++)
        {
            for (int fB = 0; fB < 2; fB++)
            {
                old[fA][fB] = dp[fA][fB];
                dp[fA][fB] = 0;
            }
        }

        int xA, yA, xB, yB, xC, yC;

        if (i >= sz(a))
        {
            xA = 0;
            yA = 0;
        }
        else if (a[i] == '?')
        {
            xA = 1;
            yA = 26;
        }
        else
        {
            xA = a[i] - 'a' + 1;
            yA = a[i] - 'a' + 1;
        }

        if (i >= sz(b))
        {
            xB = 0;
            yB = 0;
        }
        else if (b[i] == '?')
        {
            xB = 1;
            yB = 26;
        }
        else
        {
            xB = b[i] - 'a' + 1;
            yB = b[i] - 'a' + 1;
        }

        if (i >= sz(c))
        {
            xC = 0;
            yC = 0;
        }
        else if (c[i] == '?')
        {
            xC = 1;
            yC = 26;
        }
        else
        {
            xC = c[i] - 'a' + 1;
            yC = c[i] - 'a' + 1;
        }

        for (int fA = 0; fA < 2; fA++)
        {
            for (int fB = 0; fB < 2; fB++)
            {
                if (!old[fA][fB])
                {
                    continue;
                }

                for (int x = xA; x <= yA; x++)
                {
                    for (int y = xB; y <= yB; y++)
                    {
                        int tA = fA;
                        if (fA == 1)
                        {
                            if (x > y)
                            {
                                continue;
                            }
                            tA = (x == y);
                        }

                        for (int z = xC; z <= yC; z++)
                        {
                            int tB = fB;
                            if (fB == 1)
                            {
                                if (y > z)
                                {
                                    continue;
                                }
                                tB = (y == z);
                            }

                            dp[tA][tB] = add(dp[tA][tB], old[fA][fB]);
                        }
                    }
                }
            }
        }
    }

    std::cout << dp[0][0] << "\n";
}

