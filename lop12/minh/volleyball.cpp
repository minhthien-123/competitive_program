void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int j = 1; j <= m; j++)
    {
        std::cin >> b[j];
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = i + 1; j <= n; j++)
        {
            vec.pb(a[i] + a[j]);
        }
    }

    std::sort(all(vec));
    std::sort(b + 1, b + m + 1);

    for (auto sum : vec)
    {
        int l = 1, r = m;
        while (l < r)
        {
            if (b[l] + b[r] > sum)
            {
                r--;
            }
            else if (b[l] + b[r] < sum)
            {
                l++;
            }
            else
            {
                std::cout << sum;
                return ;
            }
        }
    }

    std::cout << "no volleyball today";
}

