ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj1[maxn + 7], adj2[maxn + 7];
int n;
int a[maxn + 7], b[maxn + 7];
int tin[maxn + 7], tout[maxn + 7], tour[maxn + 7], timer = 0;
int root1, root2;
int ans = 0;

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree() {}

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 5, 0);
    }

    int sum(int r)
    {
        int res = 0;
        for (int i = r; i > 0; i -= i & -i)
        {
            res += bit[i];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (int i = idx; i <= n + 1; i += i & -i)
        {
            bit[i] += delta;
        }
    }
};

FenwickTree bit;

void dfs1(int u, int p)
{
    timer++;
    tin[u] = timer;
    for (int v : adj1[u])
    {
        if (v == p)
        {
            continue;
        }
        dfs1(v, u);
    }
    tout[u] = timer;
}

void dfs2(int u, int p)
{
    ans += bit.sum(tin[u]);
    bit.add(tin[u], 1);
    bit.add(tout[u] + 1, -1);
    for (int v : adj2[u])
    {
        if (v == p)
        {
            continue;
        }
        dfs2(v, u);
    }
    bit.add(tin[u], -1);
    bit.add(tout[u] + 1, 1);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        if (a[i] == 0)
        {
            root1 = i;
        }
        else
        {
            adj1[a[i]].pb(i);
        }
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> b[i];
        if (b[i] == 0)
        {
            root2 = i;
        }
        else
        {
            adj2[b[i]].pb(i);
        }
    }

    bit = FenwickTree(n);
    dfs1(root1, -1);
    dfs2(root2, -1);

    std::cout << ans;
}

