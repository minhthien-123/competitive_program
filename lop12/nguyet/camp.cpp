ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7];

bool check(ll x)
{
    ll sum = 0, cnt = 0;
    for (int i = 1; i <= n + 1; i++)
    {
        if (a[i] > x)
        {
            return false;
        }
        if (sum + a[i] <= x)
        {
            sum += a[i];
        }
        else
        {
            sum = a[i];
            cnt++;
        }
    }
    if (sum)
    {
        cnt++;
    }
    return cnt <= m;
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n + 1; i++)
    {
        std::cin >> a[i];
    }

    int l = 0, r = 1e18, ans = -1;
    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            r = mid - 1;
            ans = mid;
        }
        else
        {
            l = mid + 1;
        }
    }

    std::cout << ans;
}

