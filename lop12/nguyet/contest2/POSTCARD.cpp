ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int m, n, k;
int a[maxn + 7][maxn + 7];
int freq[maxn * maxn + 7];

bool check(int len)
{
    memset(freq, 0, sizeof(freq));

    for (int r = 1; r <= m - len + 1; r++)
    {
        int cnt = 0;

        for (int i = r; i < r + len; i++)
        {
            for (int j = 1; j <= len; j++)
            {
                if (freq[a[i][j]] == 0)
                {
                    cnt++;
                }
                freq[a[i][j]]++;
            }
        }

        if (cnt <= k)
        {
            return true;
        }

        int last = 1;
        for (int c = 2; c <= n - len + 1; c++)
        {
            last = c;
            for (int i = r; i < r + len; i++)
            {
                freq[a[i][c - 1]]--;
                if (freq[a[i][c - 1]] == 0)
                {
                    cnt--;
                }

                if (freq[a[i][c + len - 1]] == 0)
                {
                    cnt++;
                }
                freq[a[i][c + len - 1]]++;
            }

            if (cnt <= k)
            {
                return true;
            }
        } 

        for (int i = r; i < r + len; i++)
        {
            for (int j = last; j < last + len; j++)
            {
                freq[a[i][j]]--;
            }
        }
    }

    return false;
}
void solve()
{
    std::cin >> m >> n >> k;
    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> a[i][j];
        }
    }

    int l = 1, r = std::min(m, n);
    int ans = 0;

    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << ans;
}

