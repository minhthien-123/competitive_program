ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, c2, c5, pk, k, p2, ans;
int fact[maxn], res[maxn];
bool prime[maxn];

void init()
{
    for (int i = 1; i <= maxn; i++)
    {
        prime[i] = true;
        fact[i] = 0;
    }

    prime[0] = false;
    prime[1] = false;

    for (int i = 2; i * i <= maxn; i++)
    {
        if (prime[i])
        {
            for (int j = i * i; j <= maxn; j += i)
            {
                prime[j] = false;
            }
        }
    }

    for (int i = 2; i <= maxn; i++)
    {
        if (prime[i])
        {
            pk = i;
            while (pk <= maxn)
            {
                fact[pk] = i;
                pk *= i;
            }
        }
    }

    res[1] = 1;
    for (int i = 2; i <= maxn; i++)
    {
        res[i] = res[i - 1];
        if (fact[i] > 0)
        {
            if (fact[i] != 2)
            {
                if (fact[i] != 5)
                {
                    res[i] = (res[i] * fact[i]) % 10;
                }
            }
        }
    }
}

void solve()
{
    init();
    while (std::cin >> n)
    {
        if (n == 0)
        {
            break;
        }
        c2 = 0;
        pk = 2;
        while (pk <= n)
        {
            c2++;
            pk *= 2;
        }
        c5 = 0;
        pk = 5;
        while (pk <= n)
        {
            c5++;
            pk *= 5;
        }
        k = c2 - c5;
        p2 = 1;
        for (int i = 1; i <= k; i++)
        {
            p2 = (p2 * 2) % 10;
        }
        ans = (res[n] * p2) % 10;
        std::cout << ans << "\n";
    }
}

