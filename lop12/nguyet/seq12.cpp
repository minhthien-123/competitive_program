ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int k, p;
std::vector<int> pos[10];

int dem(int x)
{
    int res = 0;
    int len = 1;
    int pow = 1;
    while (pow * 10 <= x)
    {
        res += len * 9 * pow;
        len++;
        pow *= 10;
    }
    res += len * (x - pow + 1);
    return res;
}

int dem9(int x)
{
    int res = 0;
    int pow = 1;
    while (pow <= x)
    {
        int left = x / (pow * 10);
        int digit = (x / pow) % 10;
        int right = x % pow;
        res += left * pow;
        if (digit == 9)
        {
            res += right + 1;
        }
        pow *= 10;
    }
    return res;
}

int calc(int idx)
{
    int len = 1;
    int cnt = 9;
    int pow = 1;
    while (idx > len * cnt)
    {
        idx -= len * cnt;
        len++;
        pow *= 10;
        cnt *= 10;
    }

    int num = pow + (idx - 1) / len;
    int pos = (idx - 1) % len;
    std::string s = std::to_string(num);
    return s[pos] - '0';
}

void solve()
{
    std::cin >> k >> p;

    int l = 0, r = 2e15, ans = -1;
    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (dem(mid) - dem9(mid) <= k)
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    int target = dem9(ans);
    int l1 = 0, r1 = 2e15;
    while (l1 <= r1)
    {
        int mid = (l1 + r1) / 2;
        if (dem9(mid) >= target)
        {
            ans = mid;
            r1 = mid - 1;
        }
        else
        {
            l1 = mid + 1;
        }
    }

    int krem = k - (dem(ans) - dem9(ans));
    int prem = p - dem9(ans);
    if (prem <= 0)
    {
        std::cout << 9 << "\n";
        return ;
    }
    int cur = dem(ans) + 1;
    std::string str = "";
    for (int i = 1; i <= 150; i++)
    {
        str += std::to_string(ans + i);
    }
    int idx = 0;
    int len = sz(str);
    ans = 0;
    while (prem && krem)
    {
        int digit = -1, pos = -1;
        for (int d = 9; d >= 0; d--)
        {
            for (int i = idx; i <= idx + krem && i < len; i++)
            {
                if (str[i] - '0' == d)
                {
                    digit = d;
                    pos = i;
                    break;
                }
            }

            if (digit != -1)
            {
                break;
            }
        }

        krem -= (pos - idx);
        idx = pos + 1;
        prem--;
        ans = digit;
    }
    if (prem == 0)
    {
        std::cout << ans << "\n";
    }
    else
    {
        std::cout << calc(cur + idx + prem - 1) << "\n";
    }
}

