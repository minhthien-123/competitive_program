ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7];
int cnt[maxn + 7];
ll dp[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 0; i <= n + 1; i++)
    {
        cnt[i] = 0;
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        if (a[i] <= n)
        {
            cnt[a[i]]++;
        }
    }
    int N = 0;
    while (cnt[N] > 0)
    {
        N++;
    }
    if (N == 0)
    {
        std::cout << 0 << "\n";
        return;
    }
    for (int i = 0; i <= N; i++)
    {
        dp[i] = inf;
    }
    dp[N] = 0;
    for (int v = N; v >= 1; v--)
    {
        if (dp[v] == inf)
        {
            continue;
        }
        for (int u = v - 1; u >= 0; u--)
        {
            ll cost = (cnt[u] - 1) * v + u;
            if (dp[v] + cost < dp[u])
            {
                dp[u] = dp[v] + cost;
            }
        }
    }
    std::cout << dp[0] << "\n";
}

