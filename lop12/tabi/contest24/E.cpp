ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int dp[maxn + 7][2];
int dp_up[maxn + 7][2];

void dfs1(int u, int p)
{
    dp[u][0] = 0;
    dp[u][1] = 1;
    for (int i = 0; i < sz(adj[u]); i++)
    {
        int v = adj[u][i];
        if (v != p)
        {
            dfs1(v, u);
            dp[u][0] += std::max(dp[v][0], dp[v][1]);
            dp[u][1] += dp[v][0];
        }
    }
}

void dfs2(int u, int p)
{
    int U0;
    int U1;
    if (u == 1)
    {
        U0 = 0;
        U1 = 0;
    }
    else
    {
        U0 = std::max(dp_up[u][0], dp_up[u][1]);
        U1 = dp_up[u][0];
    }
    int S0 = 0;
    int S1 = 0;
    for (int i = 0; i < sz(adj[u]); i++)
    {
        int v = adj[u][i];
        if (v != p)
        {
            S0 += std::max(dp[v][0], dp[v][1]);
            S1 += dp[v][0];
        }
    }
    for (int i = 0; i < sz(adj[u]); i++)
    {
        int v = adj[u][i];
        if (v != p)
        {
            dp_up[v][0] = U0 + S0 - std::max(dp[v][0], dp[v][1]);
            dp_up[v][1] = 1 + U1 + S1 - dp[v][0];
            dfs2(v, u);
        }
    }
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        adj[i].clear();
    }
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }
    dfs1(1, 0);
    dfs2(1, 0);
    int alpha = std::max(dp[1][0], dp[1][1]);
    bool can_plus_one = false;
    for (int i = 1; i <= n; i++)
    {
        if (sz(adj[i]) == 1)
        {
            int g0;
            int g1;
            if (i == 1)
            {
                g0 = dp[1][0];
                g1 = dp[1][1];
            }
            else
            {
                g0 = std::max(dp_up[i][0], dp_up[i][1]) + dp[i][0];
                g1 = dp_up[i][0] + dp[i][1];
            }
            if (g0 >= g1)
            {
                can_plus_one = true;
                break;
            }
        }
    }
    if (can_plus_one)
    {
        std::cout << alpha + 1 << "\n";
    }
    else
    {
        std::cout << alpha << "\n";
    }
}

