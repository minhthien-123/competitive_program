ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7];
int f[maxn + 7];
int in[maxn + 7];
bool vis[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        char c;
        std::cin >> c;
        f[i] = c - '0';
        vis[i] = false;
        in[i] = 0;
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        in[a[i]]++;
    }

    std::queue<int> qu;
    for (int i = 1; i <= n; i++)
    {
        if (in[i] == 0)
        {
            qu.push(i);
        }
    }

    std::vector<int> ans;
    while (qu.size())
    {
        int u = qu.front();
        qu.pop();

        if (f[u] == 1)
        {
            ans.pb(u);
            f[u] ^= 1;
            f[a[u]] ^= 1;
        }

        in[a[u]]--;
        if (in[a[u]] == 0)
        {
            qu.push(a[u]);
        }
    }

    for (int i = 1; i <= n; i++)
    {
        if (in[i] > 0 && !vis[i])
        {
            std::vector<int> vec;

            int cur = i;
            while (!vis[cur])
            {
                vis[cur] = true;
                vec.pb(cur);
                cur = a[cur];
            }

            int mn = inf;
            std::vector<int> res;

            for (int j = 0; j <= 1; j++)
            {
                std::vector<int> tmp;
                for (int x : vec)
                {
                    tmp.pb(f[x]);
                }

                std::vector<int> press;
                if (j)
                {
                    press.pb(vec[0]);
                    tmp[0] ^= 1;
                    tmp[1] ^= 1;
                }

                for (int k = 1; k < sz(vec); k++)
                {
                    if (tmp[k] == 1)
                    {
                        press.pb(vec[k]);
                        tmp[k] ^= 1;
                        tmp[(k + 1) % sz(vec)] ^= 1;
                    }
                }

                if (tmp[0] == 0)
                {
                    if (sz(press) < mn)
                    {
                        mn = sz(press);
                        res = press;
                    }
                }
            }

            if (mn == inf)
            {
                std::cout << -1 << "\n";
                return;
            }

            for (int x : res)
            {
                ans.pb(x);
            }
        }
    }

    std::cout << sz(ans) << "\n";
    for (int i : ans)
    {
        std::cout << i << " ";
    }
    std::cout << "\n";
}

