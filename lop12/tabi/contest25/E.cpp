ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct Combinatorics
{
    int n;
    long long MOD;
    std::vector<long long> fact, inv_fact;

    long long power(long long x, long long y)
    {
        long long res = 1;
        x %= MOD;
        while (y > 0)
        {
            if (y & 1)
            {
                res = (res * x) % MOD;
            }
            x = (x * x) % MOD;
            y >>= 1;
        }
        return res;
    }

    Combinatorics(int n, long long MOD) : n(n), MOD(MOD)
    {
        fact.assign(n + 1, 1);
        inv_fact.assign(n + 1, 1);
        for (int i = 2; i <= n; i++)
        {
            fact[i] = (fact[i - 1] * i) % MOD;
        }
        inv_fact[n] = power(fact[n], MOD - 2);
        for (int i = n - 1; i >= 1; i--)
        {
            inv_fact[i] = (inv_fact[i + 1] * (i + 1)) % MOD;
        }
    }

    long long nCr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[r] % MOD * inv_fact[n - r] % MOD;
    }

    long long nPr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[n - r] % MOD;
    }
};

std::vector<int> adj[maxn + 7];
Combinatorics comb(maxn, mod);

int a[maxn + 7];
int pos[maxn + 7], pre[maxn + 7], freq[maxn + 7], cntL[maxn + 7], cntR[maxn + 7];
int ans[maxn + 7], SumL[maxn + 7], SumR[maxn + 7];

void solve()
{
    int n;
    std::cin >> n;
    int m = 0;

    for (int i = 0; i <= n + 1; i++)
    {
        pos[i] = -1;
        pre[i] = 0;
        freq[i] = 0;
        ans[i] = 0;
    }

    for (int i = 0; i < n; i++)
    {
        std::cin >> a[i];
        if (a[i] == -1)
        {
            m++;
            pre[i + 1] = pre[i] + 1;
        }
        else
        {
            pos[a[i]] = i;
            pre[i + 1] = pre[i];
        }
    }

    for (int l = 0; l < n; l++)
    {
        for (int r = l; r < n; r++)
        {
            freq[pre[r + 1] - pre[l]]++;
        }
    }

    for (int i = 0; i <= m; i++)
    {
        for (int k = i; k <= m; k++)
        {
            ans[i] = add(ans[i], mul(freq[k], comb.nCr(k, i)));
        }
    }

    int L = n, R = -1;
    int lstL = -2, lstR = -2;
    int M = 0;
    int res = 0;

    for (int k = 0; k < n; k++)
    {
        if (pos[k] != -1)
        {
            if (pos[k] < L)
            {
                L = pos[k];
            }
            if (pos[k] > R)
            {
                R = pos[k];
            }
        }
        else
        {
            M++;
        }

        int ways = 0;
        if (L > R)
        {
            ways = ans[M];
        }
        else
        {
            if (L != lstL || R != lstR)
            {
                int lk = pre[L];
                int rk = pre[R + 1];

                for (int i = 0; i <= m; i++)
                {
                    SumL[i] = 0;
                    SumR[i] = 0;
                    cntL[i] = 0;
                    cntR[i] = 0;
                }

                for (int l = 0; l <= L; l++)
                {
                    cntL[pre[l]]++;
                }
                for (int i = 0; i <= lk; i++)
                {
                    if (cntL[i] == 0)
                    {
                        continue;
                    }
                    int avail = lk - i;
                    for (int b = 0; b <= avail; b++)
                    {
                        SumL[b] = add(SumL[b], mul(cntL[i], comb.nCr(avail, b)));
                    }
                }

                for (int r = R; r < n; r++)
                {
                    cntR[pre[r + 1]]++;
                }
                for (int j = rk; j <= m; j++)
                {
                    if (cntR[j] == 0)
                    {
                        continue;
                    }
                    int avail = j - lk;
                    for (int a = 0; a <= avail; a++)
                    {
                        SumR[a] = add(SumR[a], mul(cntR[j], comb.nCr(avail, a)));
                    }
                }

                lstL = L;
                lstR = R;
            }

            for (int a = 0; a <= M; a++)
            {
                ways = add(ways, mul(SumR[a], SumL[M - a]));
            }
        }

        ways = mul(ways, comb.fact[M]);
        ways = mul(ways, comb.fact[m - M]);
        res = add(res, ways);
    }

    std::cout << res << "\n";
}

