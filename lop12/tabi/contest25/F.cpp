ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct node
{
    int u, v;
};

std::vector<int> adj[maxn + 7];
int n, q;
int tin[maxn + 7], tout[maxn + 7], tour[maxn + 7], timer = 0;
int up[maxn + 7][lg + 1];
int depth[maxn + 7];
int a[maxn + 7];
node st[4 * maxn + 7];

void dfs(int u, int p)
{
    tin[u] = ++timer;
    tour[timer] = u;

    up[u][0] = p;
    for (int i = 1; i <= lg; i++)
    {
        up[u][i] = up[up[u][i - 1]][i - 1];
    }

    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        depth[v] = depth[u] + 1;
        dfs(v, u);
    }

    tout[u] = timer;
}

bool is_acs(int u, int v)
{
    return tin[u] <= tin[v] && tout[v] <= tout[u];
}

int lca(int u, int v)
{
    if (depth[u] < depth[v])
    {
        std::swap(u, v);
    }
    int k = depth[u] - depth[v];
    for (int i = 0; i <= lg; i++)
    {
        if ((k >> i) & 1)
        {
            u = up[u][i];
        }
    }
    if (u == v)
    {
        return u;
    }
    for (int i = lg; i >= 0; i--)
    {
        if (up[u][i] != up[v][i])
        {
            u = up[u][i];
            v = up[v][i];
        }
    }
    return up[u][0];
}

int dist(int u, int v)
{
    int p = lca(u, v);
    return depth[u] + depth[v] - 2 * depth[p];
}

node merge(node a, node b)
{
    if (a.u == 0)
    {
        return b;
    }
    if (b.u == 0)
    {
        return a;
    }

    node res = a;
    int mx = dist(a.u, a.v);
    int nodes[4] = {a.u, a.v, b.u, b.v};

    for (int i = 0; i < 4; i++)
    {
        for (int j = i + 1; j < 4; j++)
        {
            int d = dist(nodes[i], nodes[j]);
            if (d > mx)
            {
                mx = d;
                res = {nodes[i], nodes[j]};
            }
        }
    }
    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = {tour[l], tour[l]};
        return;
    }
    int mid = (l + r) / 2;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
    st[id] = merge(st[2 * id], st[2 * id + 1]);
}

node get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return {0, 0};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }

    int mid = (l + r) / 2;
    node get1 = get(2 * id, l, mid, u, v);
    node get2 = get(2 * id + 1, mid + 1, r, u, v);
    return merge(get1, get2);
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    dfs(1, 0);
    build(1, 1, timer);

    while (q--)
    {
        int x, k;
        std::cin >> x >> k;
        for (int i = 1; i <= k; i++)
        {
            std::cin >> a[i];
        }

        int anc = 0;
        for (int i = 1; i <= k; i++)
        {
            if (is_acs(a[i], x))
            {
                if (anc == 0 || depth[a[i]] > depth[anc])
                {
                    anc = a[i];
                }
            }
        }

        int L = 1, R = timer;
        if (anc != 0)
        {
            int c = x;
            for (int i = lg; i >= 0; i--)
            {
                if (depth[c] - (1 << i) > depth[anc])
                {
                    c = up[c][i];
                }
            }
            L = tin[c];
            R = tout[c];
        }

        std::vector<ii> holes;
        for (int i = 1; i <= k; i++)
        {
            if (L <= tin[a[i]] && tout[a[i]] <= R)
            {
                holes.pb({tin[a[i]], tout[a[i]]});
            }
        }

        std::sort(all(holes));
        std::vector<ii> vec;
        for (auto h : holes)
        {
            if (vec.empty() || vec.back().se < h.fi)
            {
                vec.pb(h);
            }
            else
            {
                vec.back().se = std::max(vec.back().se, h.se);
            }
        }

        node res = {0, 0};
        int cur = L;
        for (auto h : vec)
        {
            if (cur < h.fi)
            {
                res = merge(res, get(1, 1, timer, cur, h.fi - 1));
            }
            cur = std::max(cur, h.se + 1);
        }
        if (cur <= R)
        {
            res = merge(res, get(1, 1, timer, cur, R));
        }

        int ans = std::max(dist(x, res.u), dist(x, res.v));
        std::cout << ans << "\n";
    }
}

