const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int r, c, n, p;
int a[maxn + 7][maxn + 7];
int posx[maxn * maxn + 7], posy[maxn * maxn + 7];
bool vis[maxn * maxn * 2 + 7];

void solve()
{
    std::cin >> r >> c >> n >> p;
    for (int i = 1; i <= r; i++)
    {
        for (int j = 1; j <= c; j++)
        {
            std::cin >> a[i][j];
            if (a[i][j] > 0)
            {
                posx[a[i][j]] = i;
                posy[a[i][j]] = j;
            }
        }
    }

    for (int i = 1; i <= p; i++)
    {
        int x = posx[i];
        int y = posy[i];
        for (int d = 0; d < 4; d++)
        {
            int nx = x + dx[d];
            int ny = y + dy[d];
            if (nx >= 1 && nx <= r && ny >= 1 && ny <= c)
            {
                int tmp = a[nx][ny];
                if (tmp > 0)
                {
                    int k = tmp - i;
                    vis[k + maxn * maxn] = true;
                }
            }
        }
    }

    int cnt = 0;
    for (int k = 1 - p; k <= n - p; k++)
    {
        if (k == 0)
        {
            continue;
        }
        if (vis[k + maxn * maxn])
        {
            cnt++;
        }
    }

    std::cout << cnt << "/" << n - 1;
}

