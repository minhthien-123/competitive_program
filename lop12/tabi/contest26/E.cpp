ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct State
{
    int x;
    int y;
    int d;
};

std::vector<State> reachable;
int dist[256][256];

void precompute()
{
    memset(dist, -1, sizeof(dist));
    std::queue<State> q;
    dist[240][204] = 0;
    q.push({240, 204, 0});
    reachable.pb({240, 204, 0});

    int M = 170;

    while (!q.empty())
    {
        State st = q.front();
        q.pop();
        int x = st.x;
        int y = st.y;
        int d = st.d;

        int nx, ny;

        nx = x & y;
        ny = y;
        if (dist[nx][ny] == -1)
        {
            dist[nx][ny] = d + 1;
            q.push({nx, ny, d + 1});
            reachable.pb({nx, ny, d + 1});
        }

        nx = x | y;
        ny = y;
        if (dist[nx][ny] == -1)
        {
            dist[nx][ny] = d + 1;
            q.push({nx, ny, d + 1});
            reachable.pb({nx, ny, d + 1});
        }

        nx = x;
        ny = x ^ y;
        if (dist[nx][ny] == -1)
        {
            dist[nx][ny] = d + 1;
            q.push({nx, ny, d + 1});
            reachable.pb({nx, ny, d + 1});
        }

        nx = x;
        ny = y ^ M;
        if (dist[nx][ny] == -1)
        {
            dist[nx][ny] = d + 1;
            q.push({nx, ny, d + 1});
            reachable.pb({nx, ny, d + 1});
        }
    }
}

void solve()
{
    int a, b, c, d, m_val;
    std::cin >> a >> b >> c >> d >> m_val;

    int req_X = 0;
    int val_X = 0;
    int req_Y = 0;
    int val_Y = 0;

    int seen_C[8];
    int seen_D[8];
    for (int i = 0; i < 8; i++)
    {
        seen_C[i] = -1;
        seen_D[i] = -1;
    }

    bool possible = true;
    for (int i = 0; i < 30; i++)
    {
        int bit_a = (a >> i) & 1;
        int bit_b = (b >> i) & 1;
        int bit_m = (m_val >> i) & 1;
        int bit_c = (c >> i) & 1;
        int bit_d = (d >> i) & 1;

        int k = (bit_a << 2) | (bit_b << 1) | bit_m;

        if (seen_C[k] != -1)
        {
            if (seen_C[k] != bit_c || seen_D[k] != bit_d)
            {
                possible = false;
                break;
            }
        }
        else
        {
            seen_C[k] = bit_c;
            seen_D[k] = bit_d;
            req_X |= (1 << k);
            val_X |= (bit_c << k);
            req_Y |= (1 << k);
            val_Y |= (bit_d << k);
        }
    }

    if (!possible)
    {
        std::cout << -1 << "\n";
        return;
    }

    int ans = inf;
    for (auto st : reachable)
    {
        if ((st.x & req_X) == val_X)
        {
            if ((st.y & req_Y) == val_Y)
            {
                if (st.d < ans)
                {
                    ans = st.d;
                }
            }
        }
    }

    if (ans == inf)
    {
        std::cout << -1 << "\n";
    }
    else
    {
        std::cout << ans << "\n";
    }
}

