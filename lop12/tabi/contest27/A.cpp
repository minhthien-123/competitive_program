void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 0; i < k; i++)
    {
        std::cin >> a[i];
    }

    bool rcheck = false;
    int rsum = 0;
    bool r3 = false;
    for (int i = 0; i < k; i++)
    {
        int rows = a[i] / m;
        if (rows >= 2)
        {
            rsum += rows;
            if (rows >= 3)
            {
                r3 = true;
            }
        }
    }
    if (rsum >= n && (n % 2 == 0 || r3))
    {
        rcheck = true;
    }

    bool ccheck = false;
    int csum = 0;
    bool c3 = false;
    for (int i = 0; i < k; i++)
    {
        int cols = a[i] / n;
        if (cols >= 2)
        {
            csum += cols;
            if (cols >= 3)
            {
                c3 = true;
            }
        }
    }
    if (csum >= m && (m % 2 == 0 || c3))
    {
        ccheck = true;
    }

    if (rcheck || ccheck)
    {
        std::cout << "Yes\n";
    }
    else
    {
        std::cout << "No\n";
    }
}

