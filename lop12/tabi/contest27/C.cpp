void solve()
{
    int n;
    std::cin >> n;
    std::string s;
    std::cin >> s;
    s = " " + s;

    std::vector<int> a(n + 1);
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    std::vector<int> c(n + 1);
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }

    for (int i = 2; i <= n; i++)
    {
        if (c[i] < c[i - 1])
        {
            std::cout << "No\n";
            return;
        }
    }

    std::vector<int> block_starts;
    if (s[1] == '1')
    {
        block_starts.pb(1);
    }
    for (int i = 1; i <= n; i++)
    {
        if (s[i] == '0')
        {
            block_starts.pb(i);
        }
    }
    block_starts.pb(n + 1);

    std::vector<int> b(n + 1, 0);

    for (size_t idx = 0; idx < block_starts.size() - 1; idx++)
    {
        int start_idx = block_starts[idx];
        int end_idx = block_starts[idx + 1] - 1;

        if (start_idx == 1 && s[1] == '1')
        {
            int curr_b = 0;
            for (int k = 1; k <= end_idx; k++)
            {
                curr_b += a[k];
                b[k] = curr_b;
                if (k == 1)
                {
                    if (c[1] != b[1])
                    {
                        std::cout << "No\n";
                        return;
                    }
                }
                else
                {
                    if (c[k] != std::max(c[k - 1], b[k]))
                    {
                        std::cout << "No\n";
                        return;
                    }
                }
            }
        }
        else
        {
            int min_M = INF;
            bool has_req = false;
            int req_val = 0;
            int current_delta = 0;

            for (int k = start_idx; k <= end_idx; k++)
            {
                if (k > start_idx)
                {
                    current_delta += a[k];
                }

                min_M = std::min(min_M, c[k] - current_delta);

                if (k == 1)
                {
                    if (has_req && req_val != c[1])
                    {
                        std::cout << "No\n";
                        return;
                    }
                    req_val = c[1];
                    has_req = true;
                }
                else if (c[k] > c[k - 1])
                {
                    int needed_b = c[k] - current_delta;
                    if (has_req && req_val != needed_b)
                    {
                        std::cout << "No\n";
                        return;
                    }
                    req_val = needed_b;
                    has_req = true;
                }
            }

            if (has_req)
            {
                if (req_val > min_M)
                {
                    std::cout << "No\n";
                    return;
                }
                b[start_idx] = req_val;
            }
            else
            {
                b[start_idx] = min_M;
            }

            current_delta = 0;
            for (int k = start_idx + 1; k <= end_idx; k++)
            {
                current_delta += a[k];
                b[k] = b[start_idx] + current_delta;
            }
        }
    }

    std::cout << "Yes\n";
    std::cout << b[1] << " ";
    for (int i = 2; i <= n; i++)
    {
        std::cout << b[i] - b[i - 1] << " ";
    }
    std::cout << "\n";
}

