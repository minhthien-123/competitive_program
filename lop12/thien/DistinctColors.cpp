ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int color[maxn + 7];
int cnt[maxn + 7];
int mx = 0;
int sum = 0;

struct DSUonTree
{
    int sz[maxn + 7], big[maxn + 7];
    long long ans[maxn + 7];
    int current_big_child;

    void get_sz(int u, int p)
    {
        sz[u] = 1;
        big[u] = 0;
        int max_sub = 0;
        for (int v : adj[u])
        {
            if (v != p)
            {
                get_sz(v, u);
                sz[u] += sz[v];
                if (sz[v] > max_sub)
                {
                    max_sub = sz[v];
                    big[u] = v;
                }
            }
        }
    }

    void add(int u, int p, int delta)
    {
        int c = color[u];
        cnt[c] += delta;

        if (delta == 1)
        {
            if (cnt[c] > mx)
            {
                mx = cnt[c];
                sum = c;
            }
            else if (cnt[c] == mx)
            {
                sum += c;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != current_big_child)
            {
                add(v, u, delta);
            }
        }
    }

    void dfs_sack(int u, int p, bool keep)
    {
        for (int v : adj[u])
        {
            if (v != p && v != big[u])
            {
                dfs_sack(v, u, false);
            }
        }

        if (big[u] != 0)
        {
            dfs_sack(big[u], u, true);
            current_big_child = big[u];
        }

        add(u, p, 1);
        current_big_child = 0;

        ans[u] = sum;

        if (!keep)
        {
            add(u, p, -1);
            mx = 0;
            sum = 0;
        }
    }
};

DSUonTree sack;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> color[i];
    }
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    sack.get_sz(1, 0);
    sack.dfs_sack(1, 0, true);

    for (int i = 1; i <= n; i++)
    {
        std::cout << sack.ans[i] << " ";
    }
    std::cout << "\n";
}

