ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, q;
struct edge
{
    int u, v;
    ll w;
} edges[maxn + 7];

struct KRT
{
    struct Edge
    {
        int u, v;
        long long w;
        bool operator<(const Edge &other) const
        {
            return w < other.w;
        }
    };

    int n, node_cnt, lg, timer;
    std::vector<Edge> edges;
    std::vector<long long> val;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> depth, tin, tout, dsu_par;

    KRT(int n) : n(n), node_cnt(n), timer(0)
    {
        lg = std::ceil(std::log2(2 * n + 5)) + 1;
        int max_nodes = 2 * n + 7;
        val.assign(max_nodes, 0);
        adj.resize(max_nodes);
        up.assign(max_nodes, std::vector<int>(lg + 1, 0));
        depth.assign(max_nodes, 0);
        tin.assign(max_nodes, 0);
        tout.assign(max_nodes, 0);
        dsu_par.resize(max_nodes);
        std::iota(dsu_par.begin(), dsu_par.end(), 0);
    }

    void add_edge(int u, int v, long long w)
    {
        edges.push_back({u, v, w});
    }

    int acs(int v)
    {
        return v == dsu_par[v] ? v : dsu_par[v] = acs(dsu_par[v]);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build()
    {
        std::sort(edges.begin(), edges.end());
        for (const auto &e : edges)
        {
            int ru = acs(e.u);
            int rv = acs(e.v);
            if (ru != rv)
            {
                node_cnt++;
                val[node_cnt] = e.w;
                adj[node_cnt].push_back(ru);
                adj[node_cnt].push_back(rv);
                dsu_par[ru] = node_cnt;
                dsu_par[rv] = node_cnt;
            }
        }

        for (int i = node_cnt; i >= 1; i--)
        {
            if (dsu_par[i] == i && !tin[i])
            {
                dfs(i, 0);
            }
        }
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        for (int i = lg; i >= 0; i--)
        {
            if (depth[u] - (1 << i) >= depth[v])
            {
                u = up[u][i];
            }
        }
        if (u == v)
            return u;
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_highest_ancestor(int u, long long max_val)
    {
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != 0 && val[up[u][i]] <= max_val)
            {
                u = up[u][i];
            }
        }
        return u;
    }

    long long query_minimax(int u, int v)
    {
        if (acs(u) != acs(v))
        {
            return -1;
        }
        return val[get_lca(u, v)];
    }
};

ll cost[maxn + 7];

struct SparseTable
{
    int lg;
    std::vector<std::vector<ll>> st;

    SparseTable(int n)
    {
        lg = std::log2(n) + 1;
        st.assign(lg + 1, std::vector<ll>(n + 7, 0));
        for (int i = 1; i <= n; i++)
        {
            st[0][i] = cost[i];
        }
        for (int j = 1; j <= lg; j++)
        {
            for (int i = 1; i + (1 << j) - 1 <= n; i++)
            {
                st[j][i] = std::max(st[j - 1][i], st[j - 1][i + (1 << (j - 1))]);
            }
        }
    }

    int query(int l, int r)
    {
        int j = std::log2(r - l + 1);
        return std::max(st[j][l], st[j][r - (1 << j) + 1]);
    }
};

void solve()
{
    std::cin >> n >> m >> q;

    KRT krt(n);

    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        krt.add_edge(u, v, i);
    }

    krt.build();

    for (int i = 1; i < n; i++)
    {
        cost[i] = krt.val[krt.get_lca(i, i + 1)];
    }

    SparseTable spt(n);

    while (q--)
    {
        int l, r;
        std::cin >> l >> r;
        if (l == r)
        {
            std::cout << 0 << " ";
        }
        else
        {
            std::cout << spt.query(l, r - 1) << " ";
        }
    }

    std::cout << "\n";
}

