ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 7];

struct node
{
    ll gcd, min_val, cnt;
} st[4 * maxn + 7];

node merge(node L, node R)
{
    if (L.cnt == 0)
    {
        return R;
    }
    if (R.cnt == 0)
    {
        return L;
    }

    node res;
    res.gcd = std::__gcd(L.gcd, R.gcd);

    if (L.min_val < R.min_val)
    {
        res.min_val = L.min_val;
        res.cnt = L.cnt;
    }
    else if (L.min_val > R.min_val)
    {
        res.min_val = R.min_val;
        res.cnt = R.cnt;
    }
    else
    {
        res.min_val = L.min_val;
        res.cnt = L.cnt + R.cnt;
    }

    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id].gcd = a[l];
        st[id].min_val = a[l];
        st[id].cnt = 1;
        return;
    }
    int mid = (l + r) / 2;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
    st[id] = merge(st[2 * id], st[2 * id + 1]);
}

node query(int id, int l, int r, int u, int v)
{
    if (l > v || r < u)
    {
        return {0, 0, 0};
    }
    if (l >= u && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    node L = query(2 * id, l, mid, u, v);
    node R = query(2 * id + 1, mid + 1, r, u, v);
    return merge(L, R);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build(1, 1, n);

    int q;
    std::cin >> q;
    while (q--)
    {
        int l, r;
        std::cin >> l >> r;

        node res = query(1, 1, n, l, r);

        int cnt = 0;
        if (res.gcd == res.min_val)
        {
            cnt = res.cnt;
        }

        std::cout << (r - l + 1) - cnt << "\n";
    }
}

