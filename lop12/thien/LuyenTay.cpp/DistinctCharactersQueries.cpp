ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int bit[26][maxn];
int n, q;
std::string s;

void update(int c, int idx, int val)
{
    for (; idx <= n; idx += idx & -idx)
    {
        bit[c][idx] += val;
    }
}

int query(int c, int idx)
{
    int sum = 0;
    for (; idx > 0; idx -= idx & -idx)
    {
        sum += bit[c][idx];
    }
    return sum;
}

void solve()
{
    std::cin >> s;
    n = s.length();
    s = " " + s;

    for (int i = 1; i <= n; i++)
    {
        update(s[i] - 'a', i, 1);
    }

    std::cin >> q;
    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int pos;
            char c;
            std::cin >> pos >> c;

            update(s[pos] - 'a', pos, -1);
            s[pos] = c;
            update(s[pos] - 'a', pos, 1);
        }
        else
        {
            int l, r;
            std::cin >> l >> r;
            int ans = 0;

            for (int c = 0; c < 26; c++)
            {
                if (query(c, r) - query(c, l - 1) > 0)
                {
                    ans++;
                }
            }
            std::cout << ans << "\n";
        }
    }
}

