ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7];
int tin[maxn + 7], tout[maxn + 7], tour[maxn + 7];
int timer;
int st[4 * maxn + 7];
int lz[4 * maxn + 7];

void dfs(int u, int p)
{
    timer++;
    tin[u] = timer;
    tour[timer] = a[u];
    for (int i = 0; i < sz(adj[u]); i++)
    {
        int v = adj[u][i];
        if (v != p)
        {
            dfs(v, u);
        }
    }
    tout[u] = timer;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = tour[l];
        return;
    }
    int mid = (l + r) / 2;
    build(2 * id, l, mid);
    build(2 * id + 1, mid + 1, r);
    st[id] = st[2 * id] + st[2 * id + 1];
}

void fixed(int id, int l, int r)
{
    if (lz[id])
    {
        int mid = (l + r) / 2;
        lz[2 * id] ^= 1;
        st[2 * id] = (mid - l + 1) - st[2 * id];
        lz[2 * id + 1] ^= 1;
        st[2 * id + 1] = (r - mid) - st[2 * id + 1];
        lz[id] = 0;
    }
}

void update(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] = (r - l + 1) - st[id];
        lz[id] ^= 1;
        return;
    }
    fixed(id, l, r);
    int mid = (l + r) / 2;
    update(2 * id, l, mid, u, v);
    update(2 * id + 1, mid + 1, r, u, v);
    st[id] = st[2 * id] + st[2 * id + 1];
}

int get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    fixed(id, l, r);
    int mid = (l + r) / 2;
    return get(2 * id, l, mid, u, v) + get(2 * id + 1, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> n;
    for (int i = 2; i <= n; i++)
    {
        int p;
        std::cin >> p;
        adj[p].pb(i);
        adj[i].pb(p);
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    timer = 0;
    dfs(1, 0);
    build(1, 1, n);
    int q;
    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        std::string type;
        int v;
        std::cin >> type >> v;
        if (type == "pow")
        {
            update(1, 1, n, tin[v], tout[v]);
        }
        else
        {
            std::cout << get(1, 1, n, tin[v], tout[v]) << "\n";
        }
    }
}

