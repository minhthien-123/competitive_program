ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7];

struct node
{
    int sum;
    int val;
} st[4 * maxn + 7];

node merge(node a, node b)
{
    node res;
    res.sum = a.sum + b.sum;
    res.val = std::max(a.val, b.val);
    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = {a[l], a[l]};
        return;
    }

    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void update1(int id, int l, int r, int pos, int val)
{
    if (pos < l || pos > r)
    {
        return;
    }

    if (l == r)
    {
        st[id] = {val, val};
        return;
    }
    int mid = (l + r) / 2;
    update1(2 * id, l, mid, pos, val);
    update1(2 * id + 1, mid + 1, r, pos, val);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void update2(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u)
    {
        return;
    }
    if (st[id].val < val)
    {
        return;
    }
    if (l == r)
    {
        st[id] = {st[id].sum % val, st[id].sum % val};
        return;
    }
    int mid = (l + r) / 2;
    update2(id * 2, l, mid, u, v, val);
    update2(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

node get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return {0, 0};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    node get1 = get(id * 2, l, mid, u, v);
    node get2 = get(id * 2 + 1, mid + 1, r, u, v);
    return merge(get1, get2);
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    build(1, 1, n);

    while (m--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int l, r;
            std::cin >> l >> r;
            std::cout << get(1, 1, n, l, r).sum << "\n";
        }
        else if (type == 2)
        {
            int l, r, x;
            std::cin >> l >> r >> x;
            update2(1, 1, n, l, r, x);
        }
        else
        {
            int pos, val;
            std::cin >> pos >> val;
            update1(1, 1, n, pos, val);
        }
    }
}

