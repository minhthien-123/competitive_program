ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 6];
std::vector<int> adj[maxn + 7];

struct EulerTour
{
    int n, timer;
    std::vector<int> tin, tout;

    EulerTour(int n)
    {
        this->n = n;
        timer = 0;
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        timer = 0;
        dfs(root, 0);
    }
};

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    EulerTour eu(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        eu.add_edge(u, v);
    }

    eu.build(1);

    FenwickTree fw(eu.timer);

    for (int i = 1; i <= n; i++)
    {
        fw.add(eu.tin[i], a[i]);
        fw.add(eu.tout[i] + 1, -a[i]);
    }

    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int s, x;
            std::cin >> s >> x;
            int delta = x - a[s];
            a[s] = x;
            fw.add(eu.tin[s], delta);
            fw.add(eu.tout[s] + 1, -delta);
        }
        else if (type == 2)
        {
            int s;
            std::cin >> s;
            std::cout << fw.sum(eu.tin[s]) << "\n";
        }
    }
}

