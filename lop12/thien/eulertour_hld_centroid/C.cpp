ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
std::vector<int> adj[maxn + 7];

struct edge
{
    int u, v, w;
} edges[maxn + 7];

struct EulerTour
{
    int n, timer;
    std::vector<int> tin, tout, depth;
    std::vector<std::vector<int>> up;

    EulerTour(int n)
    {
        this->n = n;
        timer = 0;
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        up[u][0] = p;

        for (int j = 1; j <= lg; j++)
        {
            up[u][j] = up[up[u][j - 1]][j - 1];
        }

        for (int id : adj[u])
        {
            int v = (edges[id].u == u) ? edges[id].v : edges[id].u;
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        timer = 0;
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }

        for (int j = lg; j >= 0; j--)
        {
            if (depth[u] - (1LL << j) >= depth[v])
            {
                u = up[u][j];
            }
        }
        if (u == v)
        {
            return u;
        }

        for (int j = lg; j >= 0; j--)
        {
            if (up[u][j] != up[v][j])
            {
                u = up[u][j];
                v = up[v][j];
            }
        }
        return up[u][0];
    }
};
struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

void solve()
{
    std::cin >> n;
    EulerTour eu(n);
    for (int i = 1; i < n; i++)
    {
        std::cin >> edges[i].u >> edges[i].v >> edges[i].w;
        adj[edges[i].u].pb(i);
        adj[edges[i].v].pb(i);
    }

    eu.build();
    FenwickTree fw(eu.timer);

    for (int i = 1; i < n; i++)
    {
        int u = edges[i].u;
        int v = edges[i].v;
        int w = edges[i].w;

        if (eu.depth[u] > eu.depth[v])
        {
            std::swap(u, v);
        }

        fw.add(eu.tin[v], w);
        fw.add(eu.tout[v] + 1, -w);
    }

    std::cin >> q;
    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int x, y;
            std::cin >> x >> y;

            int u = edges[x].u;
            int v = edges[x].v;
            if (eu.depth[u] > eu.depth[v])
            {
                std::swap(u, v);
            }

            int delta = y - edges[x].w;
            edges[x].w = y;

            fw.add(eu.tin[v], delta);
            fw.add(eu.tout[v] + 1, -delta);
        }
        else if (type == 2)
        {
            int a, b;
            std::cin >> a >> b;

            int lca = eu.get_lca(a, b);

            std::cout << fw.sum(eu.tin[a]) + fw.sum(eu.tin[b]) - 2 * fw.sum(eu.tin[lca]) << "\n";
        }
    }
}

