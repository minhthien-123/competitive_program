ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int c[maxn + 7];
std::vector<int> adj[maxn + 7];

struct EulerTour
{
    int n, timer;
    std::vector<int> tin, tout, node;

    EulerTour(int n)
    {
        this->n = n;
        timer = 0;
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        node.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        node[timer] = u;
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        timer = 0;
        dfs(root, 0);
    }
};

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

struct query
{
    int l, r, id;
    friend bool operator<(query a, query b)
    {
        return a.r < b.r;
    }
};

int lst[maxn + 7], ans[maxn + 7];

struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

void solve()
{
    std::cin >> n;
    Compress comp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
        comp.add(c[i]);
    }

    comp.init();
    for (int i = 1; i <= n; i++)
    {
        c[i] = comp.get(c[i]);
    }

    EulerTour eu(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        eu.add_edge(u, v);                                                                  
    }

    eu.build(1);

    std::vector<query> queries;
    for (int i = 1; i <= n; i++)
    {
        queries.pb({eu.tin[i], eu.tout[i], i});
    }
    std::sort(all(queries));

    FenwickTree fw(eu.timer);

    int id = 0;
    for (int i = 1; i <= eu.timer; i++)
    {
        int u = eu.node[i];
        int color = c[u];

        if (lst[color] != 0)
        {
            fw.add(lst[color], -1);
        }
        fw.add(i, 1);
        lst[color] = i;

        while (id < n && queries[id].r == i)
        {
            ans[queries[id].id] = fw.sum(queries[id].l, queries[id].r);
            id++;
        }
    }

    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << " ";
    }
}

