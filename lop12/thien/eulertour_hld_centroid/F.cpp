ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
std::vector<int> adj[maxn + 7];
std::vector<ii> queries[maxn + 7];
int ans[maxn + 7];

struct DSUOnTree
{
    int n;
    std::vector<int> sz, tin, tout, euler, cnt, depth;
    int timer;

    DSUOnTree() {}
    DSUOnTree(int n)
    {
        this->n = n;
        sz.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        cnt.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        timer = 0;
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs_sz(int u, int p)
    {
        sz[u] = 1;
        timer++;
        tin[u] = timer;
        euler.push_back(u);
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs_sz(v, u);
                sz[u] += sz[v];
            }
        }
        tout[u] = timer;
    }

    void add(int u, int val)
    {
        cnt[depth[u]] += val;
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (int v : adj[u])
        {
            if (v != p && sz[v] > max_sz)
            {
                max_sz = sz[v];
                big_child = v;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    add(euler[i - 1], 1);
                }
            }
        }
        add(u, 1);

        for (auto q : queries[u])
        {
            ans[q.se] = cnt[q.fi];
        }

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                add(euler[i - 1], -1);
            }
        }
    }
};

DSUOnTree sack;

void solve()
{
    std::cin >> n;
    for (int i = 2; i <= n; i++)
    {
        int p;
        std::cin >> p;
        adj[p].pb(i);
        adj[i].pb(p);
    }

    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        int u, d;
        std::cin >> u >> d;
        queries[u].pb({d, i});
    }

    sack = DSUOnTree(n);
    sack.dfs_sz(1, 0);
    sack.dfs_sack(1, 0, true);

    for (int i = 1; i <= q; i++)
    {
        std::cout << ans[i] << "\n";
    }
}

