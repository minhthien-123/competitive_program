ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int c[maxn + 7];

struct EulerTour
{
    int n, timer;
    std::vector<std::vector<int>> adj;
    std::vector<int> tin, tout;

    EulerTour(int n)
    {
        this->n = n;
        timer = 0;
        adj.resize(n + 7);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        timer = 0;
        dfs(root, 0);
    }
};

int ans = 0;
int freq[maxn + 7], a[maxn + 7], res[maxn + 7], f[maxn + 7];

void add_val(int idx)
{
    if (freq[a[idx]] == 0)
    {
        ans++;
    }
    freq[a[idx]]++;
}

void del_val(int idx)
{
    freq[a[idx]]--;
    if (freq[a[idx]] == 0)
    {
        ans--;
    }
}

void update(int pos, int val, int L, int R)
{
    if (L <= pos && pos <= R)
    {
        del_val(pos);
        a[pos] = val;
        add_val(pos);
    }
    else
    {
        a[pos] = val;
    }
}

struct MoAlgorithm
{
    int n, block_size;

    struct Query
    {
        int l, r, t, id, bl, br;
        bool operator<(const Query &other) const
        {
            if (bl != other.bl)
            {
                return bl < other.bl;
            }
            if (br != other.br)
            {
                return (bl & 1) ? (br < other.br) : (br > other.br);
            }
            return (br & 1) ? (t < other.t) : (t > other.t);
        }
    };

    struct Update
    {
        int pos, old_val, new_val;
    };

    std::vector<Query> queries;
    std::vector<Update> updates;

    MoAlgorithm(int n)
    {
        this->n = n;
        block_size = std::pow(n, 2.0 / 3.0) + 1;
    }

    void add_query(int l, int r, int t, int id)
    {
        queries.push_back({l, r, t, id, l / block_size, r / block_size});
    }

    void add_update(int pos, int old_val, int new_val)
    {
        updates.push_back({pos, old_val, new_val});
    }

    void solve()
    {
        std::sort(queries.begin(), queries.end());
        int L = 1, R = 0, cur_t = -1;

        for (auto q : queries)
        {
            while (cur_t < q.t)
            {
                cur_t++;
                update(updates[cur_t].pos, updates[cur_t].new_val, L, R);
            }
            while (cur_t > q.t)
            {
                update(updates[cur_t].pos, updates[cur_t].old_val, L, R);
                cur_t--;
            }

            while (L > q.l)
            {
                L--;
                add_val(L);
            }
            while (R < q.r)
            {
                R++;
                add_val(R);
            }
            while (L < q.l)
            {
                del_val(L);
                L++;
            }
            while (R > q.r)
            {
                del_val(R);
                R--;
            }
            res[q.id] = ans;
        }
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }

    EulerTour et(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        et.add_edge(u, v);
    }
    et.build(1);

    MoAlgorithm mo(n);

    for (int i = 1; i <= n; i++)
    {
        a[et.tin[i]] = c[i];
        f[i] = c[i];
    }

    int id = 0;
    for (int i = 1; i <= q; i++)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int s, k;
            std::cin >> s >> k;
            mo.add_update(et.tin[s], f[s], k);
            f[s] = k;
        }
        else
        {
            int s;
            std::cin >> s;
            id++;
            mo.add_query(et.tin[s], et.tout[s], mo.updates.size() - 1, id);
        }
    }

    mo.solve();

    for (int i = 1; i <= id; i++)
    {
        std::cout << res[i] << "\n";
    }
}

