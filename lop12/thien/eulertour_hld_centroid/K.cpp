struct SegTree
{
    int n;
    std::vector<long long> st_max, st_min;
    std::vector<bool> lazy;

    SegTree() {}
    SegTree(int n)
    {
        this->n = n;
        st_max.assign(4 * n + 7, -INF);
        st_min.assign(4 * n + 7, INF);
        lazy.assign(4 * n + 7, false);
    }

    void apply(int id)
    {
        int tmp = st_max[id];
        st_max[id] = -st_min[id];
        st_min[id] = -tmp;
        lazy[id] = !lazy[id];
    }

    void push(int id)
    {
        if (lazy[id])
        {
            apply(2 * id);
            apply(2 * id + 1);
            lazy[id] = false;
        }
    }

    void update(int id, int l, int r, int pos, long long val)
    {
        if (pos < l || r < pos)
        {
            return;
        }
        if (l == r)
        {
            st_max[id] = st_min[id] = val;
            return;
        }
        push(id);
        int mid = (l + r) / 2;
        update(2 * id, l, mid, pos, val);
        update(2 * id + 1, mid + 1, r, pos, val);
        st_max[id] = std::max(st_max[2 * id], st_max[2 * id + 1]);
        st_min[id] = std::min(st_min[2 * id], st_min[2 * id + 1]);
    }

    void update2(int id, int l, int r, int u, int v)
    {
        if (u > r || v < l)
        {
            return;
        }
        if (u <= l && r <= v)
        {
            apply(id);
            return;
        }
        push(id);
        int mid = (l + r) / 2;
        update2(2 * id, l, mid, u, v);
        update2(2 * id + 1, mid + 1, r, u, v);
        st_max[id] = std::max(st_max[2 * id], st_max[2 * id + 1]);
        st_min[id] = std::min(st_min[2 * id], st_min[2 * id + 1]);
    }

    long long query(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return -INF;
        }
        if (u <= l && r <= v)
        {
            return st_max[id];
        }
        push(id);
        int mid = (l + r) / 2;
        return std::max(query(2 * id, l, mid, u, v), query(2 * id + 1, mid + 1, r, u, v));
    }
};

SegTree seg;

struct HLD
{
    int n, timer;
    std::vector<int> par, depth, heavy, head, pos, sz;

    HLD(int n)
    {
        this->n = n;
        timer = 0;
        par.resize(n + 7);
        depth.resize(n + 7);
        heavy.assign(n + 7, -1);
        head.resize(n + 7);
        pos.resize(n + 7);
        sz.resize(n + 7);
    }

    int dfs(int v, int p)
    {
        sz[v] = 1;
        par[v] = p;
        int max_sub = 0;
        for (int u : adj[v])
        {
            if (u != p)
            {
                depth[u] = depth[v] + 1;
                int sub_sz = dfs(u, v);
                sz[v] += sub_sz;
                if (sub_sz > max_sub)
                {
                    max_sub = sub_sz;
                    heavy[v] = u;
                }
            }
        }
        return sz[v];
    }

    void decompose(int v, int h, int p)
    {
        head[v] = h;
        timer++;
        pos[v] = timer;
        if (heavy[v] != -1)
        {
            decompose(heavy[v], h, v);
        }
        for (int u : adj[v])
        {
            if (u != p && u != heavy[v])
            {
                decompose(u, u, v);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
        decompose(root, root, root);
    }

    long long get(int u, int v)
    {
        if (u == v)
            return 0;
        long long res = -INF;
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
            {
                std::swap(u, v);
            }
            res = std::max(res, seg.query(1, 1, n, pos[head[u]], pos[u]));
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
        {
            std::swap(u, v);
        }
        if (pos[u] + 1 <= pos[v])
        {
            res = std::max(res, seg.query(1, 1, n, pos[u] + 1, pos[v]));
        }
        return res == -INF ? 0 : res;
    }

    void update2(int u, int v)
    {
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
            {
                std::swap(u, v);
            }
            seg.update2(1, 1, n, pos[head[u]], pos[u]);
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
        {
            std::swap(u, v);
        }
        if (pos[u] + 1 <= pos[v])
        {
            seg.update2(1, 1, n, pos[u] + 1, pos[v]);
        }
    }
};

iii edges[maxn + 7];
int node[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        adj[i].clear();
    }

    for (int i = 1; i < n; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        edges[i] = {{u, v}, w};
        adj[u].pb(v);
        adj[v].pb(u);
    }

    seg = SegTree(n);
    HLD hld(n);
    hld.build(1);

    for (int i = 1; i < n; i++)
    {
        int u = edges[i].fi.fi;
        int v = edges[i].fi.se;
        int w = edges[i].se;
        node[i] = (hld.depth[u] > hld.depth[v]) ? u : v;
        seg.update(1, 1, n, hld.pos[node[i]], w);
    }

    std::string type;
    while (std::cin >> type && type != "DONE")
    {
        if (type == "CHANGE")
        {
            int i, v;
            std::cin >> i >> v;
            seg.update(1, 1, n, hld.pos[node[i]], v);
        }
        else if (type == "NEGATE")
        {
            int u, v;
            std::cin >> u >> v;
            if (u != v)
            {
                hld.update2(u, v);
            }
        }
        else if (type == "QUERY")
        {
            int u, v;
            std::cin >> u >> v;
            std::cout << hld.get(u, v) << "\n";
        }
    }
}

