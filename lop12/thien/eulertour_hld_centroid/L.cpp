struct SegTree
{
    int n;
    std::vector<long long> st, lz;

    SegTree() {}
    SegTree(int n)
    {
        this->n = n;
        st.assign(4 * n + 7, 0);
        lz.assign(4 * n + 7, 0);
    }

    void push(int id)
    {
        st[id * 2] += lz[id];
        st[id * 2 + 1] += lz[id];
        lz[id * 2] += lz[id];
        lz[id * 2 + 1] += lz[id];
        lz[id] = 0;
    }

    void update(int id, int l, int r, int u, int v, long long val)
    {
        if (u > r || v < l)
        {
            return;
        }
        if (u <= l && r <= v)
        {
            st[id] += val;
            lz[id] += val;
            return;
        }
        push(id);
        int mid = (l + r) / 2;
        update(2 * id, l, mid, u, v, val);
        update(2 * id + 1, mid + 1, r, u, v, val);
        st[id] = std::max(st[2 * id], st[2 * id + 1]);
    }

    long long query(int id, int l, int r, int u, int v)
    {
        if (v < l || r < u)
        {
            return -INF;
        }
        if (u <= l && r <= v)
        {
            return st[id];
        }
        push(id);
        int mid = (l + r) / 2;
        return std::max(query(2 * id, l, mid, u, v), query(2 * id + 1, mid + 1, r, u, v));
    }
};

SegTree seg;

struct HLD
{
    int n, timer;
    std::vector<int> par, depth, heavy, head, pos, sz;

    HLD(int n)
    {
        this->n = n;
        timer = 0;
        par.resize(n + 7);
        depth.resize(n + 7);
        heavy.assign(n + 7, -1);
        head.resize(n + 7);
        pos.resize(n + 7);
        sz.resize(n + 7);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    int dfs(int v, int p)
    {
        sz[v] = 1;
        par[v] = p;
        int max_sub = 0;
        for (int u : adj[v])
        {
            if (u != p)
            {
                depth[u] = depth[v] + 1;
                int sub_sz = dfs(u, v);
                sz[v] += sub_sz;
                if (sub_sz > max_sub)
                {
                    max_sub = sub_sz;
                    heavy[v] = u;
                }
            }
        }
        return sz[v];
    }

    void decompose(int v, int h, int p)
    {
        head[v] = h;
        timer++;
        pos[v] = timer;
        if (heavy[v] != -1)
        {
            decompose(heavy[v], h, v);
        }
        for (int u : adj[v])
        {
            if (u != p && u != heavy[v])
            {
                decompose(u, u, v);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
        decompose(root, root, root);
    }

    long long query_path(int u, int v)
    {
        long long res = -INF;
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
            {
                std::swap(u, v);
            }
            res = std::max(res, seg.query(1, 1, n, pos[head[u]], pos[u]));
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
        {
            std::swap(u, v);
        }

        res = std::max(res, seg.query(1, 1, n, pos[u], pos[v]));
        return res;
    }

    void update_path(int u, int v, long long val)
    {
        while (head[u] != head[v])
        {
            if (depth[head[u]] < depth[head[v]])
            {
                std::swap(u, v);
            }
            seg.update(1, 1, n, pos[head[u]], pos[u], val);
            u = par[head[u]];
        }
        if (depth[u] > depth[v])
        {
            std::swap(u, v);
        }
        seg.update(1, 1, n, pos[u], pos[v], val);
    }

    int query_subtree(int u)
    {
        return seg.query(1, 1, n, pos[u], pos[u] + sz[u] - 1);
    }

    void update_subtree(int u, int val)
    {
        seg.update(1, 1, n, pos[u], pos[u] + sz[u] - 1, val);
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    seg = SegTree(n);
    HLD hld(n);
    hld.build(1);

    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int u, v, val;
            std::cin >> u >> v >> val;
            hld.update_path(u, v, val);
        }
        else if (type == 2)
        {
            int u, val;
            std::cin >> u >> val;
            hld.update_subtree(u, val);
        }
        else if (type == 3)
        {
            int u, v;
            std::cin >> u >> v;
            std::cout << hld.query_path(u, v) << "\n";
        }
        else
        {
            int u;
            std::cin >> u;
            std::cout << hld.query_subtree(u) << "\n";
        }
    }
}

