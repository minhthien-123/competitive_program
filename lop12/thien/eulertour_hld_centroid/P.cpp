ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
std::vector<int> adj[maxn + 7];

struct CentroidDecomposition
{
    int n;
    std::vector<int> sz, par;
    std::vector<char> ans;
    std::vector<bool> removed;

    CentroidDecomposition(int n)
    {
        this->n = n;
        sz.assign(n + 7, 0);
        par.assign(n + 7, 0);
        ans.assign(n + 7, 0);
        removed.assign(n + 7, false);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void get_sz(int u, int p)
    {
        sz[u] = 1;
        for (int v : adj[u])
        {
            if (v != p && !removed[v])
            {
                get_sz(v, u);
                sz[u] += sz[v];
            }
        }
    }

    int get_centroid(int u, int p, int total_sz)
    {
        for (int v : adj[u])
        {
            if (v != p && !removed[v] && sz[v] > total_sz / 2)
            {
                return get_centroid(v, u, total_sz);
            }
        }
        return u;
    }

    void build(int u, int p = 0, int depth = 0)
    {
        get_sz(u, 0);
        int centroid = get_centroid(u, 0, sz[u]);

        par[centroid] = p;
        removed[centroid] = true;

        ans[centroid] = (char)('A' + depth);

        for (int v : adj[centroid])
        {
            if (!removed[v])
            {
                build(v, centroid, depth + 1);
            }
        }
    }
};

void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    CentroidDecomposition cd(n);

    cd.build(1);

    for (int i = 1; i <= n; i++)
    {
        std::cout << cd.ans[i] << ' ';
    }
}

