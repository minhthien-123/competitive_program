ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k1, k2;
std::vector<int> adj[maxn + 7];

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree() {}

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n + 1; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
};

FenwickTree fw;

struct CentroidDecomposition
{
    int n;
    int ans = 0;
    std::vector<int> sz, par, freq;
    std::vector<bool> removed;

    CentroidDecomposition(int n)
    {
        this->n = n;
        freq.resize(n + 7, 0);
        sz.assign(n + 7, 0);
        par.assign(n + 7, 0);
        removed.assign(n + 7, false);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void get_sz(int u, int p)
    {
        sz[u] = 1;
        for (int v : adj[u])
        {
            if (v != p && !removed[v])
            {
                get_sz(v, u);
                sz[u] += sz[v];
            }
        }
    }

    int get_centroid(int u, int p, int total_sz)
    {
        for (int v : adj[u])
        {
            if (v != p && !removed[v] && sz[v] > total_sz / 2)
            {
                return get_centroid(v, u, total_sz);
            }
        }
        return u;
    }

    void get_dist(int u, int p, int depth, std::vector<int> &dists)
    {
        if (depth > k2)
        {
            return;
        }

        dists.pb(depth);
        for (int v : adj[u])
        {
            if (v != p && !removed[v])
            {
                get_dist(v, u, depth + 1, dists);
            }
        }
    }

    void build(int u, int p = 0)
    {
        get_sz(u, 0);
        int centroid = get_centroid(u, 0, sz[u]);

        par[centroid] = p;
        removed[centroid] = true;

        std::vector<int> vec;
        fw.add(1, 1);

        for (int v : adj[centroid])
        {
            if (!removed[v])
            {
                std::vector<int> cur_dist;
                get_dist(v, centroid, 1, cur_dist);

                for (int d : cur_dist)
                {
                    ans += fw.sum(std::max(0LL, k1 - d) + 1, k2 - d + 1);
                }
                for (int d : cur_dist)
                {
                    fw.add(d + 1, 1);
                    vec.pb(d);
                }
            }
        }

        fw.add(1, -1);
        for (int d : vec)
        {
            fw.add(d + 1, -1);
        }

        for (int v : adj[centroid])
        {
            if (!removed[v])
            {
                build(v, centroid);
            }
        }
    }
};

void solve()
{
    std::cin >> n >> k1 >> k2;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    fw = FenwickTree(n);
    CentroidDecomposition cd(n);
    cd.build(1);

    std::cout << cd.ans;
}

