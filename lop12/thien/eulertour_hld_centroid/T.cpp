ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
std::vector<int> adj[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_dist(int u, int v)
    {
        return depth[u] + depth[v] - 2 * depth[get_lca(u, v)];
    }
};

LCA lca(0);

struct CentroidDecomposition
{
    int n;
    std::vector<int> sz, par, ans;
    std::vector<bool> removed, flag;
    std::vector<std::multiset<int>> s;

    CentroidDecomposition(int n)
    {
        this->n = n;
        sz.assign(n + 7, 0);
        par.assign(n + 7, 0);
        ans.assign(n + 7, INF);
        removed.assign(n + 7, false);
        flag.assign(n + 7, false);
        s.assign(n + 7, std::multiset<int>());
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void get_sz(int u, int p)
    {
        sz[u] = 1;
        for (int v : adj[u])
        {
            if (v != p && !removed[v])
            {
                get_sz(v, u);
                sz[u] += sz[v];
            }
        }
    }

    int get_centroid(int u, int p, int total_sz)
    {
        for (int v : adj[u])
        {
            if (v != p && !removed[v] && sz[v] > total_sz / 2)
            {
                return get_centroid(v, u, total_sz);
            }
        }
        return u;
    }

    void build(int u, int p = 0)
    {
        get_sz(u, 0);
        int centroid = get_centroid(u, 0, sz[u]);

        par[centroid] = p;
        removed[centroid] = true;

        for (int v : adj[centroid])
        {
            if (!removed[v])
            {
                build(v, centroid);
            }
        }
    }

    void update(int u)
    {
        if (!flag[u])
        {
            int cur = u;
            while (cur != 0)
            {
                s[cur].ins(lca.get_dist(cur, u));
                cur = par[cur];
            }
        }
        else
        {
            int cur = u;
            while (cur != 0)
            {
                s[cur].erase(s[cur].find(lca.get_dist(cur, u)));
                cur = par[cur];
            }
        }
        flag[u] = !flag[u];
    }

    int query(int u)
    {
        int cur = u;
        int res = INF;
        while (cur != 0)
        {
            if (s[cur].size())
            {
                res = std::min(res, *s[cur].begin() + lca.get_dist(u, cur));
            }
            cur = par[cur];
        }

        return res;
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    lca = LCA(n);
    lca.build(1);
    CentroidDecomposition cd(n);
    cd.build(1);

    for (int i = 1; i <= q; i++)
    {
        int type, u;
        std::cin >> type >> u;
        if (type == 1)
        {
            cd.update(u);
        }
        else
        {
            std::cout << (cd.query(u) == INF ? -1 : cd.query(u)) << "\n";
        }
    }
}

