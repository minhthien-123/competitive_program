const int maxn = 1e4;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll L;
int s, t;
vii adj[maxn + 7];
ll dists[maxn + 7], distt[maxn + 7];

struct edge
{
    int u, v;
    ll w;
    bool flag;
} edges[maxn + 7];

void solve()
{
    std::cin >> n >> m >> L >> s >> t;

    s++;
    t++;

    for (int i = 1; i <= m; i++)
    {
        std::cin >> edges[i].u >> edges[i].v >> edges[i].w;
        edges[i].u++;
        edges[i].v++;
        edges[i].flag = (edges[i].w == 0);

        if (edges[i].flag)
        {
            edges[i].w = 1;
        }

        adj[edges[i].u].pb({edges[i].v, i});
        adj[edges[i].v].pb({edges[i].u, i});
    }

    for (int i = 1; i <= n; i++)
    {
        distt[i] = INF;
    }

    std::priority_queue<pll, std::vector<pll>, std::greater<pll>> pqt;
    distt[t] = 0;
    pqt.push({0, t});

    while (!pqt.empty())
    {
        auto [du, u] = pqt.top();
        pqt.pop();
        if (du > distt[u])
        {
            continue;
        }

        for (auto [v, id] : adj[u])
        {
            ll w = edges[id].w;
            
            if (distt[v] > du + w)
            {
                distt[v] = du + w;
                pqt.push({distt[v], v});
            }
        }
    }

    if (distt[s] > L)
    {
        std::cout << "NO";
        return;
    }

    for (int i = 1; i <= n; i++)
    {
        dists[i] = INF;
    }

    std::priority_queue<pll, std::vector<pll>, std::greater<pll>> pqs;
    dists[s] = 0;
    pqs.push({0, s});

    while (!pqs.empty())
    {
        auto [du, u] = pqs.top();
        pqs.pop();
        if (du > dists[u])
        {
            continue;
        }

        for (auto [v, id] : adj[u])
        {   
            if (edges[id].flag)
            {
                ll need = std::max(edges[id].w, L - dists[u] - distt[v]);
                edges[id].w = need;
            }

            ll w = edges[id].w;
            if (dists[v] > du + w)
            {
                dists[v] = du + w;
                pqs.push({dists[v], v});
            }
        }
    }

    if (dists[t] != L)
    {
        std::cout << "NO";
    }
    else
    {
        std::cout << "YES\n";
        for (int i = 1; i <= m; i++)
        {
            std::cout << edges[i].u - 1 << " " << edges[i].v - 1 << " " << edges[i].w << "\n";
        }
    }
}

