ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct pt
{
    ll d;
    int u, state;
    friend bool operator>(pt a, pt b)
    {
        return a.d > b.d;
    }
};

int n, m;
std::vector<ii> adj[maxn + 7];
int dist[maxn + 7][4];

struct Dijkstra
{
    int n;
    std::vector<std::vector<ll>> dist;
    const long long INF = 1e18;

    Dijkstra(int n)
    {
        this->n = n;
        dist.assign(n + 7, std::vector<ll>(4, INF));
    }

    void run(int s)
    {
        std::priority_queue<pt, std::vector<pt>, std::greater<pt>> pq;

        dist[1][0] = 0;
        pq.push({0, 1, 0});

        while (!pq.empty())
        {
            auto [d, u, st] = pq.top();
            pq.pop();

            if (d > dist[u][st])
                continue;

            for (auto edge : adj[u])
            {
                int v = edge.fi;
                ll w = edge.se;

                if (st == 0)
                {
                    if (dist[v][0] > d + w)
                    {
                        dist[v][0] = d + w;
                        pq.push({dist[v][0], v, 0});
                    }
                    if (dist[v][1] > d)
                    {
                        dist[v][1] = d;
                        pq.push({dist[v][1], v, 1});
                    }
                    if (dist[v][2] > d + 2 * w)
                    {
                        dist[v][2] = d + 2 * w;
                        pq.push({dist[v][2], v, 2});
                    }
                    if (dist[v][3] > d + w)
                    {
                        dist[v][3] = d + w;
                        pq.push({dist[v][3], v, 3});
                    }
                }
                else if (st == 1)
                {
                    if (dist[v][1] > d + w)
                    {
                        dist[v][1] = d + w;
                        pq.push({dist[v][1], v, 1});
                    }
                    if (dist[v][3] > d + 2 * w)
                    {
                        dist[v][3] = d + 2 * w;
                        pq.push({dist[v][3], v, 3});
                    }
                }
                else if (st == 2)
                {
                    if (dist[v][2] > d + w)
                    {
                        dist[v][2] = d + w;
                        pq.push({dist[v][2], v, 2});
                    }
                    if (dist[v][3] > d)
                    {
                        dist[v][3] = d;
                        pq.push({dist[v][3], v, 3});
                    }
                }
                else if (st == 3)
                {
                    if (dist[v][3] > d + w)
                    {
                        dist[v][3] = d + w;
                        pq.push({dist[v][3], v, 3});
                    }
                }
            }
        }
    }
};

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    Dijkstra dijk(n);
    dijk.run(1);

    for (int i = 2; i <= n; i++)
    {
        std::cout << dijk.dist[i][3] << " ";
    }
}

