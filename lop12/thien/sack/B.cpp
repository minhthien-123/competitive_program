ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];

struct DSUOnTree
{
    int n, q;
    std::vector<std::vector<int>> adj;
    std::vector<int> sz, tin, tout, euler, depth;
    int timer;
    std::vector<int> mask;
    std::vector<std::vector<ii>> queries;
    std::vector<int> ans;
    std::string s;

    DSUOnTree() {};

    DSUOnTree(int n, int q, std::string str)
    {
        this->n = n;
        this->q = q;
        adj.resize(n + 7);
        sz.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        mask.assign(n + 7, 0);
        queries.resize(n + 7);
        ans.assign(q + 7, 0);
        timer = 0;
        s = " " + str;
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void add_query(int u, int k, int id)
    {
        queries[u].push_back({k, id});
    }

    void dfs_sz(int u, int p, int d)
    {
        sz[u] = 1;
        depth[u] = d;
        timer++;
        tin[u] = timer;
        euler.push_back(u);
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs_sz(v, u, d + 1);
                sz[u] += sz[v];
            }
        }
        tout[u] = timer;
    }

    void add(int u)
    {
        mask[depth[u]] ^= (1 << (s[u] - 'a'));
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (int v : adj[u])
        {
            if (v != p && sz[v] > max_sz)
            {
                max_sz = sz[v];
                big_child = v;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    add(euler[i - 1]);
                }
            }
        }
        add(u);

        for (auto qr : queries[u])
        {
            int k = qr.fi;
            int id = qr.se;
            int current_mask = mask[k];
            if (__builtin_popcountll(current_mask) <= 1)
            {
                ans[id] = 1;
            }
            else
            {
                ans[id] = 0;
            }
        }

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                add(euler[i - 1]);
            }
        }
    }
};

DSUOnTree sack;

void solve()
{
    std::cin >> n >> q;

    for (int i = 1; i < n; i++)
    {
        std::cin >> a[i];
    }

    std::string s;
    std::cin >> s;

    sack = DSUOnTree(n, q, s);

    for (int i = 1; i < n; i++)
    {
        sack.add_edge(a[i], i + 1);
    }

    for (int i = 1; i <= q; i++)
    {
        int v, k;
        std::cin >> v >> k;
        sack.add_query(v, k, i);
    }

    sack.dfs_sz(1, 0, 1);
    sack.dfs_sack(1, 0, true);

    for (int i = 1; i <= q; i++)
    {
        if (sack.ans[i])
        {
            std::cout << "Yes\n";
        }
        else
        {
            std::cout << "No\n";
        }
    }
}

