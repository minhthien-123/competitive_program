ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];

struct DSUOnTree
{
    int n, q;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> sz, tin, tout, euler, depth;
    int timer;
    std::vector<int> cnt, ans;
    std::vector<std::vector<ii>> queries;

    DSUOnTree() {}
    DSUOnTree(int n, int q)
    {
        this->n = n;
        this->q = q;
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(20, 0));
        sz.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        cnt.assign(n + 7, 0);
        ans.assign(q + 7, 0);
        queries.resize(n + 7);
        timer = 0;
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs_sz(int u, int p, int d)
    {
        up[u][0] = p;
        for (int i = 1; i < 20; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }

        depth[u] = d;
        sz[u] = 1;
        timer++;
        tin[u] = timer;
        euler.push_back(u);

        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs_sz(v, u, d + 1);
                sz[u] += sz[v];
            }
        }
        tout[u] = timer;
    }

    int getk(int u, int k)
    {
        for (int i = 0; i < 20; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }

        return u;
    }

    void add(int u, int val)
    {
        cnt[depth[u]] += val;
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (int v : adj[u])
        {
            if (v != p && sz[v] > max_sz)
            {
                max_sz = sz[v];
                big_child = v;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    add(euler[i - 1], 1);
                }
            }
        }
        add(u, 1);

        for (auto qr : queries[u])
        {
            ans[qr.se] = cnt[qr.fi] - 1;
        }

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                add(euler[i - 1], -1);
            }
        }
    }
};

DSUOnTree sack;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    std::cin >> q;

    sack = DSUOnTree(n, q);


    for (int i = 1; i <= n; i++)
    {
        if (a[i] == 0)
        {
            sack.add_edge(0, i);
        }
        else
        {
            sack.add_edge(a[i], i);
        }
    }

    sack.dfs_sz(0, 0, 0);

    for (int i = 1; i <= q; i++)
    {
        int v, k;
        std::cin >> v >> k;

        int u = sack.getk(v, k);
        if (u == 0)
        {
            sack.ans[i] = 0;
        }
        else
        {
            sack.queries[u].push_back({sack.depth[v], i});
        }
    }

    sack.dfs_sack(0, 0, true);

    for (int i = 1; i <= q; i++)
    {
        std::cout << sack.ans[i] << " ";
    }
}

