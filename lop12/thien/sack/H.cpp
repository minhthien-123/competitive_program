ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int ans[maxn + 7];

struct DSUOnTree
{
    int n;
    std::vector<std::vector<int>> adj;
    std::vector<int> sz_node, tin, tout, euler, depth, cnt;
    int timer;
    int max_freq, mx;

    DSUOnTree() {}
    DSUOnTree(int n)
    {
        this->n = n;
        adj.resize(n + 7);
        sz_node.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        cnt.assign(n + 7, 0);
        timer = 0;
        max_freq = 0;
        mx = 0;
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs_sz(int u, int p)
    {
        sz_node[u] = 1;
        depth[u] = depth[p] + 1;
        timer++;
        tin[u] = timer;
        euler.push_back(u);
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs_sz(v, u);
                sz_node[u] += sz_node[v];
            }
        }
        tout[u] = timer;
    }

    void add_node(int u)
    {
        int d = depth[u];
        cnt[d]++;

        if (cnt[d] > max_freq)
        {
            max_freq = cnt[d];
            mx = d;
        }
        else if (cnt[d] == max_freq && d < mx)
        {
            mx = d;
        }
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (int v : adj[u])
        {
            if (v != p && sz_node[v] > max_sz)
            {
                max_sz = sz_node[v];
                big_child = v;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    add_node(euler[i - 1]);
                }
            }
        }

        add_node(u);

        ans[u] = mx - depth[u];

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                cnt[depth[euler[i - 1]]]--;
            }
            max_freq = 0;
            mx = 0;
        }
    }
};

DSUOnTree sack;

void solve()
{
    std::cin >> n;

    sack = DSUOnTree(n);
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        sack.add_edge(u, v);
    }

    sack.dfs_sz(1, 0);
    sack.dfs_sack(1, 0, 1);

    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << "\n";
    }
}

