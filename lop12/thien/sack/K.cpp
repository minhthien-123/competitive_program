struct DSUOnTree
{
    int n;
    std::vector<std::vector<ii>> adj;
    std::vector<int> sz, tin, tout, euler, depth, mask, ans, mxd;
    int timer;

    DSUOnTree() {}
    DSUOnTree(int n)
    {
        this->n = n;
        adj.resize(n + 7);
        sz.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        depth.assign(n + 7, 0);
        mask.assign(1 << 22, 0);
        ans.assign(n + 7, 0);
        mxd.assign(1 << 22, -inf);
        euler.assign(n + 7, 0);
        timer = 0;
    }

    void add_edge(int u, int v, int w)
    {
        adj[u].push_back({v, w});
        adj[v].push_back({u, w});
    }

    void dfs_sz(int u, int p)
    {
        sz[u] = 1;
        timer++;
        tin[u] = timer;
        euler[timer] = u;
        for (auto [v, w] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                mask[v] = mask[u] ^ w;
                dfs_sz(v, u);
                sz[u] += sz[v];
            }
        }
        tout[u] = timer;
    }

    void add(int u, int val)
    {
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (auto [v, w] : adj[u])
        {
            if (v != p && sz[v] > max_sz)
            {
                max_sz = sz[v];
                big_child = v;
            }
        }

        for (auto [v, w] : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
                ans[u] = std::max(ans[u], ans[v]);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
            ans[u] = std::max(ans[u], ans[big_child]);
        }

        for (auto [v, w] : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    int x = euler[i];
                    int m = mask[x];
                    ans[u] = std::max(ans[u], depth[x] + mxd[m] - 2 * depth[u]);
                    for (int j = 0; j < 22; j++)
                    {
                        ans[u] = std::max(ans[u], depth[x] + mxd[m ^ (1 << j)] - 2 * depth[u]);
                    }
                }
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    int x = euler[i];
                    mxd[mask[x]] = std::max(mxd[mask[x]], depth[x]);
                }
            }
        }

        int m = mask[u];
        ans[u] = std::max(ans[u], depth[u] + mxd[m] - 2 * depth[u]);
        for (int j = 0; j < 22; j++)
        {
            ans[u] = std::max(ans[u], depth[u] + mxd[m ^ (1 << j)] - 2 * depth[u]);
        }
        mxd[m] = std::max(mxd[m], depth[u]);

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                int x = euler[i];
                mxd[mask[x]] = -inf;
            }
        }
    }
};

DSUOnTree sack;

void solve()
{
    std::cin >> n;
    sack = DSUOnTree(n);
    for (int i = 1; i < n; i++)
    {
        int u;
        char c;
        std::cin >> u >> c;
        sack.add_edge(u, i + 1, 1 << (c - 'a'));
    }

    sack.dfs_sz(1, 0);
    sack.dfs_sack(1, 0, 1);

    for (int i = 1; i <= n; i++)
    {
        std::cout << sack.ans[i] << " ";
    }
}

