ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int a[maxn + 7];

struct Compress
{
    std::vector<int> vals;
    void add(int x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(int x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

struct Node
{
    int lc, rc;
    int sum;
};

int n, node_cnt;
Node st[maxn * 20];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

int update(int old_id, int l, int r, int pos, int val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];
    st[id].sum += val;

    if (l == r)
    {
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    return id;
}

ll query(int id, int l, int r, int u, int v)
{
    if (!id || v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id].sum;
    }
    int mid = (l + r) / 2;
    return query(st[id].lc, l, mid, u, v) + query(st[id].rc, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> n;
    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cmp.add(a[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        a[i] = cmp.get(a[i]);
    }

    roots[0] = build(1, cmp.size());
    for (int i = 1; i <= n; i++)
    {
        roots[i] = update(roots[i - 1], 1, cmp.size(), a[i], 1);
    }

    ll ans = 0;
    for (int j = 1; j <= n; j++)
    {
        ll left = (ll)query(roots[j - 1], 1, cmp.size(), a[j] + 1, cmp.size());
        ll right = (ll)query(roots[n], 1, cmp.size(), 1, a[j] - 1)  - (ll)query(roots[j], 1, cmp.size(), 1, a[j] - 1);

        ans += left * right; 
    }

    std::cout << ans;
}

