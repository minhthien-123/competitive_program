{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];

// Cây IT bền thủy (Persistent Segment Tree).
// Mỗi lần gọi hàm update sẽ sinh ra một Ver mới, gốc rễ của Ver i nằm ở mảng roots[i].
// Khởi tạo: roots[0] = seg.build(1, N);
// Cập nhật: roots[i] = seg.update(roots[i-1], 1, N, pos, val);
// Truy vấn trên version ver: ans = seg.query(roots[ver], 1, N, L, R);
struct Node
{
    int lc, rc;
    long long sum;
};

int node_cnt;
Node st[maxn * 43];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

int update(int old_id, int l, int r, int pos, long long val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];
    st[id].sum += val;

    if (l == r)
    {
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    return id;
}

long long query(int id, int l, int r, int u, int v)
{
    if (u > r || v < l || id == 0)
    {
        return 0;
    }

    if (u <= l && r <= v)
    {
        return st[id].sum;
    }

    int mid = (l + r) / 2;
    return query(st[id].lc, l, mid, u, v) + query(st[id].rc, mid + 1, r, u, v);
}

struct Compress
{
    // Rời rạc hóa (Coordinate Compression) - Rất cần khi tọa độ lên tới 1e9 nhưng số lượng điểm nhỏ
    // Cách dùng: Compress cmp; cmp.add(val)... cmp.init(); int index = cmp.get(val);
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        // Trả về index 1-based (từ 1 đến số lượng phần tử phân biệt)
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};
void solve()
{
    std::cin >> n;
    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cmp.add(a[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        a[i] = cmp.get(a[i]);
    }

    roots[0] = build(1, cmp.size());
    for (int i = 1; i <= n; i++)
    {
        roots[i] = update(roots[i - 1], 1, cmp.size(), a[i], 1);
    }

    int last_ans = 0;
    std::cin >> q;
    while (q--)
    {
        int i, j, k;
        std::cin >> i >> j >> k;

        i = i ^ last_ans;
        j = j ^ last_ans;
        k = k ^ last_ans;

        if (i < 1)
        {
            i = 1;
        }
        if (j > n)
        {
            j = n;
        }
        if (i > j)
        {
            last_ans = 0;
            std::cout << last_ans << "\n";
            continue;
        }

        // std::cout << i << " " << j << " " << k << "\n";

        int pos = std::upper_bound(cmp.vals.begin(), cmp.vals.end(), k) - cmp.vals.begin() + 1;

        if (pos > cmp.size())
        {
            last_ans = 0;
        }
        else
        {
            int cnt2 = query(roots[j], 1, cmp.size(), pos, cmp.size());
            int cnt1 = query(roots[i - 1], 1, cmp.size(), pos, cmp.size());

            last_ans = cnt2 - cnt1;
        }

        std::cout << last_ans << "\n";
    }
}

