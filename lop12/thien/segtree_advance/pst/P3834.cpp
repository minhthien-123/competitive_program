ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];

struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

struct Node
{
    int lc, rc;
    long long sum;
};

int node_cnt;
Node st[maxn * 43];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

int update(int old_id, int l, int r, int pos, long long val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];
    st[id].sum += val;

    if (l == r)
    {
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    return id;
}

long long query(int L, int R, int l, int r, int k)
{
    if (l == r)
    {
        return l;
    }
    int mid = (l + r) / 2;
    int cntL = st[st[R].lc].sum - st[st[L].lc].sum;
    if (cntL >= k)
    {
        return query(st[L].lc, st[R].lc, l, mid, k);
    }
    else
    {
        return query(st[L].rc, st[R].rc, mid + 1, r, k - cntL);
    }
}

void solve()
{
    std::cin >> n >> m;
    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cmp.add(a[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        a[i] = cmp.get(a[i]);
    }

    roots[0] = build(1, n);
    for (int i = 1; i <= n; i++)
    {
        roots[i] = update(roots[i - 1], 1, n, a[i], 1);
    }

    for (int i = 1; i <= m; i++)
    {
        int l, r, k;
        std::cin >> l >> r >> k;
        int pos = query(roots[l - 1], roots[r], 1, n, k);
        std::cout << cmp.vals[pos - 1] << "\n";
    }
}

