ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int p[maxn + 7];
std::vector<int> adj[maxn + 7];
int timer;
int tin[maxn + 7], tout[maxn + 7];
int node_at_time[maxn + 7];

void dfs(int u, int p)
{
    timer++;
    tin[u] = timer;
    node_at_time[timer] = u;
    for (int v : adj[u])
    {
        if (v != p)
        {
            dfs(v, u);
        }
    }
    tout[u] = timer;
}

void build_eu(int root = 1)
{
    timer = 0;
    dfs(root, 0);
}

struct Node
{
    int lc, rc;
    long long sum;
};

int node_cnt;
Node st[maxn * 43 + 7];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

int update(int old_id, int l, int r, int pos, long long val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];
    st[id].sum += val;

    if (l == r)
    {
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    return id;
}

long long query(int id, int l, int r, int u, int v)
{
    if (!id || v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id].sum;
    }
    int mid = (l + r) / 2;
    return query(st[id].lc, l, mid, u, v) + query(st[id].rc, mid + 1, r, u, v);
}

struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

void solve()
{
    std::cin >> n;
    Compress cmp;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> p[i];
        cmp.add(p[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        p[i] = cmp.get(p[i]);
    }
    for (int i = 2; i <= n; i++)
    {
        int x;
        std::cin >> x;
        adj[x].pb(i);
        adj[i].pb(x);
    }
    build_eu();

    int max_val = cmp.size();
    roots[0] = build(1, max_val);
    
    for (int i = 1; i <= n; i++)
    {
        int u = node_at_time[i]; 
        roots[i] = update(roots[i - 1], 1, max_val, p[u], 1);
    }

    for (int i = 1; i <= n; i++)
    {
        int L = tin[i];
        int R = tout[i];
        
        int ans = query(roots[R], 1, max_val, p[i] + 1, max_val) - query(roots[L - 1], 1, max_val, p[i] + 1, max_val);
                      
        std::cout << ans << "\n";
    }
}

