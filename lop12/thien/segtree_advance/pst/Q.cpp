ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];
struct Node
{
    int lc, rc;
    int mn;
} st[maxn * 43];
int roots[maxn + 7];
int node_cnt = 0;

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        st[id].mn = inf;
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    st[id].mn = inf;
    return id;
}

int update(int old_id, int l, int r, int pos, int val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];

    if (l == r)
    {
        st[id].mn = val;
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    st[id].mn = std::min(st[st[id].lc].mn, st[st[id].rc].mn);
    return id;
}

long long query(int id, int l, int r, int u, int v)
{
    if (!id || v < l || r < u)
    {
        return inf;
    }
    if (u <= l && r <= v)
    {
        return st[id].mn;
    }
    int mid = (l + r) / 2;
    return std::min(query(st[id].lc, l, mid, u, v), query(st[id].rc, mid + 1, r, u, v));
}

int last[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    std::vector<int> vals;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        vals.pb(a[i]);
    }

    std::sort(vals.begin(), vals.end());
    vals.erase(std::unique(vals.begin(), vals.end()), vals.end());

    for (int i = 1; i <= n; i++)
    {
        a[i] = std::lower_bound(vals.begin(), vals.end(), a[i]) - vals.begin() + 1;
    }

    roots[0] = build(1, n);

    for (int i = 1; i <= n; i++)
    {
        if (last[a[i]] != 0)
        {
            int pre = last[a[i]];
            roots[i] = update(roots[i - 1], 1, n, pre, i - pre);
        }
        else
        {
            roots[i] = roots[i - 1];
        }

        last[a[i]] = i;
    }

    for (int i = 1; i <= m; i++)
    {
        int l, r;
        std::cin >> l >> r;
        int ans = query(roots[r], 1, n, l, r);
        std::cout << (ans == inf ? -1 : ans) << "\n";
    }
}

