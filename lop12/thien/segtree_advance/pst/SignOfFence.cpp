ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7];

struct Node
{
    int lc, rc;
    long long maxL, maxR, maxVal;
};

int node_cnt;
Node st[maxn * 43];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

struct node
{
    int maxL, maxR, maxVal, len;
};

node merge(node l, node r)
{
    if (l.len == 0)
    {
        return r;
    }
    if (r.len == 0)
    {
        return l;
    }
    node res;
    res.len = l.len + r.len;
    res.maxL = l.maxL + (l.maxL == l.len ? r.maxL : 0);
    res.maxR = r.maxR + (r.maxR == r.len ? l.maxR : 0);
    res.maxVal = std::max({l.maxVal, r.maxVal, l.maxR + r.maxL});
    return res;
}

int update(int old_id, int l, int r, int pos, long long val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];

    if (l == r)
    {
        st[id].maxL = st[id].maxR = st[id].maxVal = val;
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }

    node L = {st[st[id].lc].maxL, st[st[id].lc].maxR, st[st[id].lc].maxVal, mid - l + 1};
    node R = {st[st[id].rc].maxL, st[st[id].rc].maxR, st[st[id].rc].maxVal, r - mid};
    node res = merge(L, R);

    st[id].maxL = res.maxL;
    st[id].maxR = res.maxR;
    st[id].maxVal = res.maxVal;

    return id;
}

node get_query(int id, int l, int r, int u, int v)
{
    if (!id || v < l || r < u)
    {
        return {0, 0, 0, 0};
    }
    if (u <= l && r <= v)
    {
        return {st[id].maxL, st[id].maxR, st[id].maxVal, r - l + 1};
    }
    int mid = (l + r) / 2;
    return merge(get_query(st[id].lc, l, mid, u, v), get_query(st[id].rc, mid + 1, r, u, v));
}

struct Compress
{
    std::vector<long long> vals;
    void add(long long x) { vals.push_back(x); }
    void init()
    {
        std::sort(vals.begin(), vals.end());
        vals.erase(std::unique(vals.begin(), vals.end()), vals.end());
    }
    int get(long long x)
    {
        return std::lower_bound(vals.begin(), vals.end(), x) - vals.begin() + 1;
    }
    int size() { return vals.size(); }
};

Compress cmp;
std::vector<int> pos[maxn + 7];
void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        cmp.add(a[i]);
    }
    cmp.init();
    for (int i = 1; i <= n; i++)
    {
        a[i] = cmp.get(a[i]);
        pos[a[i]].pb(i);
    }

    roots[cmp.size() + 1] = build(1, n);
    for (int h = cmp.size(); h >= 1; h--)
    {
        roots[h] = roots[h + 1];
        for (int i : pos[h])
        {
            roots[h] = update(roots[h], 1, n, i, 1);
        }
    }

    std::cin >> m;
    for (int i = 1; i <= m; i++)
    {
        int l, r, w;
        std::cin >> l >> r >> w;
        int low = 1, high = cmp.size(), ans = -1;
        while (low <= high)
        {
            int mid = (low + high) / 2;
            if (get_query(roots[mid], 1, n, l, r).maxVal >= w)
            {
                ans = mid;
                low = mid + 1;
            }
            else
            {
                high = mid - 1;
            }
        }

        if (ans != -1)
        {
            std::cout << cmp.vals[ans - 1] << "\n";
        }
        else
        {
            std::cout << 0 << "\n";
        }
    }
}

