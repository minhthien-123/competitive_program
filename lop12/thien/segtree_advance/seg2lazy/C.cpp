ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];
int st[4 * maxn + 7];
int lz1[4 * maxn + 7], lz2[4 * maxn + 7];

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id] = a[l];
        lz1[id] = -1;
        lz2[id] = 0;
        return;
    }

    lz1[id] = -1;
    lz2[id] = 0;
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

void push(int id, int l, int r)
{
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;
    if (lz1[id] != -1)
    {
        st[id * 2] = lz1[id] * (mid - l + 1);
        lz1[id * 2] = lz1[id];
        lz2[id * 2] = 0;

        st[id * 2 + 1] = lz1[id] * (r - mid);
        lz1[id * 2 + 1] = lz1[id];
        lz2[id * 2 + 1] = 0;

        lz1[id] = -1;
        lz2[id] = 0;
    }

    if (lz2[id] != 0)
    {
        st[id * 2] = (mid - l + 1) - st[id * 2];

        if (lz1[id * 2] != -1)
        {
            lz1[id * 2] ^= lz2[id];
        }
        else
        {
            lz2[id * 2] ^= lz2[id];
        }

        st[id * 2 + 1] = (r - mid) - st[id * 2 + 1];

        if (lz1[id * 2 + 1] != -1)
        {
            lz1[id * 2 + 1] ^= lz2[id];
        }
        else
        {
            lz2[id * 2 + 1] ^= lz2[id];
        }

        lz2[id] = 0;
    }
}

void update1(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] = val * (r - l + 1);
        lz1[id] = val;
        lz2[id] = 0;
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update1(id * 2, l, mid, u, v, val);
    update1(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

void update2(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        st[id] = (r - l + 1) - st[id];
        if (lz1[id] != -1)
        {
            lz1[id] ^= 1;
        }
        else
        {
            lz2[id] ^= 1;
        }
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update2(id * 2, l, mid, u, v, val);
    update2(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

int query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }

    push(id, l, r);
    int mid = (l + r) / 2;
    return query(id * 2, l, mid, u, v) + query(id * 2 + 1, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build(1, 1, n);

    for (int i = 1; i <= q; i++)
    {
        int t, u, v, x;
        std::cin >> t >> u >> v;
        if (t == 1)
        {
            std::cin >> x;
            update1(1, 1, n, u, v, x);
        }
        else if (t == 2)
        {
            update2(1, 1, n, u, v, 1);
        }
        else
        {
            std::cout << query(1, 1, n, u, v) << "\n";
        }
    }
}

