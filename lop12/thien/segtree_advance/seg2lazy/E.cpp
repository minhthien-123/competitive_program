ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int st[4 * maxn + 7], lz_add[4 * maxn + 7], lz_mul[4 * maxn + 7];
int a[maxn + 7];

void build(int id, int l, int r)
{
    lz_add[id] = 0;
    lz_mul[id] = 1;
    if (l == r)
    {
        st[id] = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

void push(int id, int l, int r)
{
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;

    if (lz_mul[id] != 1)
    {
        st[id * 2] = mul(st[id * 2], lz_mul[id]);
        st[id * 2 + 1] = mul(st[id * 2 + 1], lz_mul[id]);

        lz_mul[id * 2] = mul(lz_mul[id * 2], lz_mul[id]);
        lz_mul[id * 2 + 1] = mul(lz_mul[id * 2 + 1], lz_mul[id]);

        lz_add[id * 2] = mul(lz_add[id * 2], lz_mul[id]);
        lz_add[id * 2 + 1] = mul(lz_add[id * 2 + 1], lz_mul[id]);

        lz_mul[id] = 1;
    }

    if (lz_add[id] != 0)
    {
        st[id * 2] = add(st[id * 2], mul(lz_add[id], mid - l + 1));
        st[id * 2 + 1] = add(st[id * 2 + 1], mul(lz_add[id], r - mid));

        lz_add[id * 2] = add(lz_add[id * 2], lz_add[id]);
        lz_add[id * 2 + 1] = add(lz_add[id * 2 + 1], lz_add[id]);

        lz_add[id] = 0;
    }
}

void update_add(int id, int l, int r, int u, int v, int val)
{
    if (l > v || r < u)
        return;
    if (l >= u && r <= v)
    {
        lz_add[id] = add(lz_add[id], val);
        st[id] = add(st[id], mul(val, r - l + 1));
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update_add(id * 2, l, mid, u, v, val);
    update_add(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = add(st[id * 2], st[id * 2 + 1]);
}

void update_mul(int id, int l, int r, int u, int v, int val)
{
    if (l > v || r < u)
        return;
    if (l >= u && r <= v)
    {
        lz_mul[id] = mul(lz_mul[id], val);

        lz_add[id] = mul(lz_add[id], val);

        st[id] = mul(st[id], val);
        return;
    }
    push(id, l, r);
    int mid = (l + r) / 2;
    update_mul(id * 2, l, mid, u, v, val);
    update_mul(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = add(st[id * 2], st[id * 2 + 1]);
}
int query(int id, int l, int r, int u, int v)
{
    if (l > v || r < u)
    {
        return 0;
    }
    if (l >= u && r <= v)
    {
        return st[id];
    }

    push(id, l, r);
    int mid = (l + r) / 2;
    return add(query(id * 2, l, mid, u, v), query(id * 2 + 1, mid + 1, r, u, v));
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build(1, 1, n);

    for (int i = 1; i <= q; i++)
    {
        int type, u, v, val;
        std::cin >> type >> u >> v;
        if (type == 1)
        {
            std::cin >> val;
            update_add(1, 1, n, u, v, val);
        }
        else if (type == 2)
        {
            std::cin >> val;
            update_mul(1, 1, n, u, v, val);
        }
        else
        {
            std::cout << query(1, 1, n, u, v) << "\n";
        }
    }
}

