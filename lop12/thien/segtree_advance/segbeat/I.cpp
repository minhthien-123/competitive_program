ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct node
{
    int mx, sum;
} st[4 * maxn + 7];

int n, m;
int a[maxn + 7];

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id].mx = st[id].sum = a[l];
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id].mx = std::max(st[id * 2].mx, st[id * 2 + 1].mx);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum;
}

void update_range(int id, int l, int r, int u, int v, int x)
{
    if (v < l || r < u || st[id].mx < x)
    {
        return;
    }
    if (l == r)
    {
        int tmp = st[id].mx % x;
        st[id].mx = st[id].sum = tmp;
        return;
    }

    int mid = (l + r) / 2;
    update_range(id * 2, l, mid, u, v, x);
    update_range(id * 2 + 1, mid + 1, r, u, v, x);
    st[id].mx = std::max(st[id * 2].mx, st[id * 2 + 1].mx);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum;
}

void update_point(int id, int l, int r, int pos, int val)
{
    if (l == r)
    {
        st[id].mx = st[id].sum = val;
        return;
    }
    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        update_point(id * 2, l, mid, pos, val);
    }
    else
    {
        update_point(id * 2 + 1, mid + 1, r, pos, val);
    }
    st[id].mx = std::max(st[id * 2].mx, st[id * 2 + 1].mx);
    st[id].sum = st[id * 2].sum + st[id * 2 + 1].sum;
}

int query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return 0;
    }
    if (u <= l && r <= v)
    {
        return st[id].sum;
    }
    int mid = (l + r) / 2;
    return query(id * 2, l, mid, u, v) + query(id * 2 + 1, mid + 1, r, u, v);
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build(1, 1, n);
    for (int i = 1; i <= m; i++)
    {
        int type;
        std::cin >> type;
        if (type == 2)
        {
            int l, r, val;
            std::cin >> l >> r >> val;
            update_range(1, 1, n, l, r, val);
        }
        else if (type == 3)
        {
            int pos, val;
            std::cin >> pos >> val;
            update_point(1, 1, n, pos, val);
        }
        else if (type == 1)
        {
            int l, r;
            std::cin >> l >> r;
            std::cout << query(1, 1, n, l, r) << "\n";
        }
    }
}

