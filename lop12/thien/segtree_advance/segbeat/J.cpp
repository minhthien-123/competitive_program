ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct node
{
    int max1, max2, maxc, sum;
} st[4 * maxn + 7];

int n, q;
int a[maxn + 7];

node merge(node l, node r)
{
    node res;

    res.sum = l.sum + r.sum;

    if (l.max1 == r.max1)
    {
        res.maxc = l.maxc + r.maxc;
        res.max1 = l.max1;
        res.max2 = std::max(l.max2, r.max2);
    }
    else if (l.max1 > r.max1)
    {
        res.maxc = l.maxc;
        res.max1 = l.max1;
        res.max2 = std::max(l.max2, r.max1);
    }
    else if (l.max1 < r.max1)
    {
        res.maxc = r.maxc;
        res.max1 = r.max1;
        res.max2 = std::max(l.max1, r.max2);
    }

    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        st[id].max1 = st[id].sum = a[l];
        st[id].max2 = -INF;
        st[id].maxc = 1;
        return;
    }

    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

void apply(int id, int x)
{
    if (st[id].max1 <= x)
    {
        return;
    }
    st[id].sum -= (st[id].max1 - x) * st[id].maxc;
    st[id].max1 = x;
}

void pushdown(int id)
{
    apply(id * 2, st[id].max1);
    apply(id * 2 + 1, st[id].max1);
}

void update(int id, int l, int r, int u, int v, int val)
{
    if (v < l || r < u || st[id].max1 < val)
    {
        return;
    }
    if (u <= l && r <= v && st[id].max2 < val)
    {
        apply(id, val);
        return;
    }
    int mid = (l + r) / 2;
    pushdown(id);
    update(id * 2, l, mid, u, v, val);
    update(id * 2 + 1, mid + 1, r, u, v, val);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

node query(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return {-INF, -INF, 0, 0};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    pushdown(id);
    return merge(query(id * 2, l, mid, u, v), query(id * 2 + 1, mid + 1, r, u, v));
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build(1, 1, n);
    for (int i = 1; i <= q; i++)
    {
        int type, l, r, val;
        std::cin >> type >> l >> r;
        if (type == 0)
        {
            std::cin >> val;
            update(1, 1, n, l, r, val);
        }
        else if (type == 1)
        {
            node res = query(1, 1, n, l, r);
            std::cout << res.sum << "\n";
        }
    }
}

