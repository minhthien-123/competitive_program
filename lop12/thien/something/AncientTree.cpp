ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
int w[maxn + 7], c[maxn + 7];
std::vector<int> adj[maxn + 7];

struct DSUOnTree
{
    int n;
    std::vector<int> sz, tin, tout, euler;
    std::vector<int> cnt;
    int ans = 0;
    int timer;

    DSUOnTree(int n)
    {
        this->n = n;
        sz.assign(n + 7, 0);
        tin.assign(n + 7, 0);
        tout.assign(n + 7, 0);
        cnt.assign(maxn + 7, 0);
        timer = 0;
    }

    void dfs_sz(int u, int p)
    {
        sz[u] = 1;
        timer++;
        tin[u] = timer;
        euler.push_back(u);
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs_sz(v, u);
                sz[u] += sz[v];
            }
        }
        tout[u] = timer;
    }

    void add(int u, int val)
    {
        cnt[c[u]] += val;
    }

    void dfs_sack(int u, int p, bool keep)
    {
        int big_child = -1, max_sz = -1;
        for (int v : adj[u])
        {
            if (v != p && sz[v] > max_sz)
            {
                max_sz = sz[v];
                big_child = v;
            }
        }

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                dfs_sack(v, u, false);
            }
        }

        if (big_child != -1)
        {
            dfs_sack(big_child, u, true);
        }

        std::vector<int> tmp;

        for (int v : adj[u])
        {
            if (v != p && v != big_child)
            {
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    int col = c[euler[i - 1]];
                    if (col != 0 && cnt[col] > 0)
                    {
                        tmp.pb(col);
                    }
                }
                for (int i = tin[v]; i <= tout[v]; i++)
                {
                    int x = euler[i - 1];
                    add(x, 1);
                }
            }
        }

        std::sort(tmp.begin(), tmp.end());
        tmp.erase(std::unique(tmp.begin(), tmp.end()), tmp.end());

        if (c[u] == 0)
        {
            if (sz(tmp) >= 1)
            {
                c[u] = tmp[0];
            }
            else
            {
                for (int v : adj[u])
                {
                    if (v != p && c[v] != 0)
                    {
                        c[u] = c[v];
                        break;
                    }
                }
            }
        }

        bool cute = false;
        for (int col : tmp)
        {
            if (col != c[u])
            {
                cute = true;
                break;
            }
        }

        if (cute)
        {
            ans += w[u];
        }

        add(u, 1);

        if (!keep)
        {
            for (int i = tin[u]; i <= tout[u]; i++)
            {
                add(euler[i - 1], -1);
            }
        }
    }

    void dfs_assign(int u, int p, int pcolor)
    {
        if (c[u] == 0)
        {
            c[u] = pcolor;
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs_assign(v, u, c[u]);
            }
        }
    }
};

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> w[i];
        adj[i].clear();
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    DSUOnTree sack(n);
    sack.dfs_sz(1, 0);
    sack.dfs_sack(1, 0, true);

    if (c[1] == 0)
    {
        c[1] = 1;
    }
    sack.dfs_assign(1, 0, c[1]);

    std::cout << sack.ans << "\n";
    for (int i = 1; i <= n; i++)
    {
        std::cout << c[i] << " ";
    }
    std::cout << "\n";
}

