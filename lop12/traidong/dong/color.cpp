const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

int n, m;
std::vector<int> adj[maxn + 7];
int deg[maxn + 7];
int color[maxn + 7];
bool removed[maxn + 7];
int visited[maxn + 7];
int vis_id = 0;
std::mt19937 rng(std::chrono::steady_clock::now().time_since_epoch().count());

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    for (int i = 1; i <= n; i++)
    {
        std::shuffle(all(adj[i]), rng);
    }

    std::vector<int> comp;
    comp.reserve(n + 7);

    bool success = false;
    while (!success)
    {
        for (int i = 1; i <= n; i++)
        {
            deg[i] = sz(adj[i]);
            removed[i] = false;
            color[i] = 0;
        }

        std::vector<int> Deg;
        for (int i = 1; i <= n; i++)
        {
            if (deg[i] <= 5)
            {
                Deg.pb(i);
                removed[i] = true;
            }
        }
        std::shuffle(all(Deg), rng);

        std::queue<int> q;
        for (int x : Deg)
        {
            q.push(x);
        }

        std::vector<int> order;
        while (!q.empty())
        {
            int u = q.front();
            q.pop();
            order.pb(u);

            for (int v : adj[u])
            {
                if (!removed[v])
                {
                    deg[v]--;
                    if (deg[v] <= 5)
                    {
                        removed[v] = true;
                        q.push(v);
                    }
                }
            }
        }

        for (int i = 1; i <= n; i++)
        {
            if (!removed[i])
            {
                order.pb(i);
            }
        }

        std::reverse(all(order));

        bool run = true;
        for (int u : order)
        {
            bool used[6] = {false};

            for (int v : adj[u])
            {
                if (color[v] > 0 && color[v] < 6)
                {
                    used[color[v]] = true;
                }
            }

            int avail = 0;
            for (int c = 1; c <= 4; c++)
            {
                if (!used[c])
                {
                    avail = c;
                    break;
                }
            }

            if (avail != 0)
            {
                color[u] = avail;
                continue;
            }

            int col_cnt[5] = {0};
            for (int v : adj[u])
            {
                if (color[v] >= 1 && color[v] <= 4)
                {
                    col_cnt[color[v]]++;
                }
            }

            bool done = false;
            for (int v : adj[u])
            {
                int c1 = color[v];
                if (col_cnt[c1] != 1)
                    continue;

                for (int c2 = 1; c2 <= 4; c2++)
                {
                    if (c1 == c2)
                        continue;

                    comp.clear();
                    vis_id++;

                    comp.pb(v);
                    visited[v] = vis_id;

                    int head = 0;
                    while (head < sz(comp))
                    {
                        int curr = comp[head++];

                        for (int nxt : adj[curr])
                        {
                            if (nxt == u)
                                continue;
                            if (visited[nxt] != vis_id && (color[nxt] == c1 || color[nxt] == c2))
                            {
                                visited[nxt] = vis_id;
                                comp.pb(nxt);
                            }
                        }
                    }

                    bool conflict = false;
                    for (int w : adj[u])
                    {
                        if (w != v && color[w] == c2 && visited[w] == vis_id)
                        {
                            conflict = true;
                            break;
                        }
                    }

                    if (!conflict)
                    {
                        for (int node : comp)
                        {
                            color[node] = (color[node] == c1 ? c2 : c1);
                        }
                        color[u] = c1;
                        done = true;
                        break;
                    }
                }
                if (done)
                    break;
            }

            if (!done)
            {
                if (TIME > 2.85)
                {
                    int c = 1;
                    while (used[c])
                    {
                        c++;
                    }
                    color[u] = c;
                }
                else
                {
                    run = false;
                    break;
                }
            }
        }

        if (run)
        {
            success = true;
        }
    }

    int ans = 0;
    for (int i = 1; i <= n; i++)
    {
        ans = std::max(ans, color[i]);
    }

    std::cout << ans << "\n";
    for (int i = 1; i <= n; i++)
    {
        std::cout << color[i] << " ";
    }
}

