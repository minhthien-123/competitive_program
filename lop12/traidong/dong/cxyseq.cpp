ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 8];
ll dp[maxn + 7];
ll pre[maxn + 7], X[maxn + 7], Y[maxn + 7], C[maxn + 7];
ll st[4 * maxn + 7];

void build(int id, int l, int r)
{
    st[id] = -INF;
    if (l == r)
    {
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
}

void update(int id, int l, int r, int pos, ll k)
{
    if (pos < l || pos > r)
    {
        return;
    }
    if (l == r)
    {
        st[id] = k;
        return;
    }

    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, k);
    update(id * 2 + 1, mid + 1, r, pos, k);
    st[id] = std::max(st[id * 2], st[id * 2 + 1]);
}

ll get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return -INF;
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }

    int mid = (l + r) / 2;
    ll get1 = get(id * 2, l, mid, u, v);
    ll get2 = get(id * 2 + 1, mid + 1, r, u, v);
    return std::max(get1, get2);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> X[i] >> Y[i] >> C[i];
    }

    build(1, 0, n);
    update(1, 0, n, 0, 0);

    for (int i = 1; i <= n; i++)
    {
        dp[i] = dp[i - 1];

        ll L = std::max(0LL, i - Y[i]);
        ll R = i - X[i];

        if (L <= R)
        {
            ll mx = get(1, 0, n, L, R);
            if (mx != -INF)
            {
                dp[i] = std::max(dp[i], pre[i] - C[i] + mx);
            }
        }

        update(1, 0, n, i, dp[i] - pre[i]);
    }

    std::cout << dp[n];
}

