ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ll h[maxn + 7];
ll diff[maxn + 7], l[maxn + 7], r[maxn + 7], d[maxn + 7];
bool deleted[maxn + 7];

struct pt
{
    ll val, cnt;
};
pt get_min(pt a, pt b)
{
    if (a.val != b.val)
    {
        // return a.val < b.val;
        if (a.val < b.val)
        {
            return a;
        }
        else
        {
            return b;
        }
    }
    if (a.val == b.val)
    {
        // return a.cnt > b.cnt;
        if (a.cnt > b.cnt)
        {
            return a;
        }
        else
        {
            return b;
        }
    }
}
pt dp[maxn + 7];

pt check(ll lambda)
{
    memset(dp, inf, sizeof dp);
    dp[0] = {0, 0};
    for (int i = 1; i <= n; i++)
    {
        dp[i] = dp[i - 1];
        if (i >= 2)
        {
            ll diff = h[i] - h[i - 1];
            ll cost = diff * diff;
            dp[i] = get_min(dp[i], {dp[i - 2].val + cost - lambda, dp[i - 2].cnt + 1});
        }
    }

    return dp[n];
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i];
    }
    std::sort(h + 1, h + n + 1);

    ll l = -4e12, r = 4e12;
    ll lambda_max = 0;

    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (check(mid).cnt >= k)
        {
            lambda_max = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    pt ans = check(lambda_max);
    // std::cout << lambda_max << "\n";
    std::cout << ans.val + lambda_max * k;
}

