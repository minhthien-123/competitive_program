const int maxn = 50;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
char c[maxn + 7][maxn + 7];
bool vis[maxn + 7][maxn + 7];

void solve()
{
    std::cin >> n >> m;
    int cntG = 0;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> c[i][j];
            vis[i][j] = false;
            if (c[i][j] == 'G')
                cntG++;
        }
    }

    if (cntG == 0)
    {
        std::cout << "Yes\n";
        return;
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (c[i][j] == 'B')
            {
                for (int d = 0; d < 4; d++)
                {
                    int ni = i + dx[d];
                    int nj = j + dy[d];
                    if (ni >= 1 && ni <= n && nj >= 1 && nj <= m)
                    {
                        if (c[ni][nj] == '.')
                        {
                            c[ni][nj] = '#';
                        }
                    }
                }
            }
        }
    }

    if (c[n][m] == '#')
    {
        std::cout << "No\n";
        return;
    }

    std::queue<ii> q;
    vis[n][m] = true;
    q.push({n, m});

    while (!q.empty())
    {
        ii curr = q.front();
        q.pop();
        int x = curr.fi;
        int y = curr.se;

        for (int d = 0; d < 4; d++)
        {
            int nx = x + dx[d];
            int ny = y + dy[d];
            if (nx >= 1 && nx <= n && ny >= 1 && ny <= m)
            {
                if (!vis[nx][ny] && c[nx][ny] != '#')
                {
                    vis[nx][ny] = true;
                    q.push({nx, ny});
                }
            }
        }
    }

    bool ok = true;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (c[i][j] == 'G' && !vis[i][j])
            {
                ok = false;
            }
            if (c[i][j] == 'B' && vis[i][j])
            {
                ok = false;
            }
        }
    }

    if (ok)
    {
        std::cout << "Yes\n";
    }
    else
    {
        std::cout << "No\n";
    }
}

