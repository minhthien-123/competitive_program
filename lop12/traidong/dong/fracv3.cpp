ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct Trie
{
    int child[2];
    Trie()
    {
        child[0] = child[1] = -1;
    }
};

std::vector<Trie> trie;
ll path_mask = 0;
int path_len = 0;

inline void insert_node(ll mask, int len)
{
    int cur = 0;
    while (len--)
    {
        int bit = mask & 1;
        mask >>= 1;
        if (trie[cur].child[bit] == -1)
        {
            trie[cur].child[bit] = sz(trie);
            trie.pb(Trie());
        }
        cur = trie[cur].child[bit];
    }
}

inline void encode(int p, int q)
{
    path_mask = 0;
    path_len = 0;

    while (p != q)
    {
        if (p < q)
        {
            int steps = (q - 1) / p;
            path_len += steps;
            q -= steps * p;
        }
        else
        {
            int steps = (p - 1) / q;
            path_mask |= ((1LL << steps) - 1) << path_len;
            path_len += steps;
            p -= steps * q;
        }
    }
}

void solve()
{
    int h, k;
    std::cin >> h >> k;

    trie.clear();
    trie.reserve(20000000);
    trie.pb(Trie());

    for (int i = 1; i <= k; i++)
    {
        int p, q;
        std::cin >> p >> q;
        encode(p, q);
        insert_node(path_mask, path_len);
    }

    std::cout << sz(trie) - 1;
}

