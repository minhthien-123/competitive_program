ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;

ll get_dist(ll u, ll v)
{
    if (u == v)
    {
        return 0;
    }

    ll pu, cost_u;
    if (u % 2 == 0)
    {
        pu = u;
        cost_u = 0;
    }
    else
    {
        pu = (u == 1) ? 2 : u - 1;
        cost_u = 1;
    }

    ll pv, cost_v;
    if (v % 2 == 0)
    {
        pv = v;
        cost_v = 0;
    }
    else
    {
        pv = (v == 1) ? 2 : v - 1;
        cost_v = 1;
    }

    return cost_u + abs(pu - pv) / 2 + cost_v;
}

void solve()
{
    std::cin >> n >> q;

    while (q--)
    {
        ll A, B, C, D;
        std::cin >> A >> B >> C >> D;

        if (std::max(A, C) <= std::min(B, D))
        {
            std::cout << 0 << "\n";
            continue;
        }

        if (A > C)
        {
            std::swap(A, C);
            std::swap(B, D);
        }

        std::vector<ll> cand_u;
        cand_u.pb(B);
        if (B - 1 >= A)
        {
            cand_u.pb(B - 1);
        }

        std::vector<ll> cand_v;
        cand_v.pb(C);
        if (C + 1 <= D)
        {
            cand_v.pb(C + 1);
        }

        ll ans = 4e18;
        for (ll u : cand_u)
        {
            for (ll v : cand_v)
            {
                ans = std::min(ans, get_dist(u, v));
            }
        }

        std::cout << ans << "\n";
    }
}

