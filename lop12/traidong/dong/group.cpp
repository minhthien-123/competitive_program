ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, q;
int d[maxn + 7], deg[maxn + 7];
std::set<ii> edges;

struct node
{
    int cnt, sum;
};

node st[4 * maxn + 7];

node merge(node a, node b)
{
    node res;
    res.cnt = a.cnt + b.cnt;
    res.sum = a.sum + b.sum;
    return res;
}

void update(int id, int l, int r, int pos, int val)
{
    if (pos < l || pos > r)
    {
        return;
    }
    if (l == r)
    {
        st[id].cnt += val;
        st[id].sum += pos * val;
        return;
    }

    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, val);
    update(id * 2 + 1, mid + 1, r, pos, val);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

int get_k(int id, int l, int r, int k)
{
    if (l == r)
    {
        return l;
    }
    int mid = (l + r) / 2;
    if (st[id * 2 + 1].cnt >= k)
    {
        return get_k(id * 2 + 1, mid + 1, r, k);
    }
    else
    {
        return get_k(id * 2, l, mid, k - st[id * 2 + 1].cnt);
    }
}

int get_sumk(int id, int l, int r, int k)
{
    if (k <= 0)
    {
        return 0;
    }
    if (st[id].cnt <= k)
    {
        return st[id].sum;
    }
    if (l == r)
    {
        return k * l;
    }

    int mid = (l + r) / 2;
    if (st[id * 2 + 1].cnt >= k)
    {
        return get_sumk(id * 2 + 1, mid + 1, r, k);
    }
    else
    {
        return st[id * 2 + 1].sum + get_sumk(id * 2, l, mid, k - st[id * 2 + 1].cnt);
    }
}

void init(int u, int v)
{
    if (u > v)
    {
        std::swap(u, v);
    }

    auto it = edges.find({u, v});

    if (it != edges.end())
    {
        edges.erase(it);
        update(1, 0, n, d[u], -1);
        update(1, 0, n, d[v], -1);
        d[u]--;
        d[v]--;
        update(1, 0, n, d[u], 1);
        update(1, 0, n, d[v], 1);
    }
    else
    {
        edges.ins({u, v});
        update(1, 0, n, d[u], -1);
        update(1, 0, n, d[v], -1);
        d[u]++;
        d[v]++;
        update(1, 0, n, d[u], 1);
        update(1, 0, n, d[v], 1);
    }
}

bool check_split()
{
    int l = 1, r = n, ans = 1;

    while (l <= r)
    {
        int mid = (l + r) / 2;

        int sum = get_sumk(1, 0, n, mid) - mid * (mid - 1) / 2;
        int sumdec = get_sumk(1, 0, n, mid - 1) - (mid - 1) * (mid - 2) / 2;
        int suminc = (mid < n) ? (get_sumk(1, 0, n, mid + 1) - mid * (mid + 1) / 2) : -INF;

        if (sum >= sumdec && sum >= suminc)
        {
            ans = mid;
            l = mid + 1;
        }
        else if (sumdec <= sum && sum <= suminc)
        {
            ans = mid;
            l = mid + 1;
        }
        else if (suminc <= sum && sum <= sumdec)
        {
            r = mid - 1;
        }
    }

    int total = st[1].sum;
    int C = get_sumk(1, 0, n, ans);
    int I = total - C;
    return (C - I == ans * (ans - 1));
}

void solve()
{
    std::cin >> n >> m;
    update(1, 0, n, 0, n);
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        init(u, v);
    }

    std::cout << (check_split() ? "YES\n" : "NO\n");

    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        int u, v;
        std::cin >> u >> v;
        init(u, v);
        std::cout << (check_split() ? "YES\n" : "NO\n");
    }
}

