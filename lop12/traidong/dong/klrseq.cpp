ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k, l, r;
ll a[maxn + 8];
pll dp[maxn + 7];
ll pre[maxn + 7], X[maxn + 7], Y[maxn + 7], C[maxn + 7];
ll st[4 * maxn + 7];

pll get_cost(ll pos)
{
    return {dp[pos].fi - pre[pos], dp[pos].se};
}

pll check(ll lambda)
{
    memset(dp, 0, sizeof dp);
    dp[0] = {0, 0};

    std::deque<int> dq;

    for (int i = 1; i <= n; i++)
    {
        dp[i] = dp[i - 1];

        int newT = i - l;
        if (newT >= 0)
        {
            pll val = get_cost(newT);
            while (!dq.empty() && get_cost(dq.back()) <= val)
            {
                dq.pop_back();
            }
            dq.push_back(newT);
        }

        while (!dq.empty() && dq.front() < i - r)
        {
            dq.pop_front();
        }

        if (!dq.empty())
        {
            int best = dq.front();
            pll cand = {pre[i] + dp[best].fi - pre[best] - lambda, dp[best].se + 1};
            if (dp[i] < cand)
            {
                dp[i] = cand;
            }
        }
    }

    return dp[n];
}

void solve()
{
    std::cin >> n >> k >> l >> r;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        pre[i] = pre[i - 1] + a[i];
    }

    ll L = -3e14, R = 3e14;
    ll lambda_max = 0;

    while (L <= R)
    {
        ll mid = (L + R) / 2;

        if (check(mid).se >= k)
        {
            lambda_max = mid;
            L = mid + 1;
        }
        else
        {
            R = mid - 1;
        }
    }

    pll ans = check(lambda_max);
    std::cout << ans.fi + lambda_max * k;
}

