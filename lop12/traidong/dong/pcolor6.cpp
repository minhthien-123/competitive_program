ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
std::vector<int> adj[maxn + 7];
int deg[maxn + 7];
int color[maxn + 7];
bool removed[maxn + 7];

bool cmp(int u, int v)
{
    return deg[u] < deg[v];
}

void solve()
{
    std::cin >> n >> m;
    std::vector<int> vec;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    std::queue<int> q;
    for (int i = 1; i <= n; i++)
    {
        deg[i] = sz(adj[i]);
        if (deg[i] <= 5)
        {
            q.push(i);
            removed[i] = true;
        }
    }

    std::vector<int> order;
    while (!q.empty())
    {
        int u = q.front();
        q.pop();
        order.pb(u);

        for (int v : adj[u])
        {
            if (!removed[v])
            {
                deg[v]--;
                if (deg[v] <= 5)
                {
                    removed[v] = true;
                    q.push(v);
                }
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        if (!removed[i])
        {
            order.pb(i);
        }
    }

    std::reverse(all(order));

    int ans = 0;
    for (int u : order)
    {
        std::vector<bool> used(8, false);
        for (int v : adj[u])
        {
            if (color[v] > 0 && color[v] <= 6)
            {
                used[color[v]] = true;
            }
        }

        for (int c = 1; c <= 6; c++)
        {
            if (!used[c])
            {
                color[u] = c;
                ans = std::max(ans, c);
                break;
            }
        }

        if (color[u] == 0)
        {
            color[u] = 1;
            ans = std::max(ans, 1);
        }
    }

    std::cout << ans << "\n";
    for (int i = 1; i <= n; i++)
    {
        std::cout << color[i] << " ";
    }
}

