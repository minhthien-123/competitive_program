ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
std::bitset<maxn + 7> adj[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].set(v);
        adj[v].set(u);
    }

    bool check = false;
    for (int u = 1; u <= n; u++)
    {
        for (int v = u + 1; v <= n; v++)
        {
            std::bitset<maxn + 7> uv = adj[u] & adj[v];

            uv.reset(u);
            uv.reset(v);

            if (uv.count() < 3)
            {
                continue;
            }

            for (int w = v + 1; w <= n; w++)
            {
                std::bitset<maxn + 7> uvw = uv & adj[w];
                
                uvw.reset(w);
                
                if (uvw.count() >= 3)
                {
                    check = true;
                }
            }
        }
    }

    if (check)
    {
        std::cout << "YES";
    }
    else
    {
        std::cout << "NO";
    }
}

