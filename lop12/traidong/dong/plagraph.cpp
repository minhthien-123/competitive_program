ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ii edges[maxn + 7];
std::vector<int> adj[maxn + 7];
int p[maxn + 7], pos[maxn + 7];
int color[maxn + 7];
std::vector<int> Y[maxn + 7];

struct node
{
    int mx, id;
};

node merge(node a, node b)
{
    if (a.mx > b.mx)
    {
        return a;
    }
    return b;
}

node st[4 * maxn + 7];

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

void build(int id, int l, int r)
{
    st[id] = {-1, -1};
    if (l == r)
    {
        Y[l].clear();
        return;
    }
    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
}

void update(int id, int l, int r, int pos, const std::vector<ii> &chords)
{
    if (pos < l || pos > r)
    {
        return;
    }
    if (l == r)
    {
        if (Y[l].empty())
        {
            st[id] = {-1, -1};
        }
        else
        {
            st[id] = {chords[Y[l].back()].se, Y[l].back()};
        }
        return;
    }
    int mid = (l + r) / 2;
    update(id * 2, l, mid, pos, chords);
    update(id * 2 + 1, mid + 1, r, pos, chords);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

node query(int id, int l, int r, int u, int v)
{
    if (u > r || v < l)
    {
        return {-1, -1};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    return merge(query(id * 2, l, mid, u, v), query(id * 2 + 1, mid + 1, r, u, v));
}

bool cmp(ii a, ii b)
{
    if (a.fi != b.fi)
    {
        return a.fi < b.fi;
    }
    return a.se > b.se;
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        std::cin >> edges[i].fi >> edges[i].se;
    }

    for (int i = 0; i < n; i++)
    {
        std::cin >> p[i];
        pos[p[i]] = i;
    }

    if (n <= 3)
    {
        std::cout << "YES\n";
        return;
    }

    if (m > 3 * n - 6)
    {
        std::cout << "NO\n";
        return;
    }

    std::vector<ii> chords;
    for (int i = 1; i <= m; i++)
    {
        int u = pos[edges[i].fi];
        int v = pos[edges[i].se];
        if (u > v)
        {
            std::swap(u, v);
        }

        if ((v - u == 1) || (u == 0 && v == n - 1))
        {
            continue;
        }

        chords.pb({u, v});
    }

    int M = chords.size();

    std::sort(all(chords), cmp);

    DSU dsu(2 * M);

    build(1, 0, n);

    for (int i = 0; i < M; i++)
    {
        Y[chords[i].fi].pb(i);
    }

    for (int i = 0; i < n; i++)
    {
        if (Y[i].empty())
        {
            continue;
        }
        std::sort(all(Y[i]), [&](int id1, int id2)
                  { return chords[id1].se < chords[id2].se; });
        update(1, 0, n, i, chords);
    }

    for (int i = 0; i < M; i++)
    {
        int u = chords[i].fi;
        int v = chords[i].se;
        int best_id = -1;

        while (true)
        {
            node res = query(1, 0, n, u + 1, v - 1);

            if (res.mx <= v)
            {
                break;
            }

            int id = res.id;
            int x_pos = chords[id].fi;

            Y[x_pos].pop_back();
            update(1, 0, n, x_pos, chords);

            dsu.join(i, id + M);
            dsu.join(i + M, id);

            if (dsu.acs(i) == dsu.acs(i + M))
            {
                std::cout << "NO\n";
                return;
            }

            if (best_id == -1)
            {
                best_id = id;
            }
        }

        if (best_id != -1)
        {
            int x_pos = chords[best_id].fi;
            Y[x_pos].pb(best_id);
            update(1, 0, n, x_pos, chords);
        }
    }

    std::cout << "YES\n";
}

