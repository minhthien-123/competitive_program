int power(int x, int y)
{
    if (y == 0)
    {
        return 1;
    }
    int tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

const double EPS = 1e-8;
struct Point
{
    double x, y;
    bool operator<(const Point &o) const
    {
        if (abs(x - o.x) > EPS)
            return x < o.x;
        return y < o.y - EPS;
    }
    bool operator==(const Point &o) const
    {
        return abs(x - o.x) <= EPS && abs(y - o.y) <= EPS;
    }
};
struct Circle
{
    double x, y, r;
};
std::vector<Point> getIntersections(const Circle &c1, const Circle &c2)
{
    double d = hypot(c1.x - c2.x, c1.y - c2.y);
    if (d > c1.r + c2.r + EPS || d < abs(c1.r - c2.r) - EPS || d < EPS)
        return {};
    double a = (c1.r * c1.r - c2.r * c2.r + d * d) / (2 * d);
    double h = sqrt(std::max(0.0, c1.r * c1.r - a * a));
    double cx = c1.x + a * (c2.x - c1.x) / d;
    double cy = c1.y + a * (c2.y - c1.y) / d;
    Point p1 = {cx + h * (c1.y - c2.y) / d, cy + h * (c2.x - c1.x) / d};
    Point p2 = {cx - h * (c1.y - c2.y) / d, cy - h * (c2.x - c1.x) / d};
    if (abs(h) < EPS)
        return {p1};
    return {p1, p2};
}

int n;

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

Circle C[maxn + 7];
std::vector<Point> ptsc[maxn + 7];
std::vector<Point> pts;

void solve()
{
    std::cin >> n;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> C[i].x >> C[i].y >> C[i].r;
    }

    DSU dsu(n);

    for (int i = 1; i <= n; i++)
    {
        for (int j = i + 1; j <= n; j++)
        {
            std::vector<Point> in = getIntersections(C[i], C[j]);
            if (in.size())
            {
                dsu.join(i, j);
                for (auto p : in)
                {
                    ptsc[i].pb(p);
                    ptsc[j].pb(p);
                    pts.pb(p);
                }
            }
        }
    }

    int E = 0;
    for (int i = 1; i <= n; i++)
    {
        std::sort(all(ptsc[i]));
        ptsc[i].erase(std::unique(all(ptsc[i])), ptsc[i].end());
        int m = ptsc[i].size();
        E += m;
    }

    std::sort(all(pts));
    pts.erase(std::unique(all(pts)), pts.end());
    int V = pts.size();

    int k = 0;
    for (int i = 1; i <= n; i++)
    {
        if (dsu.acs(i) == i)
        {
            k++;
        }
    }

    std::cout << E << " " << V << " " << k << "\n";

    std::cout << E - V + k + 1;
}

