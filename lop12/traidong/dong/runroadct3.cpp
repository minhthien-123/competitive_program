ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

ll C2(ll k)
{
    if (k < 2)
    {
        return 0;
    }
    return mul(mul(k, k - 1), inv);
}

int n, t;
int h[maxn + 7];
std::vector<int> adj[maxn + 7];

bool vis[maxn + 7];
int sub_sz[maxn + 7];
ll total = 0;

int dfs_sz(int u, int p, int max_h)
{
    vis[u] = true;
    int count = 1;
    for (int v : adj[u])
    {
        if (v != p && h[v] <= max_h)
        {
            count += dfs_sz(v, u, max_h);
        }
    }
    return count;
}

void dfs_calc(int u, int p, int S, int max_h)
{
    sub_sz[u] = 1;
    for (int v : adj[u])
    {
        if (v != p && h[v] <= max_h)
        {
            dfs_calc(v, u, S, max_h);
            sub_sz[u] += sub_sz[v];

            ll sz_u = sub_sz[v];
            ll sz_v = S - sub_sz[v];

            ll case1 = mul(sz_u, C2(sz_v));
            ll case2 = mul(sz_v, C2(sz_u));
            ll ways = add(case1, case2);
            ll cost = mul(2, ways);

            total = add(total, cost);
        }
    }
}

ll calc(int max_h)
{
    if (max_h < 0)
    {
        return 0;
    }

    for (int i = 1; i <= n; i++)
    {
        vis[i] = false;
    }

    total = 0;

    for (int i = 1; i <= n; i++)
    {
        if (!vis[i] && h[i] <= max_h)
        {
            int S = dfs_sz(i, 0, max_h);

            if (S >= 3)
            {
                dfs_calc(i, 0, S, max_h);
            }
        }
    }

    return total;
}

void solve()
{
    std::cin >> n >> t;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i];
    }

    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    ll ans = sub(calc(t), calc(t - 1));
    std::cout << ans;
}

