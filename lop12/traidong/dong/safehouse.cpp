const int maxn = 1e3;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m, k;
ll dp[1 << 11][maxn + 7]; 
ll cost[1 << 11];
ll F[1 << 11];
std::vector<pll> adj[maxn + 7];
int terminal[15];

struct edge
{
    int u, v;
    ll w;
    friend bool operator<(edge a, edge b)
    {
        return a.w < b.w;
    }
};

std::vector<edge> edges;

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

bool check(int mask)
{
    int cnt1 = 0, cnt2 = 0;

    for (int i = 0; i < k; i++)
    {
        if ((mask >> i) & 1)
        {
            cnt1++;
        }
        if ((mask >> (k + i)) & 1)
        {
            cnt2++;
        }
    }
    return (cnt1 > 0 && cnt1 == cnt2);
}

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 1; i <= m; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
        edges.pb({u, v, w});
    }

    for (int i = 0; i < k; i++)
    {
        terminal[i] = i + 1;
        terminal[k + i] = n - k + 1 + i;
    }

    for (int mask = 0; mask < (1 << (2 * k)); mask++)
    {
        for (int u = 1; u <= n; u++)
        {
            dp[mask][u] = INF;
        }
    }

    for (int i = 0; i < 2 * k; i++)
    {
        dp[1 << i][terminal[i]] = 0;
    }

    for (int mask = 1; mask < (1 << (2 * k)); mask++)
    {
        for (int u = 1; u <= n; u++)
        {
            for (int sub = (mask - 1) & mask; sub > 0; sub = (sub - 1) & mask)
            {
                if (sub <= (mask ^ sub))
                {
                    dp[mask][u] = std::min(dp[mask][u], dp[sub][u] + dp[mask ^ sub][u]);
                }
            }
        }

        std::priority_queue<pll, std::vector<pll>, std::greater<pll>> pq;
        for (int u = 1; u <= n; u++)
        {
            if (dp[mask][u] < INF)
            {
                pq.push({dp[mask][u], u});
            }
        }

        while (!pq.empty())
        {
            auto [du, u] = pq.top();
            pq.pop();

            if (du > dp[mask][u])
            {
                continue;
            }

            for (auto [v, w] : adj[u])
            {
                if (dp[mask][u] + w < dp[mask][v])
                {
                    dp[mask][v] = dp[mask][u] + w;
                    pq.push({dp[mask][v], v});
                }
            }
        }

        cost[mask] = INF;
        for (int u = 1; u <= n; u++)
        {
            cost[mask] = std::min(cost[mask], dp[mask][u]);
        }
    }

    for (int mask = 0; mask < (1 << (2 * k)); mask++)
    {                                                                                                       
        F[mask] = INF;
        if (check(mask))
        {
            F[mask] = cost[mask];
        }
    }

    for (int mask = 1; mask < (1 << (2 * k)); mask++)
    {
        for (int sub = (mask - 1) & mask; sub > 0; sub = (sub - 1) & mask)
        {
            if (F[sub] != INF && F[mask ^ sub] != INF)
            {
                F[mask] = std::min(F[mask], F[sub] + F[mask ^ sub]);
            }
        }
    }

    ll ans = F[(1 << (2 * k)) - 1];
    if (ans >= INF)
    {
        std::cout << "No solution";
    }
    else
    {
        std::cout << ans;
    }
}

