ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
std::vector<ii> adj[maxn + 7];
int tin[maxn + 7], tout[maxn + 7], timer = 0;

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth, dist;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
        dist.assign(n + 7, 0);
    }

    void dfs(int u, int p)
    {
        timer++;
        tin[u] = timer;
        up[u][0] = p;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (auto [v, w] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dist[v] = dist[u] + w;
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_dist(int u, int v)
    {
        return dist[u] + dist[v] - 2 * dist[get_lca(u, v)];
    }
};

std::set<ii> s;

int get_p(int u)
{
    auto it = s.lower_bound({tin[u], u});
    if (it == s.begin())
        return s.rbegin()->se;
    return prev(it)->se;
}

int get_q(int u)
{
    auto it = s.upper_bound({tin[u], u});
    if (it == s.end())
        return s.begin()->se;
    return it->se;
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    LCA lca(n);
    lca.build();

    int q;
    std::cin >> q;

    ll ans = 0;
    while (q--)
    {
        char type;
        std::cin >> type;
        if (type == '+')
        {
            int u;
            std::cin >> u;

            if (s.empty())
            {
                s.ins({tin[u], u});
            }
            else
            {
                int p = get_p(u);
                int q = get_q(u);
                ans += lca.get_dist(u, p) + lca.get_dist(u, q) - lca.get_dist(p, q);
                s.ins({tin[u], u});
            }
        }
        else if (type == '-')
        {
            int u;
            std::cin >> u;

            if (sz(s) <= 2)
            {
                ans = 0;
                s.erase({tin[u], u});
            }
            else
            {
                int p = get_p(u);
                int q = get_q(u);
                ans -= (lca.get_dist(u, p) + lca.get_dist(u, q) - lca.get_dist(p, q));
                s.erase({tin[u], u});
            }
        }
        else
        {
            std::cout << ans / 2 << "\n";
        }
    }
}

