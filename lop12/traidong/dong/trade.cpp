const int maxn = 1e6;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ll a[maxn + 7];
pll dp[maxn + 7][2];

pll check(ll lambda)
{
    dp[0][0] = {0, 0};
    dp[0][1] = {-INF, 0};

    for (int i = 1; i <= n; i++)
    {
        dp[i][1] = std::max(dp[i - 1][1], {dp[i - 1][0].fi - a[i], dp[i - 1][0].se});
        dp[i][0] = std::max(dp[i - 1][0], {dp[i - 1][1].fi + a[i] - lambda, dp[i - 1][1].se + 1});
    }

    return std::max(dp[n][0], dp[n][1]);
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    ll l = 0, r = 4e18, best_lambda = 0;
    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (check(mid).se >= k)
        {
            best_lambda = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    pll res = check(best_lambda);
    std::cout << res.fi + k * best_lambda;
}

