ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll a[maxn + 7][maxn + 7];

struct Combinatorics
{
    int n;
    long long MOD;
    std::vector<long long> fact, inv_fact;

    long long power(long long x, long long y)
    {
        long long res = 1;
        x %= MOD;
        while (y > 0)
        {
            if (y & 1)
            {
                res = (res * x) % MOD;
            }
            x = (x * x) % MOD;
            y >>= 1;
        }
        return res;
    }

    Combinatorics(int n, long long MOD) : n(n), MOD(MOD)
    {
        fact.assign(n + 1, 1);
        inv_fact.assign(n + 1, 1);
        for (int i = 2; i <= n; i++)
        {
            fact[i] = (fact[i - 1] * i) % MOD;
        }
        inv_fact[n] = power(fact[n], MOD - 2);
        for (int i = n - 1; i >= 1; i--)
        {
            inv_fact[i] = (inv_fact[i + 1] * (i + 1)) % MOD;
        }
    }

    long long nCr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[r] % MOD * inv_fact[n - r] % MOD;
    }

    long long nPr(int n, int r)
    {
        if (r < 0 || r > n)
        {
            return 0;
        }
        return fact[n] * inv_fact[n - r] % MOD;
    }

    ll ways(int r1, int c1, int r2, int c2)
    {
        int dr = r2 - r1;
        int dc = c2 - c1;
        if (dr < 0 || dc < 0)
        {
            return 0;
        }
        return nCr(dr + dc, dr);
    }
};

struct Point
{
    int r, c;
};

ll dp_grid[maxn + 7][maxn + 7];
std::map<int, std::vector<Point>> groups;

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
            groups[a[i][j]].pb({i, j});
        }
    }

    Combinatorics com(n * m, mod);

    ll total = com.ways(1, 1, n, m);
    ll ans = 0;
    int bl = 500;

    for (auto [val, cell] : groups)
    {
        int k = cell.size();
        ll res = 0;

        if (k <= bl)
        {
            std::sort(all(cell), [](const Point &p1, const Point &p2)
                      {
                        if (p1.r != p2.r) return p1.r < p2.r;
                        return p1.c < p2.c; });

            std::vector<int> dp(k);
            for (int i = 0; i < k; i++)
            {
                dp[i] = com.ways(1, 1, cell[i].r, cell[i].c);
                for (int j = 0; j < i; j++)
                {
                    if (cell[j].r <= cell[i].r && cell[j].c <= cell[i].c)
                    {
                        ll term = mul(dp[j], com.ways(cell[j].r, cell[j].c, cell[i].r, cell[i].c));
                        dp[i] = sub(dp[i], term);
                    }
                }

                ll cur = mul(dp[i], com.ways(cell[i].r, cell[i].c, n, m));
                res = add(res, cur);
            }
        }
        else
        {
            for (int i = 1; i <= n; i++)
            {
                for (int j = 1; j <= m; j++)
                {
                    if (a[i][j] == val)
                    {
                        dp_grid[i][j] = 0;
                    }
                    else if (i == 1 && j == 1)
                    {
                        dp_grid[i][j] = 1;
                    }
                    else
                    {
                        ll sum = 0;
                        if (i > 1)
                            sum += dp_grid[i - 1][j];
                        if (j > 1)
                            sum += dp_grid[i][j - 1];
                        dp_grid[i][j] = sum % mod;
                    }
                }
            }
            ll avoid = dp_grid[n][m];
            res = sub(total, avoid);
        }

        ll contrib = mul(res, val);
        ans = add(ans, contrib);
    }

    std::cout << ans;
}

