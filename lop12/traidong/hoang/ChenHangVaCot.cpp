ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int q, val;

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }

    int find_kth(int k)
    {
        int idx = 0;
        for (int i = (1 << 20); i > 0; i >>= 1)
        {
            if (idx + i <= n && bit[idx + i] < k)
            {
                idx += i;
                k -= bit[idx];
            }
        }

        return idx + 1;
    }

    void reset()
    {
        bit.assign(n + 7, 0);
    }
};

struct pt
{
    int opt, x, y;
} query[maxn + 7];

int r = 0, c = 0;
int row_pos[maxn + 7], col_pos[maxn + 7];
ii row_info[maxn + 7], col_info[maxn + 7]; // {time, val}
int row_ini, col_ini;

void solve()
{
    std::cin >> q >> val;
    for (int i = 1; i <= q; i++)
    {
        std::cin >> query[i].opt >> query[i].x >> query[i].y;

        if (query[i].opt == 1)
        {
            r++;
        }
        else if (query[i].opt == 2)
        {
            c++;
        }
    }

    FenwickTree row(r + 1);
    FenwickTree col(c + 1);

    for (int i = 1; i <= r + 1; i++)
    {
        row.add(i, 1);
    }
    for (int i = 1; i <= c + 1; i++)
    {
        col.add(i, 1);
    }

    for (int i = q; i >= 1; i--)
    {
        if (query[i].opt == 1)
        {
            int k = query[i].x + 1;
            int pos = row.find_kth(k);
            row.add(pos, -1);
            row_pos[i] = pos;
            row_info[pos] = {i, query[i].y};
        }
        else if (query[i].opt == 2)
        {
            int k = query[i].x + 1;
            int pos = col.find_kth(k);
            col.add(pos, -1);
            col_pos[i] = pos;
            col_info[pos] = {i, query[i].y};
        }
    }

    row_ini = row.find_kth(1);
    row_info[row_ini] = {0, val};
    col_ini = col.find_kth(1);
    col_info[col_ini] = {0, val};

    row.reset();
    col.reset();

    row.add(row_ini, 1);
    col.add(col_ini, 1);

    for (int i = 1; i <= q; i++)
    {
        if (query[i].opt == 1)
        {
            row.add(row_pos[i], 1);
        }
        else if (query[i].opt == 2)
        {
            col.add(col_pos[i], 1);
        }
        else
        {
            int row_idx = row.find_kth(query[i].x);
            int col_idx = col.find_kth(query[i].y);

            // std::cout << row_idx << " " << col_idx << " ";

            auto [row_time, row_val] = row_info[row_idx];
            auto [col_time, col_val] = col_info[col_idx];

            // std::cout << row_val << " " << col_val << "\n";

            if (row_time > col_time)
            {
                std::cout << row_val;
            }
            else
            {
                std::cout << col_val;
            }
            std::cout << "\n";
        }
    }
}

