ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll a[maxn + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    std::sort(a + 1, a + n + 1);

    int maxlen = 0;
    int L = -1, R = -1;

    int r = 2;
    for (int l = 1; l <= n - 2; l++)
    {
        ll lim = a[l] + a[l + 1];
        if (r < l + 2)
        {
            r = l + 2;
        }

        while (r <= n && a[r] < lim)
        {
            r++;
        }

        int current_len = r - l;
        if (current_len >= 3 && current_len > maxlen)
        {
            maxlen = current_len;
            L = l;
            R = r - 1;
        }
    }
    
    if (maxlen < 3)
    {
        std::cout << 0 << "\n";
        return;
    }

    std::cout << maxlen << " ";
    for (int i = L; i <= R; i++)
    {
        std::cout << a[i] << " ";
    }
    std::cout << "\n";
}

