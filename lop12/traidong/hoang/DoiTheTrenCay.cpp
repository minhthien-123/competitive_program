ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll c[maxn + 7];
std::vector<int> adj[maxn + 7];
int tin[maxn + 8], tout[maxn + 7], timer = 0;
ll min_cost[maxn + 7];
ll W[maxn + 7];
ll dist[maxn + 7];

bool is_acs(int u, int v)
{
    return tin[u] <= tin[v] && tout[v] <= tout[u];
}

void dfs_cost(int u, int p)
{
    min_cost[u] = c[u];
    ll min1 = INF, min2 = INF;
    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        dfs_cost(v, u);
        if (min_cost[v] < min1)
        {
            min2 = min1;
            min1 = min_cost[v];
        }
        else if (min_cost[v] < min2)
        {
            min2 = min_cost[v];
        }
    }
    if (min2 != INF)
    {
        min_cost[u] = std::min(min_cost[u], min1 + min2);
    }
}
void dfs(int u, int p)
{
    tin[u] = ++timer;

    int best1 = -1, best2 = -1;
    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        if (best1 == -1 || min_cost[v] < min_cost[best1])
        {
            best2 = best1;
            best1 = v;
        }
        else if (best2 == -1 || min_cost[v] < min_cost[best2])
        {
            best2 = v;
        }
    }

    for (int v : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        if (v == best1)
        {
            W[v] = min_cost[best2];
        }
        else
        {
            W[v] = min_cost[best1];
        }

        dist[v] = dist[u] + W[v];
        dfs(v, u);
    }
    tout[u] = ++timer;
}

void reset()
{
    for (int i = 1; i <= n; i++)
    {
        adj[i].clear();
        min_cost[i] = 0;
        W[i] = 0;
        tin[i] = tout[i] = 0;
        dist[i] = 0;
    }
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> c[i];
    }
    reset();
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    dfs_cost(1, 0);
    dist[1] = 0;
    dfs(1, 0);

    while (m--)
    {
        int x, y;
        std::cin >> x >> y;
        if (!is_acs(y, x))
        {
            std::cout << "-1\n";
        }
        else
        {
            std::cout << dist[x] - dist[y] << "\n";
        }
    }
}

