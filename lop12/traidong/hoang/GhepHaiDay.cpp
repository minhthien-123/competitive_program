ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll a[maxn + 7], b[maxn + 7];
ll pre[maxn + 7][2], suf[maxn + 7][2];

bool check(ll x)
{
    pre[0][0] = 0;
    pre[0][1] = -INF;
    for (int i = 1; i <= n; i++)
    {
        pre[i][0] = std::max(pre[i - 1][0], pre[i - 1][1]);
        pre[i][1] = -INF;
        if (a[i] >= x)
        {
            pre[i][1] = pre[i - 1][0] + 1;                                                                                                      
        }
    }

    suf[n + 1][0] = 0;
    suf[n + 1][1] = -INF;
    for (int i = n; i >= 1; i--)
    {
        suf[i][0] = std::max(suf[i + 1][0], suf[i + 1][1]);
        suf[i][1] = -INF;
        if (b[i] >= x)
        {
            suf[i][1] = suf[i + 1][0] + 1;
        }
    }

    for (int k = 0; k <= n; k++)
    {
        ll ans1 = std::max(suf[k + 1][0], suf[k + 1][1]);
        ll ans2 = suf[k + 1][0];

        ll total = std::max(pre[k][0] + ans1, pre[k][1] + ans2);
        if (total >= m)
        {
            return true;
        }
    }

    return false;
}

void solve()
{
    std::cin >> n >> m;
    std::vector<ll> vec;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        vec.pb(a[i]);
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> b[i];
        vec.pb(b[i]);
    }

    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());

    int l = 0, r = sz(vec) - 1;
    ll ans = -1;

    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(vec[mid]))
        {
            ans = vec[mid];
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << ans << "\n";
}

