ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
ll a[maxn + 7], h[maxn + 7];
int st[lg][maxn + 7];

const int max_nodes = 6000005;
struct TrieXor
{
    int child[max_nodes][2];
    int cnt[max_nodes];
    int node_cnt;

    void init()
    {
        node_cnt = 0;
        child[0][0] = child[0][1] = -1;
        cnt[0] = 0;
    }

    int new_node()
    {
        node_cnt++;
        child[node_cnt][0] = child[node_cnt][1] = -1;
        cnt[node_cnt] = 0;
        return node_cnt;
    }

    void insert(int x)
    {
        int curr = 0;
        for (int i = 30; i >= 0; i--)
        {
            int bit = (x >> i) & 1;
            if (child[curr][bit] == -1)
            {
                child[curr][bit] = new_node();
            }
            curr = child[curr][bit];
            cnt[curr]++;
        }
    }

    void remove(int x)
    {
        int curr = 0;
        for (int i = 30; i >= 0; i--)
        {
            int bit = (x >> i) & 1;
            curr = child[curr][bit];
            cnt[curr]--;
        }
    }

    int query_max(int x)
    {
        int curr = 0;
        int ans = 0;
        for (int i = 30; i >= 0; i--)
        {
            int bit = (x >> i) & 1;
            int target = 1 - bit;
            if (child[curr][target] != -1 && cnt[child[curr][target]] > 0)
            {
                ans |= (1 << i);
                curr = child[curr][target];
            }
            else
            {
                curr = child[curr][bit];
            }
        }
        return ans;
    }

    int query_min(int x)
    {
        int curr = 0;
        int ans = 0;
        for (int i = 30; i >= 0; i--)
        {
            int bit = (x >> i) & 1;
            int target = bit;
            if (child[curr][target] != -1 && cnt[child[curr][target]] > 0)
            {
                curr = child[curr][target];
            }
            else
            {
                ans |= (1 << i);
                curr = child[curr][1 - bit];
            }
        }
        return ans;
    }
} trie;

void build_spt()
{
    for (int i = 1; i <= n; i++)
    {
        st[0][i] = i;
    }

    for (int j = 1; (1 << j) <= n; j++)
    {
        for (int i = 1; i + (1 << j) - 1 <= n; i++)
        {
            int idx1 = st[j - 1][i];
            int idx2 = st[j - 1][i + (1 << (j - 1))];
            st[j][i] = (h[idx1] <= h[idx2]) ? idx1 : idx2;
        }
    }
}

int get_min_idx(int L, int R)
{
    int len = R - L + 1;
    int j = 31 - __builtin_clz(len);
    int idx1 = st[j][L];
    int idx2 = st[j][R - (1 << j) + 1];
    return (h[idx1] <= h[idx2]) ? idx1 : idx2;
}

ll ans = -INF;

inline void update_ans(int x, ll h_m)
{
    ll best;
    if (h_m > 0)
    {
        best = trie.query_max(x) - k;
    }
    else if (h_m < 0)
    {
        best = trie.query_min(x) - k;
    }
    else
    {
        best = -k;
    }

    ans = std::max(ans, h_m * best);
}

void calc(int L, int R, bool keep)
{
    if (L > R)
    {
        return;
    }
    if (L == R)
    {
        if (keep)
        {
            trie.insert(a[L]);
        }
        return;
    }

    int m = get_min_idx(L, R);

    if (m - L <= R - m)
    {
        calc(L, m - 1, false);
        calc(m + 1, R, true);

        if (m < R)
        {
            update_ans(a[m], h[m]);
        }
        
        trie.insert(a[m]);

        for (int i = L; i < m; i++)
        {
            update_ans(a[i], h[m]);
        }

        if (keep)
        {
            for (int i = L; i < m; i++)
            {
                trie.insert(a[i]);
            }
        }
        else
        {
            for (int i = m; i <= R; i++)
            {
                trie.remove(a[i]);
            }
        }
    }
    else
    {
        calc(m + 1, R, false);
        calc(L, m - 1, true);

        if (m > L)
        {
            update_ans(a[m], h[m]);
        }
        trie.insert(a[m]);

        for (int i = m + 1; i <= R; i++)
        {
            update_ans(a[i], h[m]);
        }

        if (keep)
        {
            for (int i = m + 1; i <= R; i++)
            {
                trie.insert(a[i]);
            }
        }
        else
        {
            for (int i = L; i <= m; i++)
            {
                trie.remove(a[i]);
            }
        }
    }
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    build_spt();
    trie.init();
    ans = -INF;

    calc(1, n, 0);

    std::cout << ans << "\n";
}

