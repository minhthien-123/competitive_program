ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int p[maxn + 7];
int cnt;
ll ans = 0;

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v, int w)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            ans += w;
            sz[u] += sz[v];
            cnt--;
        }
    }
};

int pos[maxn + 7];
ii L[maxn + 7], R[maxn + 7];

void solve()
{
    std::cin >> n >> m;
    cnt = m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> p[i];
        pos[p[i]] = i;
    }

    DSU dsu(m);

    for (int i = 1; i <= m; i++)
    {
        int l, r;
        std::cin >> l >> r;
        L[i] = {l, i};
        R[i] = {r, i};
        dsu.par[i] = i;
    }

    std::sort(L + 1, L + m + 1);
    std::sort(R + 1, R + m + 1, std::greater<ii>());

    int posL = m + 1;
    int posR = m + 1;

    int min_pos = n + 1;
    int max_pos = 0;

    for (int v = 0; v < n; v++)
    {
        min_pos = std::min(min_pos, pos[v]);
        max_pos = std::max(max_pos, pos[v]);

        while (posL > 1 && L[posL - 1].fi > min_pos)
        {
            posL--;
            dsu.join(L[m].se, L[posL].se, v);
        }

        while (posR > 1 && R[posR - 1].fi < max_pos)
        {
            posR--;
            dsu.join(R[m].se, R[posR].se, v);
        }

        if (L[m].fi > pos[v] && R[m].fi < pos[v])
        {
            dsu.join(L[m].se, R[m].se, v);
        }
    }

    ans += 1LL * (cnt - 1) * n;
    std::cout << ans;
}

