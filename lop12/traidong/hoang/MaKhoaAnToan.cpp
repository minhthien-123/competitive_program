ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}
int n;
std::string s[maxn + 7];
int dist[maxn + 7];
std::vector<int> q[26];
int cnt[maxn + 7];
int pw10[5] = {1, 10, 100, 1000, 10000};

void solve()
{
    std::cin >> n;
    for (int i = 0; i < maxn; i++)
    {
        dist[i] = 26;
    }
    cnt[26] = maxn;

    for (int k = 0; k < n; k++)
    {
        std::string s;
        std::cin >> s;

        int code = 0;
        for (char c : s)
        {
            code = code * 10 + (c - '0');
        }

        if (dist[code] > 0)
        {
            cnt[dist[code]]--;
            dist[code] = 0;
            cnt[0]++;
            q[0].pb(code);
        }

        for (int d = 0; d <= 25; d++)
        {
            for (int i = 0; i < q[d].size(); i++)
            {
                int u = q[d][i];

                if (dist[u] != d)
                {
                    continue;
                }

                for (int j = 0; j < 5; j++)
                {
                    int digit = (u / pw10[j]) % 10;

                    int v = u + (digit == 9 ? -9 * pw10[j] : pw10[j]);
                    if (dist[v] > d + 1)
                    {
                        cnt[dist[v]]--;
                        dist[v] = d + 1;
                        cnt[d + 1]++;
                        q[d + 1].pb(v);
                    }

                    v = u + (digit == 0 ? 9 * pw10[j] : -pw10[j]);
                    if (dist[v] > d + 1)
                    {
                        cnt[dist[v]]--;
                        dist[v] = d + 1;
                        cnt[d + 1]++;
                        q[d + 1].pb(v);
                    }
                }
            }
            q[d].clear();
        }

        int mx = 25;
        while (mx >= 0 && cnt[mx] == 0)
        {
            mx--;
        }

        std::cout << mx << " " << cnt[mx] << "\n";
    }
}

