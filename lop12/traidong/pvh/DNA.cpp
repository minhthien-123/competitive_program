ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::string s1, s2;
int dp[maxn + 7][maxn + 7];

void solve()
{
    std::cin >> s1 >> s2;
    int n1 = sz(s1);
    int n2 = sz(s2);
    s1 = " " + s1;
    s2 = " " + s2;

    for (int i = 1; i <= n1; i++)
    {
        dp[i][0] = i;
    }
    for (int j = 1; j <= n2; j++)
    {
        dp[0][j] = j;
    }

    for (int i = 1; i <= n1; i++)
    {
        for (int j = 1; j <= n2; j++)
        {
            if (s1[i] == s2[j])
            {
                dp[i][j] = dp[i - 1][j - 1];
            }
            else
            {
                dp[i][j] = std::min({dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + 1});
            }
        }
    }

    std::cout << (dp[n1][n2] <= 2 ? "Yes" : "No");
}

