const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ii a[maxn + 7];
std::vector<ii> vals;
int freq[maxn + 7];

void solve()
{
    std::cin >> n;

    int mn = INF, mx = -INF;
    int rmin = INF, rmax = -INF;
    int bmin = INF, bmax = -INF;

    for (int i = 1; i <= n; i++)
    {
        int x, y;
        std::cin >> x >> y;
        if (x > y)
        {
            std::swap(x, y);
        }

        a[i] = {x, y};

        mx = std::max(mx, y);
        mn = std::min(mn, x);

        rmin = std::min(rmin, y);
        bmax = std::max(bmax, x);

        vals.pb({x, i});
        vals.pb({y, i});
    }

    int ans = (mx - rmin) * (bmax - mn);

    // std::cout << ans << "\n";

    std::sort(all(vals));
    int cnt = 0;
    int l = 0;
    int res = INF;

    for (int r = 0; r < 2 * n; r++)
    {
        if (freq[vals[r].se] == 0)
        {
            cnt++;
        }
        freq[vals[r].se]++;

        while (cnt == n)
        {
            res = std::min(res, vals[r].fi - vals[l].fi);
            freq[vals[l].se]--;
            if (freq[vals[l].se] == 0)
            {
                cnt--;
            }
            l++;
        }
    }

    ans = std::min(ans, (mx - mn) * res);

    // std::cout << (mx - mn) * res << "\n";

    std::cout << ans;
}

