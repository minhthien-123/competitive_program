ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ii range[maxn + 7];
int f[maxn + 7];

int fact[maxn + 7];
int invFact[maxn + 7];

void precompute()
{
    fact[0] = 1;
    invFact[0] = 1;
    for (int i = 1; i <= maxn; i++)
    {
        fact[i] = mul(fact[i - 1], i);
    }
    invFact[maxn] = power(fact[maxn], mod - 2);
    for (int i = maxn - 1; i >= 1; i--)
    {
        invFact[i] = mul(invFact[i + 1], i + 1);
    }
}

int nCr(int n_val, int r_val)
{
    if (r_val < 0 || r_val > n_val)
    {
        return 0;
    }
    return mul(fact[n_val], mul(invFact[r_val], invFact[n_val - r_val]));
}

int catalan(int k)
{
    if (k < 0)
    {
        return 0;
    }
    if (k == 0)
    {
        return 1;
    }
    return sub(nCr(2 * k, k), nCr(2 * k, k + 1));
}

void solve()
{
    precompute();
    std::cin >> n >> m;
    if (n % 2 != 0)
    {
        std::cout << 0 << "\n";
        return;
    }

    for (int i = 1; i <= m; i++)
    {
        std::cin >> range[i].fi >> range[i].se;
        if (range[i].fi > range[i].se)
        {
            std::swap(range[i].fi, range[i].se);
        }
    }

    std::sort(range + 1, range + m + 1);
    m = std::unique(range + 1, range + m + 1) - (range + 1);

    range[0] = {0, n + 1};
    std::sort(range, range + m + 1, [&](ii x, ii y)
              { 
        if (x.fi != y.fi) return x.fi < y.fi;
        return x.se > y.se; });

    std::stack<int> st;
    st.push(0);

    for (int i = 1; i <= m; i++)
    {
        if (range[i].fi >= range[i].se || (range[i].se - range[i].fi + 1) % 2 != 0)
        {
            std::cout << 0 << "\n";
            return;
        }

        while (!st.empty() && range[st.top()].se < range[i].fi)
        {
            st.pop();
        }

        if (!st.empty() && (range[st.top()].se <= range[i].se || range[st.top()].fi == range[i].fi))
        {
            std::cout << 0 << "\n";
            return;
        }

        f[st.top()] += (range[i].se - range[i].fi + 1);
        st.push(i);
    }

    int ans = 1;
    for (int i = 0; i <= m; i++)
    {
        int space = (i == 0) ? (n - f[0]) : ((range[i].se - range[i].fi - 1) - f[i]);

        if (space < 0 || space % 2 != 0)
        {
            std::cout << 0 << "\n";
            return;
        }

        ans = mul(ans, catalan(space / 2));
    }

    std::cout << ans << "\n";
}

