ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int dp[2][1 << 8][3];
// dp[cur][mask][top]
// top = 0 -> ô trên không cắm xuống, không nối left
// top = 1 -> ô trên phải cắm xuống
// top = 2 -> ô trên đã là thanh ngang
int m, n;

void solve()
{
    std::cin >> m >> n;
    int cur = 1, nxt = 0;
    dp[cur][0][0] = 1;

    for (int j = 0; j < n; j++)
    {
        for (int i = 0; i < m; i++)
        {
            memset(dp[nxt], 0, sizeof(dp[nxt]));
            for (int mask = 0; mask < (1 << m); mask++)
            {
                for (int top = 0; top < 3; top++)
                {
                    int ways = dp[cur][mask][top];
                    if (!ways)
                    {
                        continue;
                    }

                    bool left = (mask & (1 << i));

                    if (left)
                    {
                        if (top == 1)
                        {
                            continue;
                        }
                        int nmask = mask ^ (1 << i);
                        int ntop = 0;
                        dp[nxt][nmask][ntop] = add(dp[nxt][nmask][ntop], ways);
                        continue;
                    }

                    if (top == 1)
                    {
                        int nmask = mask;
                        int ntop = 0;
                        dp[nxt][nmask][ntop] = add(dp[nxt][nmask][ntop], ways);
                        continue;
                    }

                    // đục lỗ (i, j)
                    int nmask = mask;
                    int ntop = 0;
                    dp[nxt][nmask][ntop] = add(dp[nxt][nmask][ntop], ways);

                    // đặt viên gạch cắm xuống (i + 1, j)
                    if (i + 1 < m)
                    {
                        int nmask = mask;
                        int ntop = 1;
                        dp[nxt][nmask][ntop] = add(dp[nxt][nmask][ntop], ways);
                    }

                    // đặt sang phải (i, j + 1)
                    if (j + 1 < n && top != 2)
                    {
                        int nmask = mask | (1 << i);
                        int ntop = (i + 1 < m) ? 2 : 0;
                        dp[nxt][nmask][ntop] = add(dp[nxt][nmask][ntop], ways);
                    }
                }
            }

            cur ^= 1;
            nxt ^= 1;
        }
    }

    std::cout << dp[cur][0][0];
}

