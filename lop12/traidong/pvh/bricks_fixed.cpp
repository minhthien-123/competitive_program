ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::map<vi, int> states;
int state_id = 0;
std::vector<vi> state;
std::vector<vi> trans;
int dp[2][1 << 8];
int n, m;
// mask_in cấu hình cột trước sang cột hiện tại
// mask_out cấu hình cột hiện tại sang cột tiếp theo

void gen_next_masks(int r, int mask_in, int mask_out, int holes, vi &nxt)
{
    if (r == m)
    {
        nxt.pb({mask_out});
        return;
    }

    // ô hiện tại bị đục lỗ
    if ((holes >> r) & 1)
    {
        if ((mask_in >> r) & 1)
        {
            return;
        }
        gen_next_masks(r + 1, mask_in, mask_out, holes, nxt);
        return;
    }

    // ô hiện tại không bị đục lỗ
    if ((mask_in >> r) & 1)
    {
        gen_next_masks(r + 1, mask_in, mask_out, holes, nxt);
    }
    else
    {
        // đặt gạch ngang
        gen_next_masks(r + 1, mask_in, mask_out | (1 << r), holes, nxt);

        // đặt gạch dọc
        if (r + 1 < m && !((holes >> (r + 1)) & 1) && !((mask_in >> (r + 1)) & 1))
        {
            gen_next_masks(r + 2, mask_in, mask_out, holes, nxt);
        }
    }
}

int idx(vi v)
{
    std::sort(all(v));
    v.erase(std::unique(all(v)), v.end());
    if (!states.count(v))
    {
        states[v] = sz(state);
        state.pb(v);
        trans.pb(vi(1 << m, -1));
    }
    return states[v];
}

void solve()
{
    std::cin >> m >> n;

    idx({0});

    for (int i = 0; i < sz(state); i++)
    {
        vi cur = state[i];

        for (int holes = 0; holes < (1 << m); holes++)
        {
            vi nxt;
            for (int mask_in : cur)
            {
                gen_next_masks(0, mask_in, 0, holes, nxt);
            }

            if (sz(nxt))
            {
                trans[i][holes] = idx(nxt);
            }
        }
    }

    int N = sz(state);
    std::vector<int> dp[2];
    dp[0].assign(N, 0);
    dp[1].assign(N, 0);

    int cur = 0, nxt = 1;
    dp[0][states[{0}]] = 1;

    for (int j = 0; j < n; j++)
    {
        std::fill(all(dp[nxt]), 0);

        for (int u = 0; u < N; u++)
        {
            if (!dp[cur][u])
            {
                continue;
            }

            for (int holes = 0; holes < (1 << m); holes++)
            {
                int v = trans[u][holes];
                if (v != -1)
                {
                    dp[nxt][v] = add(dp[nxt][v], dp[cur][u]);
                }
            }
        }

        cur ^= 1;
        nxt ^= 1;
    }

    ll ans = 0;
    for (int u = 0; u < N; u++)
    {
        bool check = false;
        for (int p : state[u])
        {
            if (p == 0)
            {
                check = true;
                break;
            }
        }
        if (check)
        {
            ans = add(ans, dp[cur][u]);
        }
    }

    std::cout << ans;
}

