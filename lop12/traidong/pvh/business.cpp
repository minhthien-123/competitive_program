ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
int p[maxn + 7];
int dist[maxn + 7];
std::vector<int> adj[maxn + 7];

std::vector<int> bfs(int s)
{
    std::vector<int> d(n + 1, -1);
    std::queue<int> q;
    d[s] = 0;
    q.push(s);
    while (!q.empty())
    {
        int u = q.front();
        q.pop();
        for (int v : adj[u])
        {
            if (d[v] == -1)
            {
                d[v] = d[u] + 1;
                q.push(v);
            }
        }
    }
    return d;
}

bool check(int mid)
{
    int s = -1;
    for (int i = 1; i <= n; i++)
    {
        if (dist[i] > mid)
        {
            s = i;
            break;
        }
    }

    if (s == -1)
    {
        return (k < n);
    }

    auto d = bfs(s);
    int A = s;
    for (int i = 1; i <= n; i++)
    {
        if (dist[i] > mid && d[i] > d[A])
        {
            A = i;
        }
    }

    auto dA = bfs(A);
    int B = A;
    for (int i = 1; i <= n; i++)
    {
        if (dist[i] > mid && dA[i] > dA[B])
        {
            B = i;
        }
    }

    int D = dA[B];
    if (D > 2 * mid)
    {
        return false;
    }

    auto dB = bfs(B);

    for (int c = 1; c <= n; c++)
    {
        if (dist[c] > 0 && dA[c] <= mid && dB[c] <= mid)
        {
            return true;
        }
    }

    return false;
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= k; i++)
    {
        std::cin >> p[i];
    }

    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb(v);
        adj[v].pb(u);
    }

    std::queue<int> qu;
    for (int i = 1; i <= n; i++)
    {
        dist[i] = inf;
    }

    for (int i = 1; i <= k; i++)
    {
        dist[p[i]] = 0;
        qu.push(p[i]);
    }

    while (!qu.empty())
    {
        int u = qu.front();
        qu.pop();

        for (int v : adj[u])
        {
            if (dist[v] > dist[u] + 1)
            {
                dist[v] = dist[u] + 1;
                qu.push(v);
            }
        }
    }

    int l = 0, r = n, res = n;
    while (l <= r)
    {
        int mid = (l + r) / 2;

        if (check(mid))
        {
            res = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    std::cout << res << "\n"; 
}
