void solve()
{
    std::cin >> k;
    while (std::cin >> s)
    {
        for (int i = 0; i < sz(s); i++)
        {
            flag[s[i] - 'a'][i] = 1;
        }
    }

    for (int i = 0; i < sz(s); i++)
    {
        int cnt = 0;
        for (int c = 0; c < k; c++)
        {
            if (!flag[c][i])
            {
                cnt++;
            }
        }
        res *= cnt;
    }
    std::cout << res;
}

