ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ll a[maxn + 7];
int dp[maxn + 7];
int bit[35][maxn + 7];

int get_mask(ll x)
{
    int mask = 0;
    if (x % 2 == 0)
    {
        mask |= (1 << 0);
    }
    if (x % 3 == 0)
    {
        mask |= (1 << 1);
    }
    if (x % 5 == 0)
    {
        mask |= (1 << 2);
    }
    if (x % 7 == 0)
    {
        mask |= (1 << 3);
    }
    if (x % 11 == 0)
    {
        mask |= (1 << 4);
    }
    return mask;
}

void update(int mask, int idx, int val)
{
    for (; idx <= m; idx += idx & -idx)
    {
        bit[mask][idx] = std::max(bit[mask][idx], val);
    }
}

int query(int mask, int idx)
{
    int res = 0;
    for (; idx > 0; idx -= idx & -idx)
    {
        res = std::max(res, bit[mask][idx]);
    }
    return res;
}

void solve()
{
    std::cin >> n;
    std::vector<ll> v;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        v.pb(a[i]);
    }

    std::sort(all(v));
    v.erase(std::unique(all(v)), v.end());
    m = sz(v);

    for (int i = 1; i <= n; i++)
    {
        int pos = std::lower_bound(all(v), a[i]) - v.begin() + 1;
        int mask = get_mask(a[i]);

        int best = 0;
        for (int k = 0; k < 32; k++)
        {
            if ((mask & k) == 0)
            {
                best = std::max(best, query(k, pos - 1));
            }
        }

        update(mask, pos, best + 1);
    }

    int ans = 0;
    for (int i = 0; i < 32; i++)
    {
        ans = std::max(ans, query(i, m));
    }

    std::cout << ans;
}

