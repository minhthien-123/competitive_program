ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int theta;
int n, m;
int tour[maxq + 7], tin[maxq + 7], tout[maxq + 7];
int depth[maxq + 7];
int timer = 0;
std::vector<ii> adj[maxq + 7];

void dfs(int u, int p)
{
    timer++;
    tour[timer] = u;
    tin[u] = timer;
    for (auto [v, w] : adj[u])
    {
        if (v != p)
        {
            depth[v] = depth[u] + w;
            dfs(v, u);
            timer++;
            tour[timer] = u;
        }
    }
    tout[u] = timer;
}

int st[20][maxq];
int lg[maxq];

int getmin(int u, int v)
{
    return depth[u] < depth[v] ? u : v;
}

void build()
{
    for (int i = 1; i <= timer; i++)
    {
        st[0][i] = tour[i];
    }

    for (int j = 1; (1 << j) <= timer; j++)
    {
        for (int i = 1; i + (1 << j) - 1 <= timer; i++)
        {
            st[j][i] = getmin(st[j - 1][i], st[j - 1][i + (1 << (j - 1))]);
        }
    }
}

int getlca(int u, int v)
{
    int l = tin[u];
    int r = tin[v];

    if (l > r)
    {
        std::swap(l, r);
    }

    int k = 31 - __builtin_clz(r - l + 1);
    return getmin(st[k][l], st[k][r - (1 << k) + 1]);
}

int seed;
int getRandom(void)
{
    seed = (1997LL * seed + 227) % 1000003;
    return seed;
}

int answer(int z, int l, int s)
{
    int a = getlca(z, l);
    int b = getlca(l, s);
    int c = getlca(s, z);

    int x = a;
    if (depth[b] > depth[x])
    {
        x = b;
    }
    if (depth[c] > depth[x])
    {
        x = c;
    }
    return x;
}

void solve()
{
    std::cin >> theta >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    dfs(1, 0);
    build();

    ll res = 0;
    int q;
    std::cin >> q >> seed;
    for (int i = 1; i <= q; i++)
    {
        int z = getRandom() % n + 1;
        int l = getRandom() % n + 1;
        int s = getRandom() % n + 1;

        int x;
        if (z == l || l == s || s == z)
        {
            x = 22071997;
        }
        else
        {
            x = answer(z, l, s);
        }

        res = ((1LL * res << 30) ^ x) % 998244353;
    }
    std::cout << res;
}

