ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int m;
ll a[maxn + 7][maxn + 7];
ll dp[maxn + 7][maxn + 7];
int S, T, V;

void solve()
{
    std::cin >> m;

    for (int i = 0; i <= 2 * m + 2; i++)
    {
        for (int j = 0; j <= 2 * m + 2; j++)
        {
            dp[i][j] = -INF;
        }
    }

    for (int i = 1; i <= 1 + 3 * m * (m + 1); i++)
    {
        int x, y, z;
        std::cin >> x >> y >> z;
        std::cin >> a[x + m][y + m];
    }

    std::cin >> S >> T >> V;

    dp[m][0] = a[m][0];

    for (int r = 0; r <= 2 * m; r++)
    {
        for (int q = 0; q <= 2 * m; q++)
        {
            if (r == 0 && q == m)
            {
                continue;
            }

            int Q = q - m;
            int R = r - m;
            if (std::abs(Q) > m || std::abs(R) > m || std::abs(-Q - R) > m)
            {   
                continue;
            }

            ll val1 = (q >= 1) ? dp[q - 1][r] : -INF;
            ll val2 = (q <= 2 * m - 1 && r >= 1) ? dp[q + 1][r - 1] : -INF;
            ll val3 = (r >= 1) ? dp[q][r - 1] : -INF;

            int best = std::max({val1, val2, val3});

            if (best != -INF)
            {
                dp[q][r] = a[q][r] + best;
            }
        }
    }

    std::cout << dp[S + m][T + m];
}

