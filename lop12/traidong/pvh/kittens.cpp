ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;

State swap(const State &a, int c1, int c2, int c3, int n)
{
    State res{};
    int idx = 0;
    for (int i = 0; i < c1; i++)
    {
        res[idx++] = a[i];
    }
    for (int i = c2; i < c3; i++)
    {
        res[idx++] = a[i];
    }
    for (int i = c1; i < c2; i++)
    {
        res[idx++] = a[i];
    }
    for (int i = c3; i < n; i++)
    {
        res[idx++] = a[i];
    }
    return res;
}

void solve()
{
    std::cin >> n;
    State s{}, t{};
    for (int i = 0; i < n; i++)
    {
        int val;
        std::cin >> val;
        s[i] = (int8_t)val;
        t[i] = (int8_t)(i + 1);
    }

    std::map<State, int> dists, distt;
    std::queue<State> q1, q2;

    dists[s] = 0;
    q1.push(s);

    distt[t] = 0;
    q2.push(t);

    while (!q1.empty())
    {
        State u = q1.front();
        q1.pop();
        int d = dists[u];

        if (d == 2)
        {
            continue;
        }

        for (int c1 = 0; c1 <= n; c1++)
        {
            for (int c2 = c1 + 1; c2 <= n; c2++)
            {
                for (int c3 = c2 + 1; c3 <= n; c3++)
                {
                    State v = swap(u, c1, c2, c3, n);
                    if (dists.find(v) == dists.end())
                    {
                        dists[v] = d + 1;
                        q1.push(v);
                    }
                }
            }
        }
    }

    while (!q2.empty())
    {
        State u = q2.front();
        q2.pop();
        int d = distt[u];

        if (d == 2)
        {
            continue;
        }

        for (int c1 = 0; c1 <= n; c1++)
        {
            for (int c2 = c1 + 1; c2 <= n; c2++)
            {
                for (int c3 = c2 + 1; c3 <= n; c3++)
                {
                    State v = swap(u, c1, c2, c3, n);
                    if (distt.find(v) == distt.end())
                    {
                        distt[v] = d + 1;
                        q2.push(v);
                    }
                }
            }
        }
    }

    int ans = 5;
    for (auto it = dists.begin(); it != dists.end(); it++)
    {
        if (distt.find(it->first) != distt.end())
        {
            ans = std::min(ans, it->second + distt[it->first]);
        }
    }

    if (ans <= 4)
    {
        std::cout << ans << "\n";
    }
    else
    {
        std::cout << "5 or more\n";
    }
}

