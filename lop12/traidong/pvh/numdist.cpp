ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int a[maxn + 7];
ll cnt[8][10];

void solve()
{
    std::cin >> n;
    for (int p = 0; p < 8; p++)
    {
        for (int d = 0; d < 10; d++)
        {
            cnt[p][d] = 0;
        }
    }

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        int x = a[i];
        for (int p = 0; p < 8; p++)
        {
            cnt[p][x % 10]++;
            x /= 10;
        }
    }

    ll ans = 0;
    for (int p = 0; p < 8; p++)
    {
        for (int d = 0; d < 9; d++)
        {
            for (int e = d + 1; e < 10; e++)
            {
                ll pairs = mul(cnt[p][d], cnt[p][e]);
                ans = mul(ans, pairs);
            }
        }
    }

    std::cout << ans;
}

