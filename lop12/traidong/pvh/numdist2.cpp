const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 998244353;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y) { return (x + y + 2 * mod) % mod; }
ll sub(ll x, ll y) { return (x - y + 2 * mod) % mod; }
ll mul(ll x, ll y) { return (x % mod * (y % mod)) % mod; }
ll power(ll x, ll y)
{
    ll res = 1;
    x %= mod;
    while (y > 0)
    {
        if (y & 1)
            res = (res * x) % mod;
        x = (x * x) % mod;
        y >>= 1;
    }
    return res;
}

int n;
int a[maxn + 7];
ll g[256];
int dig[maxn + 7][8];
int freq[10000000];
int pat[maxn + 7]; 

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        int tmp = a[i];
        for (int j = 0; j < 8; j++)
        {
            dig[i][j] = tmp % 10;
            tmp /= 10;
        }
    }

    for (int mask = 0; mask < 256; mask++)
    {
        int cnt = 0;
        ll pairs = 0;

        for (int i = 1; i <= n; i++)
        {
            int val = 0;
            for (int j = 7; j >= 0; j--)
            {
                if ((mask >> j) & 1)
                {
                    val = val * 10 + dig[i][j];
                }
            }

            if (freq[val] == 0)
            {
                pat[++cnt] = val;
            }
            freq[val]++;
        }

        for (int i = 1; i <= cnt; i++)
        {
            int v = pat[i];
            int count = freq[v];
            pairs += 1LL * count * (count - 1) / 2;
            freq[v] = 0;
        }

        g[mask] = pairs;
    }

    for (int i = 0; i < 8; i++)
    {
        for (int mask = 255; mask >= 0; mask--)
        {
            if ((mask & (1 << i)) == 0)
            {
                g[mask] -= g[mask | (1 << i)];
            }
        }
    }

    ll ans = 1;
    for (int mask = 0; mask < 256; mask++)
    {
        ll cnt = g[mask];
        if (cnt)
        {
            int dist = 8 - __builtin_popcount(mask);
            ans = mul(ans, power(dist, cnt));
        }
    }

    std::cout << ans;
}

