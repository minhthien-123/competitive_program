ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
ii adj[maxn + 7];
std::vector<int> adj1[maxn + 7], adj2[maxn + 7];
int vis1[maxn + 7], vis2[maxn + 7];
int step = 0;
int cnt1, cnt2;

struct Edge
{
    int u, v;
    ll w;
    friend bool operator<(Edge a, Edge b)
    {
        return a.w < b.w;
    }
} edges[5004];

void dfs1(int u)
{
    vis1[u] = step;
    cnt1++;
    for (int v : adj1[u])
    {
        if (vis1[v] != step)
        {
            dfs1(v);
        }
    }
}

void dfs2(int u)
{
    vis2[u] = step;
    cnt2++;
    for (int v : adj2[u])
    {
        if (vis2[v] != step)
        {
            dfs2(v);
        }
    }
}

bool check(int L, int R)
{
    for (int i = 1; i <= n; i++)
    {
        adj1[i].clear();
        adj2[i].clear();
    }

    for (int i = L; i < R; i++)
    {
        int u = edges[i].u;
        int v = edges[i].v;
        adj1[u].pb(v);
        adj2[v].pb(u);
    }

    step++;
    cnt1 = 0;
    dfs1(1);
    if (cnt1 < n)
    {
        return false;
    }

    cnt2 = 0;
    dfs2(1);
    return cnt2 == n;
}

void solve()
{
    std::cin >> n >> m;

    if (n == 1)
    {
        std::cout << 0 << "\n";
        return;
    }

    for (int i = 1; i <= m; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        edges[i] = {u, v, w};
    }

    std::sort(edges + 1, edges + m + 1);

    int L = 1, R = 1;
    ll ans = INF;

    while (L <= m)
    {
        while (R <= m + 1 && !check(L, R))
        {
            R++;
        }

        if (R > m + 1)
        {
            break;
        }

        ll diff = edges[R - 1].w - edges[L].w;
        ans = std::min(ans, diff);
        L++;
    }

    std::cout << (ans == INF ? -1 : ans);
}

