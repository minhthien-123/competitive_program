ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, k;
int x[maxn + 7], y[maxn + 7], s[maxn + 7];
int u[maxn + 7], v[maxn + 7];
bool vis[maxn + 7];

bool check1(db k)
{
    db maxL = -INF, minR = INF;
    db maxT = -INF, minB = INF;

    for (int i = 1; i <= n; i++)
    {
        maxL = std::max(maxL, u[i] - s[i] * k);
        minR = std::min(minR, u[i] + s[i] * k);

        maxT = std::max(maxT, v[i] - s[i] * k);
        minB = std::min(minB, v[i] + s[i] * k);
    }

    return (maxL <= minR) && (maxT <= minB);
}

bool check2(db k)
{
    db minR = INF, maxL = -INF, minT = INF, maxB = -INF;
    bool check = true;

    for (int i = 1; i <= n; i++)
    {
        if (!vis[i])
        {
            check = false;
            minR = std::min(minR, u[i] + s[i] * k);
            minT = std::min(minT, v[i] + s[i] * k);
            maxL = std::max(maxL, u[i] - s[i] * k);
            maxB = std::max(maxB, v[i] - s[i] * k);
        }
    }
    if (check)
    {
        return 1;
    }

    bool ok1 = true;
    for (int i = 1; i <= n; i++)
    {
        if (!vis[i])
        {
            bool cover1 = (maxL >= u[i] - s[i] * k && maxL <= u[i] + s[i] * k && maxB >= v[i] - s[i] * k && maxB <= v[i] + s[i] * k);
            bool cover2 = (minR >= u[i] - s[i] * k && minR <= u[i] + s[i] * k && minT >= v[i] - s[i] * k && minT <= v[i] + s[i] * k);
            if (!cover1 && !cover2)
            {
                ok1 = false;
                break;
            }
        }
    }
    if (ok1)
    {
        return 1;
    }

    bool ok2 = true;
    for (int i = 1; i <= n; i++)
    {
        if (!vis[i])
        {
            bool cover1 = (maxL >= u[i] - s[i] * k && maxL <= u[i] + s[i] * k && minT >= v[i] - s[i] * k && minT <= v[i] + s[i] * k);
            bool cover2 = (minR >= u[i] - s[i] * k && minR <= u[i] + s[i] * k && maxB >= v[i] - s[i] * k && maxB <= v[i] + s[i] * k);
            if (!cover1 && !cover2)
            {
                ok2 = false;
                break;
            }
        }
    }
    return ok2;
}

bool check3(db k)
{
    db minR = INF, maxL = -INF, minT = INF, maxB = -INF;
    for (int i = 1; i <= n; i++)
    {
        minR = std::min(minR, u[i] + s[i] * k);
        minT = std::min(minT, v[i] + s[i] * k);
        maxL = std::max(maxL, u[i] - s[i] * k);
        maxB = std::max(maxB, v[i] - s[i] * k);
    }

    db posu[4] = {maxL, maxL, minR, minR};
    db posv[4] = {maxB, minT, maxB, minT};

    for (int p = 0; p < 4; p++)
    {
        for (int i = 1; i <= n; i++)
        {
            if (posu[p] >= u[i] - s[i] * k && posu[p] <= u[i] + s[i] * k && posv[p] >= v[i] - s[i] * k && posv[p] <= v[i] + s[i] * k)
            {
                vis[i] = 1;
            }
            else
            {
                vis[i] = 0;
            }
        }
        if (check2(k))
        {
            return 1;
        }
    }
    return 0;
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> x[i] >> y[i] >> s[i];
    }
    for (int i = 1; i <= n; i++)
    {
        u[i] = (db)(x[i] - y[i]);
        v[i] = (db)(x[i] + y[i]);
    }

    if (k == 1)
    {
        db l = 0, r = 1e8, ans = -1;
        for (int step = 0; step < 45; step++)
        {
            db mid = (l + r) / 2;
            if (check1(mid))
            {
                ans = mid;
                r = mid;
            }
            else
            {
                l = mid;
            }
        }

        std::cout << std::fixed << std::setprecision(6) << ans;
    }

    if (k == 2)
    {
        db l = 0, r = 1e8, ans = -1;
        for (int step = 0; step < 45; step++)
        {
            db mid = (l + r) / 2;
            if (check2(mid))
            {
                ans = mid;
                r = mid;
            }
            else
            {
                l = mid;
            }
        }

        std::cout << std::fixed << std::setprecision(6) << ans;
    }

    if (k == 3)
    {
        db l = 0, r = 1e8, ans = -1;
        for (int step = 0; step < 45; step++)
        {
            db mid = (l + r) / 2;
            if (check3(mid))
            {
                ans = mid;
                r = mid;
            }
            else
            {
                l = mid;
            }
        }

        std::cout << std::fixed << std::setprecision(6) << ans;
    }
}

