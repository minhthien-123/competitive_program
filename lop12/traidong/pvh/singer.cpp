ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {               
        return tmp * tmp % mod * x % mod;
    }
}

int n, d, t;
int dp[maxn + 7][maxn + 7];
int pre[maxn + 7], diag[maxn + 7];

void solve()
{
    std::cin >> n >> d >> t;

    int k = d - 2;

    memset(dp, 0, sizeof dp);
    dp[0][0] = 1;

    for (int i = 1; i <= n; i++)
    {
        for (int cnt = 0; cnt <= t; cnt++)
        {
            pre[cnt] = add(pre[cnt], dp[i - 1][cnt]);
            if (i - k - 1 >= 0)
            {
                pre[cnt] = sub(pre[cnt], dp[i - k - 1][cnt]);
            }
        }
        
        for (int cnt = t; cnt >= 1; cnt--)
        {
            if (i - k - 1 >= 0)
            {
                diag[cnt] = add(diag[cnt - 1], dp[i - k - 1][cnt - 1]);
            }
            else
            {
                diag[cnt] = 0;
            }
        }
        diag[0] = 0;

        for (int cnt = 0; cnt <= t; cnt++)
        {
            dp[i][cnt] = add(pre[cnt], diag[cnt]);
        }
    }

    ll ans = mul(dp[n][t], 2);
    std::cout << ans;
}

