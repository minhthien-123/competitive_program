ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int a[maxn + 7];
int c[maxn + 7], rank[maxn + 7], pos[maxn + 8];
ii arr[maxn + 7];
int x[maxn + 7];

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 7, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size() - 1)
    {
        for (int i = 1; i <= n; i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r > 0; r -= r & -r)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
        {
            return 0;
        }
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx <= n; idx += idx & -idx)
        {
            bit[idx] += delta;
        }
    }
    void add_range(int l, int r, int delta)
    {
        add(l, delta);
        add(r + 1, -delta);
    }
};

void solve()
{
    std::cin >> n;
    FenwickTree bitc(n), bitx(n);
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        arr[i] = {a[i], i};
    }

    std::sort(arr + 1, arr + n + 1);
    for (int i = 1; i <= n; i++)
    {
        rank[arr[i].se] = i;
        pos[i] = arr[i].se;
    }

    for (int i = 1; i < n; i++)
    {
        std::cin >> c[i];
        bitc.add(i, c[i]);
    }

    ll cost = 0;
    for (int i = 1; i < n; i++)
    {
        x[i] = x[i - 1] + (rank[i] > i) - (pos[i] < i);
        bitx.add(i, x[i] - x[i - 1]);
        cost += 2LL * x[i] * c[i];
    }

    int q;
    std::cin >> q;
    std::cout << cost << "\n";

    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 2)
        {
            int i, v;
            std::cin >> i >> v;

            int xp = bitx.sum(i);

            cost += 2LL * xp * (v - c[i]);
            bitc.add(i, v - c[i]);
            c[i] = v;

            std::cout << cost << "\n";
        }
        else
        {
            int x, y;
            std::cin >> x >> y;

            if (x == y)
            {
                std::cout << cost << "\n";
                continue;
            }
            if (x > y)
            {
                std::swap(x, y);
            }

            int u = rank[x];
            int v = rank[y];

            if (u < v)
            {
                int L = std::max(x, u);
                int R = std::min(y - 1, v - 1);
                if (L <= R)
                {
                    cost += 2LL * bitc.sum(L, R);
                    bitx.add_range(L, R, 1);
                }
            }
            else if (u > v)
            {
                int L = std::max(x, v);
                int R = std::min(y - 1, u - 1);
                if (L <= R)
                {
                    cost -= 2LL * bitc.sum(L, R);
                    bitx.add_range(L, R, -1);
                }
            }

            std::swap(rank[x], rank[y]);

            std::cout << cost << "\n";
        }
    }
}

