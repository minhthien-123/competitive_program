ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash() {}

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};

int n, k;
std::string s[55];
std::vector<StringHash> S;
int best_id = -1, best_pos = -1, best_len = 0;

bool check(int mid)
{
    std::unordered_map<ll, ll> mp;
    mp.reserve(maxn * 2);

    for (int i = 0; i < n; i++)
    {
        int len = sz(s[i]);
        if (len < mid)
        {
            continue;
        }
        for (int j = 0; j <= len - mid; j++)
        {
            pll cur = S[i].get_hash(j + 1, j + mid);
            ll key = ((ll)cur.fi << 32) | (ll)cur.se;
            mp[key] |= (1ULL << i);
        }
    }

    for (int i = 0; i < n; i++)
    {
        int len = sz(s[i]);
        if (len < mid)
        {
            continue;
        }
        for (int j = 0; j <= len - mid; j++)
        {
            pll cur = S[i].get_hash(j + 1, j + mid);
            ll key = ((ll)cur.fi << 32) | (ll)cur.se;
            if (__builtin_popcountll(mp[key]) >= k)
            {
                best_id = i;
                best_pos = j;
                best_len = mid;
                return true;
            }
        }
    }

    return false;
}

void solve()
{
    std::cin >> n >> k;
    int mx = 0;
    for (int i = 0; i < n; i++)
    {
        std::cin >> s[i];
        mx = std::max(mx, sz(s[i]));
        S.push_back(s[i]);
    }

    int l = 1, r = mx;
    while (l <= r)
    {
        int mid = (l + r) / 2;
        if (check(mid))
        {
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    if (best_id != -1 && best_len > 0)
    {
        std::cout << s[best_id].substr(best_pos, best_len);
    }
}

