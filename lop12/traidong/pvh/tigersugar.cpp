ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
ll X1[maxn + 7], X2[maxn + 7];
ll Y1[maxn + 7], Y2[maxn + 7];
ii path[maxn + 7];

void solve()
{
    std::cin >> n;

    std::vector<ll> X, Y;
    for (int i = 0; i < n; i++)
    {
        ll x1, y1, x2, y2;
        std::cin >> x1 >> y1 >> x2 >> y2;

        X1[i] = std::min(x1, x2);
        X2[i] = std::max(x1, x2);
        Y1[i] = std::min(y1, y2);
        Y2[i] = std::max(y1, y2);

        X.pb(X1[i]);
        X.pb(X2[i]);

        Y.pb(Y1[i]);
        Y.pb(Y2[i]);
    }

    std::sort(X.begin(), X.end());
    std::sort(Y.begin(), Y.end());

    ll optx = X[n - 1];
    ll opty = Y[n - 1];

    ll ans = 0;
    for (int i = 0; i < n; i++)
    {
        if (optx < X1[i])
        {
            ans += X1[i] - optx;
            path[i].fi = X1[i];
        }
        else if (optx > X2[i])
        {
            ans += optx - X2[i];
            path[i].fi = X2[i];
        }
        else
        {
            path[i].fi = optx;
        }

        if (opty < Y1[i])
        {
            ans += Y1[i] - opty;
            path[i].se = Y1[i];
        }
        else if (opty > Y2[i])
        {
            ans += opty - Y2[i];
            path[i].se = Y2[i];
        }
        else
        {
            path[i].se = opty;
        }
    }

    std::cout << ans << "\n";
    std::cout << optx << " " << opty << "\n";
    for (int i = 0; i < n; i++)
    {
        std::cout << path[i].fi << " " << path[i].se << "\n";
    }
}

