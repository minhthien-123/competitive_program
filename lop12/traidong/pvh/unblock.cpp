ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
int a[maxn + 7][maxn + 7];
char c[maxn + 7][maxn + 7];
bool vis[maxn + 7][maxn + 7];
ll dp[maxn + 7][maxn + 7];
std::vector<ii> adj[maxn * maxn + 7];

int idx(int i, int j)
{
    return (i - 1) * m + j;
}

ll dfs(int r, int c, int pr, int pc)
{
    ll sum = 0;

    for (auto [nr, nc] : adj[idx(r, c)])
    {
        if (nr == pr && nc == pc)
        {
            continue;
        }

        ll child = dfs(nr, nc, r, c);
        if (child > 0)
        {
            sum += child;
        }
    }

    return dp[r][c] = a[r][c] + sum;
}
void solve()
{
    std::cin >> n >> m;
    int si, sj;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> c[i][j];
            if (c[i][j] == 'O')
            {
                si = i;
                sj = j;
            }
        }
    }
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
        }
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            // OH. -> H.O
            // j-1      j+1
            // H.O -> OH.
            // j+2    j

            if (c[i][j] == 'H')
            {
                if (j - 1 >= 1)
                {
                    int u = idx(i, j - 1);
                    int v = idx(i, j + 1);
                    adj[u].pb({i, j + 1});
                    adj[v].pb({i, j - 1});
                }
                if (j + 2 <= m)
                {
                    int u = idx(i, j);
                    int v = idx(i, j + 2);
                    adj[u].pb({i, j + 2});
                    adj[v].pb({i, j});
                }
            }
            else if (c[i][j] == 'V')
            {
                if (i - 1 >= 1)
                {
                    int u = idx(i - 1, j);
                    int v = idx(i + 1, j);
                    adj[u].pb({i + 1, j});
                    adj[v].pb({i - 1, j});
                }
                if (i + 2 <= n)
                {
                    int u = idx(i, j);
                    int v = idx(i + 2, j);
                    adj[u].pb({i + 2, j});
                    adj[v].pb({i, j});
                }
            }
        }
    }

    ll ans = dfs(si, sj, -1, -1);

    std::cout << ans;
}

