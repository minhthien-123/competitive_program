int32_t p[maxn + 7];
int32_t pre[maxn + 7];
int32_t rate[maxn + 7];
int32_t q[maxn + 8];
int32_t a[maxn + 7], b[maxn + 7];

std::pair<ll, ll> get_hashz(int l, int r)
{
    long long hash1 = (h1z[r] - h1z[l - 1] * p1z[r - l + 1] % MOD1 + MOD1) % MOD1;
    long long hash2 = (h2z[r] - h2z[l - 1] * p2z[r - l + 1] % MOD2 + MOD2) % MOD2;
    return {hash1, hash2};
}

std::pair<long long, long long> get_hash(int l, int r)
{
    long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
    long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
    return {hash1, hash2};
}

bool check(int n, int m)
{
    int base_block = -1;
    int non_zero_j = -1;

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (p[(i - 1) * n + j] != 0)
            {
                base_block = i;
                non_zero_j = j;
                break;
            }
        }
        if (base_block != -1)
        {
            break;
        }
    }

    if (base_block == -1)
    {
        std::cout << "YES\n";
        std::cout << m << " ";
        for (int i = 1; i <= m; i++)
        {
            std::cout << 0 << " ";
        }
        std::cout << "\n";
        std::cout << n << " ";
        for (int j = 1; j <= n; j++)
        {
            std::cout << 0 << " ";
        }
        std::cout << "\n";
        return true;
    }

    for (int j = 1; j <= n; j++)
    {
        b[j] = p[(base_block - 1) * n + j];
    }

    ll inv_b = power(b[non_zero_j], MOD - 2);
    for (int i = 1; i <= m; i++)
    {
        a[i] = p[(i - 1) * n + non_zero_j] * inv_b % MOD;
    }

    for (int i = 1; i <= m; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            int idx = (i - 1) * n + j;
            if (p[idx] != 1LL * a[i] * b[j] % MOD)
            {
                return false;
            }
        }
    }

    std::cout << "YES\n";
    std::cout << m << " ";
    for (int i = 1; i <= m; i++)
    {
        std::cout << a[i] << " ";
    }
    std::cout << "\n";
    std::cout << n << " ";
    for (int j = 1; j <= n; j++)
    {
        std::cout << b[j] << " ";
    }
    std::cout << "\n";

    return true;
}

void solve()
{
    std::cin >> k >> MOD;
    p1z[0] = 1;
    p2z[0] = 1;
    p1[0] = 1;
    p2[0] = 1;

    for (int i = 1; i <= k; i++)
    {
        std::cin >> p[i];
    }

    int q_id = 0;
    for (int i = 1; i <= k; i++)
    {
        p1z[i] = (p1z[i - 1] * BASE1) % MOD1;
        p2z[i] = (p2z[i - 1] * BASE2) % MOD2;

        h1z[i] = (h1z[i - 1] * BASE1 + (p[i] == 0)) % MOD1;
        h2z[i] = (h2z[i - 1] * BASE2 + (p[i] == 0)) % MOD2;

        pre[i] = pre[i - 1] + (p[i] != 0);

        if (p[i] != 0)
        {
            q[++q_id] = p[i];
        }
    }

    h1[0] = 1;
    h2[0] = 1;
    for (int i = 1; i < q_id; i++)
    {
        rate[i] = 1LL * q[i + 1] * power(q[i], MOD - 2) % MOD;

        p1[i] = (p1[i - 1] * BASE1) % MOD1;
        p2[i] = (p2[i - 1] * BASE2) % MOD2;

        h1[i] = (h1[i - 1] * BASE1 + rate[i]) % MOD1;
        h2[i] = (h2[i - 1] * BASE2 + rate[i]) % MOD2;
    }

    for (int n = 2; n <= k / 2; n++)
    {
        if (k % n != 0)
        {
            continue;
        }

        int m = k / n;

        int base = -1;
        std::pair<ll, ll> basez, baser;

        bool ok = true;
        for (int r = 0; r < m; r++)
        {
            int s = r * n + 1;
            int t = r * n + n;
            int non = pre[t] - pre[s - 1];

            if (non == 0)
            {
                continue;
            }

            auto hashz = get_hashz(s, t);

            std::pair<ll, ll> hashr = {0, 0};
            if (non >= 2)
            {
                int sq = pre[s - 1] + 1;
                hashr = get_hash(sq, sq + non - 2);
            }

            if (base == -1)
            {
                base = r;
                basez = hashz;
                baser = hashr;
            }
            else
            {
                if (hashz != basez)
                {
                    ok = false;
                    break;
                }
                if (non >= 2 && hashr != baser)
                {
                    ok = false;
                    break;
                }
            }
        }

        if (ok)
        {
            if (check(n, m))
            {
                return;
            }
        }
    }

    std::cout << "NO\n";
}

