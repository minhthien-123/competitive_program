int match(char c1, char c2)
{
    if (c1 == '?' && c2 == '?')
    {
        return 3;
    }
    if (c1 == '?')
    {
        if (c2 == ')' || c2 == ']' || c2 == '}')
        {
            return 1;
        }
        return 0;
    }
    if (c2 == '?')
    {
        if (c1 == '(' || c1 == '[' || c1 == '{')
        {
            return 1;
        }
        return 0;
    }
    if (c1 == '(' && c2 == ')')
    {
        return 1;
    }
    if (c1 == '[' && c2 == ']')
    {
        return 1;
    }
    if (c1 == '{' && c2 == '}')
    {
        return 1;
    }
    return 0;
}

int calc(int l, int r, int k)
{
    if (k < 0)
    {
        return 0;
    }
    if (l > r)
    {
        return 1;
    }
    if (vis[l][r][k])
    {
        return dp[l][r][k];
    }

    vis[l][r][k] = true;

    ll res = 0;
    for (int m = l + 1; m <= r; m += 2)
    {
        int dem = match(s[l], s[m]);
        if (dem > 0)
        {
            res += calc(l + 1, m - 1, k - 1) * calc(m + 1, r, k) * dem;
        }
    }

    return dp[l][r][k] = res;
}

void solve()
{
    int n, k;
    std::cin >> n >> k;
    if ((n & 1) || (k > n / 2))
    {
        std::cout << 0;
        return;
    }
    std::cin >> s;

    std::cout << calc(0, n - 1, k) - calc(0, n - 1, k - 1);
}

