ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, root;
int U[maxn + 7], V[maxn + 7];
int S;
int in[maxn + 7];
int depth[maxn + 7], color[maxn + 7];
bool flag[maxn + 7];

int dfs(int u)
{
    if (depth[u] != 0)
    {
        return depth[u];
    }

    int mx = 0;
    for (int v : adj[u])
    {
        mx = std::max(mx, dfs(v));
    }

    return depth[u] = mx + 1;
}
void solve()
{
    std::cin >> n >> S;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> U[i] >> V[i];
        adj[V[i]].pb(U[i]);
    }

    int cur = 1;
    int count = 1;
    while (thiendeptrai)
    {
        if (count > n)
        {
            break;
        }
        std::vector<int> vec;

        for (int v = 0; v < n; v++)
        {
            if (!flag[v])
            {
                bool ok = true;

                for (int u : adj[v])
                {
                    if (!flag[u])
                    {
                        ok = false;
                        break;
                    }
                }

                if (ok)
                {
                    vec.pb(v);
                }
            }
        }

        int cnt = 0;
        for (int i : vec)
        {
            if (cnt >= S)
            {
                break;
            }
            color[i] = cur;
            cnt++;
            flag[i] = true;
            count++;
        }

        cur++;
    }

    std::vector<int> res;
    for (int i = 1; i <= n; i++)
    {
        res.pb(color[i]);
    }
}

