ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
ll a[maxn + 7];
ll d[27][maxn + 7];
ll st[maxn + 7][20];

struct gcdseq
{
    int l, r;
    ll c;
} query[maxn + 7];

ll lcm(ll a, ll b)
{
    return a / std::__gcd(a, b) * b;
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        int l, r, c;
        std::cin >> l >> r >> c;
        query[i] = {l, r, c};
        d[c][l]++;
        d[c][r + 1]--;
    }

    for (int i = 1; i <= 20; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            d[i][j] += d[i][j - 1];
        }
    }

    for (int i = 1; i <= n; i++)
    {
        ll cur = 1;
        for (int v = 1; v <= 20; v++)
        {
            if (d[v][i] > 0)
            {
                cur = lcm(cur, v);
            }
        }
        a[i] = cur;
        st[i][0] = a[i];
    }

    for (int j = 1; (1 << j) <= n; j++)
    {
        for (int i = 1; i + (1 << j) - 1 <= n; i++)
        {
            st[i][j] = std::__gcd(st[i][j - 1], st[i + (1 << (j - 1))][j - 1]);
        }
    }

    for (int i = 1; i <= m; i++)
    {
        auto [l, r, c] = query[i];
        int k = std::__lg(r - l + 1);
        int tmp = std::__gcd(st[l][k], st[r - (1 << k) + 1][k]);

        if (tmp != c)
        {
            std::cout << -1;
            return;
        }
    }

    for (int i = 1; i <= n; i++)
    {
        std::cout << a[i] << " ";
    }
}

