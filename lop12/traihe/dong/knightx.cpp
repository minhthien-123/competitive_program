ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::mt19937_64 rd(std::chrono::steady_clock::now().time_since_epoch().count());

int Rand(int l, int r)
{
    if (l > r)
    {
        std::swap(l, r);
    }
    std::uniform_int_distribution<int> dist(l, r);
    return dist(rd);
}

std::vector<int> adj[maxn + 7];
int n, k;
int a[maxn + 7][maxn + 7];
bool vis[maxn + 7][maxn + 7];
ii tour[10005];
bool found = false;
int sx, sy;

int get(int x, int y)
{
    int count = 0;
    for (int i = 0; i < 8; i++)
    {
        int nx = x + kx[i];
        int ny = y + ky[i];
        if (nx >= 1 && nx <= n && ny >= 1 && ny <= n && !vis[nx][ny])
        {
            count++;
        }
    }
    return count;
}

bool dfs(int x, int y, int step)
{
    if (found == true)
    {
        return true;
    }
    tour[step] = {x, y};
    vis[x][y] = true;
    if (step == n * n)
    {
        found = true;
        return true;
    }

    std::vector<ii> nxt;
    for (int i = 0; i < 8; i++)
    {
        int nx = x + kx[i];
        int ny = y + ky[i];
        if (nx >= 1 && nx <= n && ny >= 1 && ny <= n && !vis[nx][ny])
        {
            nxt.pb({get(nx, ny), i});
        }
    }

    std::sort(all(nxt));

    for (auto p : nxt)
    {
        int d = p.se;
        int nx = x + kx[d];
        int ny = y + ky[d];
        if (dfs(nx, ny, step + 1))
        {
            return true;
        }
    }

    return false;
}

