void solve()
{
    std::cin >> n >> k;

    while (!found)
    {
        memset(vis, 0, sizeof vis);

        sx = Rand(1, n);
        sy = Rand(1, n);

        dfs(sx, sy, 1);
    }

    int cur = 1;
    int s = (n * n) / k;
    int rem = (n * n) % k;
    int need = s + (rem > 0);
    if (rem > 0)
    {
        rem--;
    }

    int cnt = 0;
    for (int i = 1; i <= n * n; i++)
    {
        auto [x, y] = tour[i];
        a[x][y] = cur;
        cnt++;

        if (cnt == need)
        {
            cur++;
            cnt = 0;
            need = s + (rem > 0);
            if (rem > 0)
            {
                rem--;
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cout << a[i][j] << " ";
        }
        std::cout << "\n";
    }
}

