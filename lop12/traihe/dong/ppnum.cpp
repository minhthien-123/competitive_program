bool isprime[30];

void sieve()
{
    memset(isprime, true, sizeof(isprime));
    isprime[0] = isprime[1] = false;
    for (int i = 2; i * i <= 25; ++i)
    {
        if (isprime[i])
        {
            for (int j = i * i; j <= 25; j += i)
            {
                isprime[j] = false;
            }
        }
    }
}

ll f(int pos, bool flagL, bool flagR)
{
    int len = n - pos - 1;
    if (pos > len)
    {
        if (flagL)
        {
            return 1;
        }
        return flagR;
    }

    ll &memo = dp[pos][flagL][flagR];
    if (memo != -1 && flagL)
    {
        return memo;
    }

    int lim = flagL ? 9 : digit[pos];
    int start = (pos == 0) ? 1 : 0;
    ll res = 0;

    if (pos == len)
    {
        for (int d = start; d <= lim; d++)
        {
            if (isprime[d + d])
            {
                bool nxt_flagL = flagL || (d < lim);
                bool nxt_flagR;
                if (d < digit[len])
                {
                    nxt_flagR = true;
                }
                else if (d > digit[len])
                {
                    nxt_flagR = false;
                }
                else
                {
                    nxt_flagR = flagR;
                }
                res += f(pos + 1, nxt_flagL, nxt_flagR);
            }
        }
    }
    else
    {
        for (int dl = start; dl <= lim; dl++)
        {
            for (int dr = 0; dr <= 9; dr++)
            {
                if (isprime[dl + dr])
                {
                    bool nxt_flagL = flagL || (dl < lim);
                    bool nxt_flagR;
                    if (dr < digit[len])
                    {
                        nxt_flagR = true;
                    }
                    else if (dr > digit[len])
                    {
                        nxt_flagR = false;
                    }
                    else
                    {
                        nxt_flagR = flagR;
                    }
                    res += f(pos + 1, nxt_flagL, nxt_flagR);
                }
            }
        }
    }

    if (flagL)
    {
        memo = res;
    }

    return res;
}

ll g(ll k)
{
    if (k <= 0)
    {
        return 0;
    }

    std::vector<int> tmp;
    ll temp = k;
    while (temp > 0)
    {
        tmp.pb(temp % 10);
        temp /= 10;
    }
    int len = sz(tmp);
    std::reverse(all(tmp));

    ll ans = 0;
    for (int i = 1; i < len; i++)
    {
        n = i;
        for (int j = 0; j < i; j++)
        {
            digit[j] = 9;
        }
        memset(dp, -1, sizeof(dp));
        ans += f(0, 0, 1);
    }

    n = len;
    for (int j = 0; j < n; j++)
    {
        digit[j] = tmp[j];
    }
    memset(dp, -1, sizeof(dp));
    ans += f(0, 0, 1);

    return ans;
}

void solve()
{
    sieve();
    std::cin >> a >> b;
    std::cout << g(b) - g(a - 1) << "\n";
}

