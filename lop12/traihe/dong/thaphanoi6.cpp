ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
ll dp[maxn + 7], res[maxn + 7];

void init(int n)
{
    dp[0] = 0;
    dp[1] = 1;
    res[1] = 0;
    for (int i = 2; i <= n; i++)
    {
        dp[i] = INF;
        for (int k = 1; k < i; k++)
        {
            if (i - k > 60)
            {
                continue;
            }

            ll cost3 = (1LL << (i - k)) - 1;
            if (dp[k] != INF && 2 * dp[k] + cost3 < dp[i])
            {
                dp[i] = 2 * dp[k] + cost3;
                res[i] = k;
            }
        }
    }
}

void hanoi3(int n, char A, char B, char C)
{
    if (n == 0)
    {
        return;
    }

    if (n == 1)
    {
        std::cout << A << B << "\n";
        return;
    }
    hanoi3(n - 1, A, C, B);
    std::cout << A << B << "\n";
    hanoi3(n - 1, C, B, A);
}

void hanoi4(int n, char A, char D, char B, char C)
{
    if (n == 0)
    {
        return;
    }
    if (n == 1)
    {
        std::cout << A << D << "\n";
        return;
    }
    int k = res[n];
    hanoi4(k, A, B, C, D);
    hanoi3(n - k, A, D, C);
    hanoi4(k, B, D, A, C);
}

void solve()
{
    std::cin >> n;
    init(n);
    std::cout << dp[n] << "\n";
    hanoi4(n, 'A', 'D', 'B', 'C');
}

