int n;
ll s;
ll w[maxn], v[maxn];
ll dp[500005];

void solve()
{
    std::cin >> n >> s;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> w[i];
    }

    int id = 1;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> v[i];
        if (v[i] * w[id] > v[id] * w[i])
        {
            id = i;
        }
        else if (v[i] * w[id] == v[id] * w[i])
        {
            if (w[i] < w[id])
            {
                id = i;
            }
        }
    }

    ll ans = 0;
    ll limit = 300000;

    if (s > limit)
    {
        ll cnt = (s - limit) / w[id];
        ans += cnt * v[id];
        s -= cnt * w[id];
    }

    for (int i = 0; i <= s; i++)
    {
        dp[i] = 0;
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = w[i]; j <= s; j++)
        {
            ll val = dp[j - w[i]] + v[i];
            if (val > dp[j])
            {
                dp[j] = val;
            }
        }
    }

    std::cout << ans + dp[s] << "\n";
}

