ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
char c[maxn + 7][maxn + 7];
int id1[maxn + 7][maxn + 7], id2[maxn + 7][maxn + 7];
bool vis[maxn + 7][maxn + 8];
std::set<ii> edges;

bool valid(int x, int y)
{
    return x >= 1 && x <= n && y >= 1 && y <= n;
}

void bfs(int sx, int sy, int a[][maxn + 7])
{
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            vis[i][j] = false;
        }
    }
    edges.clear();

    std::queue<ii> qu;
    vis[sx][sy] = true;
    qu.push({sx, sy});

    while (qu.size())
    {
        auto [x, y] = qu.front();
        qu.pop();

        for (int d = 0; d < 4; d++)
        {
            int nx = x + dx[d];
            int ny = y + dy[d];

            if (!valid(nx, ny) || vis[nx][ny] || c[nx][ny] != '#')
            {
                continue;
            }

            if (a[x][y] != a[nx][ny])
            {
                edges.ins({a[x][y], a[nx][ny]});
            }
            vis[nx][ny] = true;
            qu.push({nx, ny});
        }
    }
}

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> adj, up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= lg; ++i)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
            std::swap(u, v);
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; ++i)
        {
            if ((k >> i) & 1)
                u = up[u][i];
        }
        if (u == v)
            return u;
        for (int i = lg; i >= 0; --i)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int dist(int u, int v)
    {
        int l = get_lca(u, v);
        return depth[u] + depth[v] - 2 * depth[l];
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            std::cin >> c[i][j];
        }
    }

    ii root1, root2;
    int id = 0;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= n; j++)
        {
            if (c[i][j] == '#')
            {
                if (c[i][j - 1] != '#')
                {
                    id1[i][j] = ++id;
                }
                else
                {
                    id1[i][j] = id1[i][j - 1];
                }
            }
        }
    }

    LCA lca1(id);
    for (int i = 1; i < n; i++)
    {
        int last_u = 0, last_v = 0;
        for (int j = 1; j <= n; j++)
        {
            if (c[i][j] == '#' && c[i + 1][j] == '#')
            {
                int u = id1[i][j];
                int v = id1[i + 1][j];
                if (u != last_u || v != last_v)
                {
                    lca1.add_edge(u, v);
                    last_u = u;
                    last_v = v;
                }
            }
        }
    }
    lca1.build(1);

    id = 0;
    for (int j = 1; j <= n; j++)
    {
        for (int i = 1; i <= n; i++)
        {
            if (c[i][j] == '#')
            {
                if (c[i - 1][j] != '#')
                {
                    id2[i][j] = ++id;
                }
                else
                {
                    id2[i][j] = id2[i - 1][j];
                }
            }
        }
    }

    LCA lca2(id);
    for (int j = 1; j < n; j++)
    {
        int last_u = 0, last_v = 0;
        for (int i = 1; i <= n; i++)
        {
            if (c[i][j] == '#' && c[i][j + 1] == '#')
            {
                int u = id2[i][j];
                int v = id2[i][j + 1];
                if (u != last_u || v != last_v)
                {
                    lca2.add_edge(u, v);
                    last_u = u;
                    last_v = v;
                }
            }
        }
    }
    lca2.build(1);

    while (q--)
    {
        int r1, c1, r2, c2;
        std::cin >> r1 >> c1 >> r2 >> c2;
        int s1 = id1[r1][c1], t1 = id1[r2][c2];
        int s2 = id2[r1][c1], t2 = id2[r2][c2];
        int dist1 = lca1.dist(s1, t1);
        int dist2 = lca2.dist(s2, t2);
        std::cout << dist1 + dist2 << "\n";
    }
}

