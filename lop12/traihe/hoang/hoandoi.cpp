ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

 int n, q;
int mn[maxn + 7], mx[maxn + 7];
int par[20][maxn + 7];
int sz[20][maxn + 7];

struct DSU
{
    DSU(int n)
    {
        for (int k = 0; k < 19; k++)
        {
            for (int i = 0; i <= n + 1; i++)
            {
                par[k][i] = i;
                sz[k][i] = 1;
                mn[i] = i;
                mx[i] = i;
            }
        }
    }

    int acs(int k, int v)
    {
        return v == par[k][v] ? v : par[k][v] = acs(k, par[k][v]);
    }

    void join(int u, int v, int k)
    {
        u = acs(k, u);
        v = acs(k, v);
        if (u != v)
        {
            if (sz[k][u] < sz[k][v])
            {
                std::swap(u, v);
            }
            par[k][v] = u;
            sz[k][u] += sz[k][v];
            if (k == 0)
            {
                mn[u] = std::min(mn[u], mn[v]);
                mx[u] = std::max(mx[u], mx[v]);
            }
        }
    }

    void down(int u, int v, int k)
    {
        if (par[k][u] != par[k][v])
        {
            join(u, v, k);
            if (k > 0)
            {
                down(u, v, k - 1);
                down(u + (1 << (k - 1)), v + (1 << (k - 1)), k - 1);
            }
        }
    }
};

void solve()
{
    std::cin >> n >> q;
    DSU dsu(n);

    while (q--)
    {
        int type;
        std::cin >> type;
        if (type == 1)
        {
            int x;
            std::cin >> x;
            int root = dsu.acs(0, x);
            std::cout << mn[root] << " " << mx[root] << "\n";
        }
        else
        {
            int l, r, len;
            std::cin >> l >> r >> len;
            int k = 31 - __builtin_clz(len);
            dsu.down(l, r, k);
            dsu.down(l + len - (1 << k), r + len - (1 << k), k);
        }
    }
}

