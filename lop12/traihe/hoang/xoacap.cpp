ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
int a[maxn + 7];
int par[maxn + 7], parc[maxn + 7], depth[maxn + 7];
std::map<int, int> mp[maxn + 7];
int f[maxn + 7];
int cur = 0;
int num = 0;

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> adj, up;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        adj.resize(n + 7);
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
    }

    void add_edge(int u, int v)
    {
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    void dfs(int u, int p)
    {
        up[u][0] = p;
        for (int i = 1; i <= num; ++i)
        {
            up[i][0] = par[i];
        }
        for (int v : adj[u])
        {
            if (v != p)
            {
                dfs(v, u);
            }
        }
    }

    void build()
    {
        for (int i = 1; i <= num; ++i)
        {
            up[i][0] = par[i];
        }
        for (int j = 1; j < 20; j++)
        {
            for (int i = 0; i <= num; i++)
            {
                up[i][j] = up[up[i][j - 1]][j - 1];
            }
        }
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
            std::swap(u, v);
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; ++i)
        {
            if ((k >> i) & 1)
                u = up[u][i];
        }
        if (u == v)
            return u;
        for (int i = lg; i >= 0; --i)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 1; i <= n; i++)
    {
        int color = a[i];

        if (cur != 0 && parc[cur] == color)
        {
            cur = par[cur];
        }
        else
        {
            auto it = mp[cur].find(color);
            if (it != mp[cur].end())
            {
                cur = it->se;
            }
            else
            {
                num++;
                par[num] = cur;
                parc[num] = color;
                depth[num] = depth[cur] + 1;
                mp[cur][color] = num;
                cur = num;
            }
        }

        f[i] = cur;
    }

    LCA lca(num);
    lca.build();

    for (int i = 1; i <= num; i++)
    {
        if (par[i])
        {
            lca.add_edge(i, par[i]);
        }
    }

    for (int i = 1; i <= q; i++)
    {
        int l, r;
        std::cin >> l >> r;
        int u = f[l - 1];
        int v = f[r];
        int p = lca.get_lca(u, v);
        int ans = depth[u] + depth[v] - 2 * depth[p];
        std::cout << ans << "\n";
    }
}

