struct StringHash
{
    int n;
    const long long MOD1 = 1e9 + 7, MOD2 = 1e9 + 9;
    const long long BASE1 = 311, BASE2 = 313;
    std::vector<long long> h1, h2, p1, p2;

    StringHash(const std::string &s)
    {
        n = s.length();
        h1.assign(n + 7, 0);
        h2.assign(n + 7, 0);
        p1.assign(n + 7, 1);
        p2.assign(n + 7, 1);
        for (int i = 1; i <= n; i++)
        {
            p1[i] = (p1[i - 1] * BASE1) % MOD1;
            p2[i] = (p2[i - 1] * BASE2) % MOD2;
            h1[i] = (h1[i - 1] * BASE1 + s[i - 1]) % MOD1;
            h2[i] = (h2[i - 1] * BASE2 + s[i - 1]) % MOD2;
        }
    }

    std::pair<long long, long long> get_hash(int l, int r)
    {
        long long hash1 = (h1[r] - h1[l - 1] * p1[r - l + 1] % MOD1 + MOD1) % MOD1;
        long long hash2 = (h2[r] - h2[l - 1] * p2[r - l + 1] % MOD2 + MOD2) % MOD2;
        return {hash1, hash2};
    }
};

const int mod1 = 1e9 + 7;
const int mod2 = 1e9 + 9;
const int base = 311;

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    std::stack<int> st;
    h1[0] = 0;
    h2[0] = 0;

    for (int i = 1; i <= n; i++)
    {
        if (!st.empty() && a[st.top()] + a[i] == k)
        {
            st.pop();
            if (st.empty())
            {
                h1[i] = 0;
                h2[i] = 0;
            }
            else
            {
                h1[i] = h1[st.top()];
                h2[i] = h2[st.top()];
            }
        }
        else
        {
            int pre = 0;
            if (st.size())
            {
                pre = st.top();
            }
            h1[i] = (h1[pre] * base + a[i]) % mod1;
            h2[i] = (h2[pre] * base + a[i]) % mod2;
            st.push(i);
        }
    }

    std::cin >> q;
    while(q--)
    {
        int l, r;
        std::cin >> l >> r;

        if (h1[l - 1] == h1[r] && h2[l - 1] == h2[r])
        {
            std::cout << "YES\n";
        }
        else
        {
            std::cout << "NO\n";
        }
    }
}

