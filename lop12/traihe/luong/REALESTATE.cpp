ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int c[maxn + 7];

struct Dinic
{
    struct Edge
    {
        int to;
        long long cap, flow;
    };
    int n, s, t;
    std::vector<Edge> edges;
    std::vector<std::vector<int>> adj;
    std::vector<int> level, ptr;
    const long long INF = 1e18;

    Dinic(int n, int s, int t) : n(n), s(s), t(t)
    {
        adj.resize(n + 7);
        level.resize(n + 7);
        ptr.resize(n + 7);
    }

    void add_edge(int from, int to, long long cap)
    {
        adj[from].push_back(edges.size());
        edges.push_back({to, cap, 0});
        adj[to].push_back(edges.size());
        edges.push_back({from, 0, 0});
    }

    bool bfs()
    {
        std::fill(level.begin(), level.end(), -1);
        level[s] = 0;
        std::queue<int> q;
        q.push(s);
        while (!q.empty())
        {
            int v = q.front();
            q.pop();
            for (int id : adj[v])
            {
                auto &edge = edges[id];
                if (edge.cap - edge.flow > 0 && level[edge.to] == -1)
                {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    long long dfs(int v, long long pushed)
    {
        if (pushed == 0 || v == t)
            return pushed;
        for (int &cid = ptr[v]; cid < adj[v].size(); ++cid)
        {
            int id = adj[v][cid];
            auto &edge = edges[id];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.cap - edge.flow == 0)
                continue;
            long long push = dfs(tr, std::min(pushed, edge.cap - edge.flow));
            if (push == 0)
                continue;
            edge.flow += push;
            edges[id ^ 1].flow -= push;
            return push;
        }
        return 0;
    }

    long long max_flow()
    {
        long long flow = 0;
        while (bfs())
        {
            std::fill(ptr.begin(), ptr.end(), 0);
            while (long long pushed = dfs(s, INF))
            {
                flow += pushed;
            }
        }
        return flow;
    }
};

int st[4 * maxn + 7];

void build(int id, int l, int r, int sink, Dinic &dinic)
{
    st[id] = n + id;
    if (l == r)
    {
        dinic.add_edge(st[id], sink, c[l]);
        return;
    }

    int mid = (l + r) / 2;
    build(id * 2, l, mid, sink, dinic);
    build(id * 2 + 1, mid + 1, r, sink, dinic);

    dinic.add_edge(st[id], st[id * 2], INF);
    dinic.add_edge(st[id], st[id * 2 + 1], INF);
}

void connect(int id, int l, int r, int u, int v, int node, Dinic &dinic)
{
    if (v < l || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        dinic.add_edge(node, st[id], INF);
        return;
    }

    int mid = (l + r) / 2;
    connect(2 * id, l, mid, u, v, node, dinic);
    connect(2 * id + 1, mid + 1, r, u, v, node, dinic);
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= m; i++)
    {
        std::cin >> c[i];
    }

    int source = 0, sink = n + 4 * m + 1;

    Dinic dinic(sink + 5, source, sink);

    build(1, 1, m, sink, dinic);

    ll profit = 0;
    for (int i = 1; i <= n; i++)
    {
        int l, r;
        ll p;
        std::cin >> l >> r >> p;
        profit += p;

        dinic.add_edge(source, i, p);
        connect(1, 1, m, l, r, i, dinic);
    }

    ll mincut = dinic.max_flow();
    std::cout << profit - mincut << "\n";
}

