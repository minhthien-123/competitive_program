ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m, q, k;

struct Dinic
{
    struct Edge
    {
        int to;
        int cap, flow, rev;
    };
    int n, s, t;
    std::vector<std::vector<Edge>> adj;
    std::vector<int> level, ptr;
    const int inf = 1e9;

    Dinic(int n, int s, int t) : n(n), s(s), t(t)
    {
        adj.resize(n + 7);
        level.resize(n + 7);
        ptr.resize(n + 7);
    }

    void add_edge(int from, int to, int cap)
    {
        adj[from].push_back({to, cap, 0, (int)adj[to].size()});
        adj[to].push_back({from, 0, 0, (int)adj[from].size() - 1});
    }

    bool bfs()
    {
        std::fill(level.begin(), level.end(), -1);
        level[s] = 0;
        std::queue<int> q;
        q.push(s);
        while (!q.empty())
        {
            int v = q.front();
            q.pop();
            for (auto &edge : adj[v])
            {
                if (edge.cap - edge.flow > 0 && level[edge.to] == -1)
                {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    int dfs(int v, int pushed)
    {
        if (pushed == 0 || v == t)
            return pushed;
        for (int &cid = ptr[v]; cid < adj[v].size(); ++cid)
        {
            auto &edge = adj[v][cid];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.cap - edge.flow == 0)
                continue;
            int push = dfs(tr, std::min(pushed, edge.cap - edge.flow));
            if (push == 0)
                continue;
            edge.flow += push;
            adj[tr][edge.rev].flow -= push;
            return push;
        }
        return 0;
    }

    int max_flow()
    {
        int flow = 0;
        while (bfs())
        {
            std::fill(ptr.begin(), ptr.end(), 0);
            while (int pushed = dfs(s, inf))
            {
                flow += pushed;
            }
        }
        return flow;
    }
};

struct query
{
    int u, v, l, r;
};

int demand[maxn + 7];
int in[maxn + 7], out[maxn + 7];
query Q[maxn + 7];

void solve()
{
    std::cin >> n >> m >> k >> q;

    int source = n + 1, sink = n + 2;

    for (int i = 1; i <= m; i++)
    {
        int u, v, l, r;
        std::cin >> u >> v >> l >> r;
        Q[i] = {u, v, l, r};
    }

    for (int i = 1; i <= q; i++)
    {
        Dinic dinic(n + 2, source, sink);
        for (int j = 1; j <= n; j++)
        {
            demand[j] = 0;
        }

        for (int j = 1; j <= k; j++)
        {
            int l, r;
            std::cin >> l >> r;
            Q[j].l = l;
            Q[j].r = r;
        }

        for (int j = 1; j <= m; j++)
        {
            auto [u, v, l, r] = Q[j];
            dinic.add_edge(u, v, r - l);
            demand[u] -= l;
            demand[v] += l;
        }

        int sum = 0;
        for (int j = 1; j <= n; j++)
        {
            if (demand[j] > 0)
            {
                dinic.add_edge(source, j, demand[j]);
                sum += demand[j];
            }
            else if (demand[j] < 0)
            {
                dinic.add_edge(j, sink, -demand[j]);
            }
        }

        int mf = dinic.max_flow();

        if (mf < sum)
        {
            std::cout << 0;
        }
        else
        {
            std::cout << 1;
        }
    }
}

