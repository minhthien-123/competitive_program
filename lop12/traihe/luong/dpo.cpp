ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int divs_st[maxn + 7], divs_en[maxn + 7];
int divs_list[1200005];

int n, k;
int a[maxn + 7], phi[maxn + 7], cnt[maxn + 7];
ll cost = 0;
int L = 1, R = 0;

void init()
{
    for (int i = 1; i <= maxn; i++)
    {
        phi[i] = i;
    }
    for (int i = 2; i <= maxn; i++)
    {
        if (phi[i] == i)
        {
            for (int j = i; j <= maxn; j += i)
            {
                phi[j] -= phi[j] / i;
            }
        }
    }

    static int cnt_divs[maxn + 7];
    for (int i = 1; i <= maxn; i++)
    {
        for (int j = i; j <= maxn; j += i)
        {
            cnt_divs[j]++;
        }
    }

    int cur = 0;
    for (int i = 1; i <= maxn; i++)
    {
        divs_st[i] = cur;
        cur += cnt_divs[i];
        divs_en[i] = divs_st[i];
    }

    for (int i = 1; i <= maxn; i++)
    {
        for (int j = i; j <= maxn; j += i)
        {
            divs_list[divs_en[j]++] = i;
        }
    }
}

inline void add_val(int idx)
{
    int val = a[idx];
    for (int i = divs_st[val]; i < divs_en[val]; ++i)
    {
        int x = divs_list[i];
        cost += 1LL * phi[x] * cnt[x];
        cnt[x]++;
    }
}

inline void del_val(int idx)
{
    int val = a[idx];
    for (int i = divs_st[val]; i < divs_en[val]; ++i)
    {
        int x = divs_list[i];
        cnt[x]--;
        cost -= 1LL * phi[x] * cnt[x];
    }
}

inline void mo(int l, int r)
{
    while (L < l)
        del_val(L++);
    while (R > r)
        del_val(R--);
    while (L > l)
        add_val(--L);
    while (R < r)
        add_val(++R);
}

struct DnC_DP
{
    int n, k;
    std::vector<std::vector<long long>> dp;
    const long long INF = 1e18;

    DnC_DP(int n, int k) : n(n), k(k)
    {
        dp.assign(k + 1, std::vector<long long>(n + 7, INF));
    }

    void compute(int dp_idx, int l, int r, int opt_l, int opt_r)
    {
        if (l > r)
        {
            return;
        }
        int mid = (l + r) / 2;
        int best_k = -1;
        long long best_val = INF;

        for (int j = std::min(mid - 1, opt_r); j >= opt_l; j--)
        {
            if (dp[dp_idx - 1][j] != INF)
            {
                mo(j + 1, mid);
                long long cur_val = dp[dp_idx - 1][j] + cost;
                if (cur_val < best_val)
                {
                    best_val = cur_val;
                    best_k = j;
                }
            }
        }

        dp[dp_idx][mid] = best_val;

        int safe_opt = best_k;
        if (safe_opt == -1)
        {
            safe_opt = opt_l;
        }

        compute(dp_idx, l, mid - 1, opt_l, safe_opt);
        compute(dp_idx, mid + 1, r, safe_opt, opt_r);
    }

    void solve()
    {
        dp[0][0] = 0;
        for (int i = 1; i <= k; i++)
        {
            compute(i, 1, n, 0, n - 1);
        }
    }
};

void solve()
{
    init();

    FastIO::read(n);
    FastIO::read(k);

    for (int i = 1; i <= n; i++)
    {
        FastIO::read(a[i]);
    }

    DnC_DP dnc(n, k);
    dnc.solve();

    FastIO::write(dnc.dp[k][n]);
    FastIO::putChar('\n');
}

