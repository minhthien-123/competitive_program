namespace FastIO
{
    static constexpr int SZ = 1 << 20;

    char ibuf[SZ];
    int ipos = 0, ilen = 0;

    char obuf[SZ];
    int opos = 0;

    inline char getChar()
    {
        if (ipos == ilen)
        {
            ilen = fread(ibuf, 1, SZ, stdin);
            ipos = 0;
            if (!ilen)
            {
                return EOF;
            }
        }
        return ibuf[ipos++];
    }

    template <typename T>
    inline void read(T &x)
    {
        x = 0;
        bool neg = false;
        char c = getChar();
        while (c != '-' && (c < '0' || c > '9'))
        {
            c = getChar();
        }
        if (c == '-')
        {
            neg = true;
            c = getChar();
        }
        while (c >= '0' && c <= '9')
        {
            x = x * 10 + c - '0';
            c = getChar();
        }
        if (neg)
        {
            x = -x;
        }
    }

    inline void putChar(char c)
    {
        if (opos == SZ)
        {
            fwrite(obuf, 1, SZ, stdout);
            opos = 0;
        }
        obuf[opos++] = c;
    }

    template <typename T>
    inline void write(T x)
    {
        if (x == 0)
        {
            putChar('0');
            return;
        }

        if (x < 0)
        {
            putChar('-');
            x = -x;
        }

        char s[24];
        int n = 0;

        while (x)
        {
            s[n++] = char(x % 10 + '0');
            x /= 10;
        }

        while (n--)
        {
            putChar(s[n]);
        }
    }

    inline void flush()
    {
        fwrite(obuf, 1, opos, stdout);
        opos = 0;
    }
}

const int maxn = 1e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
