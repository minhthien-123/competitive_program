ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int demand[maxn + 7], in[maxn + 7], out[maxn + 7];

struct Dinic
{
    struct Edge
    {
        int to;
        long long cap, flow, rev;
    };
    int n, s, t;
    std::vector<std::vector<Edge>> adj;
    std::vector<int> level, ptr;
    const long long INF = 1e18;

    Dinic(int n, int s, int t) : n(n), s(s), t(t)
    {
        adj.resize(2 * n + 7);
        level.resize(2 * n + 7);
        ptr.resize(2 * n + 7);
    }

    void add_edge(int from, int to, long long cap)
    {
        adj[from].push_back({to, cap, 0, (long long)adj[to].size()});
        adj[to].push_back({from, 0, 0, (long long)adj[from].size() - 1});
    }

    bool bfs()
    {
        std::fill(level.begin(), level.end(), -1);
        level[s] = 0;
        std::queue<int> q;
        q.push(s);
        while (!q.empty())
        {
            int v = q.front();
            q.pop();
            for (auto &edge : adj[v])
            {
                if (edge.cap - edge.flow > 0 && level[edge.to] == -1)
                {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    long long dfs(int v, long long pushed)
    {
        if (pushed == 0 || v == t)
            return pushed;
        for (int &cid = ptr[v]; cid < adj[v].size(); ++cid)
        {
            auto &edge = adj[v][cid];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.cap - edge.flow == 0)
                continue;
            long long push = dfs(tr, std::min(pushed, edge.cap - edge.flow));
            if (push == 0)
                continue;
            edge.flow += push;
            adj[tr][edge.rev].flow -= push;
            return push;
        }
        return 0;
    }

    long long max_flow()
    {
        long long flow = 0;
        while (bfs())
        {
            std::fill(ptr.begin(), ptr.end(), 0);
            while (long long pushed = dfs(s, INF))
            {
                flow += pushed;
            }
        }
        return flow;
    }
};

void solve()
{
    std::cin >> n >> m;
    int source = 2 * n + 1, sink = 2 * n + 2;
    int vsource = 2 * n + 3, vsink = 2 * n + 4;

    Dinic dinic(2 * n + 4, vsource, vsink);

    for (int i = 1; i <= n; i++)
    {
        int a, b;
        std::cin >> a >> b;
        dinic.add_edge(i, i + n, b - a);
        demand[i] -= a;
        demand[i + n] += a;
    }

    for (int i = 1; i <= m; i++)
    {
        int u, v, l, r;
        std::cin >> u >> v >> l >> r;
        out[u]++;
        in[v]++;
        dinic.add_edge(u + n, v, r - l);
        demand[u + n] -= l;
        demand[v] += l;
    }

    for (int i = 1; i <= n; i++)
    {
        if (in[i] == 0)
        {
            dinic.add_edge(source, i, INF);
        }
        if (out[i] == 0)
        {
            dinic.add_edge(i + n, sink, INF);
        }
    }

    ll sum_demand = 0;
    for (int i = 1; i <= sink; i++)
    {
        if (demand[i] > 0)
        {
            dinic.add_edge(vsource, i, demand[i]);
            sum_demand += demand[i];
        }
        else if (demand[i] < 0)
        {
            dinic.add_edge(i, vsink, -demand[i]);
        }
    }

    ll flow1 = dinic.max_flow();

    dinic.add_edge(sink, source, INF);
    ll flow2 = dinic.max_flow();

    if (flow1 + flow2 != sum_demand)
    {
        std::cout << -1;
    }
    else
    {
        ll ans = 0;
        for (auto e : dinic.adj[sink])
        {
            if (e.to == source)
            {
                ans = e.flow;
                break;
            }
        }

        std::cout << ans;
    }
}

