ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m, s, t;

struct Dinic {
    struct Edge {
        int to;
        long long cap, flow, rev;
    };
    int n, s, t;
    std::vector<std::vector<Edge>> adj;
    std::vector<int> level, ptr;
    const long long INF = 1e18;

    Dinic(int n, int s, int t) : n(n), s(s), t(t) {
        adj.resize(n + 7);
        level.resize(n + 7);
        ptr.resize(n + 7);
    }

    void add_edge(int from, int to, long long cap) {
        adj[from].push_back({to, cap, 0, (long long)adj[to].size()});
        adj[to].push_back({from, 0, 0, (long long)adj[from].size() - 1});
    }

    bool bfs() {
        std::fill(level.begin(), level.end(), -1);
        level[s] = 0;
        std::queue<int> q;
        q.push(s);
        while (!q.empty()) {
            int v = q.front(); q.pop();
            for (auto& edge : adj[v]) {
                if (edge.cap - edge.flow > 0 && level[edge.to] == -1) {
                    level[edge.to] = level[v] + 1;
                    q.push(edge.to);
                }
            }
        }
        return level[t] != -1;
    }

    long long dfs(int v, long long pushed) {
        if (pushed == 0 || v == t) return pushed;
        for (int& cid = ptr[v]; cid < adj[v].size(); ++cid) {
            auto& edge = adj[v][cid];
            int tr = edge.to;
            if (level[v] + 1 != level[tr] || edge.cap - edge.flow == 0) continue;
            long long push = dfs(tr, std::min(pushed, edge.cap - edge.flow));
            if (push == 0) continue;
            edge.flow += push;
            adj[tr][edge.rev].flow -= push;
            return push;
        }
        return 0;
    }

    long long max_flow() {
        long long flow = 0;
        while (bfs()) {
            std::fill(ptr.begin(), ptr.end(), 0);
            while (long long pushed = dfs(s, INF)) {
                flow += pushed;
            }
        }
        return flow;
    }
};

void solve()
{
    std::cin >> n >> m >> s >> t;

    Dinic dinic(n, s, t);

    for (int i = 1; i <= m; i++)
    {
        int u, v, c;
        std::cin >> u >> v >> c;
        dinic.add_edge(u, v, c);
    }

    std::cout << dinic.max_flow();
}

