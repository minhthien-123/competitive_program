ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::mt19937_64 rng(std::chrono::steady_clock::now().time_since_epoch().count());

ll Rand(ll l, ll r)
{
    assert(l <= r);
    std::uniform_int_distribution<ll> distrib(l, r);
    return distrib(rng);
}

std::vector<int> adj[maxn + 7];

int a[maxn + 7];
int pre[maxn + 7], cnt[maxn + 7];
ll val[maxn + 7], f[maxn + 7];
ll cost;
int L, R;

void add_val(int idx)
{
    cost += cnt[pre[idx]];
    cnt[pre[idx]]++;
}

void del_val(int idx)
{
    cnt[pre[idx]]--;
    cost -= cnt[pre[idx]];
}

void mo(int l, int r)
{
    while (L > l)
    {
        L--;
        add_val(L);
    }
    while (R < r)
    {
        R++;
        add_val(R);
    }
    while (L < l)
    {
        del_val(L);
        L++;
    }
    while (R > r)
    {
        del_val(R);
        R--;
    }
}

struct DnC_DP
{
    int n, k;
    std::vector<std::vector<long long>> dp;
    const long long INF = 1e18;

    DnC_DP(int n, int k) : n(n), k(k)
    {
        dp.assign(k + 1, std::vector<long long>(n + 7, INF));
    }

    void compute(int dp_idx, int l, int r, int opt_l, int opt_r)
    {
        if (l > r)
            return;
        int mid = (l + r) / 2;
        int best_k = -1;
        long long best_val = INF;

        for (int j = opt_l; j <= std::min(mid - 1, opt_r); j++)
        {
            if (dp[dp_idx - 1][j] != INF)
            {
                mo(j, mid);
                long long cur_val = dp[dp_idx - 1][j] + cost;
                if (cur_val < best_val)
                {
                    best_val = cur_val;
                    best_k = j;
                }
            }
        }

        dp[dp_idx][mid] = best_val;
        int safe_opt = (best_k == -1) ? opt_l : best_k;

        compute(dp_idx, l, mid - 1, opt_l, safe_opt);
        compute(dp_idx, mid + 1, r, safe_opt, opt_r);
    }

    void solve()
    {
        dp[0][0] = 0;
        for (int i = 1; i <= k; i++)
        {
            compute(i, 1, n, 0, n - 1);
        }
    }
};

void solve()
{
    int n, k;
    std::cin >> n >> k;

    std::vector<int> vec;
    vec.pb(-1);
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        vec.pb(a[i]);
    }

    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());

    for (int i = 0; i < sz(vec); i++)
    {
        val[i] = Rand(1, 1e18);
    }

    for (int i = 1; i <= n; i++)
    {
        int id = std::lower_bound(all(vec), a[i]) - vec.begin();
        f[i] = f[i - 1] ^ val[id];
    }

    std::vector<ll> vec2;
    vec2.pb(0);
    for (int i = 1; i <= n; i++)
    {
        vec2.pb(f[i]);
    }
    std::sort(all(vec2));
    vec2.erase(std::unique(all(vec2)), vec2.end());

    for (int i = 0; i <= n; i++)
    {
        pre[i] = std::lower_bound(all(vec2), f[i]) - vec2.begin();
    }

    L = 1;
    R = 0;
    cost = 0;

    DnC_DP dnc(n, k);
    dnc.solve();

    std::cout << dnc.dp[k][n] << "\n";
}

