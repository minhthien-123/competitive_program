ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m, q;
ll a[maxn + 7][maxn + 7], dp1[maxn + 7][maxn + 7], dp2[maxn + 7][maxn + 7], ans[200000 + 7];

struct spacetime
{
    int c1, r1, c2, r2, id;
};
std::vector<spacetime> query;

void dnc(int r1, int r2, int c1, int c2, std::vector<spacetime> &v)
{
    if (v.empty())
    {
        return;
    }

    if (r1 == r2 && c1 == c2)
    {
        for (auto &i : v)
        {
            ans[i.id] = std::min(ans[i.id], a[r1][c1]);
        }
        return;
    }

    int mid = (r1 + r2) / 2;

    std::vector<spacetime> p, p1, p2;

    for (auto &i : v)
    {
        if (i.r2 < mid)
        {
            p1.pb(i);
        }
        else if (i.r1 > mid)
        {
            p2.pb(i);
        }
        else
        {
            p.pb(i);
        }
    }

    for (int k = c1; k <= c2; k++)
    {
        for (int i = mid; i >= r1; i--)
        {
            for (int j = k; j >= c1; j--)
            {
                if (i == mid && j == k)
                {
                    dp1[i][j] = a[i][j];
                }
                else
                {
                    ll res = INF;
                    if (i + 1 <= mid)
                    {
                        res = std::min(res, dp1[i + 1][j]);
                    }
                    if (j + 1 <= k)
                    {
                        res = std::min(res, dp1[i][j + 1]);
                    }
                    dp1[i][j] = res + a[i][j];
                }
            }
        }
        for (int i = mid; i <= r2; i++)
        {
            for (int j = k; j <= c2; j++)
            {
                if (i == mid && j == k)
                {
                    dp2[i][j] = a[i][j];
                }
                else
                {
                    ll res = INF;
                    if (i - 1 >= mid)
                    {
                        res = std::min(res, dp2[i - 1][j]);
                    }
                    if (j - 1 >= k)
                    {
                        res = std::min(res, dp2[i][j - 1]);
                    }
                    dp2[i][j] = res + a[i][j];
                }
            }
        }

        for (auto q : p)
        {
            if (q.c1 <= k && q.c2 >= k)
            {
                ans[q.id] = std::min(ans[q.id], dp1[q.r1][q.c1] + dp2[q.r2][q.c2] - a[mid][k]);
            }
        }
    }

    dnc(r1, mid - 1, c1, c2, p1);
    dnc(mid + 1, r2, c1, c2, p2);
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            std::cin >> a[i][j];
        }
    }
    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        spacetime qq;
        std::cin >> qq.r1 >> qq.c1 >> qq.r2 >> qq.c2;
        qq.id = i;
        query.pb(qq);
        ans[i] = INF;
    }

    dnc(1, n, 1, m, query);

    for (int i = 1; i <= q; i++)
    {
        std::cout << ans[i] << '\n';
    }
}

