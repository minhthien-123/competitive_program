ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
ll k;
int a[maxn + 7], p[maxn + 7];
ll s[maxn + 7];

void solve()
{
    std::cin >> n >> m >> k;

    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j < i; j++)
        {
            if (i - j <= a[i] || i - j <= a[j])
            {
                p[i]++;
            }
        }
    }

    s[n + 1] = 1;
    for (int i = n; i >= 1; i--)
    {
        ll cnt = m - p[i];
        if (cnt <= 0)
        {
            s[i] = 0;
        }
        else
        {
            s[i] = s[i + 1] * cnt;
        }
    }

    if (k >= s[1])
    {
        std::cout << -1 << "\n";
        return;
    }

    std::string str = "";
    for (int i = 1; i <= n; i++)
    {
        for (int c = 0; c < m; c++)
        {
            bool check = true;
            for (int j = 1; j < i; j++)
            {
                if ((i - j <= a[j] || i - j <= a[i]) && (str[j - 1] - 'a' == c))
                {
                    check = false;
                    break;
                }
            }

            if (check)
            {
                if (k < s[i + 1])
                {
                    str += char('a' + c);
                    break;
                }
                else
                {
                    k -= s[i + 1];
                }
            }
        }
    }

    std::cout << str << "\n";
}

