ll nCr(ll n, ll k)
{
    if (k < 0 || k > n)
    {
        return 0;
    }
    ll res = 1;
    for (int i = 1; i <= k; i++)
    {
        res = res * (n - i + 1) / i;
    }

    return res;
}

ll calc(int nx, int ny, int nz)
{
    ll cntx = nCr(nx + ny + nz, nx);
    ll cnty = nCr(ny + nz, ny);
    return cntx * cnty;
}

void solve()
{
    std::cin >> M >> N >> P;
    int q;
    std::cin >> q;
    while (q--)
    {
        int k;
        std::cin >> k;
        std::string ans = "";
        int len = M + N + P;
        int m = M, n = N, p = P;
        for (int i = 1; i <= len; i++)
        {
            ll cntx = calc(m - 1, n, p);
            if (k <= cntx)
            {
                ans += 'X';
                m--;
                continue;
            }
            k -= cntx;

            ll cnty = calc(m, n - 1, p);
            if (k <= cnty)
            {
                ans += 'Y';
                n--;
                continue;
            }
            k -= cnty;

            ans += 'Z';
            p--;
        }

        std::cout << ans << "\n";
    }

}

