ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<ii> adj[maxn + 7];

void solve()
{
    int n, m, k;
    std::cin >> n >> m >> k;

    for (int i = 1; i <= n; i++)
    {
        adj[i].clear();
    }

    for (int i = 0; i < m; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
    }

    std::vector<ll> dist(n + 1, INF);
    dist[1] = 0;

    std::priority_queue<ii, std::vector<ii>, std::greater<ii>> pq;
    pq.push({0, 1});
    while (!pq.empty())
    {
        auto [d, u] = pq.top();
        pq.pop();
        if (d > dist[u])
        {
            continue;
        }
        for (auto [v, w] : adj[u])
        {
            if (dist[v] > dist[u] + w)
            {
                dist[v] = dist[u] + w;
                pq.push({dist[v], v});
            }
        }
    }

    for (int j = 1; j <= k; j++)
    {
        std::vector<ll> tmp = dist;
        bool flag = false;

        for (int u = 1; u <= n; u++)
        {
            if (dist[u] != INF)
            {
                for (auto [v, w] : adj[u])
                {
                    if (tmp[v] > dist[u] - w)
                    {
                        tmp[v] = dist[u] - w;
                        flag = true;
                    }
                }
            }
        }

        if (!flag)
        {
            break;
        }

        for (int u = 1; u <= n; u++)
        {
            if (tmp[u] < dist[u])
            {
                pq.push({tmp[u], u});
            }
        }

        while (!pq.empty())
        {
            auto [d, u] = pq.top();
            pq.pop();

            if (d > tmp[u])
            {
                continue;
            }

            for (auto [v, w] : adj[u])
            {
                if (tmp[v] > tmp[u] + w)
                {
                    tmp[v] = tmp[u] + w;
                    pq.push({tmp[v], v});
                }
            }
        }

        dist = std::move(tmp);
    }

    std::cout << dist[n] << "\n";
}

