ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
ll a[maxn + 7];
int f[maxn + 7], ans[maxn + 7];
std::vector<std::pair<int, ll>> ad[maxn + 7], er[maxn + 7];
ll st[4 * maxn + 8];

void update(int id, int l, int r, int pos, ll val)
{
    if (pos < l || pos > r)
    {
        return;
    }
    if (l == r)
    {
        st[id] += val;
        return;
    }

    int mid = (l + r) / 2;
    update(2 * id, l, mid, pos, val);
    update(2 * id + 1, mid + 1, r, pos, val);
    st[id] = st[id * 2] + st[id * 2 + 1];
}

int get(int id, int l, int r, ll val)
{
    if (l == r)
    {
        return l;
    }
    int mid = (l + r) / 2;
    if (st[id * 2] >= val)
    {
        return get(2 * id, l, mid, val);
    }
    else
    {
        val -= st[2 * id];
        return get(id * 2 + 1, mid + 1, r, val);
    }
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 1; i <= q; i++)
    {
        int l, r;
        ll s;
        std::cin >> l >> r >> s;
        ad[l].pb({i, s});
        if (r + 1 <= n)
        {
            er[r + 1].pb({i, s});
        }
    }

    for (int k = 1; k <= n; k++)
    {
        for (auto [pos, val] : ad[k])
        {
            update(1, 1, q, pos, val);
        }
        for (auto [pos, val] : er[k])
        {
            update(1, 1, q, pos, -val);
        }

        if (st[1] < a[k])
        {
            f[k] = q + 1;
        }
        else
        {
            f[k] = get(1, 1, q, a[k]);
        }
    }

    for (int i = 1; i <= n; i++)
    {
        ans[i] = 0;
        for (int k = i; k <= n; k += i)
        {
            ans[i] = std::max(ans[i], f[k]);
        }
    }

    for (int i = 1; i <= n; i++)
    {
        if (ans[i] > q)
        {
            std::cout << -1 << " ";
        }
        else
        {
            std::cout << ans[i] << " ";
        }
    }
}

