ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];

ll dp[maxn + 7][maxn + 7], tmp[maxn + 7][maxn + 7];
ll row[maxn + 7], col[maxn + 7], d1[2 * maxn + 7], d2[2 * maxn + 7];

void solve()
{
    int r, c, n;
    std::cin >> r >> c >> n;

    for (int i = 1; i <= r; i++)
    {
        for (int j = 1; j <= c; j++)
        {
            dp[i][j] = 1;
        }
    }

    for (int step = 1; step <= n; step++)
    {
        ll sum = 0;
        for (int i = 1; i <= r; i++)
        {
            row[i] = 0;
        }
        for (int j = 1; j <= c; j++)
        {
            col[j] = 0;
        }
        for (int i = 1; i <= r + c + 1; i++)
        {
            d1[i] = 0;
            d2[i] = 0;
        }

        for (int i = 1; i <= r; i++)
        {
            for (int j = 1; j <= c; j++)
            {
                sum = add(sum, dp[i][j]);
                row[i] = add(row[i], dp[i][j]);
                col[j] = add(col[j], dp[i][j]);
                d1[i - j + c] = add(d1[i - j + c], dp[i][j]);
                d2[i + j] = add(d2[i + j], dp[i][j]);
            }
        }

        for (int i = 1; i <= r; i++)
        {
            for (int j = 1; j <= c; j++)
            {
                ll val = sum;
                val = sub(val, row[i]);
                val = sub(val, col[j]);
                val = sub(val, d1[i - j + c]);
                val = sub(val, d2[i + j]);
                val = add(val, mul(3, dp[i][j]));
                tmp[i][j] = val;
            }
        }

        for (int i = 1; i <= r; i++)
        {
            for (int j = 1; j <= c; j++)
            {
                dp[i][j] = tmp[i][j];
            }
        }
    }

    ll ans = 0;
    for (int i = 1; i <= r; i++)
    {
        for (int j = 1; j <= c; j++)
        {
            ans = add(ans, dp[i][j]);
        }
    }

    std::cout << ans << "\n";
}

