ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> a[maxn + 7];
int n, q;
int cnt[maxn + 7];
std::string name[maxn + 7];
int cntd[maxn + 7], score[maxn + 7], id[maxn + 7];

bool cmp(int i, int j)
{
    if (score[i] != score[j])
    {
        return score[i] > score[j];
    }
    if (cntd[i] != cntd[j])
    {
        return cntd[i] > cntd[j];
    }
    return name[i] < name[j];
}

void solve()
{
    std::cin >> n >> q;

    for (int i = 1; i <= n; i++)
    {
        std::string str = "", s;
        char c;
        int m;
        while (std::cin >> s)
        {
            if (s[0] >= '0' && s[0] <= '9')
            {
                m = std::stoi(s);
                break;
            }
            if (str != "")
            {
                str += " ";
            }
            str += s;
        }

        name[i] = str;
        cntd[i] = q - m;

        for (int j = 1; j <= m; j++)
        {
            int x;
            std::cin >> x;
            a[i].pb(x);
            cnt[x]++;
        }
    }

    ll sum = 0;
    for (int i = 1; i <= q; i++)
    {
        sum += cnt[i];
    }

    for (int i = 1; i <= n; i++)
    {
        score[i] = sum;
        for (auto x : a[i])
        {
            score[i] -= cnt[x];
        }
        id[i] = i;
    }

    std::sort(id + 1, id + n + 1, cmp);

    for (int i = 1; i <= n; i++)
    {
        std::cout << name[id[i]] << " " << score[id[i]] << "\n";
    }
}

