const int maxn = 250005;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
ll w[maxn + 7];
ll dp1[maxn + 7], dp2[maxn + 7];
ll st[lg + 1][maxn + 7];

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> w[i];
    }

    dp1[0] = 0;
    ll mx1 = -w[1], mx2 = w[1];
    for (int i = 1; i <= n; i++)
    {
        dp1[i] = std::max(w[i] + mx1, mx2 - w[i]);
        if (i < n)
        {
            mx1 = std::max(mx1, dp1[i] - w[i + 1]);
            mx2 = std::max(mx2, dp1[i] + w[i + 1]);
        }
    }

    dp2[n + 1] = 0;
    mx1 = -w[n], mx2 = w[n];
    for (int i = n; i >= 1; i--)
    {
        dp2[i] = std::max(w[i] + mx1, mx2 - w[i]);
        if (i > 1)
        {
            mx1 = std::max(mx1, dp2[i] - w[i - 1]);
            mx2 = std::max(mx2, dp2[i] + w[i - 1]);
        }
    }

    for (int j = 1; j < n; j++)
    {
        st[0][j] = dp1[j] + dp2[j + 1];
    }
    for (int i = 1; i <= lg; i++)
    {
        for (int j = 1; j + (1 << i) - 1 < n; j++)
        {
            st[i][j] = std::max(st[i - 1][j], st[i - 1][j + (1 << (i - 1))]);
        }
    }

    std::cout << dp1[n] << " ";

    while (q--)
    {
        char type;
        int x, y;
        std::cin >> type >> x >> y;
        if (x > y)
        {
            std::swap(x, y);
        }

        if (type == 'L')
        {
            ll mx_1L = -INF, mx_2L = -INF, mx_3L = -INF, mx_4L = -INF;
            ll cur_M = -INF, cur_m = INF;

            for (int k = x; k <= y; k++)
            {
                cur_M = std::max(cur_M, w[k]);
                cur_m = std::min(cur_m, w[k]);
            }

            ll M = cur_M, m = cur_m;
            for (int i = x; i >= 1; i--)
            {
                M = std::max(M, w[i]);
                m = std::min(m, w[i]);
                ll A = dp1[i - 1];

                mx_1L = std::max(mx_1L, A + M - m);
                mx_2L = std::max(mx_2L, A);
                mx_3L = std::max(mx_3L, A + M);
                mx_4L = std::max(mx_4L, A - m);
            }

            ll mx_1R = -INF, mx_2R = -INF, mx_3R = -INF, mx_4R = -INF;
            M = cur_M, m = cur_m;
            for (int j = y; j <= n; j++)
            {
                M = std::max(M, w[j]);
                m = std::min(m, w[j]);
                ll B = dp2[j + 1];

                mx_1R = std::max(mx_1R, B);
                mx_2R = std::max(mx_2R, B + M - m);
                mx_3R = std::max(mx_3R, B - m);
                mx_4R = std::max(mx_4R, B + M);
            }

            ll ans = std::max({mx_1L + mx_1R, mx_2L + mx_2R, mx_3L + mx_3R, mx_4L + mx_4R});
            std::cout << ans << " ";
        }
        else if (type == 'H')
        {
            int l = x, r = y - 1;
            if (l <= r)
            {
                int k = std::log2(r - l + 1);
                ll ans = std::max(st[k][l], st[k][r - (1 << k) + 1]);
                std::cout << ans << " ";
            }
        }
    }
    std::cout << "\n";
}

