ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int theta;
int n, q;
int a[maxn + 7], pre[maxn + 7], last[maxn + 7], ans[maxn + 7];
std::vector<int> vec;

struct sumxor
{
    int l, r, id;

    friend bool operator<(sumxor a, sumxor b)
    {
        return a.r < b.r;
    }
} query[maxn + 7];

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size())
    {
        for (int i = 0; i < a.size(); i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r >= 0; r = (r & (r + 1)) - 1)
        {
            res ^= bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx < n; idx = idx | (idx + 1))
        {
            bit[idx] ^= delta;
        }
    }
};

void solve()
{
    std::cin >> theta;
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        vec.pb(a[i]);
        pre[i] = pre[i - 1] ^ a[i];
    }

    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());

    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        std::cin >> query[i].l >> query[i].r;
        query[i].id = i;
    }

    std::sort(query + 1, query + q + 1);

    FenwickTree bit(n + 5);

    int id = 1;
    for (int i = 1; i <= n; i++)
    {
        int it = std::lower_bound(all(vec), a[i]) - vec.begin();
        if (last[it] != 0)
        {
            bit.add(last[it], a[i]);
        }
        bit.add(i, a[i]);
        last[it] = i;

        while (id <= q && query[id].r == i)
        {
            int l = query[id].l;
            int qid = query[id].id;

            int uni = bit.sum(i) ^ bit.sum(l - 1);
            int all = pre[i] ^ pre[l - 1];
            ans[qid] = uni ^ all;
            id++;
        }
    }

    for (int i = 1; i <= q; i++)
    {
        std::cout << ans[i] << " ";
    }
}

