ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
ii h[maxn + 7];
ii t[maxn + 7];
bool vis[maxn + 7];
ll ans[maxn + 7];

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);

        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

ll calc(ll len)
{
    return len * (len + 1) / 2;
}

void solve()
{
    std::cin >> n >> q;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i].fi;
        h[i].se = i;
    }
    for (int i = 1; i <= q; i++)
    {
        std::cin >> t[i].fi;
        t[i].se = i;
    }

    std::sort(h + 1, h + n + 1);
    std::sort(t + 1, t + q + 1);

    DSU dsu(n);
    ll res = 0;
    int j = 1;

    for (int i = 1; i <= q; i++)
    {
        ll cur = t[i].fi;
        ll id = t[i].se;

        while (j <= n && h[j].fi <= cur)
        {
            int pos = h[j].se;
            vis[pos] = true;
            res++;

            if (pos > 1 && vis[pos - 1])
            {
                int u = dsu.acs(pos);
                int v = dsu.acs(pos - 1);
                if (u != v)
                {
                    res -= calc(dsu.sz[u]);
                    res -= calc(dsu.sz[v]);
                    dsu.join(u, v);
                    int z = dsu.acs(pos);
                    res += calc(dsu.sz[z]);
                }
            }

            if (pos < n && vis[pos + 1])
            {
                int u = dsu.acs(pos);
                int v = dsu.acs(pos + 1);
                if (u != v)
                {
                    res -= calc(dsu.sz[u]);
                    res -= calc(dsu.sz[v]);
                    dsu.join(u, v);
                    int z = dsu.acs(pos);
                    res += calc(dsu.sz[z]);
                }
            }
            j++;
        }

        ans[id] = res;
    }

    for (int i = 1; i <= q; i++)
    {
        std::cout << ans[i] << "\n";
    }

}

