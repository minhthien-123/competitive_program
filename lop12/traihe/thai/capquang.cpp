ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<ii> adj[maxn + 7];
int n, m;
bool check[maxn + 7];
int U[maxn + 7], V[maxn + 7];
int d[maxn + 7], up[maxn + 7];
int f[maxn + 7], idx[maxn + 7];
int ans[maxn + 7];
std::vector<int> nxt[maxn + 7];

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);

        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

void dfs(int u, int p, int index)
{
    d[u] = d[p] + 1;
    up[u] = p;
    idx[u] = index;
    for (auto [v, id] : adj[u])
    {
        if (v != p)
        {
            dfs(v, u, id);
        }
    }
}

void solve()
{
    std::cin >> n >> m;

    for (int i = 1; i <= m; i++)
    {
        int u, v;
        std::cin >> u >> v;
        U[i] = u;
        V[i] = v;
        f[i] = INF;
    }

    for (int i = 1; i < n; i++)
    {
        int id;
        std::cin >> id;
        check[id] = true;

        int u = U[id];
        int v = V[id];

        adj[u].pb({v, id});
        adj[v].pb({u, id});
    }

    dfs(1, 0, 0);

    DSU dsu(n);

    for (int i = 1; i <= m; i++)
    {
        if (!check[i])
        {
            int u = dsu.acs(U[i]);
            int v = dsu.acs(V[i]);
            while (u != v)
            {
                if (d[u] < d[v])
                {
                    std::swap(u, v);
                }
                int dex = idx[u];
                f[dex] = i;
                dsu.par[u] = dsu.acs(up[u]);
                u = dsu.acs(u);
            }
        }
    }

    std::priority_queue<int> pq;
    for (int i = 1; i <= m; i++)
    {
        if (check[i])
        {
            if (f[i] == INF)
            {
                pq.push(i);
            }
            else
            {
                nxt[f[i]].pb(i);
            }
        }
        else
        {
            pq.push(i);
        }
    }

    int tmp = m;
    while (sz(pq))
    {
        int cur = pq.top();
        pq.pop();
        ans[cur] = tmp;
        tmp--;
        for (int x : nxt[cur])
        {
            pq.push(x);
        }
    }

    for (int i = 1; i <= m; i++)
    {
        std::cout << ans[i] << " ";
    }
}

