ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<std::pair<int, ll>> adj[maxn + 7];
int n, k;
ll cnt = 0;

ll dfs(int u, int p, ll x)
{
    std::vector<int> vec;

    for (auto [v, w] : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        ll val = dfs(v, u, x) + w;
        vec.pb(val);
    }

    std::sort(all(vec));

    while (sz(vec) >= 2 && vec[sz(vec) - 1] + vec[sz(vec) - 2] > x)
    {
        cnt++;
        vec.pop_back();
    }

    if (sz(vec) == 1 && vec.back() > x)
    {
        cnt++;
        vec.pop_back();
    }

    if (vec.empty())
    {
        return 0;
    }
    else
    {
        return vec.back();
    }
}

bool check(ll x)
{
    cnt = 0;
    dfs(1, 0, x);
    return (cnt + 1) <= k;
}

void solve()
{
    std::cin >> n >> k;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        ll w;
        std::cin >> u >> v >> w;
        adj[u].pb({v, w});
        adj[v].pb({u, w});
    }

    ll l = 0, r = 1e18, ans = -1;

    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            r = mid - 1;
        }
        else
        {
            l = mid + 1;
        }
    }

    std::cout << ans;
}

