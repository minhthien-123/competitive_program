ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, m;
int a[maxn + 7], b[maxn + 7], c[maxn + 7];

bool check(ll x)
{
    __int128_t cnt = 0;
    __int128_t cnt2 = 0;
    for (int i = 1; i <= n; i++)
    {
        if (x <= m * c[i])
        {
            int need = (x + c[i] - 1) / c[i];
            cnt += m - need;
        }
        else
        {
            int tmp = x - m * c[i];
            int need = (tmp + b[i] - 1) / b[i];
            cnt2 += need;
        }
    }

    return (cnt >= cnt2);
}

void solve()
{
    std::cin >> n >> m;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }
    for (int i = 1; i <= n; i++)
    {
        std::cin >> b[i];
        c[i] = std::max(a[i], b[i]);
    }

    ll l = 0, r = 1e18, ans = 0;

    while (l <= r)
    {
        ll mid = (l + r) / 2;
        if (check(mid))
        {
            ans = mid;
            l = mid + 1;
        }
        else
        {
            r = mid - 1;
        }
    }

    std::cout << ans;
}

