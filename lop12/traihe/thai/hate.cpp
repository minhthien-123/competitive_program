ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7], tree[maxn + 7];
struct edge
{
    int u, v, id;
};

int n;
int a[maxn + 7], b[maxn + 7];
bool vis[maxn + 7];
bool used[maxn + 7];
int dp[maxn + 7][2];
int bu, bv;
int cnt;
std::vector<edge> edges;

void dfs(int u, int p)
{
    vis[u] = true;

    for (int e : adj[u])
    {
        if (e == p)
        {
            continue;
        }
        if (used[e])
        {
            continue;
        }
        used[e] = true;

        int v;
        if (u == edges[e].u)
        {
            v = edges[e].v;
        }
        else
        {
            v = edges[e].u;
        }

        if (vis[v])
        {
            bu = u;
            bv = v;
        }
        else
        {
            tree[u].pb(e);
            tree[v].pb(e);
            dfs(v, e);
        }
    }
}

void calc(int u, int p, int ban)
{
    dp[u][0] = 0;
    dp[u][1] = a[u];
    if (u == ban)
    {
        dp[u][1] = -inf;
    }

    for (int e : tree[u])
    {
        int v;
        if (u == edges[e].u)
        {
            v = edges[e].v;
        }
        else
        {
            v = edges[e].u;
        }

        if (e == p)
        {
            continue;
        }

        calc(v, e, ban);
        dp[u][0] += std::max(dp[v][0], dp[v][1]);
        dp[u][1] += dp[v][0];
    }
}

void solve()
{
    std::cin >> n;
    edges.clear();
    for (int i = 0; i <= n; i++)
    {
        adj[i].clear();
        tree[i].clear();
        vis[i] = false;
        used[i] = false;
    }

    cnt = 0;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i] >> b[i];
        if (b[i] != -1)
        {
            edges.pb({i, b[i], cnt});
            adj[i].pb(cnt);
            adj[b[i]].pb(cnt);
            cnt++;
        }
    }

    int ans = 0;
    for (int i = 1; i <= n; i++)
    {
        if (!vis[i])
        {
            bu = bv = -1;
            dfs(i, -1);
            if (bu == -1)
            {
                calc(i, -1, -1);
                ans += std::max(dp[i][0], dp[i][1]);
            }
            else
            {
                calc(i, -1, bu);
                int res1 = std::max(dp[i][0], dp[i][1]);
                calc(i, -1, bv);
                int res2 = std::max(dp[i][0], dp[i][1]);
                ans += std::max(res1, res2);
            }
        }
    }

    std::cout << ans << "\n";
}

