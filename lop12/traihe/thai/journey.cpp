ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
ll x[maxn + 7], s[maxn + 7];
ll a[maxn + 7], b[maxn + 7];
ll sta[25][maxn + 7], stb[25][maxn + 7];

ll geta(int l, int r)
{
    int j = 31 - __builtin_clz(r - l + 1);
    return std::max(sta[j][l], sta[j][r - (1 << j) + 1]);
}

ll getb(int l, int r)
{
    int j = 31 - __builtin_clz(r - l + 1);
    return std::min(stb[j][l], stb[j][r - (1 << j) + 1]);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> x[i];
    }
    a[1] = INF;
    for (int i = 2; i <= n; i++)
    {
        a[i] = 2 * x[i] - x[i - 1];
    }
    b[n] = -INF;
    for (int i = n - 1; i >= 1; i--)
    {
        b[i] = 2 * x[i] - x[i + 1];
    }

    for (int i = 1; i <= n; i++)
    {
        sta[0][i] = a[i];
        stb[0][i] = b[i];
    }
    for (int j = 1; j <= 20; j++)
    {
        for (int i = 1; i + (1 << j) - 1 <= n; i++)
        {
            sta[j][i] = std::max(sta[j - 1][i], sta[j - 1][i + (1 << (j - 1))]);
            stb[j][i] = std::min(stb[j - 1][i], stb[j - 1][i + (1 << (j - 1))]);
        }
    }

    std::cin >> q;
    for (int i = 1; i <= q; i++)
    {
        int s;
        std::cin >> s;
        int p = 1;
        auto it = std::lower_bound(x + 1, x + n + 1, s) - x;
        if (it > n)
        {
            p = n;
        }
        else if (it == 1)
        {
            p = 1;
        }
        else
        {
            ll dr = x[it] - s;
            ll dl = s - x[it - 1];
            if (dl <= dr)
            {
                p = it - 1;
            }
            else
            {
                p = it;
            }
        }

        ll dist = abs(s - x[p]);
        int l = p, r = p;
        int pos = 0;

        while (l > 1 || r < n)
        {
            if (l == 1)
            {
                if (pos == 0)
                {
                    dist += x[n] - x[1];
                }
                else
                {
                    dist += x[n] - x[r];
                }
                break;
            }
            if (r == n)
            {
                if (pos == 1)
                {
                    dist += x[n] - x[1];
                }
                else
                {
                    dist += x[l] - x[1];
                }
                break;
            }

            if (pos == 0)
            {
                if (x[l] - x[l - 1] <= x[r + 1] - x[l])
                {
                    int L = 1, R = l, k = 1;
                    while (L <= R)
                    {
                        int mid = (L + R) / 2;
                        if (geta(mid, l) > x[r + 1])
                        {
                            k = mid;
                            L = mid + 1;
                        }
                        else
                        {
                            R = mid - 1;
                        }
                    }
                    dist += x[l] - x[k];
                    l = k;
                }
                else
                {
                    dist += x[r + 1] - x[l];
                    r++;
                    pos = 1;
                }
            }
            else
            {
                if (x[r + 1] - x[r] < x[r] - x[l - 1])
                {
                    int L = r, R = n, k = R;
                    while (L <= R)
                    {
                        int mid = (L + R) / 2;
                        if (getb(r, mid) <= x[l - 1])
                        {
                            k = mid;
                            R = mid - 1;
                        }
                        else
                        {
                            L = mid + 1;
                        }
                    }
                    dist += x[k] - x[r];
                    r = k;
                }
                else
                {
                    dist += x[r] - x[l - 1];
                    l--;
                    pos = 0;
                }
            }
        }

        std::cout << dist << "\n";
    }
}

