ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
int a[maxn + 7], b[maxn + 7], p[maxn + 7], q[maxn + 7];
std::vector<int> f;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
        f.pb(a[i]);
    }
    for (int j = 1; j <= n; j++)
    {
        std::cin >> b[j];
        if (j > 1)
        {
            f.pb(b[j]);
        }
    }
    std::sort(all(f));

    for (int i = 2; i <= n; i++)
    {
        p[i] = std::max(p[i - 1], a[i]);
    }
    for (int j = 2; j <= n; j++)
    {
        q[j] = std::max(q[j - 1], b[j]);
    }

    std::vector<int> vec;
    for (int i = 2; i <= n; i++)
    {
        vec.pb(p[i]);
        vec.pb(q[i]);
    }

    std::sort(all(vec));
    vec.erase(std::unique(all(vec)), vec.end());

    ll mx = -INF, ans = 0, lst = 0;

    for (auto val : vec)
    {
        int cnt1 = std::upper_bound(p + 2, p + n + 1, val) - (p + 2);
        int cnt2 = std::upper_bound(q + 2, q + n + 1, val) - (q + 2);

        ll cnt = 1LL * cnt1 * cnt2 - lst;
        lst = 1LL * cnt1 * cnt2;

        ll dem = std::upper_bound(all(f), val) - std::lower_bound(all(f), val);

        if (cnt + dem >= mx)
        {
            mx = cnt + dem;
            ans = val;
        }
    }

    std::cout << ans << " " << mx << "\n";
}

