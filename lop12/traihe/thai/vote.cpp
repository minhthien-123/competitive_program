ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, q;
int a[maxn + 7];

struct node
{
    int sum, pre, suf, mx;
} st[4 * maxn + 7];

node merge(node a, node b)
{
    node res;
    res.sum = a.sum + b.sum;
    res.pre = std::max(a.pre, a.sum + b.pre);
    res.suf = std::max(a.suf + b.sum, b.suf);
    res.mx = std::max({a.mx, b.mx, a.suf + b.pre});
    return res;
}

void build(int id, int l, int r)
{
    if (l == r)
    {
        if (a[l] == 1)
        {
            st[id] = {1, 1, 1, 1};
        }
        else
        {
            st[id] = {-1, 0, 0, 0};
        }
        return;
    }

    int mid = (l + r) / 2;
    build(id * 2, l, mid);
    build(id * 2 + 1, mid + 1, r);
    st[id] = merge(st[id * 2], st[id * 2 + 1]);
}

node get(int id, int l, int r, int u, int v)
{
    if (v < l || r < u)
    {
        return {0, -INF, -INF, -INF};
    }
    if (u <= l && r <= v)
    {
        return st[id];
    }
    int mid = (l + r) / 2;
    node get1 = get(id * 2, l, mid, u, v);
    node get2 = get(id * 2 + 1, mid + 1, r, u, v);
    return merge(get1, get2);
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        char c;
        std::cin >> c;
        if (c == 'X')
        {
            a[i] = 1;
        }
        else
        {
            a[i] = -1;
        }
    }

    build(1, 1, n);
    std::cin >> q;

    for (int i = 1; i <= q; i++)
    {
        int l, r;
        std::cin >> l >> r;
        node res = get(1, 1, n, l, r);
        std::cout << res.mx - res.sum << "\n";
    }
}

