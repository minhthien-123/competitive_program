struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p)
    {
        tin[u] = ++timer;
        up[u][0] = p;
        for (int i = 1; i <= lg; ++i)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
        }
        for (auto [v, id] : adj[u])
        {
            if (v != p)
            {
                node[id] = v;
                depth[v] = depth[u] + 1;
                dfs(v, u);
            }
        }
        tout[u] = timer;
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
            std::swap(u, v);
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; ++i)
        {
            if ((k >> i) & 1)
                u = up[u][i];
        }
        if (u == v)
            return u;
        for (int i = lg; i >= 0; --i)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }
};

struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size())
    {
        for (int i = 0; i < a.size(); i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r >= 0; r = (r & (r + 1)) - 1)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx < n; idx = idx | (idx + 1))
        {
            bit[idx] += delta;
        }
    }
};

struct ParallelBinarySearch
{
    int q, max_val;
    std::vector<int> L, R, ans;
    std::vector<std::vector<int>> check_at;
    FenwickTree cost, cnt;

    ParallelBinarySearch(int q, int max_val) : cost(n + 7), cnt(n + 7)
    {
        this->q = q;
        this->max_val = max_val;
        L.assign(q + 7, 1);
        R.assign(q + 7, max_val);
        ans.assign(q + 7, -1);
        check_at.resize(max_val + 7);
    }

    void reset_data_structure()
    {
        cost.bit.assign(cost.n, 0);
        cnt.bit.assign(cnt.n, 0);
    }

    void apply_step(int step)
    {
        int u = a[step].node;
        int C = a[step].C;
        cost.add(tin[u], C);
        cost.add(tout[u] + 1, -C);
        cnt.add(tin[u], 1);
        cnt.add(tout[u] + 1, -1);
    }

    bool check_condition(int id)
    {
        int u = query[id].s;
        int v = query[id].t;
        int lca = query[id].lca;

        int Cost = cost.sum(tin[u]) + cost.sum(tin[v]) - 2 * cost.sum(tin[lca]);
        if (Cost <= query[id].y)
        {
            res[id] = cnt.sum(tin[u]) + cnt.sum(tin[v]) - 2 * cnt.sum(tin[lca]);
            return true;
        }
        return false;
    }

    void run()
    {
        bool changed = true;
        while (changed)
        {
            changed = false;
            for (int i = 1; i <= max_val; i++)
            {
                check_at[i].clear();
            }

            for (int i = 1; i <= q; i++)
            {
                if (L[i] <= R[i])
                {
                    int mid = (L[i] + R[i]) / 2;
                    check_at[mid].push_back(i);
                    changed = true;
                }
            }

            if (!changed)
            {
                break;
            }

            reset_data_structure();

            for (int step = 1; step <= max_val; step++)
            {
                apply_step(step);

                for (int id : check_at[step])
                {
                    if (check_condition(id))
                    {
                        ans[id] = step;
                        L[id] = step + 1;
                    }
                    else
                    {
                        R[id] = step - 1;
                    }
                }
            }
        }
    }
};

void dfs(int u, int p)
{
    for (auto [v, id] : adj[u])
    {
        if (v == p)
        {
            continue;
        }
        pre[v] = pre[u] + cntsta[v];
        dfs(v, u);
    }
}

void solve()
{
    std::cin >> n >> m >> q;
    for (int i = 1; i < n; i++)
    {
        int u, v;
        std::cin >> u >> v;
        adj[u].pb({v, i});
        adj[v].pb({u, i});
    }

    LCA lca(n);
    lca.build(1);

    for (int i = 1; i <= m; i++)
    {
        int p, c;
        std::cin >> p >> c;
        a[i] = {i, c, p};
    }
    for (int i = 1; i <= m; i++)
    {
        a[i].node = node[a[i].node];
        cntsta[a[i].node]++;
    }

    dfs(1, 0);

    std::sort(a + 1, a + m + 1);
    for (int k = 1; k <= q; k++)
    {
        std::cin >> query[k].s >> query[k].t >> query[k].x >> query[k].y;
        query[k].lca = lca.get_lca(query[k].s, query[k].t);
        query[k].cnt = pre[query[k].s] + pre[query[k].t] - 2 * pre[query[k].lca];
    }

    ParallelBinarySearch pbs(q, m);
    pbs.run();

    for (int k = 1; k <= q; k++)
    {
        int dem = query[k].cnt - res[k];
        if (dem <= query[k].x)
        {
            std::cout << query[k].x - dem << "\n";
        }
        else
        {
            std::cout << "-1\n";
        }
    }
}

