const int maxn = 1e5;
const int maxm = 2e5;
const ll INF = 1e18;
const int inf = 1e9;
const int mod = 1e9 + 7;
const int inv = (mod + 1) / 2;
const int lg = 20;
const int dx[] = {0, 1, 0, -1, -1, -1, 1, 1};
const int dy[] = {1, 0, -1, 0, -1, 1, -1, 1};

ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<iii> adj[maxn + 7];
int n, m, k;
int d[maxn + 7];
iii edges[maxm + 7];
std::vector<int> vec;
int ans[maxm + 7];

void bfs01(int s)
{
    for (int i = 1; i <= n; i++)
    {
        d[i] = INF;
    }
    std::deque<int> dq;
    dq.push_front(s);
    d[s] = 0;

    while (sz(dq))
    {
        int u = dq.front();
        dq.pop_front();

        for (auto e : adj[u])
        {
            int v = e.fi.fi;
            int w = e.fi.se;
            if (d[v] > d[u] + w)
            {
                d[v] = d[u] + w;

                if (w == 0)
                {
                    dq.push_front(v);
                }
                else
                {
                    dq.push_back(v);
                }
            }
        }
    }
}

void solve()
{
    std::cin >> n >> m >> k;
    for (int i = 1; i <= m; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        adj[u].pb({{v, w}, i});
        adj[v].pb({{u, w}, i});
        edges[i] = {{u, v}, w};
        if (w == 1)
        {
            vec.pb(i);
        }
    }

    bfs01(1);

    if (d[n] < k)
    {
        std::cout << "NO";
    }
    else
    {
        std::cout << "YES\n";

        for (int i : vec)
        {
            int u = edges[i].fi.fi;
            int v = edges[i].fi.se;

            if (d[u] == INF || d[v] == INF)
            {
                ans[i] = 1;
                continue;
            }

            int mxd = std::max(d[u], d[v]);

            if (d[u] != d[v] && mxd <= k)
            {
                ans[i] = mxd;
            }
            else
            {
                ans[i] = 1;
            }
        }

        for (int i : vec)
        {
            std::cout << ans[i] << "\n";
        }
    }
}

