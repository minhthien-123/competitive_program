ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
ii a[maxn + 7];
int f[maxn + 7];

bool cmp(ii a, ii b)
{
    if (a.fi == b.fi)
    {
        return a.se < b.se;
    }
    return a.fi > b.fi;
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i].fi;
        a[i].se = i;
        f[i] = a[i].fi;
    }
    std::set<int> s;
    for (int i = 1; i <= n; i++)
    {
        s.ins(i);
    }

    std::sort(a + 1, a + n + 1, cmp);
    bool flag = false;
    std::vector<int> v;
    v.pb(0);
    for (int i = 1; i <= n; i++)
    {
        if (a[i].se > v.back())
        {
            v.pb(a[i].se);
            s.erase(a[i].se);
        }
        else
        {
            int tmp1 = v.back();
            if (!flag)
            {
                int tmp2 = v[v.size() - 2];
                if (tmp2 < a[i].se && a[i].se < tmp1)
                {
                    v.pb(a[i].se);
                    s.erase(a[i].se);
                    flag = true;
                }
            }
        }
    }

    for (int i = 1; i <= n; i++)
    {
        if (s.find(i) == s.end())
        {
            continue;
        }
        if (!flag)
        {
            auto pos = s.upper_bound(v.back());
            if (pos != s.end())
            {
                v.pb(*pos);
                s.erase(*pos);
                flag = true;
            }
        }
    }

    for (int i = 1; i < v.size(); i++)
    {
        std::cout << f[v[i]] << " ";
    }
    std::cout << "\n";
}

