ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, q;
int a[maxn + 7];
int inv_p[maxv + 7];

struct Sieve
{
    int n;
    std::vector<int> min_prime;
    std::vector<int> primes;

    Sieve(int n) : n(n)
    {
        min_prime.assign(n + 1, 0);
        for (int i = 2; i <= n; i++)
        {
            if (min_prime[i] == 0)
            {
                min_prime[i] = i;
                primes.push_back(i);
            }
            for (int p : primes)
            {
                if (p > min_prime[i] || i * p > n)
                {
                    break;
                }
                min_prime[i * p] = p;
            }
        }
        for (int i = 2; i <= 200000; i++)
        {
            if (min_prime[i] == i)
            {
                inv_p[i] = power(i, mod - 2);
            }
        }
    }

    bool is_prime(int x)
    {
        if (x < 2)
        {
            return false;
        }
        return min_prime[x] == x;
    }
};
Sieve sieve(maxv);

struct Node
{
    int lc, rc;
    int prod;
};

int node_cnt;
Node st[maxn * 100];
int roots[maxn + 7];

int build(int l, int r)
{
    node_cnt++;
    int id = node_cnt;
    st[id].prod = 1;
    if (l == r)
    {
        return id;
    }
    int mid = (l + r) / 2;
    st[id].lc = build(l, mid);
    st[id].rc = build(mid + 1, r);
    return id;
}

int update(int old_id, int l, int r, int pos, long long val)
{
    node_cnt++;
    int id = node_cnt;
    st[id] = st[old_id];
    st[id].prod = mul(st[id].prod, val);

    if (l == r)
    {
        return id;
    }

    int mid = (l + r) / 2;
    if (pos <= mid)
    {
        st[id].lc = update(st[old_id].lc, l, mid, pos, val);
    }
    else
    {
        st[id].rc = update(st[old_id].rc, mid + 1, r, pos, val);
    }
    int p1 = st[id].lc ? st[st[id].lc].prod : 1;
    int p2 = st[id].rc ? st[st[id].rc].prod : 1;
    st[id].prod = mul(p1, p2);
    return id;
}

long long query(int id, int l, int r, int u, int v)
{
    if (!id || v < l || r < u)
    {
        return 1;
    }
    if (u <= l && r <= v)
    {
        return st[id].prod;
    }
    int mid = (l + r) / 2;
    return mul(query(st[id].lc, l, mid, u, v), query(st[id].rc, mid + 1, r, u, v));
}

int last[maxv + 7];

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    roots[0] = build(1, n);
    for (int i = 1; i <= n; i++)
    {
        int prod = 1;
        std::vector<ii> upd;

        int tmp = a[i];
        while (tmp > 1)
        {
            int p = sieve.min_prime[tmp];
            int pk = 1;
            while (tmp % p == 0)
            {
                pk *= p;
                tmp /= p;
                if (last[pk] != 0)
                {
                    upd.pb({last[pk], inv_p[p]});
                }
                prod = mul(prod, p);
                last[pk] = i;
            }
        }

        if (a[i] > 1)
        {
            upd.pb({i, prod});
        }

        std::sort(all(upd));
        int cur = roots[i - 1];

        for (int j = 0; j < sz(upd);)
        {
            int k = j;
            int val = 1;
            while (k < sz(upd) && upd[k].fi == upd[j].fi)
            {
                val = mul(val, upd[k].se);
                k++;
            }
            cur = update(cur, 1, n, upd[j].fi, val);
            j = k;
        }

        roots[i] = cur;
    }

    std::cin >> q;
    int last = 0;
    for (int i = 0; i < q; i++)
    {
        int x, y;
        std::cin >> x >> y;
        int l = (last + x) % n + 1;
        int r = (last + y) % n + 1;
        if (l > r)
        {
            std::swap(l, r);
        }
        last = query(roots[r], 1, n, l, r);
        std::cout << last << "\n";
    }
}

