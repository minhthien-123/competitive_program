{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
std::vector<ii> adj[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up, mx;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        mx.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p, int w)
    {
        up[u][0] = p;
        mx[u][0] = w;
        for (int i = 1; i <= lg; i++)
        {
            up[u][i] = up[up[u][i - 1]][i - 1];
            mx[u][i] = std::max(mx[u][i - 1], mx[up[u][i - 1]][i - 1]);
        }
        for (auto [v, we] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u, we);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root, 0);
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_max_edge(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int ans = 0;

        for (int j = lg; j >= 0; j--)
        {
            if (depth[u] - (1 << j) >= depth[v])
            {
                ans = std::max(ans, mx[u][j]);
                u = up[u][j];
            }
        }

        if (u == v)
        {
            return ans;
        }

        for (int j = lg; j >= 0; j--)
        {
            if (up[u][j] != up[v][j])
            {
                ans = std::max({ans, mx[u][j], mx[v][j]});
                u = up[u][j];
                v = up[v][j];
            }
        }

        ans = std::max({ans, mx[u][0], mx[v][0]});
        return ans;
    }
};

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

struct edge
{
    int u, v, w;
    friend bool operator<(edge a, edge b)
    {
        return a.w < b.w;
    }
};

void solve()
{
    std::cin >> n >> m;
    std::vector<edge> edges;
    for (int i = 1; i <= m; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        edges.pb({u, v, w});
    }
    std::sort(all(edges));
    DSU dsu(n);

    int sum = 0;
    int cnt = 0;

    for (auto [u, v, w] : edges)
    {
        if (dsu.acs(u) != dsu.acs(v))
        {
            dsu.join(u, v);
            sum += w;
            adj[u].pb({v, w});
            adj[v].pb({u, w});
            cnt++;
            if (cnt == n - 1)
            {
                break;
            }
        }
    }

    LCA lca(n);
    lca.build(1);

    int q;
    std::cin >> q;
    while (q--)
    {
        int s, t;
        std::cin >> s >> t;
        int mx = lca.get_max_edge(s, t);
        std::cout << sum - mx << "\n";
    }
}

