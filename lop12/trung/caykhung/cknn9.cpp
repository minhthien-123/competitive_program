ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, m;
std::vector<ii> adj[maxn + 7];

struct LCA
{
    int n, lg;
    std::vector<std::vector<int>> up, mx1, mx2;
    std::vector<int> depth;

    LCA(int n)
    {
        this->n = n;
        lg = std::ceil(std::log2(n + 1));
        up.assign(n + 7, std::vector<int>(lg + 1, 0));
        mx1.assign(n + 7, std::vector<int>(lg + 1, 0));
        mx2.assign(n + 7, std::vector<int>(lg + 1, 0));
        depth.assign(n + 7, 0);
    }

    void dfs(int u, int p, int w)
    {
        up[u][0] = p;
        mx1[u][0] = w;
        mx2[u][0] = -1;

        for (int j = 1; j <= lg; j++)
        {
            up[u][j] = up[up[u][j - 1]][j - 1];
            int b1 = -1, b2 = -1;
            combine(b1, b2, mx1[u][j - 1], mx2[u][j - 1]);
            combine(b1, b2, mx1[up[u][j - 1]][j - 1], mx2[up[u][j - 1]][j - 1]);
            mx1[u][j] = b1;
            mx2[u][j] = b2;
        }

        for (auto [v, we] : adj[u])
        {
            if (v != p)
            {
                depth[v] = depth[u] + 1;
                dfs(v, u, we);
            }
        }
    }

    void build(int root = 1)
    {
        depth[root] = 0;
        dfs(root, root, 0);
    }

    void combine(int &b1, int &b2, int v1, int v2)
    {
        int a[4] = {b1, b2, v1, v2};
        b1 = -1;
        b2 = -1;
        for (int c : a)
        {
            if (c > b1)
            {
                b2 = b1;
                b1 = c;
            }
            else if (c < b1 && c > b2)
            {
                b2 = c;
            }
        }
    }

    int get_lca(int u, int v)
    {
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }
        int k = depth[u] - depth[v];
        for (int i = 0; i <= lg; i++)
        {
            if ((k >> i) & 1)
            {
                u = up[u][i];
            }
        }
        if (u == v)
        {
            return u;
        }
        for (int i = lg; i >= 0; i--)
        {
            if (up[u][i] != up[v][i])
            {
                u = up[u][i];
                v = up[v][i];
            }
        }
        return up[u][0];
    }

    int get_replace(int u, int v, int w)
    {
        int b1 = -1, b2 = -1;
        if (depth[u] < depth[v])
        {
            std::swap(u, v);
        }

        for (int j = lg; j >= 0; j--)
        {
            if (depth[u] - (1 << j) >= depth[v])
            {
                combine(b1, b2, mx1[u][j], mx2[u][j]);
                u = up[u][j];
            }
        }

        if (u != v)
        {
            for (int j = lg; j >= 0; j--)
            {
                if (up[u][j] != up[v][j])
                {
                    combine(b1, b2, mx1[u][j], mx2[u][j]);
                    combine(b1, b2, mx1[v][j], mx2[v][j]);
                    u = up[u][j];
                    v = up[v][j];
                }
            }
            combine(b1, b2, mx1[u][0], mx2[u][0]);
            combine(b1, b2, mx1[v][0], mx2[v][0]);
        }

        if (b1 != -1 && b1 < w)
        {
            return b1;
        }
        if (b2 != -1 && b2 < w)
        {
            return b2;
        }
        return -1;
    }
};

struct DSU
{
    std::vector<int> par, sz;

    DSU(int n)
    {
        par.resize(n + 7);
        sz.resize(n + 7);
        for (int i = 0; i <= n + 1; i++)
        {
            par[i] = i;
            sz[i] = 1;
        }
    }

    int acs(int v)
    {
        return v == par[v] ? v : par[v] = acs(par[v]);
    }

    void join(int u, int v)
    {
        u = acs(u);
        v = acs(v);
        if (u != v)
        {
            if (sz[u] < sz[v])
            {
                std::swap(u, v);
            }
            par[v] = u;
            sz[u] += sz[v];
        }
    }
};

struct edge
{
    int u, v, w;
    bool flag;
    friend bool operator<(edge a, edge b)
    {
        return a.w < b.w;
    }
};

void solve()
{
    std::cin >> n >> m;
    std::vector<edge> edges;
    for (int i = 1; i <= m; i++)
    {
        int u, v, w;
        std::cin >> u >> v >> w;
        edges.pb({u, v, w, false});
    }
    std::sort(all(edges));
    DSU dsu(n);

    int sum = 0;
    int cnt = 0;

    for (int i = 0; i < m; i++)
    {
        int u = edges[i].u;
        int v = edges[i].v;
        int w = edges[i].w;
        if (dsu.acs(u) != dsu.acs(v))
        {
            dsu.join(u, v);
            sum += w;
            adj[u].pb({v, w});
            adj[v].pb({u, w});
            edges[i].flag = true;
            cnt++;
            if (cnt == n - 1)
            {
                break;
            }
        }
    }

    LCA lca(n);
    lca.build(1);
    int mn = INF;

    for (int i = 0; i < m; i++)
    {
        if (!edges[i].flag)
        {
            int val = lca.get_replace(edges[i].u, edges[i].v, edges[i].w);
            if (val != -1)
            {
                mn = std::min(mn, edges[i].w - val);
            }
        }
    }

    std::cout << (mn == INF ? -1 : sum + mn);
}

