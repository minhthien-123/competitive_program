struct FenwickTree
{
    std::vector<int> bit;
    int n;

    FenwickTree(int n)
    {
        this->n = n;
        bit.assign(n + 1, 0);
    }

    FenwickTree(std::vector<int> const &a) : FenwickTree(a.size())
    {
        for (int i = 0; i < a.size(); i++)
        {
            add(i, a[i]);
        }
    }

    int sum(int r)
    {
        int res = 0;
        for (; r >= 0; r = (r & (r + 1)) - 1)
        {
            res += bit[r];
        }
        return res;
    }

    int sum(int l, int r)
    {
        if (l > r)
            return 0;
        return sum(r) - sum(l - 1);
    }

    void add(int idx, int delta)
    {
        for (; idx < n; idx = idx | (idx + 1))
        {
            bit[idx] += delta;
        }
    }
};

FenwickTree fw(0);

int mxL[maxn + 7], mxR[maxn + 7];
int ans = 0;

void dnc(int l, int r)
{
    if (l >= r)
    {
        return;
    }
    int mid = (l + r) / 2;

    mxL[mid] = pre[mid];
    for (int i = mid - 1; i >= l; i--)
    {
        mxL[i] = std::max(pre[i], mxL[i + 1]);
    }

    mxR[mid + 1] = -inf;
    for (int i = mid + 2; i <= r; i++)
    {
        mxR[i] = std::max(pre[i - 1], mxR[i - 1]);
    }

    int R = mid + 1;

    for (int L = mid; L >= l; L--)
    {
        while (R <= r && mxR[R] <= mxL[L])
        {
            fw.add(pre[R] + offset, 1);
            R++;
        }

        int cnt = mxL[L] - pre[L] + offset;
        ans += fw.sum(cnt, 2 * offset);
    }

    for (int j = mid + 1; j < R; j++)
    {
        fw.add(pre[j] + offset, -1);
    }

    int L = mid;
    for (int R = mid + 1; R <= r; R++)
    {
        while (L >= l && mxL[L] < mxR[R])
        {
            fw.add(pre[L] + offset, 1);
            L--;
        }

        int cnt = mxR[R] - pre[R] + offset;
        ans += fw.sum(cnt, 2 * offset);
    }

    for (int j = mid; j > L; j--)
    {
        fw.add(pre[j] + offset, -1);
    }

    dnc(l, mid);
    dnc(mid + 1, r);
}

void solve()
{
    std::cin >> n;
    std::cin >> s;

    for (int i = 1; i <= n; i++)
    {
        pre[i] = pre[i - 1] + (s[i - 1] == '(' ? 1 : -1);
    }

    fw = FenwickTree(2 * offset + 8);

    dnc(0, n);

    std::cout << ans;
}

