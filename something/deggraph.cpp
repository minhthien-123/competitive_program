ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x * y) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n;
ll s[maxn + 7];
ll dp[maxn + 7];
int trace[maxn + 7], deg[maxn + 7];
ll w[maxn + 7];
std::vector<ii> nodes;

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n - 1; i++)
    {
        std::cin >> s[i];
    }

    for (int i = 1; i <= n - 2; i++)
    {
        w[i] = s[i + 1] - s[1];
    }

    for (int i = 1; i <= n - 2; i++)
    {
        dp[i] = -INF;
        trace[i] = -1;
    }
    dp[0] = 0;

    for (int i = 1; i <= n - 2; i++)
    {
        for (int j = 1; j <= i; j++)
        {
            if (dp[i - j] != -INF)
            {
                ll tmp = dp[i - j] + w[j];
                if (tmp > dp[i])
                {
                    dp[i] = tmp;
                    trace[i] = j;
                }
            }
        }
    }

    ll ans = 1LL * n * s[1] + dp[n - 2];
    std::cout << ans << "\n";
    std::cout << n - 1 << "\n";

    for (int i = 1; i <= n; i++)
    {
        deg[i] = 1;
    }

    int cur = n - 2;
    int idx = 1;
    while (cur > 0)
    {
        int x = trace[cur];
        deg[idx] += x;
        idx++;
        cur -= x;
    }

    for (int i = 1; i <= n; i++)
    {
        nodes.pb({deg[i], i});
    }

    for (int k = 1; k <= n - 1; k++)
    {
        std::sort(all(nodes));

        int id1 = -1;
        for (int i = 0; i < sz(nodes); i++)
        {
            if (nodes[i].fi == 1)
            {
                id1 = i;
                break;
            }
        }

        int id2 = sz(nodes) - 1;
        if (id1 == id2)
        {
            id2--;
        }

        std::cout << nodes[id1].se << " " << nodes[id2].se << "\n";

        nodes[id1].fi--;
        nodes[id2].fi--;
    }
}

