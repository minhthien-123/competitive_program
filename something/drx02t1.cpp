ll n, k;
std::string s;
int f[26] = {0};

void solve()
{
    std::cin >> n >> k;
    std::cin >> s;

    ll cnt = 0;

    int d = 0;
    int l = 0;

    for (int r = 0; r < n; r++)
    {
        int id = s[r] - 'a';
        if (f[id] == 0)
        {
            d++;
        }
        f[id]++;

        while (d >= k)
        {
            int lid = s[l] - 'a';
            f[lid]--;
            if (f[lid] == 0)
            {
                d--;
            }
            l++;
        }

        cnt += (r - l + 1);
    }

    ll ans = n * (n + 1) / 2 - cnt;
    std::cout << ans << "\n";
}

