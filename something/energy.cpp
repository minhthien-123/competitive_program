ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n;
int a[maxn], dp[maxn];
int tree[4 * maxn], lazy[4 * maxn];
int idx[maxn], top = 0;

void push(int id)
{
    if (lazy[id] != 0)
    {
        tree[2 * id] += lazy[id];
        lazy[2 * id] += lazy[id];
        tree[2 * id + 1] += lazy[id];
        lazy[2 * id + 1] += lazy[id];
        lazy[id] = 0;
    }
}

void update(int id, int l, int r, int u, int v, int val)
{
    if (l > v || r < u)
    {
        return;
    }
    if (u <= l && r <= v)
    {
        tree[id] += val;
        lazy[id] += val;
        return;
    }
    push(id);
    int mid = l + (r - l) / 2;
    update(2 * id, l, mid, u, v, val);
    update(2 * id + 1, mid + 1, r, u, v, val);
    tree[id] = std::max(tree[2 * id], tree[2 * id + 1]);
}

void update(int id, int l, int r, int pos, int val)
{
    if (l == r)
    {
        tree[id] = val;
        lazy[id] = 0;
        return;
    }
    push(id);
    int mid = l + (r - l) / 2;
    if (pos <= mid)
    {
        update(2 * id, l, mid, pos, val);
    }
    else
    {
        update(2 * id + 1, mid + 1, r, pos, val);
    }
    tree[id] = std::max(tree[2 * id], tree[2 * id + 1]);
}

int query(int id, int l, int r, int u, int v)
{
    if (l > v || r < u)
    {
        return -INF;
    }
    if (u <= l && r <= v)
    {
        return tree[id];
    }
    push(id);
    int mid = l + (r - l) / 2;
    return std::max(query(2 * id, l, mid, u, v), query(2 * id + 1, mid + 1, r, u, v));
}

void solve()
{
    std::cin >> n;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> a[i];
    }

    for (int i = 1; i <= 4 * n; ++i)
    {
        tree[i] = -INF;
        lazy[i] = 0;
    }

    top = 0;
    idx[++top] = 0;

    for (int i = 1; i <= n; i++)
    {
        update(1, 1, n, i, dp[i - 1] - a[i]);

        while (top > 1 && a[idx[top]] > a[i])
        {
            int top_id = idx[top]; 
            top--;                 
            int pre = idx[top];    

            update(1, 1, n, pre + 1, top_id, a[i] - a[top_id]);
        }
        update(1, 1, n, i, i, a[i]);
        idx[++top] = i;

        dp[i] = a[i] + query(1, 1, n, 1, i);
    }

    std::cout << dp[n];
}

