ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];
int n, s, dp[maxn + 7], l[maxn + 7], r[maxn + 7], sum = 0, ans[maxn + 7];
ii trace[maxn + 7];
void solve()
{
    std::cin >> n >> s;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> l[i] >> r[i];
        sum += l[i];
    }
    if (sum > s)
    {
        std::cout << "NO";
        return;
    }
    int res = s - sum;
    for (int i = 1; i <= n; i++)
    {
        int diff = std::min(res, r[i] - l[i]);
        res -= diff;
        ans[i] = l[i] + diff;
    }
    if (res != 0)
    {
        std::cout << "NO";
        return;
    }
    std::cout << "YES\n";
    for (int i = 1; i <= n; i++)
    {
        std::cout << ans[i] << " ";
    }
}

