ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

std::vector<int> adj[maxn + 7];

int fact[maxn], inv_fact[maxn];

void precompute()
{
    fact[0] = 1;
    inv_fact[0] = 1;
    for (int i = 1; i < maxn; i++)
    {
        fact[i] = mul(fact[i - 1], i);
    }
    inv_fact[maxn - 1] = power(fact[maxn - 1], mod - 2);
    for (int i = maxn - 2; i >= 1; i--)
    {
        inv_fact[i] = mul(inv_fact[i + 1], i + 1);
    }
}

ll nCr(int n, int k)
{
    if (k < 0 || k > n || n < 0)
    {
        return 0;
    }
    return mul(fact[n], mul(inv_fact[k], inv_fact[n - k]));
}

int preo[maxn + 7], preq[maxn + 7];

void solve()
{
    std::string s;
    std::cin >> s;
    int n = sz(s);

    int C = 0;
    int Q = 0;

    for (int i = 0; i < n; i++)
    {
        if (s[i] == ')')
        {
            C++;
        }
        if (s[i] == '?')
        {
            Q++;
        }
    }

    for (int i = 0; i < n; i++)
    {
        preo[i + 1] = preo[i] + (s[i] == '(');
        preq[i + 1] = preq[i] + (s[i] == '?');
    }

    ll ans = 0;

    for (int k = 0; k <= n; k++)
    {
        ll term1 = mul(preo[k], nCr(Q, k - C));
        ll term2 = mul(preq[k], nCr(Q - 1, k - C));

        ans = add(ans, add(term1, term2));
    }

    std::cout << ans << "\n";
}

