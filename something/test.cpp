ll add(ll x, ll y)
{
    return (x + y + 2 * mod) % mod;
}
ll sub(ll x, ll y)
{
    return (x - y + 2 * mod) % mod;
}
ll mul(ll x, ll y)
{
    return (x % mod * (y % mod)) % mod;
}
ll power(ll x, ll y)
{
    if (y == 0)
    {
        return 1;
    }
    ll tmp = power(x, y / 2);
    if (y % 2 == 0)
    {
        return (tmp * tmp) % mod;
    }
    else
    {
        return tmp * tmp % mod * x % mod;
    }
}

int n, l;
int h[maxn], w[maxn];
int dp[maxn], val[maxn];

void solve()
{
    std::cin >> n >> l;
    for (int i = 1; i <= n; i++)
    {
        std::cin >> h[i] >> w[i];
    }

    std::deque<int> dq;
    std::multiset<int> ms;

    int left = 0;
    int w_sum = 0;
    dp[0] = 0;

    for (int i = 1; i <= n; i++)
    {
        w_sum += w[i];

        // Dịch con trỏ left để đảm bảo tổng chiều rộng trên kệ không vượt quá L
        while (w_sum > l)
        {
            left++;
            w_sum -= w[left];
        }

        // Loại bỏ các phần tử nằm ngoài cửa sổ [left + 1, i]
        while (!dq.empty() && dq.front() <= left)
        {
            ms.erase(ms.find(val[dq.front()]));
            dq.pop_front();
        }

        // Cập nhật lại giá trị cho phần tử đầu tiên của deque do 'left' vừa tăng
        // Khoảng tối ưu của phần tử này bây giờ bắt đầu từ 'left'
        if (!dq.empty())
        {
            ms.erase(ms.find(val[dq.front()]));
            val[dq.front()] = dp[left] + h[dq.front()];
            ms.insert(val[dq.front()]);
        }

        // Maintain monotonic deque giảm dần theo chiều cao H
        while (!dq.empty() && h[dq.back()] <= h[i])
        {
            ms.erase(ms.find(val[dq.back()]));
            dq.pop_back();
        }

        // Tính toán giá trị min dp[] cho quyển sách thứ i và thêm vào ms
        int prev = dq.empty() ? left : dq.back();
        val[i] = dp[prev] + h[i];
        dq.push_back(i);
        ms.insert(val[i]);

        // dp[i] là cấu hình có tổng chiều cao nhỏ nhất hiện tại
        dp[i] = *ms.begin();
    }

    std::cout << dp[n] << "\n";
}

